#!/usr/bin/env node

// Mechanical concept-fixture splitter. This script is never imported by the app.
// It keeps Home/search metadata byte-identical to the detailed fixture source
// without putting provider, account, model, installation, manager-resource,
// memory, terminal, log, path, or receipt bodies on the startup module path.

import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const shared = resolve(here, "../_shared");
const details = await import("../_shared/data-details.mjs");

const providerSummaries = details.PROVIDERS.map((provider) => ({
  id: provider.id,
  name: provider.name,
  group: provider.group,
  state: provider.state,
  stateLabel: provider.stateLabel,
  summary: provider.summary
}));

const managerSummaries = details.MANAGERS.map((manager) => ({
  id: manager.id,
  title: manager.title,
  purpose: manager.purpose,
  icon: manager.icon,
  full: Boolean(manager.full),
  insertionOnly: Boolean(manager.insertionOnly),
  owner: manager.owner || null,
  ownerStatus: manager.ownerStatus || null
}));

const categorySummaries = details.CATEGORIES.map((category) => ({
  id: category.id,
  title: category.title,
  route: category.route,
  icon: category.icon,
  purpose: category.purpose,
  description: category.description,
  subcategories: (category.subcategories || []).map((subcategory) => ({
    id: subcategory.id,
    title: subcategory.title,
    description: subcategory.description,
    settings: []
  }))
}));

const values = {
  CATEGORY_SUMMARIES: categorySummaries,
  MANAGERS: managerSummaries,
  PROVIDERS: providerSummaries,
  SPELLING_FIXTURE: details.SPELLING_FIXTURE,
  SETUP_SESSIONS: details.SETUP_SESSIONS,
  RECENT_CHANGES: details.RECENT_CHANGES,
  RECEIPT_HISTORY: details.RECEIPT_HISTORY,
  SCENARIOS: details.SCENARIOS,
  SEARCH_METADATA: details.buildCompactSearchMetadata(),
  CONCEPT_MANAGER_ASSIGNMENTS: details.CONCEPT_MANAGER_ASSIGNMENTS,
  GENERIC_MANAGER_STATE_DEFINITIONS: details.GENERIC_MANAGER_STATE_DEFINITIONS,
  MANAGER_STATE_FIXTURE_IDS: details.MANAGER_STATE_FIXTURE_IDS,
  SIMULATED_REVIEW_PROFILES: details.SIMULATED_REVIEW_PROFILES,
  SIMULATED_REVIEW_PROFILE_NOTICE: details.SIMULATED_REVIEW_PROFILE_NOTICE,
  RESOURCE_ADMISSION_PROJECTION_CONTRACT: details.RESOURCE_ADMISSION_PROJECTION_CONTRACT
};

const banner = `// Generated by verify/generate-core-data.mjs from data-details.mjs.\n// Compact startup values only; do not add detailed manager/provider payloads here.\n\n`;
const body = `${banner}export const CORE_DATA = Object.freeze(${JSON.stringify(values)});\n`;
await writeFile(resolve(shared, "data-core-values.mjs"), body, "utf8");
console.log(JSON.stringify({ path: "_shared/data-core-values.mjs", bytes: Buffer.byteLength(body), providers: providerSummaries.length, managers: managerSummaries.length, searchMetadata: values.SEARCH_METADATA.length, detailSettingsExcluded: details.allSettings().length }));
