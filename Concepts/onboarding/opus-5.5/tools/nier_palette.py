    L = mode == 'light'
    ink = c['accent']
    ink_rgb = ','.join(map(str, rgb(ink)))
    shadow_rgb = ','.join(map(str, rgb(light['text'])))  # the ink; in dark it is darker than the canvas
    a = lambda hexv, alpha: f"rgba({','.join(map(str, rgb(hexv)))},{alpha})"
