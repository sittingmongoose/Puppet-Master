/* NieR — the art family drawn while NieR Mode is painted (O55.theme().art === 'nier') and in a NieR preview (an element
   with data-o55-nier-preview="dark|light", the look screen's NieR thumbnail); O55.art.artFamily decides.

   PLACEHOLDER until ART-DRAW. Most props below are Basic's drawings re-inked in NieR's tokens (ink on parchment, square
   caps, mitre joins, square corners, the NieR face): every entry made with fromBasic() is borrowed (A.nier.borrowed()
   lists them). NieR's own already: the curtain (ink slices, 30-art.css), the identity card (ink cells, no hue), the
   signal link and the string. The family is complete end to end: the rig, cheers, the joy face and lock-on, confetti,
   the scene cross-transition and the curtain all key on 'nier'. ART-DRAW replaces the entries of `props` one by one
   (and `hand`, `round`, `defs`, `background`, `overlay`) with the unit marionettes of design/puppets-final/spec.md;
   METRICS.nier (55-scenes.js) already holds the final unit's numbers (hook [0, -66]).
   Everything is exported as O55.art.nier (the family definition itself, so a replaced entry is live at once):
     palette(mode, tok, ctx) -> pal   tokens(tok, mode) -> NieR tokens (a preview probe when tok is not NieR's)
     props { <prop>(ctx, item) }      has(ctx, key) -> NieR part installed (true when not known: a preview)
     material(svg) -> svg             fromBasic(name) -> a prop drawn by Basic in the NieR material
     borrowed() -> the prop names still drawn by Basic
   No colour literal: every colour comes from the tokens (13-nier.css, generated by tools/nier_palette.py). */
(function () {
  'use strict';
  const O55 = window.O55, A = O55.art, U = O55.util;
  const BASIC = A.families.basic; /* 51-art-basic.js runs first (build order) */

  /* ---------------------------------------------------------------- tokens */
  /* NieR's tokens for a mode. A scene drawn in 'nier' normally has them already (root-owned while NieR Mode is
     painted, or a preview owner); otherwise (the family asked for by name on a look that is not NieR's) they are read
     from a hidden probe element carrying data-o55-nier-preview, so the generated tables stay the only source. */
  const probes = {};
  function tokens(tok, mode) {
    if (tok && tok.nier) return tok;
    mode = mode === 'light' ? 'light' : 'dark';
    let el = probes[mode];
    if (!el || !el.isConnected) {
      el = probes[mode] = document.createElement('span');
      el.setAttribute('data-o55-nier-preview', mode); el.setAttribute('aria-hidden', 'true'); el.hidden = true;
      (document.body || document.documentElement).appendChild(el);
    }
    return A.tokens(el);
  }
  /* an installed NieR part (html data-o55-nier-parts, read into the tokens); a preview while NieR Mode is off draws
     every part. ctx is a render context, or anything with `tok`. */
  const has = (ctx, key) => !ctx || !ctx.tok || !ctx.tok.nierParts || ctx.tok.nierParts.indexOf(key) >= 0;

  /* ---------------------------------------------------------------- palette */
  /* NieR's keys (spec.md section 9; what the unit drawings read), then Basic's keys for the borrowed drawings. */
  function palette(mode, tok) {
    const t = tokens(tok, mode), dark = mode === 'dark', ink = t.text, ink2 = A.rgba(ink, dark ? 0.5 : 0.55);
    return {
      dark, nier: true,
      ink, ink2, faint: A.rgba(ink, 0.2), hatch: A.rgba(ink, 0.09), grid: A.rgba(ink, 0.12), /* lines: ink, secondary, seams, far hatching, dot grid */
      ground: t.bg, raised: t.raised || t.surface, surface: t.surface, onInk: t.onInk || t.bg, /* paper: the scene ground, raised faces, stage top, on an ink block */
      ochre: t.orange, rust: t.error, olive: t.lime, line: t.border, muted: t.muted, /* ochre once per scene; rust only in confetti */
      tones: [ink, t.orange, ink2, ink], /* A.tone: sparks t0..t3 */
      /* Basic's keys, for the borrowed drawings only (drop them with the last fromBasic entry) */
      paper: A.mix(t.bg, t.surface, 0.5), gridMajor: A.rgba(ink, dark ? 0.12 : 0.15),
      fill: A.rgba(ink, dark ? 0.07 : 0.06), fill2: A.rgba(ink, dark ? 0.14 : 0.12),
      accent: t.orange, accentFill: A.rgba(t.orange, 0.14), text: t.text, dim: A.rgba(t.text, 0.6)
    };
  }

  /* ---------------------------------------------------------------- the NieR material over Basic's drawings */
  const FACE = "'PM NieR Sans', Inter, system-ui, sans-serif";
  function material(svg) {
    return String(svg)
      .replace(/stroke-linecap="round"/g, 'stroke-linecap="square"')
      .replace(/stroke-linejoin="round"/g, 'stroke-linejoin="miter"')
      .replace(/ rx="[\d.]+"/g, ' rx="0"')
      .replace(/font-family="Inter, system-ui, sans-serif"/g, `font-family="${FACE}"`);
  }
  const fromBasic = (name) => { const f = (ctx, item) => (BASIC.props[name] ? material(BASIC.props[name](ctx, item)) : ''); f.borrowed = true; return f; };
  const dia = (x, y, r) => `M${x.toFixed(1)} ${(y - r).toFixed(1)}L${(x + r).toFixed(1)} ${y.toFixed(1)}L${x.toFixed(1)} ${(y + r).toFixed(1)}L${(x - r).toFixed(1)} ${y.toFixed(1)}Z`;
  const txt = (p, x, y, s, size, anchor, color) => `<text x="${x}" y="${y}" font-size="${size || 7}" letter-spacing="1.4" font-family="${FACE}" font-weight="500" text-anchor="${anchor || 'middle'}" fill="${color || p.ink2}">${U.esc(String(s).toUpperCase())}</text>`;

  /* ---------------------------------------------------------------- props (ART-DRAW: replace one by one) */
  /* Basic's helper, with a stub of string from the NieR hook (METRICS.nier.hook, the unit's knot at y -66) down to
     Basic's head top (y -63), so a tied placeholder hangs exactly where the final unit will. */
  const basicHelper = fromBasic('helper');
  function helper(ctx, item) {
    const svg = basicHelper(ctx, item), o = item.opts || {};
    if (!o.rig) return svg;
    const hook = A.metrics('nier').hook, w = (0.85 / (item.s || 1)).toFixed(2);
    return svg.replace(/<\/g>$/, `<path d="M${hook[0]} ${hook[1]}V-63" fill="none" stroke="${ctx.pal.ink2}" stroke-width="${w}" stroke-linecap="square"/></g>`);
  }
  helper.borrowed = true;

  const props = {
    bar: fromBasic('bar'),           /* centred on its origin; studs at METRICS.nier.anchors; must end in </g> */
    helper,                          /* feet on y 0, knot at METRICS.nier.hook; wave arm = .o55-arm group; ends in </g> */
    stage: fromBasic('stage'),       /* origin = front edge centre, placed at floor + 28 */
    curtain(ctx) {
      /* ten slices of parchment, each with an ink hairline, leave to alternate sides (30-art.css .o55-cur-sl/-sr, --k);
         the ink plate across the middle is cut first (.o55-cur-plate); all of it is gone at 1.94 s (.o55-cur-all) */
      const p = ctx.pal, n = 10, h = A.H / n;
      let out = '';
      for (let i = 0; i < n; i++) {
        const y = -A.H / 2 + i * h;
        out += `<g class="o55-cur o55-cur-${i % 2 ? 'sr' : 'sl'}" style="--k:${i}"><rect x="-240" y="${y.toFixed(1)}" width="480" height="${(h + 0.6).toFixed(1)}" fill="${p.paper}"/>`
          + `<path d="M-240 ${(y + h).toFixed(1)}H240" stroke="${p.faint}" stroke-width="0.8"/></g>`;
      }
      const plate = `<g class="o55-cur o55-cur-plate"><rect x="-150" y="-14" width="300" height="28" fill="${p.ink}"/>`
        + `<path d="${dia(-130, 0, 6)}${dia(130, 0, 6)}" fill="${p.onInk}"/><path d="M-112 0H112" stroke="${p.onInk}" stroke-width="1" stroke-opacity="0.5"/></g>`;
      return `<g class="o55-cur-all">${out}${plate}</g>`;
    },
    computer: fromBasic('computer'),
    nas: fromBasic('nas'),
    key: fromBasic('key'),
    lock: fromBasic('lock'),
    node: fromBasic('node'),         /* round while borrowed; the final square node sets the family's round: false */
    pathline: fromBasic('pathline'),
    cloud: fromBasic('cloud'),
    folder: fromBasic('folder'),
    spark: fromBasic('spark'),
    rings: fromBasic('rings'),       /* .o55-ring pulses (stepped under .o55-f-nier) */
    badge: fromBasic('badge'),
    identity(ctx, item) {
      const p = ctx.pal, o = item.opts || {};
      return `<g><rect x="-32" y="-32" width="64" height="64" fill="${p.raised}" stroke="${p.ink}" stroke-width="1.2"/>`
        + `<g transform="translate(-22 -22)">${A.identitySvg(o.seed || 'nas', 44, 'nier', p.ink).replace('<svg', '<svg x="0" y="0"')}</g>`
        + (o.words ? txt(p, 0, 46, o.words, 6.2, 'middle', p.ink) : '') + '</g>';
    },
    note: fromBasic('note'),
    dimv: fromBasic('dimv'),
    /* You's stepped signal to the control unit (hero; added only when the family draws `operator`): pts = [the raised
       hand, under the bar's left end cap] in scene units, item at 0,0. Segments 4.5 long every 11, marching away from
       the hand (.o55-nier-mk, still at 0.55), ending in a paper diamond. Scenery, not a string: the rig never moves it. */
    link(ctx, item) {
      const p = ctx.pal, pts = (item.opts || {}).pts || [];
      if (pts.length < 2) return '';
      const [a, b] = pts, L = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1, ux = (b[0] - a[0]) / L, uy = (b[1] - a[1]) / L;
      let segs = '';
      for (let d = 7, k = 0; d < L - 8; d += 11, k++) {
        segs += `<path class="o55-nier-mk o55-nier-mk${k % 3}" opacity="0.55" d="M${(a[0] + ux * d).toFixed(1)} ${(a[1] + uy * d).toFixed(1)}L${(a[0] + ux * (d + 4.5)).toFixed(1)} ${(a[1] + uy * (d + 4.5)).toFixed(1)}"/>`;
      }
      return `<g class="o55-nier-link" fill="none" stroke="${p.ink}" stroke-width="1" stroke-linecap="square">${segs}`
        + `<path d="${dia(b[0], b[1] + 2, 2.6)}" fill="${p.ground}" stroke-width="0.9" stroke-linejoin="miter"/></g>`;
    }
    /* still to come with the units (spec.md section 6): operator (You, seated; hero only), machine (hero only) */
  };

  /* ---------------------------------------------------------------- the family */
  const NIER = A.nier = {
    placeholder: true,
    borrowed: () => Object.keys(props).filter((k) => props[k].borrowed),
    palette, props, tokens, has, material, fromBasic,
    /* a marionette string: a hairline in ink 0.55 with square ends (the rig sets its d every frame, and sags it when slack) */
    string: (ctx, d, isHand) => `<path class="o55-sp" d="${d}" fill="none" stroke="${ctx.pal.ink2}" stroke-width="${isHand ? 0.75 : 0.85}" stroke-linecap="square"/>`,
    hand: { wave: [24, -61] }, /* = the hand hook inside the borrowed helper's wave arm; the final unit's is [19.5, -58.5] */
    /* round: (unset) the borrowed node is round; the final chamfered node sets round: false (A.edge) */
    defs(ctx) {
      /* the parchment's dot grid: 1.2-unit squares every 16 (part Parchment ground) */
      return `<pattern id="${ctx.uid}-dots" width="16" height="16" patternUnits="userSpaceOnUse"><rect width="1.2" height="1.2" fill="${ctx.pal.grid}" shape-rendering="crispEdges"/></pattern>`;
    },
    background(ctx) {
      /* placeholder ground: parchment, its dot grid, four corner brackets and the kicker's ink square and rule (part
         YoRHa headers). ART-DRAW adds the kicker text, the glyph strip, the far ruins and the title block (spec.md 7). */
      const p = ctx.pal, W = A.W, H = A.H, br = (x, y, dx, dy) => `M${x + dx * 14} ${y}H${x}V${y + dy * 14}`;
      return `<rect width="${W}" height="${H}" fill="${p.ground}"/>` + (has(ctx, 'ground') ? `<rect width="${W}" height="${H}" fill="${ctx.url('dots')}"/>` : '')
        + `<path d="${br(22, 22, 1, 1)}${br(W - 22, 22, -1, 1)}${br(22, H - 22, 1, -1)}${br(W - 22, H - 22, -1, -1)}" fill="none" stroke="${p.ink2}" stroke-width="1" stroke-linecap="square"/>`
        + (has(ctx, 'headers') ? `<rect x="40" y="28" width="8" height="8" fill="${p.ink}"/><path d="M40 42H${W - 40}" fill="none" stroke="${p.faint}" stroke-width="0.8"/>` : '');
    },
    overlay() { return ''; }
  };
  A.defineFamily('nier', NIER);
})();
