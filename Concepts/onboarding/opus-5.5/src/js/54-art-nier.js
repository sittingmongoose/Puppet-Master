      + K.P(YOU.ivy, 's2', 0.9) + K.P(YOU.ground, 's', 1.3)
      + K.P('M-3 -1H7L7.6 14H11', 's', 2.1) + K.P('M-1 -1.5H9.5L10.4 14.5H14', 's', 2.3)
      + K.P('M-8 -26H6L8 -23L5 -1H-7L-10 -23Z', 'i')
