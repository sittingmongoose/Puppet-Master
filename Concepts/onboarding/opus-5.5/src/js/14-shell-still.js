/* The still page (PERF-3, the owner's choice B, 2026-11-11: "pause the icons after a while without input"). The page's
   endless decorative loops (breathing marks, spinning rings, loaders, working pulses) kept the compositor drawing a
   frame on every refresh with nobody at the page, about 119 a second at 120 Hz in every look: Glass Dark Home cost 450
   ms a second of GPU-thread time against 62 with them paused (pm7-perf lane E's P1). After STILL_AFTER with no pointer
   move, press, wheel, key or touch, data-pm-still on <html> holds every one of them where it is; the next input lets
   them go on from there in the same event, so nothing restarts or jumps.
   The rules that hold them are generated by the build from the finished page (tools/still_page.py: one rule per rule
   that gives an element an endless animation, with the same selector under html[data-pm-still~="<group>"], so the
   toggle restyles only the elements that loop, or the nearest small element above one whose own kind is everywhere).
   The toggle is spread over four frames, one group a frame, the first inside the waking event: in one frame it
   restyled about 750 elements of Basic Dark Home (68 ms of style on the VM host), a quarter of that keeps the waking
   move smooth, and every loop is running again within four frames of the input. A <style> that script fills at run
   time (the loaders' #pm-logo-anim) is not in the page's text: its loops get the same rules here, in group 1, written
   once the page goes still (PM_STILL_SHEETS, set by the build).
   Not held: anything finite (entrances, one-shots, transitions), what script draws (clocks, the terminal's cursor, a
   progress value), and nothing at all under Reduced Motion, while the onboarding window is open (the app beneath is
   held by the window already, 10-window.css, and the window's stage keeps its own loop) or during the Guided Tour (the
   app is what the tour shows, and its words describe marks that move).
   The idle warm queue (PM_WARM, 11-motion-start.js) keeps its own clock of the same inputs: being still is not one of
   its gates, and a held loop sends no animation event, so it neither waits for nor wakes this.
   Checks only: ?pm-still=<ms> sets the wait (read once; ?pm-still=off never goes still). window.PM_STILL tells a
   check the state: { still(), after, since(): ms since the last input, mirrored(): rules written for run-time sheets }.
   Kit check: pm7-tools/browser-check/checks/perf-still-page.check.mjs. */
window.PM_STILL_SHEETS=[];
(function () {
  'use strict';
  const STILL_AFTER = 20000;
  const ATTR = 'data-pm-still', GROUPS = 4; // GROUPS: tools/still_page.py GROUPS
  const html = document.documentElement;
  let after = STILL_AFTER;
  try {
    const m = /(?:^|[?&])pm-still=(off|\d+)(?:&|$)/.exec(location.search);
    if (m) after = m[1] === 'off' ? Infinity : Math.max(200, Number(m[1]));
  } catch (_) { /* no location */ }
  let lastInput = performance.now(), timer = 0, mirror = null, mirrored = 0, still = false, held = 0, step = 0;
  const seenRules = new Map(); // a run-time sheet -> how many of its rules were looked at

  const reduced = () => {
    try { return !!(window.O55 && window.O55.motion && window.O55.motion.reduced && window.O55.motion.reduced()); } catch (_) { return false; }
  };
  /* states in which the page never goes still (and which wake it if they begin while it is) */
  const heldBack = () => reduced() || html.hasAttribute('data-o55-open') || html.hasAttribute('data-o55-tour') ||
    !!(window.PM_BUSY && window.PM_BUSY.drag && window.PM_BUSY.drag());

  /* the selector under html[data-pm-still~="1"], as tools/still_page.py writes it: a first compound that is <html> takes
     the attribute itself; one with no tag, id or class (an attribute such as [data-theme], which is on <html>) is written
     both ways */
  const stilled = (sel) => {
    sel = sel.trim();
    const head = /^(html|:root)(?![\w-])/.exec(sel);
    const at = '[' + ATTR + '~="1"]';
    if (head) return [sel.slice(0, head[0].length) + at + sel.slice(head[0].length)];
    const out = ['html' + at + ' ' + sel];
    const first = /^[^\s>+~]+/.exec(sel);
    if (first && first[0].length < sel.length && /^[[:]/.test(first[0]) && !/[.#]/.test(first[0].replace(/\[[^\]]*\]|\((?:[^()]|\([^()]*\))*\)/g, ''))) out.push('html' + at + sel);
    return out;
  };
  const endless = (style) => /(?:^|[\s,])infinite(?:[\s,;]|$)/i.test(style.getPropertyValue('animation') + ' ' + style.getPropertyValue('animation-iteration-count'));
  /* the same rules for the loops of a sheet that script writes; only rules not looked at before are read */
  const mirrorRules = (rules, from, wrap, out) => {
    for (let i = from; i < rules.length; i++) {
      const r = rules[i];
      if (r.type === 1) {
        if (endless(r.style)) out.push(wrap(r.selectorText.split(/,(?![^(]*\))/).flatMap(stilled).join(', ') + ' { animation-play-state: paused !important; }'));
      } else if (r.cssRules && r.conditionText !== undefined) {
        const cond = (r.type === 4 ? '@media ' : r.type === 12 ? '@supports ' : '@container ') + r.conditionText;
        mirrorRules(r.cssRules, 0, (t) => wrap(cond + ' { ' + t + ' }'), out);
      }
    }
  };
  const mirrorSheets = () => {
    const out = [];
    for (const id of window.PM_STILL_SHEETS || []) {
      const el = document.getElementById(id), sheet = el && el.sheet;
      if (!sheet) continue;
      let rules; try { rules = sheet.cssRules; } catch (_) { continue; }
      const from = seenRules.get(sheet) || 0;
      if (rules.length === from) continue;
      mirrorRules(rules, from, (t) => t, out);
      seenRules.set(sheet, rules.length);
    }
    if (!out.length) return;
    if (!mirror || !mirror.isConnected) {
      mirror = document.createElement('style');
      mirror.id = 'pm-still-runtime';
      document.head.appendChild(mirror);
    }
    for (const t of out) { try { mirror.sheet.insertRule(t, mirror.sheet.cssRules.length); mirrored++; } catch (_) { /* a selector this browser does not take */ } }
  };

  /* one group a frame: going still adds tokens 1..GROUPS, waking takes them off again, the first in the input's own
     event; an input while going still turns the steps round */
  const write = () => { if (held) html.setAttribute(ATTR, Array.from({ length: held }, (_, i) => i + 1).join(' ')); else html.removeAttribute(ATTR); };
  const walk = () => {
    step = 0;
    if (still ? held >= GROUPS : held <= 0) return;
    held += still ? 1 : -1;
    write();
    step = requestAnimationFrame(walk);
  };
  const goStill = () => {
    if (still) return;
    mirrorSheets();
    still = true;
    if (!step) walk();
  };
  const wake = () => {
    if (!still && !held) return;
    still = false;
    if (step) { cancelAnimationFrame(step); step = 0; }
    walk();
  };

  /* one timer at a time: an input only notes its time; the timer, when it comes, waits again for whatever is left */
  const arm = (ms) => { clearTimeout(timer); timer = setTimeout(check, Math.max(16, ms)); };
  function check() {
    timer = 0;
    if (after === Infinity) return;
    const left = after - (performance.now() - lastInput);
    if (left > 0) { arm(left); return; }
    if (heldBack()) { arm(after); return; }
    goStill();
  }
  const input = (e) => {
    if (!e.isTrusted) return;
    lastInput = performance.now();
    wake();
    if (!timer) arm(after);
  };
  ['pointermove', 'pointerdown', 'wheel', 'keydown', 'touchstart'].forEach((t) => window.addEventListener(t, input, { capture: true, passive: true }));
  /* Reduced Motion, the onboarding window or the tour beginning while still: let the loops go (each has its own rules) */
  try {
    new MutationObserver(() => { if (still && heldBack()) { wake(); arm(after); } })
      .observe(html, { attributes: true, attributeFilter: ['data-motion', 'data-o55-open', 'data-o55-tour'] });
  } catch (_) { /* none */ }
  if (after !== Infinity) arm(after);
  try { const mq = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)'); if (mq && mq.addEventListener) mq.addEventListener('change', () => { if (mq.matches) wake(); }); } catch (_) { /* none */ }
  window.PM_STILL = {
    still: () => still,
    after,
    since: () => performance.now() - lastInput,
    mirrored: () => mirrored
  };
})();
