def _hex_to_rgb(h: str):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i : i + 2], 16) / 255.0 for i in (0, 2, 4))


def _chan(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def rel_lum(hex_color: str) -> float:
    r, g, b = _hex_to_rgb(hex_color)
    return 0.2126 * _chan(r) + 0.7152 * _chan(g) + 0.0722 * _chan(b)


def contrast_ratio(fg: str, bg) -> float:
    if isinstance(bg, tuple):
        bg = min(bg, key=rel_lum)
    L1, L2 = rel_lum(fg), rel_lum(bg)
    hi, lo = max(L1, L2), min(L1, L2)
    return (hi + 0.05) / (lo + 0.05)


def fnum(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return s if s else "0"


def tile_markup(pal, uid):
    defs, pre = [], []
    rx = fnum(pal["rx"])
    if isinstance(pal["tile"], tuple):
        top, bottom = pal["tile"]
        gid = f"gradTile-{uid}"
        defs.append(
            f'<linearGradient id="{gid}" x1="0" y1="0" x2="0" y2="{CANVAS}" gradientUnits="userSpaceOnUse">'
            f'<stop offset="0" stop-color="{top}"/><stop offset="1" stop-color="{bottom}"/></linearGradient>'
        )
        tile_fill = f"url(#{gid})"
    else:
        tile_fill = pal["tile"]

    if "retro_light_shadow" in pal["treatments"]:
        pre.append(
            f'<rect x="{RL_SHADOW}" y="{RL_SHADOW}" width="{RL_TILE}" height="{RL_TILE}" rx="{rx}" fill="#1A1A1A"/>'
        )
        pre.append(
            f'<rect id="tile-{uid}" width="{RL_TILE}" height="{RL_TILE}" rx="{rx}" fill="{tile_fill}"/>'
        )
    else:
        pre.append(
            f'<rect id="tile-{uid}" width="{CANVAS}" height="{CANVAS}" rx="{rx}" fill="{tile_fill}"/>'
        )

    for t in pal["treatments"]:
        if t == "retro_dark_border":
            pre.append(
                f'<rect x=".6" y=".6" width="42" height="42" fill="none" stroke="{pal["mark"]}" stroke-width="1.2"/>'
            )
        elif t.startswith("hairline:"):
            color = t.split(":", 1)[1]
            hrx = fnum(max(pal["rx"] - 0.4, 0))
            pre.append(
                f'<rect x=".5" y=".5" width="42.2" height="42.2" rx="{hrx}" fill="none" stroke="{color}" stroke-width="1"/>'
            )
        elif t == "glass_edge_gradient":
            gid = f"gradEdge-{uid}"
            defs.append(
                f'<linearGradient id="{gid}" x1="0" y1="0" x2="0" y2="{CANVAS}" gradientUnits="userSpaceOnUse">'
                f'<stop offset="0" stop-color="#FFFFFF" stop-opacity=".55"/>'
                f'<stop offset="1" stop-color="#FFFFFF" stop-opacity=".10"/></linearGradient>'
            )
            pre.append(
                f'<rect x=".5" y=".5" width="42.2" height="42.2" rx="9.6" fill="none" stroke="url(#{gid})" stroke-width="1"/>'
            )
        elif t == "glass_edge_solid":
            pre.append(
                '<rect x=".5" y=".5" width="42.2" height="42.2" rx="9.6" fill="none" stroke="rgba(255,255,255,.95)" stroke-width="1"/>'
            )
    return defs, pre, tile_fill


