def splice_index(data_blob):
    if not INDEX.exists():
        raise SystemExit("index.html missing — create the dashboard shell first")
    html = INDEX.read_text(encoding="utf-8")
    begin = html.find(MARK_BEGIN)
    end = html.find(MARK_END)
    if begin == -1 or end == -1 or end < begin:
        raise SystemExit("index.html is missing the CURSORICON:DATA markers")
    payload = json.dumps(data_blob, separators=(",", ":")).replace("</", "<\\/")
    block = (
        MARK_BEGIN
        + '\n<script id="cursoricon-data" type="application/json">'
        + payload
        + "</script>\n"
    )
    return html[:begin] + block + html[end:]


def write_file(path: Path, content: str | bytes):
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_text(content, encoding="utf-8")


def read_file(path: Path, as_bytes: bool):
    if not path.exists():
        return None
    return path.read_bytes() if as_bytes else path.read_text(encoding="utf-8")


def main():
    check = "--check" in sys.argv
    files, data_blob, warnings = build_all()
    for w in warnings:
        print("WARN:", w)

    drift = []
    for rel, content in sorted(files.items(), key=lambda x: x[0]):
        path = HERE / rel
        is_bin = isinstance(content, bytes)
        if check:
            on_disk = read_file(path, is_bin)
            if on_disk != content:
                drift.append(rel)
        else:
            write_file(path, content)

    spliced = splice_index(data_blob)
    if check:
        if spliced != INDEX.read_text(encoding="utf-8"):
            drift.append("index.html (data region)")
        if drift:
            print("DRIFT detected in:\n  " + "\n  ".join(drift))
            sys.exit(1)
        print(f"--check OK: {len(files)} files + index.html data region match")
    else:
        INDEX.write_text(spliced, encoding="utf-8")
        n_bin = sum(1 for v in files.values() if isinstance(v, bytes))
        print(f"wrote {len(files)} files ({n_bin} binary) + spliced index.html data region")


if __name__ == "__main__":
    main()
