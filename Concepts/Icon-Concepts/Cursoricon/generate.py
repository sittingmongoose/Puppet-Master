def require_resvg():
    if not RESVG.is_file():
        raise SystemExit(
            f"resvg not found at {RESVG} — install with Homebrew (brew install resvg) "
            "to bake app/tray PNG packs"
        )


def resvg_png(svg_text: str, size: int) -> bytes:
    require_resvg()
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        src = td / "in.svg"
        out = td / "out.png"
        src.write_text(svg_text, encoding="utf-8")
        subprocess.run(
            [str(RESVG), str(src), str(out), "-w", str(size), "-h", str(size)],
            check=True,
            capture_output=True,
        )
        return out.read_bytes()


def build_ico(png_by_size: dict[int, bytes]) -> bytes:
    sizes = [s for s in ICO_SIZES if s in png_by_size]
    count = len(sizes)
    header = bytearray(6 + count * 16)
    struct.pack_into("<HHH", header, 0, 0, 1, count)
    offset = 6 + count * 16
    blobs = []
    for i, sz in enumerate(sizes):
        data = png_by_size[sz]
        o = 6 + i * 16
        dim = 0 if sz >= 256 else sz
        header[o] = dim
        header[o + 1] = dim
        header[o + 2] = 0
        header[o + 3] = 0
        struct.pack_into("<HHII", header, o + 4, 1, 32, len(data), offset)
        offset += len(data)
        blobs.append(data)
    return bytes(header) + b"".join(blobs)


def build_icns(png_by_size: dict[int, bytes]) -> bytes:
    """Build ICNS via iconutil (macOS) for correctness."""
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        iconset = td / "pm.iconset"
        iconset.mkdir()
        mapping = {
            16: ["icon_16x16.png"],
            32: ["diana.k@example.org", "icon_32x32.png"],
            64: ["ivan.p@example.net"],
            128: ["icon_128x128.png"],
            256: ["wendy.h@example.net", "icon_256x256.png"],
            512: ["wendy.h@example.net", "icon_512x512.png"],
            1024: ["walt.e@example.net"],
        }
        for sz, names in mapping.items():
            if sz not in png_by_size:
                continue
            for name in names:
                (iconset / name).write_bytes(png_by_size[sz])
        out = td / "pm.icns"
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(out)], check=True)
        return out.read_bytes()


