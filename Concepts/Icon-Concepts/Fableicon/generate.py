def reduced_kill_block(anim_slug, s, u):
    """App-level reduced-motion kill-path (PM7 sets data-motion="reduced" / data-reduced-motion="1"
    on <html> independently of the OS preference, which leaves the media block active). Killing the
    animations alone is not enough for motions whose setup lives in static declarations (dims,
    display'd overlays) — those need explicit reverts so the frozen state is the pristine logo.
    Standalone files are unaffected (their :root is the svg itself, so these selectors never match;
    the media query is their only path)."""
    roots = (':root[data-motion="reduced"]', ':root[data-reduced-motion="1"]')
    rules = [("*", "animation: none !important;")]
    rules += {
        "spin": [(".a-puppets, .a-strings", "opacity: 1 !important;")],
        "shimmer": [(f"#shimmer-{u}", "display: none !important;")],
        "bardraw": [(f"#barLine-{u}", "display: none !important;"),
                    (".a-barMain, .a-puppets, .a-strings", "opacity: 1 !important;")],
        "stringpulse": [(f"#pulses-{u}", "display: none !important;"),
                        (".a-strings", "opacity: 1 !important;")],
    }.get(anim_slug, [])
    out = []
    for targets, decl in rules:
        sels = [f"{r} {s} {t.strip()}" for r in roots for t in targets.split(",")]
        out.append(", ".join(sels) + f" {{ {decl} }}")
    return "\n".join(out) + "\n"


def build_animated(static_svg, pal, anim_slug):
    """Animated file = static markup with a new root id + embedded stylesheet."""
    root = f"{pal['slug']}-ld"
    svg = static_svg.replace(f'id="pmx-{pal["slug"]}"', f'id="pmx-{root}"', 1)
    css = anim_css(anim_slug, pal, root)
    if "prefers-reduced-motion" not in css:
        raise SystemExit(f"reduced-motion gate: {anim_slug} css lacks prefers-reduced-motion")
    style = f"<style>\n{css}</style>\n"
    if svg.count("</svg>") != 1:
        raise SystemExit("unexpected svg structure")
    return svg.replace("</svg>", style + "</svg>")


