def build_all():
    parts = parse_source()
    source_sha = hashlib.sha256(SOURCE.read_bytes()).hexdigest()

    files = {}
    themes_meta = []
    mix_css = {a["slug"]: {} for a in ANIMS}

    for pal in PALETTES:
        static = build_static(parts, pal)
        anim_slug = PAIRING[pal["slug"]]
        animated = build_animated(static, pal, anim_slug)
        files[f"icons/static/pm-{pal['slug']}.svg"] = static
        files[f"icons/animated/pm-{pal['slug']}-loading.svg"] = animated
        for anim in ANIMS:
            mix_css[anim["slug"]][pal["slug"]] = anim_css(anim["slug"], pal, "mix")
        themes_meta.append(dict(
            slug=pal["slug"], label=pal["label"], family=pal["family"], mode=pal["mode"],
            pageBg=pal["page_bg"], surface=pal["surface"], text=pal["text"], muted=pal["muted"],
            mark=pal["mark"], string=pal["string"], tileDesc=pal["tile_desc"],
            rx=pal["rx"], motion=anim_slug, staticSvg=static, animatedSvg=animated,
        ))

    files["icons/template/pm-tray-Template.svg"] = build_template(parts, "#000000", "template")
    files["icons/template/pm-tray-white.svg"] = build_template(parts, "#FFFFFF", "template-w")

    layers = build_slint_layers(parts)
    for name, text in layers.items():
        files[f"slint/layers/{name}"] = text
    slint_comps = build_slint_components()
    for name, text in slint_comps.items():
        files[f"slint/{name}"] = text

    data_blob = dict(
        sourceSha=source_sha,
        themes=themes_meta,
        anims=[dict(a) for a in ANIMS],
        mixCss=mix_css,
        template=dict(black=files["icons/template/pm-tray-Template.svg"],
                      white=files["icons/template/pm-tray-white.svg"]),
        slintFiles={n.replace("pm_loading_", "").replace(".slint", ""): t for n, t in slint_comps.items()},
        slintFileNames=sorted(slint_comps.keys()),
        slintLayers=layers,
    )

    manifest = dict(
        generator="generate.py",
        sourceSha256=source_sha,
        themes=[{k: v for k, v in t.items() if k not in ("staticSvg", "animatedSvg")} for t in themes_meta],
        anims=[dict(a) for a in ANIMS],
        pairing=PAIRING,
        files=sorted(files.keys()) + ["manifest.json"],
    )
    files["manifest.json"] = json.dumps(manifest, indent=2, sort_keys=False) + "\n"

    return files, data_blob


def splice_index(data_blob):
    html = INDEX.read_text(encoding="utf-8")
    begin = html.find(MARK_BEGIN)
    end = html.find(MARK_END)
    if begin == -1 or end == -1 or end < begin:
        raise SystemExit("index.html is missing the FABLEICON:DATA markers")
    payload = json.dumps(data_blob, separators=(",", ":")).replace("</", "<\\/")
    block = (MARK_BEGIN + "\n<script id=\"fableicon-data\" type=\"application/json\">"
             + payload + "</script>\n")
    return html[:begin] + block + html[end:]


def main():
    check = "--check" in sys.argv
    files, data_blob = build_all()

    drift = []
    for rel, content in sorted(files.items()):
        path = HERE / rel
        if check:
            on_disk = path.read_text(encoding="utf-8") if path.exists() else None
            if on_disk != content:
                drift.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    spliced = splice_index(data_blob)
    if check:
        if spliced != INDEX.read_text(encoding="utf-8"):
            drift.append("index.html (data region)")
        if drift:
            print("DRIFT detected in:\n  " + "\n  ".join(drift))
            sys.exit(1)
        print(f"--check OK: {len(files)} files + index.html data region match")
    else:
        INDEX.write_text(spliced, encoding="utf-8")
        print(f"wrote {len(files)} files + spliced index.html data region")


if __name__ == "__main__":
    main()
