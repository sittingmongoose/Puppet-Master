def parse_source():
    text = SOURCE.read_text(encoding="utf-8")
    parts = {}
    for d in re.findall(r'd="([^"]+)"', text):
        for prefix, name in D_PREFIX_TO_PART.items():
            if d.startswith(prefix):
                parts[name] = d
    missing = set(D_PREFIX_TO_PART.values()) - set(parts)
    if missing:
        raise SystemExit(f"source svg does not contain expected paths: {sorted(missing)} "
                         "- was source/pm-logo-source.svg replaced with different artwork?")
    for rect in (STRING_L, STRING_R):
        if f'x="{rect["x"]}"' not in text:
            raise SystemExit(f"source svg missing string rect x={rect['x']}")
    return parts


