    lines = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {CANVAS} {CANVAS}" id="pmx-{name}">']
    lines.append('<defs>')
    lines.append(f'<mask id="pmask-{name}"><rect width="{CANVAS}" height="{CANVAS}" fill="#fff"/>'
                 f'<path d="{parts["glyphPKeyline"]}" fill="#000"/></mask>')
    lines.append('</defs>')
    lines.append(f'<g fill="{color}" mask="url(#pmask-{name})">')
    lines.append(f'  <path d="{parts["bracketL"]}"/>')
    lines.append(f'  <path d="{parts["bracketR"]}"/>')
    lines.append(f'  <path d="{parts["glyphM"]}"/>')
    lines.append(f'  <path d="{parts["glyphPFill"]}"/>')
    lines.append('</g>')
    lines.append(f'<g fill="{color}">')
    lines.append(f'  <path d="{parts["barTipL"]}"/>')
    lines.append(f'  <path d="{parts["barTipR"]}"/>')
    lines.append(f'  <path d="{parts["barMain"]}"/>')
    lines.append(f'  <rect x="{fnum(lx)}" y="15.6" width="1.6" height="8.59" rx=".8"/>')
    lines.append(f'  <rect x="{fnum(rxp)}" y="16.28" width="1.6" height="12.18" rx=".8"/>')
    lines.append('</g>')
    lines.append('</svg>')
    return "\n".join(lines) + "\n"


