def fnum(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return s if s else "0"


def tile_markup(pal, uid):
    """Tile + treatments. Returns (defs, pre_art, tile_ref_for_keyline)."""
    defs, pre = [], []
    rx = fnum(pal["rx"])
    if isinstance(pal["tile"], tuple):
        top, bottom = pal["tile"]
        gid = f"gradTile-{uid}"
        defs.append(
            f'<linearGradient id="{gid}" x1="0" y1="0" x2="0" y2="{CANVAS}" gradientUnits="userSpaceOnUse">'
            f'<stop offset="0" stop-color="{top}"/><stop offset="1" stop-color="{bottom}"/></linearGradient>')
        tile_fill = f"url(#{gid})"
    else:
        tile_fill = pal["tile"]

    if "retro_light_shadow" in pal["treatments"]:
        pre.append(f'<rect x="{RL_SHADOW}" y="{RL_SHADOW}" width="{RL_TILE}" height="{RL_TILE}" rx="{rx}" fill="#1A1A1A"/>')
        pre.append(f'<rect id="tile-{uid}" width="{RL_TILE}" height="{RL_TILE}" rx="{rx}" fill="{tile_fill}"/>')
    else:
        pre.append(f'<rect id="tile-{uid}" width="{CANVAS}" height="{CANVAS}" rx="{rx}" fill="{tile_fill}"/>')

    for t in pal["treatments"]:
        if t == "retro_dark_border":
            pre.append(f'<rect x=".6" y=".6" width="42" height="42" fill="none" stroke="{pal["mark"]}" stroke-width="1.2"/>')
        elif t.startswith("hairline:"):
            color = t.split(":", 1)[1]
            hrx = fnum(max(pal["rx"] - 0.4, 0))
            pre.append(f'<rect x=".5" y=".5" width="42.2" height="42.2" rx="{hrx}" fill="none" stroke="{color}" stroke-width="1"/>')
        elif t == "glass_edge_gradient":
            gid = f"gradEdge-{uid}"
            defs.append(
                f'<linearGradient id="{gid}" x1="0" y1="0" x2="0" y2="{CANVAS}" gradientUnits="userSpaceOnUse">'
                f'<stop offset="0" stop-color="#FFFFFF" stop-opacity=".55"/>'
                f'<stop offset="1" stop-color="#FFFFFF" stop-opacity=".10"/></linearGradient>')
            pre.append(f'<rect x=".5" y=".5" width="42.2" height="42.2" rx="9.6" fill="none" stroke="url(#{gid})" stroke-width="1"/>')
        elif t == "glass_edge_solid":
            pre.append('<rect x=".5" y=".5" width="42.2" height="42.2" rx="9.6" fill="none" stroke="rgba(255,255,255,.95)" stroke-width="1"/>')
    return defs, pre, tile_fill


def build_static(parts, pal):
    """Instrumented master for one palette. Every animation hook is present but
    inert (identity sandwiches, display="none" overlays), so any motion's CSS can
    be appended onto this exact markup."""
    uid = pal["slug"]
    rx = fnum(pal["rx"])
    mark, string = pal["mark"], pal["string"]
    defs, pre, tile_fill = tile_markup(pal, uid)

    defs.append(f'<clipPath id="tileClip-{uid}"><rect width="{CANVAS}" height="{CANVAS}" rx="{rx}"/></clipPath>')
    shim_alpha = ".35" if pal["mode"] == "dark" else ".55"
    defs.append(
        f'<linearGradient id="shimGrad-{uid}" x1="0" y1="0" x2="1" y2="0">'
        f'<stop offset="0" stop-color="#FFFFFF" stop-opacity="0"/>'
        f'<stop offset=".5" stop-color="#FFFFFF" stop-opacity="{shim_alpha}"/>'
        f'<stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/></linearGradient>')

