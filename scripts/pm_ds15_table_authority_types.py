"""DS15 guard table authority_types: Exact authority types before any boolean or integer interpretation.

Method B guard rows (scripts/pm_guard_isolation.py) for the DS15 checkers. Each predicate reads one
observation the checker derives from the complete boundary input (recomputed hashes and identities,
canonical-byte sizes, resolved records, presence, typed copies). Predicates never recompute, repair or
call helpers. The checkers refuse only through these rows, in this order
(pm-ds15-event-contracts.py:refusal), and check that every factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-ds15-table-generate.py; edit the row spec there.
"""
import pm_guard_isolation as g

FIELDS = ('boolean_violations', 'integer_type_violations', 'integer_range_violations')


def AT01_booleans(value, context):
    return 'authority_boolean_type' if value['boolean_violations'] != 0 else None


def AT02_integer_type(value, context):
    return 'authority_integer_type' if value['integer_type_violations'] != 0 else None


def AT03_integer_minimum(value, context):
    return 'authority_integer_range' if value['integer_range_violations'] != 0 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('AT01_booleans', g.Invariant('/boolean_violations', 'every named boolean authority key holds an exact boolean (exact_boolean)'), 'authority_boolean_type', AT01_booleans),
        g.Guard('AT02_integer_type', g.Invariant('/integer_type_violations', 'every named integer authority key holds an exact integer (current_integer integer_type; admitted_sequence may be null)'), 'authority_integer_type', AT02_integer_type),
        g.Guard('AT03_integer_minimum', g.Invariant('/integer_range_violations', 'every named integer authority key is at least 0 (current_integer minimum 0)'), 'authority_integer_range', AT03_integer_minimum),
    ])

    def check(value):
        table.require('AT01_booleans', value, context)
        table.require('AT02_integer_type', value, context)
        table.require('AT03_integer_minimum', value, context)
        return True
    return g.Case(table, check, context)
