"""DS15 guard table cp_guard: Checkpoint CAS, state, token selection and live snapshot.

Method B guard rows (scripts/pm_guard_isolation.py) for the DS15 checkers. Each predicate reads one
observation the checker derives from the complete boundary input (recomputed hashes and identities,
canonical-byte sizes, resolved records, presence, typed copies). Predicates never recompute, repair or
call helpers. The checkers refuse only through these rows, in this order
(pm-ds15-event-contracts.py:refusal), and check that every factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-ds15-table-generate.py; edit the row spec there.
"""
import pm_guard_isolation as g

FIELDS = ('expected_previous', 'stored_previous', 'state', 'token', 'selected_token', 'live_snapshot_id', 'current_live_snapshot_id')


def CG01_cas_previous(value, context):
    return 'checkpoint_refused' if value['expected_previous'] != value['stored_previous'] else None


def CG06_state_current(value, context):
    return 'checkpoint_refused' if value['state'] != 'current' else None


def CG07_token_selected(value, context):
    return 'checkpoint_refused' if value['token'] != value['selected_token'] else None


def CG08_live_snapshot(value, context):
    return 'checkpoint_refused' if value['live_snapshot_id'] != value['current_live_snapshot_id'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CG01_cas_previous', g.Invariant('/expected_previous', 'the expected previous checkpoint is the stored one (CAS)'), 'checkpoint_refused', CG01_cas_previous),
        g.Guard('CG06_state_current', g.Invariant('/state', 'the proposed checkpoint state is current'), 'checkpoint_refused', CG06_state_current),
        g.Guard('CG07_token_selected', g.Invariant('/token', 'the checkpoint token is the selected token'), 'checkpoint_refused', CG07_token_selected),
        g.Guard('CG08_live_snapshot', g.Invariant('/live_snapshot_id', 'the live snapshot is the current one'), 'checkpoint_refused', CG08_live_snapshot),
    ])

    def check(value):
        table.require('CG01_cas_previous', value, context)
        table.require('CG06_state_current', value, context)
        table.require('CG07_token_selected', value, context)
        table.require('CG08_live_snapshot', value, context)
        return True
    return g.Case(table, check, context)
