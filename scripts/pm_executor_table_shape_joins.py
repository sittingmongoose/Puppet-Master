import pm_guard_isolation as g
FIELDS = ('payload_project', 'current_project', 'payload_generation_canonical', 'current_generation_canonical')


def SJ02_project(value, context):
    return 'Project join' if value['payload_project'] != value['current_project'] else None


def SJ03_generation(value, context):
    return 'generation join' if value['payload_generation_canonical'] != value['current_generation_canonical'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SJ02_project', g.Invariant('/payload/project_id', 'equals the current Project'), 'Project join', SJ02_project),
        g.Guard('SJ03_generation', g.Invariant('/payload/replan_generation', 'equals the current generation by canonical bytes'), 'generation join', SJ03_generation),
    ])

    def check(value):
        table.require('SJ02_project', value, context)
        table.require('SJ03_generation', value, context)
        return True
    return g.Case(table, check, context)
