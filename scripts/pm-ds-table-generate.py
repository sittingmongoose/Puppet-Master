#!/usr/bin/env python3
"""Generate lane DS Method B guard-table modules from the row spec.

Each phase becomes scripts/pm_ds_table_<phase>.py. Each row predicate reads the
one boolean observation the checker derived for that row from its complete
input and refuses with the row's exact code when the observation does not hold;
predicates never recompute, repair or call helpers. Checkers refuse only
through these rows (scripts/pm_ds_tables.py), in spec order. Edit the spec in
scripts/pm_ds_guard_spec.py and regenerate; never edit a table module.

usage: python3 scripts/pm-ds-table-generate.py [--check]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from pm_ds_guard_spec import SPEC  # noqa: E402

PREFIX = 'pm_ds_table_'


def parse(text):
    rows = []
    for line in text.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        name, code, words = (part.strip() for part in line.split('|', 2))
        if not name.isidentifier() or not code or not words:
            raise ValueError(f'bad row spec: {line!r}')
        rows.append((name, code, words))
    names = [r[0] for r in rows]
    if len(names) != len(set(names)):
        raise ValueError(f'duplicate row names: {names}')
    return rows


def render(phase, title, owner, rows):
    fields = tuple(name for name, _, _ in rows)
    lines = [
        f'"""DS guard table {phase}: {title}.',
        '',
        f'Checker: {owner}.',
        'Method B guard rows (scripts/pm_guard_isolation.py). Each predicate reads the one boolean',
        "observation the checker derives for its row from the complete input. Predicates never",
        'recompute, repair or call helpers. The checker refuses only through these rows, in this order.',
        'Generated by scripts/pm-ds-table-generate.py from scripts/pm_ds_guard_spec.py; never edit by hand.',
        '"""',
        'import pm_guard_isolation as g',
        '',
        f'FIELDS = {fields!r}',
        '',
    ]
    for name, code, _ in rows:
        lines += [f'def {name}(value, context):',
                  f'    return {code!r} if value[{name!r}] is not True else None', '']
    lines += ['def case(value):', '    context = None', '    table = g.GuardTable([']
    for name, code, words in rows:
        lines.append(f'        g.Guard({name!r}, g.Invariant({"/" + name!r}, {words!r}), {code!r}, {name}),')
    lines += ['    ])', '', '    def check(value):']
    for name, _, _ in rows:
        lines.append(f'        table.require({name!r}, value, context)')
    lines += ['        return True', '    return g.Case(table, check, context)', '']
    return '\n'.join(lines)


def outputs():
    out = {}
    for phase, (title, owner, text) in SPEC.items():
        if not phase.isidentifier():
            raise ValueError(f'bad phase {phase!r}')
        out[ROOT / 'scripts' / f'{PREFIX}{phase}.py'] = render(phase, title, owner, parse(text))
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail when a table module is stale, missing or extra')
    args = parser.parse_args()
    expected = outputs()
    present = set((ROOT / 'scripts').glob(PREFIX + '*.py'))
    stale = sorted(str(p.relative_to(ROOT)) for p, text in expected.items() if not p.exists() or p.read_text() != text)
    extra = sorted(str(p.relative_to(ROOT)) for p in present - set(expected))
    rows = sum(len(parse(text)) for _, _, text in SPEC.values())
    if args.check:
        status = 'pass' if not stale and not extra else 'fail'
        print({'status': status, 'tables': len(expected), 'rows': rows, 'stale': stale, 'extra': extra})
        return 0 if status == 'pass' else 1
    for path in present - set(expected):
        path.unlink()
    for path, text in expected.items():
        path.write_text(text)
    print({'tables': len(expected), 'rows': rows})
    return 0


if __name__ == '__main__':
    sys.exit(main())
