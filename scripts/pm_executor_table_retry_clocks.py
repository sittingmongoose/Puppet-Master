"""DX guard table retry_clocks: Retry: received <= failed <= scheduled <= observed.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('failed', 'received', 'scheduled', 'observed')


def RK01_received_failed(value, context):
    return 'original failure/scheduling clocks' if value['failed'][0] * value['received'][1] < value['received'][0] * value['failed'][1] else None


def RK02_failed_scheduled(value, context):
    return 'original failure/scheduling clocks' if value['scheduled'][0] * value['failed'][1] < value['failed'][0] * value['scheduled'][1] else None


def RK03_scheduled_observed(value, context):
    return 'original failure/scheduling clocks' if value['observed'][0] * value['scheduled'][1] < value['scheduled'][0] * value['observed'][1] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RK01_received_failed', g.Invariant('/records/failure/body/response_received_at_utc', 'is not after the failure'), 'original failure/scheduling clocks', RK01_received_failed),
        g.Guard('RK02_failed_scheduled', g.Invariant('/records/failure/body/failed_at_utc', 'is not after scheduling'), 'original failure/scheduling clocks', RK02_failed_scheduled),
        g.Guard('RK03_scheduled_observed', g.Invariant('/records/retry/body/scheduled_at_utc', 'is not after the observation'), 'original failure/scheduling clocks', RK03_scheduled_observed),
    ])

    def check(value):
        table.require('RK01_received_failed', value, context)
        table.require('RK02_failed_scheduled', value, context)
        table.require('RK03_scheduled_observed', value, context)
        return True
    return g.Case(table, check, context)
