"""DCH guard table cs_value: checkpoint_storage_valid: value bytes and retained checkpoint provenance.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('value_encoding_error', 'provenance_present', 'value_sha256', 'provenance_sha256')


def CS01_value_encodable(value, context):
    return 'checkpoint_storage_refused' if value['value_encoding_error'] is not None else None


def CS02_provenance_commitment(value, context):
    return 'checkpoint_storage_refused' if value['value_encoding_error'] is None and value['provenance_present'] is True and value['value_sha256'] != value['provenance_sha256'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CS01_value_encodable', g.Invariant('/value', 'the checkpoint value encodes under its recipe'), 'checkpoint_storage_refused', CS01_value_encodable),
        g.Guard('CS02_provenance_commitment', g.Invariant('/source/checkpoint_access/source_value_sha256', 'equals SHA-256 of the checkpoint value bytes'), 'checkpoint_storage_refused', CS02_provenance_commitment),
    ])

    def check(value):
        table.require('CS01_value_encodable', value, context)
        table.require('CS02_provenance_commitment', value, context)
        return True
    return g.Case(table, check, context)
