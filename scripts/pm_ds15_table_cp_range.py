"""DS15 guard table cp_range: Checkpoint advance range.

Method B guard rows (scripts/pm_guard_isolation.py) for the DS15 checkers. Each predicate reads one
observation the checker derives from the complete boundary input (recomputed hashes and identities,
canonical-byte sizes, resolved records, presence, typed copies). Predicates never recompute, repair or
call helpers. The checkers refuse only through these rows, in this order
(pm-ds15-event-contracts.py:refusal), and check that every factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-ds15-table-generate.py; edit the row spec there.
"""
import pm_guard_isolation as g

FIELDS = ('scan_low', 'expected_low', 'index_rows', 'expected_rows', 'through_sequence_id', 'scan_high', 'selected_high')


def CN01_low(value, context):
    return 'checkpoint_refused' if value['scan_low'] != value['expected_low'] else None


def CN02_rows(value, context):
    return 'checkpoint_refused' if value['index_rows'] != value['expected_rows'] else None


def CN04_through(value, context):
    return 'checkpoint_refused' if value['through_sequence_id'] != value['scan_high'] else None


def CN05_selected_high(value, context):
    return 'checkpoint_refused' if value['scan_high'] != value['selected_high'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CN01_low', g.Invariant('/scan_low', 'the scan starts right after the prior checkpoint (or at the source start)'), 'checkpoint_refused', CN01_low),
        g.Guard('CN02_rows', g.Invariant('/index_rows', 'the index rows are exactly the source rows in low..high'), 'checkpoint_refused', CN02_rows),
        g.Guard('CN04_through', g.Invariant('/through_sequence_id', 'the checkpoint advances through the scan high'), 'checkpoint_refused', CN04_through),
        g.Guard('CN05_selected_high', g.Invariant('/scan_high', 'the scan high is the selected high'), 'checkpoint_refused', CN05_selected_high),
    ])

    def check(value):
        table.require('CN01_low', value, context)
        table.require('CN02_rows', value, context)
        table.require('CN04_through', value, context)
        table.require('CN05_selected_high', value, context)
        return True
    return g.Case(table, check, context)
