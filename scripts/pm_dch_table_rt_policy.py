"""DCH guard table rt_policy: retry_outcome: current append policy of both records (standing check 1).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('original_policy', 'retry_policy')


def RT02_original_replay_only(value, context):
    return 'replay_only_not_appendable' if value['original_policy'] == 'projector_replay_only' else None


def RT03_retry_replay_only(value, context):
    return 'replay_only_not_appendable' if value['retry_policy'] == 'projector_replay_only' else None


def RT04_original_policy(value, context):
    return 'invalid_append_policy' if value['original_policy'] not in ('dedupe_by_idempotency_key', 'projector_replay_only') else None


def RT05_retry_policy(value, context):
    return 'invalid_append_policy' if value['retry_policy'] not in ('dedupe_by_idempotency_key', 'projector_replay_only') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RT02_original_replay_only', g.Invariant('/original/replay_policy', 'the original is not projector_replay_only'), 'replay_only_not_appendable', RT02_original_replay_only),
        g.Guard('RT03_retry_replay_only', g.Invariant('/retry/replay_policy', 'the retry is not projector_replay_only'), 'replay_only_not_appendable', RT03_retry_replay_only),
        g.Guard('RT04_original_policy', g.Invariant('/original/replay_policy', 'the original is dedupe_by_idempotency_key'), 'invalid_append_policy', RT04_original_policy),
        g.Guard('RT05_retry_policy', g.Invariant('/retry/replay_policy', 'the retry is dedupe_by_idempotency_key'), 'invalid_append_policy', RT05_retry_policy),
    ])

    def check(value):
        table.require('RT02_original_replay_only', value, context)
        table.require('RT03_retry_replay_only', value, context)
        table.require('RT04_original_policy', value, context)
        table.require('RT05_retry_policy', value, context)
        return True
    return g.Case(table, check, context)
