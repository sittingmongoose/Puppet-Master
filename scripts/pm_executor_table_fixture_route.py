"""DX guard table fixture_route: Fixture dispatch: known type route, numeric boundary and helper.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('kind', 'name')


def FR01_type_route(value, context):
    return 'unknown type fixture route' if value['kind'] == 'type_route' and value['name'] not in ('capture', 'history', 'shape') else None


def FR02_numeric_boundary(value, context):
    return 'unknown numeric boundary' if value['kind'] == 'numeric_boundary' and value['name'] not in ('identity', 'digest', 'canonical', 'payload_bytes') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('FR01_type_route', g.Invariant('/type_cases/*/route', 'is capture, history or shape'), 'unknown type fixture route', FR01_type_route),
        g.Guard('FR02_numeric_boundary', g.Invariant('/numeric_cases/*/boundary', 'is identity, digest, canonical or payload_bytes'), 'unknown numeric boundary', FR02_numeric_boundary),
    ])

    def check(value):
        table.require('FR01_type_route', value, context)
        table.require('FR02_numeric_boundary', value, context)
        return True
    return g.Case(table, check, context)
