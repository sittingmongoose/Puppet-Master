"""DT guard table usage_values_b: usage_values_valid: pricing evidence and quota visibility.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('cost_status', 'pricing_missing', 'quota_status', 'quota_values_present', 'credits_status', 'credits_remaining_present', 'window_kind', 'window_times_present')


def UV5_pricing_present(value, context):
    return 'transition_refused' if value['cost_status'] in ('priced', 'estimated') and value['pricing_missing'] != [] else None


def UV6_hidden_quota(value, context):
    return 'transition_refused' if value['quota_status'] in ('unknown', 'disabled', 'not_exposed') and value['quota_values_present'] != [] else None


def UV7_hidden_credits(value, context):
    return 'transition_refused' if value['credits_status'] in ('unknown', 'disabled', 'not_exposed') and value['credits_remaining_present'] is True else None


def UV8_unknown_window(value, context):
    return 'transition_refused' if value['window_kind'] == 'unknown' and value['window_times_present'] is True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('UV5_pricing_present', g.Invariant('/payload/cost', 'a priced or estimated cost carries every pricing field'), 'transition_refused', UV5_pricing_present),
        g.Guard('UV6_hidden_quota', g.Invariant('/payload/quota', 'an unknown, disabled or unexposed quota has no values'), 'transition_refused', UV6_hidden_quota),
        g.Guard('UV7_hidden_credits', g.Invariant('/payload/quota/credits_remaining', 'unknown, disabled or unexposed credits have no remaining value'), 'transition_refused', UV7_hidden_credits),
        g.Guard('UV8_unknown_window', g.Invariant('/payload/quota', 'an unknown window has no reset or cooldown'), 'transition_refused', UV8_unknown_window),
    ])

    def check(value):
        table.require('UV5_pricing_present', value, context)
        table.require('UV6_hidden_quota', value, context)
        table.require('UV7_hidden_credits', value, context)
        table.require('UV8_unknown_window', value, context)
        return True
    return g.Case(table, check, context)
