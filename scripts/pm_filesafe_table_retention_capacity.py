import pm_guard_isolation as g

FIELDS = ('storage_full', 'max_cardinality', 'project_record_count')


def RC01_storage(value, context):
    return 'capacity_full' if value['storage_full'] is not False else None


def RC02_count(value, context):
    return 'capacity_full' if value['storage_full'] is False and value['max_cardinality'] is not None and value['project_record_count'] >= value['max_cardinality'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RC01_storage', g.Invariant('/storage_full', 'is false'), 'capacity_full', RC01_storage),
        g.Guard('RC02_count', g.Invariant('/project_record_count', 'is below a bounded max_cardinality while storage has room'), 'capacity_full', RC02_count),
    ])

