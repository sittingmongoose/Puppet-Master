"""DT guard table cp_token: checkpoint_result: read token, Storage identity and token bindings (standing check 7).

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('token_digest', 'current_token_digest', 'token_storage', 'source_storage', 'proposed_storage', 'selection_storage', 'checkpoint_key', 'expected_key', 'checkpoint_ref', 'expected_ref', 'dataset_name', 'expected_dataset')


def CP13_current_token(value, context):
    return 'source_changed' if value['token_digest'] != value['current_token_digest'] else None


def CP14_token_storage(value, context):
    return 'source_changed' if value['token_storage'] != value['source_storage'] else None


def CP15_checkpoint_storage(value, context):
    return 'source_changed' if value['proposed_storage'] != value['token_storage'] else None


def CP16_selection_storage(value, context):
    return 'source_changed' if value['selection_storage'] != value['token_storage'] else None


def CP17_checkpoint_key(value, context):
    return 'source_changed' if value['checkpoint_key'] != value['expected_key'] else None


def CP18_checkpoint_ref(value, context):
    return 'source_changed' if value['checkpoint_ref'] != value['expected_ref'] else None


def CP19_dataset_name(value, context):
    return 'source_changed' if value['dataset_name'] != value['expected_dataset'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP13_current_token', g.Invariant('/proposed/index_read_token', 'canonical bytes equal the current token'), 'source_changed', CP13_current_token),
        g.Guard('CP14_token_storage', g.Invariant('/proposed/index_read_token/storage_instance_id', 'equals the verified source Storage instance'), 'source_changed', CP14_token_storage),
        g.Guard('CP15_checkpoint_storage', g.Invariant('/proposed/storage_instance_id', 'equals the token Storage instance'), 'source_changed', CP15_checkpoint_storage),
        g.Guard('CP16_selection_storage', g.Invariant('/proposed/index_read_token/source_selection/storage_instance_id', 'equals the token Storage instance'), 'source_changed', CP16_selection_storage),
        g.Guard('CP17_checkpoint_key', g.Invariant('/proposed/index_read_token/checkpoint_key', 'is event_record_index_checkpoint.v1 of the token Storage instance'), 'source_changed', CP17_checkpoint_key),
        g.Guard('CP18_checkpoint_ref', g.Invariant('/proposed/index_read_token/checkpoint_ref', 'is the key plus the generation pointer'), 'source_changed', CP18_checkpoint_ref),
        g.Guard('CP19_dataset_name', g.Invariant('/proposed/index_read_token/index_dataset_name', 'is event_record_index.v2 at the generation'), 'source_changed', CP19_dataset_name),
    ])

    def check(value):
        table.require('CP13_current_token', value, context)
        table.require('CP14_token_storage', value, context)
        table.require('CP15_checkpoint_storage', value, context)
        table.require('CP16_selection_storage', value, context)
        table.require('CP17_checkpoint_key', value, context)
        table.require('CP18_checkpoint_ref', value, context)
        table.require('CP19_dataset_name', value, context)
        return True
    return g.Case(table, check, context)
