"""DCH guard table st_index_dataset: stop index_read_valid: index dataset names.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('token_dataset', 'expected_dataset', 'node_dataset', 'source_dataset')


def IX18_token_dataset(value, context):
    return 'stop_index_refused' if value['token_dataset'] != value['expected_dataset'] else None


def IX19_node_dataset(value, context):
    return 'stop_index_refused' if value['node_dataset'] != value['expected_dataset'] else None


def IX20_source_dataset(value, context):
    return 'stop_index_refused' if value['source_dataset'] != value['expected_dataset'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IX18_token_dataset', g.Invariant('/token/index_dataset_name', 'is event_record_index.v2@<generation>'), 'stop_index_refused', IX18_token_dataset),
        g.Guard('IX19_node_dataset', g.Invariant('/source/checkpoint/generations/<g>/index_dataset_name', 'is event_record_index.v2@<generation>'), 'stop_index_refused', IX19_node_dataset),
        g.Guard('IX20_source_dataset', g.Invariant('/source/dataset_name', 'is event_record_index.v2@<generation>'), 'stop_index_refused', IX20_source_dataset),
    ])

    def check(value):
        table.require('IX18_token_dataset', value, context)
        table.require('IX19_node_dataset', value, context)
        table.require('IX20_source_dataset', value, context)
        return True
    return g.Case(table, check, context)
