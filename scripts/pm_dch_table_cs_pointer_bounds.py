"""DCH guard table cs_pointer_bounds: checkpoint_storage_valid: pointer encodability and size (entailed by CS06: an exact pointer is at most 131 bytes; defence in depth).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('pointer_encoding_error', 'pointer_size')


def CS04_pointer_encodable(value, context):
    return 'checkpoint_storage_refused' if value['pointer_encoding_error'] is not None else None


def CS05_pointer_size(value, context):
    return 'checkpoint_storage_refused' if value['pointer_encoding_error'] is None and value['pointer_size'] > 16384 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CS04_pointer_encodable', g.Invariant('/source/checkpoint_storage/pointer', 'the inline pointer encodes'), 'checkpoint_storage_refused', CS04_pointer_encodable),
        g.Guard('CS05_pointer_size', g.Invariant('/source/checkpoint_storage/pointer', 'the inline pointer encodes to at most 16384 bytes'), 'checkpoint_storage_refused', CS05_pointer_size),
    ])

    def check(value):
        table.require('CS04_pointer_encodable', value, context)
        table.require('CS05_pointer_size', value, context)
        return True
    return g.Case(table, check, context)
