import pm_guard_isolation as g

FIELDS = ('row_schema_version', 'want_schema_version', 'row_value_schema_id', 'want_value_schema_id', 'backup_required', 'authority_class')


def IB09_schema_version(value, context):
    return 'physical_binding' if value['row_schema_version'] != value['want_schema_version'] else None


def IB10_value_schema_id(value, context):
    return 'physical_binding' if value['row_value_schema_id'] != value['want_value_schema_id'] else None


def IB11_not_backed_up(value, context):
    return 'physical_recovery' if value['backup_required'] else None


def IB12_derived(value, context):
    return 'physical_recovery' if value['authority_class'] != 'derived_rebuildable' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IB09_schema_version', g.Invariant('/families/<projection>/schema_version', 'equals the binding record'), 'physical_binding', IB09_schema_version),
        g.Guard('IB10_value_schema_id', g.Invariant('/families/<projection>/value_schema_id', 'equals the binding record'), 'physical_binding', IB10_value_schema_id),
        g.Guard('IB11_not_backed_up', g.Invariant('/families/<projection>/recovery_disposition/backup_required', 'is not set'), 'physical_recovery', IB11_not_backed_up),
        g.Guard('IB12_derived', g.Invariant('/families/<projection>/recovery_disposition/authority_class', 'is derived_rebuildable'), 'physical_recovery', IB12_derived),
    ])

    def check(value):
        table.require('IB09_schema_version', value, context)
        table.require('IB10_value_schema_id', value, context)
        table.require('IB11_not_backed_up', value, context)
        table.require('IB12_derived', value, context)
        return True
    return g.Case(table, check, context)
