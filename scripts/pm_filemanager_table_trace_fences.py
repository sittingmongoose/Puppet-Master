"""DFM guard table trace_fences: Ordering, first receipt, replay and source fences (validate_case).

Method B guard rows for scripts/pm-filemanager-event-contracts.py, generated by
scripts/pm-filemanager-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(recomputed keys, identities and digests, exact types, resolved rows); a
predicate never recomputes, repairs or calls helpers. The checker refuses
only through these rows, in this order (table_refusals in the checker).
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('stages_exact', 'first_receipt_true', 'replay_zero', 'retry_zero', 'source_true', 'access_true', 'restore_true')


def TF01_ordering(value, context):
    return 'invalid ordering' if value['stages_exact'] is not True else None


def TF02_first_receipt(value, context):
    return 'unresolved first receipt' if value['first_receipt_true'] is not True else None


def TF03_replay_effects(value, context):
    return 'replay/duplicate effect' if value['replay_zero'] is not True else None


def TF04_retry_appends(value, context):
    return 'replay/duplicate effect' if value['retry_zero'] is not True else None


def TF05_source_verified(value, context):
    return 'source/access/restore fence' if value['source_true'] is not True else None


def TF06_access_allowed(value, context):
    return 'source/access/restore fence' if value['access_true'] is not True else None


def TF07_restore_coherent(value, context):
    return 'source/access/restore fence' if value['restore_true'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TF01_ordering', g.Invariant('/stages', 'is exactly effect, receipt, append, first ack, terminal'), 'invalid ordering', TF01_ordering),
        g.Guard('TF02_first_receipt', g.Invariant('/original_first_receipt_resolved', 'is exactly true'), 'unresolved first receipt', TF02_first_receipt),
        g.Guard('TF03_replay_effects', g.Invariant('/replay_effect_count', 'is exactly the integer 0'), 'replay/duplicate effect', TF03_replay_effects),
        g.Guard('TF04_retry_appends', g.Invariant('/retry_append_count', 'is exactly the integer 0'), 'replay/duplicate effect', TF04_retry_appends),
        g.Guard('TF05_source_verified', g.Invariant('/current_source_verified', 'is exactly true'), 'source/access/restore fence', TF05_source_verified),
        g.Guard('TF06_access_allowed', g.Invariant('/access_allowed', 'is exactly true'), 'source/access/restore fence', TF06_access_allowed),
        g.Guard('TF07_restore_coherent', g.Invariant('/restore_coherent', 'is exactly true'), 'source/access/restore fence', TF07_restore_coherent),
    ])

    def check(value):
        table.require('TF01_ordering', value, context)
        table.require('TF02_first_receipt', value, context)
        table.require('TF03_replay_effects', value, context)
        table.require('TF04_retry_appends', value, context)
        table.require('TF05_source_verified', value, context)
        table.require('TF06_access_allowed', value, context)
        table.require('TF07_restore_coherent', value, context)
        return True
    return g.Case(table, check, context)
