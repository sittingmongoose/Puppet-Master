import pm_guard_isolation as g

FIELDS = ('scope_partition', 'expected_partition', 'project_id_present', 'payload_project_id', 'scope_project_id', 'run_id_present', 'payload_run_id', 'ctx_run_id', 'scope_kind', 'node_present', 'node_id', 'attempt_id')


def PS01_partition(value, context):
    return 'payload_scope_partition' if value['scope_partition'] != value['expected_partition'] else None


def PS02_project_copy(value, context):
    return 'payload_project_copy' if value['project_id_present'] is True and value['payload_project_id'] != value['scope_project_id'] else None


def PS03_run_copy(value, context):
    return 'payload_run_copy' if value['run_id_present'] is True and value['payload_run_id'] != value['ctx_run_id'] else None


def PS04_node_id(value, context):
    return 'payload_orchestrator_ids' if value['scope_kind'] == 'project' and value['node_present'] is True and not value['node_id'] else None


def PS05_attempt_id(value, context):
    return 'payload_orchestrator_ids' if value['scope_kind'] == 'project' and value['node_present'] is True and not value['attempt_id'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('PS01_partition', g.Invariant('/scope_partition', 'equals the partition derived from the scope'), 'payload_scope_partition', PS01_partition),
        g.Guard('PS02_project_copy', g.Invariant('/payload_project_id', 'a payload project_id equals the scope project_id'), 'payload_project_copy', PS02_project_copy),
        g.Guard('PS03_run_copy', g.Invariant('/payload_run_id', 'a payload run_id equals the execution-context run_id'), 'payload_run_copy', PS03_run_copy),
        g.Guard('PS04_node_id', g.Invariant('/node_id', 'a Project payload that names node_id gives a nonempty node_id'), 'payload_orchestrator_ids', PS04_node_id),
        g.Guard('PS05_attempt_id', g.Invariant('/attempt_id', 'a Project payload that names node_id gives a nonempty attempt_id'), 'payload_orchestrator_ids', PS05_attempt_id),
    ])

    def check(value):
        table.require('PS01_partition', value, context)
        table.require('PS02_project_copy', value, context)
        table.require('PS03_run_copy', value, context)
        table.require('PS04_node_id', value, context)
        table.require('PS05_attempt_id', value, context)
        return True
    return g.Case(table, check, context)
