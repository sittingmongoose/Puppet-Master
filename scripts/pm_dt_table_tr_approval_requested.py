import pm_guard_isolation as g

FIELDS = ('episode_state', 'actions_truthy', 'payload_actions', 'before_actions')


def AR1_blocked(value, context):
    return 'transition_refused' if value['episode_state'] != 'blocked' else None


def AR2_actions_present(value, context):
    return 'transition_refused' if value['actions_truthy'] is False else None


def AR3_actions_copy(value, context):
    return 'transition_refused' if value['payload_actions'] != value['before_actions'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('AR1_blocked', g.Invariant('/before/episode_state', 'is blocked'), 'transition_refused', AR1_blocked),
        g.Guard('AR2_actions_present', g.Invariant('/payload/allowed_action_ids', 'is nonempty'), 'transition_refused', AR2_actions_present),
        g.Guard('AR3_actions_copy', g.Invariant('/payload/allowed_action_ids', 'equals the blocked episode actions'), 'transition_refused', AR3_actions_copy),
    ])

    def check(value):
        table.require('AR1_blocked', value, context)
        table.require('AR2_actions_present', value, context)
        table.require('AR3_actions_copy', value, context)
        return True
    return g.Case(table, check, context)
