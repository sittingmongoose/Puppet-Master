"""DF guard table mat_grant_window: Materialization: granted override window.

Method B guard rows for the DF FileSafe checkers. Each predicate reads one
observation record that the lane checker derives from the complete boundary
input (recomputed digests, decoded values, resolved routes, presence);
predicates never recompute, repair or call helpers. The checkers refuse only
through these rows (pm_filesafe_tables.refusals), in this order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-filesafe-table-generate.py; do not edit by hand.
"""
import pm_guard_isolation as g

FIELDS = ('issued_us', 'expires_us', 'maximum_us', 'ts_us')


def MG01_issued_before_expiry(value, context):
    return 'grant_expiry' if value['issued_us'] >= value['expires_us'] else None


def MG02_requested_maximum(value, context):
    return 'grant_expiry' if value['expires_us'] > value['maximum_us'] else None


def MG03_live_at_issue(value, context):
    return 'grant_expired_at_issue' if value['ts_us'] > value['expires_us'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('MG01_issued_before_expiry', g.Invariant('/payload/expires_at', 'issued_at is before expires_at'), 'grant_expiry', MG01_issued_before_expiry),
        g.Guard('MG02_requested_maximum', g.Invariant('/payload/expires_at', 'expires_at is at most the requested maximum'), 'grant_expiry', MG02_requested_maximum),
        g.Guard('MG03_live_at_issue', g.Invariant('/payload/ts', 'ts is at or before expires_at'), 'grant_expired_at_issue', MG03_live_at_issue),
    ])

    def check(value):
        table.require('MG01_issued_before_expiry', value, context)
        table.require('MG02_requested_maximum', value, context)
        table.require('MG03_live_at_issue', value, context)
        return True
    return g.Case(table, check, context)
