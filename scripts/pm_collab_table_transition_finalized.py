"""DC guard table transition_finalized: artifact_finalized: findings, artifact, targets, partial coverage and stale targets.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('finalized_ref', 'open_findings', 'artifact_known', 'target_hashes', 'run_target_hashes', 'completed_reviewer_count', 'requested_reviewer_count', 'partial_coverage_accepted', 'run_waiver_count', 'stale_target_accepted', 'run_stale_accepted')


def TR61_not_finalized(value, context):
    return 'conflict:already_finalized' if value['finalized_ref'] is not None else None


def TR62_findings_dispositioned(value, context):
    return 'conflict:findings_not_dispositioned' if value['open_findings'] != 0 else None


def TR63_artifact_added(value, context):
    return 'conflict:artifact_not_added' if value['artifact_known'] is not True else None


def TR64_targets(value, context):
    return 'conflict:target_hash_mismatch' if value['target_hashes'] != value['run_target_hashes'] else None


def TR65_partial_accepted(value, context):
    return 'conflict:partial_not_accepted' if value['completed_reviewer_count'] < value['requested_reviewer_count'] and not value['partial_coverage_accepted'] else None


def TR66_partial_waivers(value, context):
    return 'conflict:partial_not_accepted' if value['completed_reviewer_count'] < value['requested_reviewer_count'] and value['partial_coverage_accepted'] and value['run_waiver_count'] == 0 else None


def TR67_stale_accepted(value, context):
    return 'conflict:stale_not_accepted' if value['stale_target_accepted'] and not value['run_stale_accepted'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR61_not_finalized', g.Invariant('/collaboration_run_id', 'has no finalized artifact'), 'conflict:already_finalized', TR61_not_finalized),
        g.Guard('TR62_findings_dispositioned', g.Invariant('/collaboration_run_id', 'every finding is dispositioned'), 'conflict:findings_not_dispositioned', TR62_findings_dispositioned),
        g.Guard('TR63_artifact_added', g.Invariant('/artifact_version_ref', 'is an added artifact'), 'conflict:artifact_not_added', TR63_artifact_added),
        g.Guard('TR64_targets', g.Invariant('/target_hashes', 'equal the run target hashes'), 'conflict:target_hash_mismatch', TR64_targets),
        g.Guard('TR65_partial_accepted', g.Invariant('/partial_coverage_accepted', 'partial coverage is accepted'), 'conflict:partial_not_accepted', TR65_partial_accepted),
        g.Guard('TR66_partial_waivers', g.Invariant('/partial_coverage_accepted', 'accepted partial coverage has a recorded waiver'), 'conflict:partial_not_accepted', TR66_partial_waivers),
        g.Guard('TR67_stale_accepted', g.Invariant('/stale_target_accepted', 'a stale target is accepted by the run'), 'conflict:stale_not_accepted', TR67_stale_accepted),
    ])

    def check(value):
        table.require('TR61_not_finalized', value, context)
        table.require('TR62_findings_dispositioned', value, context)
        table.require('TR63_artifact_added', value, context)
        table.require('TR64_targets', value, context)
        table.require('TR65_partial_accepted', value, context)
        table.require('TR66_partial_waivers', value, context)
        table.require('TR67_stale_accepted', value, context)
        return True
    return g.Case(table, check, context)
