"""DC guard table transition_lifecycle: Lifecycle families: state machine, sequence and open attempts.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('short', 'completion_trigger', 'run_status', 'lifecycle_seq', 'expected_lifecycle_seq', 'open_attempts')


def TR17_lifecycle_state(value, context):
    allowed = ('paused',) if value['short'] == 'resumed' else ('active',) if value['short'] == 'paused' or (value['short'] == 'completed' and value['completion_trigger'] != 'chat_room_end') else ('active', 'paused')
    return 'conflict:run_state_invalid' if value['run_status'] not in allowed else None


def TR18_lifecycle_seq(value, context):
    return 'conflict:stale_lifecycle_seq' if value['lifecycle_seq'] != value['expected_lifecycle_seq'] else None


def TR19_open_attempts(value, context):
    return 'conflict:open_attempts' if value['open_attempts'] is True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR17_lifecycle_state', g.Invariant('/state_before', 'the run state allows the lifecycle family'), 'conflict:run_state_invalid', TR17_lifecycle_state),
        g.Guard('TR18_lifecycle_seq', g.Invariant('/lifecycle_seq', 'is the run sequence plus one'), 'conflict:stale_lifecycle_seq', TR18_lifecycle_seq),
        g.Guard('TR19_open_attempts', g.Invariant('/collaboration_run_id', 'cancelled/failed/completed: no attempt is open'), 'conflict:open_attempts', TR19_open_attempts),
    ])

    def check(value):
        table.require('TR17_lifecycle_state', value, context)
        table.require('TR18_lifecycle_seq', value, context)
        table.require('TR19_open_attempts', value, context)
        return True
    return g.Case(table, check, context)
