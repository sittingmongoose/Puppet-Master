"""DX guard table scheduler_selected: scheduler.pass: each selected node carries its ready score tuple and lane.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('score_canonical', 'ready_canonical', 'lane', 'ready_lane')


def SH07_score_tuple(value, context):
    return 'selected score' if value['score_canonical'] != value['ready_canonical'] else None


def SH08_lane(value, context):
    return 'selected score' if value['lane'] != value['ready_lane'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SH07_score_tuple', g.Invariant('/payload/selected_nodes/*/score_tuple', 'equals the ready score tuple by canonical bytes'), 'selected score', SH07_score_tuple),
        g.Guard('SH08_lane', g.Invariant('/payload/selected_nodes/*/lane', 'equals the ready scheduler lane'), 'selected score', SH08_lane),
    ])

    def check(value):
        table.require('SH07_score_tuple', value, context)
        table.require('SH08_lane', value, context)
        return True
    return g.Case(table, check, context)
