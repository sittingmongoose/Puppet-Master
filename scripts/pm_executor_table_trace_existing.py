"""DX guard table trace_existing: Trace model: a known identity resolves its first receipt.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('custody_available', 'prior_digest', 'digest')


def TA01_custody_available(value, context):
    return 'dedupe_unavailable' if value['custody_available'] is not True else None


def TA02_same_body(value, context):
    return 'idempotency_conflict' if value['custody_available'] is True and value['prior_digest'] != value['digest'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TA01_custody_available', g.Invariant('/rows/{identity}', 'the stored first-receipt custody is available'), 'dedupe_unavailable', TA01_custody_available),
        g.Guard('TA02_same_body', g.Invariant('/rows/{identity}/digest', 'a retry carries the original semantic body'), 'idempotency_conflict', TA02_same_body),
    ])

    def check(value):
        table.require('TA01_custody_available', value, context)
        table.require('TA02_same_body', value, context)
        return True
    return g.Case(table, check, context)
