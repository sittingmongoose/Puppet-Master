import pm_guard_isolation as g

FIELDS = ('size',)


def CP01_encodable(value, context):
    return 'checkpoint_size' if value['size'] is None else None


def CP02_size_limit(value, context):
    return 'checkpoint_size' if value['size'] is not None and value['size'] > 16384 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP01_encodable', g.Invariant('/size', 'the checkpoint has an exact SP-1100 EVENT_VALUE encoding'), 'checkpoint_size', CP01_encodable),
        g.Guard('CP02_size_limit', g.Invariant('/size', 'the encoded checkpoint is at most 16384 bytes'), 'checkpoint_size', CP02_size_limit),
    ])

    def check(value):
        table.require('CP01_encodable', value, context)
        table.require('CP02_size_limit', value, context)
        return True
    return g.Case(table, check, context)
