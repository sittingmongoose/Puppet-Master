"""DT guard table cp_cas: checkpoint_result: lease and compare-and-swap previous value.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('lease_type', 'expected_previous_digest', 'previous_digest', 'lease_current')


def CP10_lease_type(value, context):
    return 'cas_lost' if value['lease_type'] != 'bool' else None


def CP11_expected_previous(value, context):
    return 'cas_lost' if value['expected_previous_digest'] != value['previous_digest'] else None


def CP12_lease_current(value, context):
    return 'cas_lost' if value['lease_current'] is False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP10_lease_type', g.Invariant('/context/lease_current', 'is exactly a bool'), 'cas_lost', CP10_lease_type),
        g.Guard('CP11_expected_previous', g.Invariant('/context/expected_previous', 'canonical bytes equal the prior checkpoint'), 'cas_lost', CP11_expected_previous),
        g.Guard('CP12_lease_current', g.Invariant('/context/lease_current', 'is True'), 'cas_lost', CP12_lease_current),
    ])

    def check(value):
        table.require('CP10_lease_type', value, context)
        table.require('CP11_expected_previous', value, context)
        table.require('CP12_lease_current', value, context)
        return True
    return g.Case(table, check, context)
