"""DX guard table identity_replay_fixed: Identity recipe self-checks no input can refuse (pure-function properties; reported unprovable).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('metadata_changed_identity', 'identity', 'other_storage_event_id', 'recomputed_identity', 'metadata_changed_digest', 'digest')


def IR01_metadata_neutral(value, context):
    return 'identity replay recipe' if value['metadata_changed_identity'] != value['identity'] else None


def IR03_storage_bound(value, context):
    return 'identity replay recipe' if value['other_storage_event_id'] == value['identity'][1] else None


def IR04_deterministic(value, context):
    return 'identity replay recipe' if value['recomputed_identity'] != value['identity'] else None


def IR05_body_digest(value, context):
    return 'identity replay recipe' if value['metadata_changed_digest'] == value['digest'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IR01_metadata_neutral', g.Invariant('/ts', 'a changed observation time keeps the identity'), 'identity replay recipe', IR01_metadata_neutral),
        g.Guard('IR03_storage_bound', g.Invariant('/storage_instance_id', 'another Storage instance gives another event id'), 'identity replay recipe', IR03_storage_bound),
        g.Guard('IR04_deterministic', g.Invariant('/identity', 'recomputing the identity resolves the stored first receipt'), 'identity replay recipe', IR04_deterministic),
        g.Guard('IR05_body_digest', g.Invariant('/ts', 'a changed observation time changes the body digest'), 'identity replay recipe', IR05_body_digest),
    ])

    def check(value):
        table.require('IR01_metadata_neutral', value, context)
        table.require('IR03_storage_bound', value, context)
        table.require('IR04_deterministic', value, context)
        table.require('IR05_body_digest', value, context)
        return True
    return g.Case(table, check, context)
