"""DCH guard table st_request_writer: stop request_valid: current writer admission and replay policy (standing check 1).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('historical', 'writer_admitted', 'active_reply', 'dedupe_available', 'replay_policy')


def RQ11_writer_admitted(value, context):
    return 'stop_request_refused' if value['historical'] is False and value['writer_admitted'] is not True else None


def RQ12_active_reply(value, context):
    return 'stop_request_refused' if value['historical'] is False and value['active_reply'] is not True else None


def RQ13_dedupe_available(value, context):
    return 'stop_request_refused' if value['historical'] is False and value['dedupe_available'] is not True else None


def RQ14_replay_policy(value, context):
    return 'stop_request_refused' if value['replay_policy'] not in ('dedupe_by_idempotency_key', 'projector_replay_only') else None


def RQ15_current_not_replay_only(value, context):
    return 'stop_request_refused' if value['historical'] is False and value['replay_policy'] == 'projector_replay_only' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RQ11_writer_admitted', g.Invariant('/context/writer_admitted', 'a current request is exactly writer-admitted'), 'stop_request_refused', RQ11_writer_admitted),
        g.Guard('RQ12_active_reply', g.Invariant('/context/active_reply', 'a current request targets an active reply'), 'stop_request_refused', RQ12_active_reply),
        g.Guard('RQ13_dedupe_available', g.Invariant('/context/dedupe_available', 'a current request has dedupe available'), 'stop_request_refused', RQ13_dedupe_available),
        g.Guard('RQ14_replay_policy', g.Invariant('/record/replay_policy', 'is dedupe_by_idempotency_key or the compatibility projector_replay_only'), 'stop_request_refused', RQ14_replay_policy),
        g.Guard('RQ15_current_not_replay_only', g.Invariant('/record/replay_policy', 'a current writer never accepts projector_replay_only'), 'stop_request_refused', RQ15_current_not_replay_only),
    ])

    def check(value):
        table.require('RQ11_writer_admitted', value, context)
        table.require('RQ12_active_reply', value, context)
        table.require('RQ13_dedupe_available', value, context)
        table.require('RQ14_replay_policy', value, context)
        table.require('RQ15_current_not_replay_only', value, context)
        return True
    return g.Case(table, check, context)
