"""DC guard table source_outputs: Source custody: producer attempt, vote constraints, Plan result and artifact custody.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('body_producer_attempt', 'context_producer_attempt', 'record_conflicts', 'body_conflicts', 'plan_result_sha256', 'context_plan_result_sha256', 'artifact_ref', 'record_artifact_refs')


def SF48_producer_attempt(value, context):
    return 'source_producer_attempt' if value['body_producer_attempt'] != value['context_producer_attempt'] else None


def SF49_vote_constraints(value, context):
    return 'source_vote_constraints' if value['record_conflicts'] != value['body_conflicts'] else None


def SF50_plan_result(value, context):
    return 'source_plan_result' if value['plan_result_sha256'] is None or value['plan_result_sha256'] != value['context_plan_result_sha256'] else None


def SF51_artifact_custody(value, context):
    return 'source_artifact_custody' if value['artifact_ref'] is not None and value['artifact_ref'] not in value['record_artifact_refs'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SF48_producer_attempt', g.Invariant('/semantic_body/attempt_id', 'proposal/vote: equals the captured producer attempt'), 'source_producer_attempt', SF48_producer_attempt),
        g.Guard('SF49_vote_constraints', g.Invariant('/semantic_body/hard_constraint_conflict_ids', 'vote: equals the record conflicts'), 'source_vote_constraints', SF49_vote_constraints),
        g.Guard('SF50_plan_result', g.Invariant('/semantic_body/plan_hash', 'plan_synthesized: equals the captured Plan-create result'), 'source_plan_result', SF50_plan_result),
        g.Guard('SF51_artifact_custody', g.Invariant('/semantic_body/artifact_ref', 'is one of the record artifact refs'), 'source_artifact_custody', SF51_artifact_custody),
    ])

    def check(value):
        table.require('SF48_producer_attempt', value, context)
        table.require('SF49_vote_constraints', value, context)
        table.require('SF50_plan_result', value, context)
        table.require('SF51_artifact_custody', value, context)
        return True
    return g.Case(table, check, context)
