"""DF guard table payload_restore: Payload owner: restore outcome state digests.

Method B guard rows for the DF FileSafe checkers. Each predicate reads one
observation record that the lane checker derives from the complete boundary
input (recomputed digests, decoded values, resolved routes, presence);
predicates never recompute, repair or call helpers. The checkers refuse only
through these rows (pm_filesafe_tables.refusals), in this order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-filesafe-table-generate.py; do not edit by hand.
"""
import pm_guard_isolation as g

FIELDS = ('outcome', 'target', 'after', 'before')


def PR01_clean_target(value, context):
    return 'payload_restore_outcome' if value['outcome'] == 'restored_clean' and value['target'] != value['after'] else None


def PR02_unchanged(value, context):
    return 'payload_restore_outcome' if value['outcome'] in ('restore_failed', 'restore_refused') and value['before'] != value['after'] else None


def PR03_skipped_target(value, context):
    return 'payload_restore_outcome' if value['outcome'] == 'restore_skipped' and value['target'] != value['before'] else None


def PR04_skipped_after(value, context):
    return 'payload_restore_outcome' if value['outcome'] == 'restore_skipped' and value['before'] != value['after'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('PR01_clean_target', g.Invariant('/post_restore_state_sha256', 'restored_clean ends at the target state'), 'payload_restore_outcome', PR01_clean_target),
        g.Guard('PR02_unchanged', g.Invariant('/post_restore_state_sha256', 'restore_failed and restore_refused end at the pre-restore state'), 'payload_restore_outcome', PR02_unchanged),
        g.Guard('PR03_skipped_target', g.Invariant('/pre_restore_state_sha256', 'restore_skipped starts at the target state'), 'payload_restore_outcome', PR03_skipped_target),
        g.Guard('PR04_skipped_after', g.Invariant('/post_restore_state_sha256', 'restore_skipped ends at the pre-restore state'), 'payload_restore_outcome', PR04_skipped_after),
    ])

    def check(value):
        table.require('PR01_clean_target', value, context)
        table.require('PR02_unchanged', value, context)
        table.require('PR03_skipped_target', value, context)
        table.require('PR04_skipped_after', value, context)
        return True
    return g.Case(table, check, context)
