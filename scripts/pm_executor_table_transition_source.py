"""DX guard table transition_source: Transition: observation mirror, reserved sequence, revision and predecessor.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('observed_canonical', 'original_canonical', 'transition_sequence_canonical', 'payload_sequence_canonical', 'transition_revision_canonical', 'record_revision_canonical', 'before', 'record_state')


def TX01_observed_payload(value, context):
    return 'conditional presence/original observation' if value['observed_canonical'] != value['original_canonical'] else None


def TX02_reserved_sequence(value, context):
    return 'reserved sequence' if value['transition_sequence_canonical'] != value['payload_sequence_canonical'] else None


def TX03_transition_revision(value, context):
    return 'transition revision' if value['transition_revision_canonical'] != value['record_revision_canonical'] else None


def TX04_predecessor(value, context):
    return 'source predecessor' if value['before'] != value['record_state'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TX01_observed_payload', g.Invariant('/transition/observed_payload', 'equals the complete owner observation'), 'conditional presence/original observation', TX01_observed_payload),
        g.Guard('TX02_reserved_sequence', g.Invariant('/transition/event_sequence', 'equals the payload event_sequence'), 'reserved sequence', TX02_reserved_sequence),
        g.Guard('TX03_transition_revision', g.Invariant('/transition/revision', 'equals the transition record revision'), 'transition revision', TX03_transition_revision),
        g.Guard('TX04_predecessor', g.Invariant('/transition/before', 'equals the transition record state'), 'source predecessor', TX04_predecessor),
    ])

    def check(value):
        table.require('TX01_observed_payload', value, context)
        table.require('TX02_reserved_sequence', value, context)
        table.require('TX03_transition_revision', value, context)
        table.require('TX04_predecessor', value, context)
        return True
    return g.Case(table, check, context)
