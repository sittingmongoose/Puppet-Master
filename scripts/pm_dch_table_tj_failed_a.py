"""DCH guard table tj_failed_a: test_joins: failed terminal copies of the actual outcome.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('payload_test_outcome', 'kind', 'payload_exit_code', 'exit_code', 'payload_error_ref', 'outcome_error_ref')


def TJ09_outcome_kind_copy(value, context):
    return 'test_join_refused' if value['payload_test_outcome'] != value['kind'] else None


def TJ10_exit_code_copy(value, context):
    return 'test_join_refused' if value['payload_exit_code'] != value['exit_code'] else None


def TJ11_error_ref_copy(value, context):
    return 'test_join_refused' if value['payload_error_ref'] != value['outcome_error_ref'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TJ09_outcome_kind_copy', g.Invariant('/payload/test_outcome', 'equals the actual outcome kind'), 'test_join_refused', TJ09_outcome_kind_copy),
        g.Guard('TJ10_exit_code_copy', g.Invariant('/payload/exit_code', 'equals the actual outcome exit code'), 'test_join_refused', TJ10_exit_code_copy),
        g.Guard('TJ11_error_ref_copy', g.Invariant('/payload/error_ref', 'equals the actual outcome error_ref'), 'test_join_refused', TJ11_error_ref_copy),
    ])

    def check(value):
        table.require('TJ09_outcome_kind_copy', value, context)
        table.require('TJ10_exit_code_copy', value, context)
        table.require('TJ11_error_ref_copy', value, context)
        return True
    return g.Case(table, check, context)
