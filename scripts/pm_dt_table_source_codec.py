"""DT guard table source_codec: decode_source: pm.dt.source.json.v1 strict decode.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('size', 'utf8', 'json', 'duplicate_keys', 'nonfinite_constants', 'canonical')


def DS01_size(value, context):
    return 'source stage exceeds 1048576 encoded bytes' if value['size'] > 1048576 else None


def DS02_utf8(value, context):
    return 'invalid UTF-8' if value['utf8'] is False else None


def DS03_json(value, context):
    return 'invalid JSON' if value['utf8'] is True and value['json'] is False else None


def DS04_unique_keys(value, context):
    return 'duplicate key' if value['duplicate_keys'] != 0 else None


def DS05_finite(value, context):
    return 'nonfinite number' if value['nonfinite_constants'] != 0 else None


def DS06_canonical(value, context):
    return 'noncanonical source bytes' if value['json'] is True and value['duplicate_keys'] == 0 and value['nonfinite_constants'] == 0 and value['canonical'] is False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('DS01_size', g.Invariant('/raw', 'is at most 1048576 bytes'), 'source stage exceeds 1048576 encoded bytes', DS01_size),
        g.Guard('DS02_utf8', g.Invariant('/raw', 'is strict UTF-8'), 'invalid UTF-8', DS02_utf8),
        g.Guard('DS03_json', g.Invariant('/raw', 'is JSON text'), 'invalid JSON', DS03_json),
        g.Guard('DS04_unique_keys', g.Invariant('/raw', 'has no duplicate object key'), 'duplicate key', DS04_unique_keys),
        g.Guard('DS05_finite', g.Invariant('/raw', 'has no nonfinite constant'), 'nonfinite number', DS05_finite),
        g.Guard('DS06_canonical', g.Invariant('/raw', 'equals the canonical encoding of its value'), 'noncanonical source bytes', DS06_canonical),
    ])

    def check(value):
        table.require('DS01_size', value, context)
        table.require('DS02_utf8', value, context)
        table.require('DS03_json', value, context)
        table.require('DS04_unique_keys', value, context)
        table.require('DS05_finite', value, context)
        table.require('DS06_canonical', value, context)
        return True
    return g.Case(table, check, context)
