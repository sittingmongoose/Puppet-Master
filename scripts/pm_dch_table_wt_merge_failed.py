"""DCH guard table wt_merge_failed: ACD-618 actual failed merge, preserving the binding.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('lock', 'operation', 'strategy', 'payload_strategy', 'status', 'error', 'payload_error', 'conflicts', 'payload_conflicts', 'commit', 'rebase_attempted', 'rebase_steps')


def WF01_lock(value, context):
    return 'worktree_refused' if value['lock'] != value['operation'] else None


def WF02_strategy(value, context):
    return 'worktree_refused' if value['strategy'] != value['payload_strategy'] else None


def WF03_failed(value, context):
    return 'worktree_refused' if value['status'] != 'failed' else None


def WF04_error(value, context):
    return 'worktree_refused' if value['error'] != value['payload_error'] else None


def WF05_conflicts(value, context):
    return 'worktree_refused' if value['conflicts'] is not value['payload_conflicts'] else None


def WF06_no_commit(value, context):
    return 'worktree_refused' if value['commit'] is not None else None


def WF07_abort(value, context):
    return 'worktree_refused' if value['strategy'] == 'rebase' and value['payload_conflicts'] is True and value['rebase_attempted'] is True and value['rebase_steps'] != ['auto_abort'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WF01_lock', g.Invariant('/operation/outcome/lock_owner', 'the original operation holds the merge lock'), 'worktree_refused', WF01_lock),
        g.Guard('WF02_strategy', g.Invariant('/operation/outcome/strategy', 'equals the original strategy'), 'worktree_refused', WF02_strategy),
        g.Guard('WF03_failed', g.Invariant('/operation/outcome/status', 'the merge failed'), 'worktree_refused', WF03_failed),
        g.Guard('WF04_error', g.Invariant('/operation/outcome/error', 'equals the actual sanitized error'), 'worktree_refused', WF04_error),
        g.Guard('WF05_conflicts', g.Invariant('/operation/outcome/has_conflicts', 'equals the original conflicts observation'), 'worktree_refused', WF05_conflicts),
        g.Guard('WF06_no_commit', g.Invariant('/operation/outcome/result_commit_sha', 'a failure claims no success commit'), 'worktree_refused', WF06_no_commit),
        g.Guard('WF07_abort', g.Invariant('/operation/outcome/rebase_steps', 'a rebase conflict was auto-aborted'), 'worktree_refused', WF07_abort),
    ])

    def check(value):
        table.require('WF01_lock', value, context)
        table.require('WF02_strategy', value, context)
        table.require('WF03_failed', value, context)
        table.require('WF04_error', value, context)
        table.require('WF05_conflicts', value, context)
        table.require('WF06_no_commit', value, context)
        table.require('WF07_abort', value, context)
        return True
    return g.Case(table, check, context)
