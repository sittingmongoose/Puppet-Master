"""DT guard table gate_score: gate_score_join: numeric gate results keep the dispatch score context.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('payload_score', 'outcome_score', 'payload_threshold', 'before_threshold', 'payload_dispatch_ref', 'before_dispatch_ref', 'payload_dispatch_tuple', 'before_dispatch_tuple', 'scored', 'tuple_present', 'payload_node_id', 'tuple_node_id', 'dispatch_ref_truthy')


def GS1_score_copy(value, context):
    return 'transition_refused' if value['payload_score'] != value['outcome_score'] else None


def GS2_threshold_copy(value, context):
    return 'transition_refused' if value['payload_threshold'] != value['before_threshold'] else None


def GS3_dispatch_ref_copy(value, context):
    return 'transition_refused' if value['payload_dispatch_ref'] != value['before_dispatch_ref'] else None


def GS4_dispatch_tuple_copy(value, context):
    return 'transition_refused' if value['payload_dispatch_tuple'] != value['before_dispatch_tuple'] else None


def GS5_scored_tuple(value, context):
    return 'transition_refused' if value['scored'] is True and value['tuple_present'] is False else None


def GS6_scored_node(value, context):
    return 'transition_refused' if value['scored'] is True and value['tuple_present'] is True and value['payload_node_id'] != value['tuple_node_id'] else None


def GS7_scored_ref(value, context):
    return 'transition_refused' if value['scored'] is True and value['dispatch_ref_truthy'] is False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('GS1_score_copy', g.Invariant('/payload/score', 'canonical bytes equal the evaluator score'), 'transition_refused', GS1_score_copy),
        g.Guard('GS2_threshold_copy', g.Invariant('/payload/score_threshold', 'canonical bytes equal the dispatch threshold'), 'transition_refused', GS2_threshold_copy),
        g.Guard('GS3_dispatch_ref_copy', g.Invariant('/payload/dispatch_score_ref', 'canonical bytes equal the dispatch ref'), 'transition_refused', GS3_dispatch_ref_copy),
        g.Guard('GS4_dispatch_tuple_copy', g.Invariant('/payload/dispatch_score_tuple', 'canonical bytes equal the dispatch tuple'), 'transition_refused', GS4_dispatch_tuple_copy),
        g.Guard('GS5_scored_tuple', g.Invariant('/payload/dispatch_score_tuple', 'a scored result carries a dispatch tuple'), 'transition_refused', GS5_scored_tuple),
        g.Guard('GS6_scored_node', g.Invariant('/payload/node_id', 'a scored result names the dispatch tuple node'), 'transition_refused', GS6_scored_node),
        g.Guard('GS7_scored_ref', g.Invariant('/payload/dispatch_score_ref', 'a scored result carries a nonempty dispatch ref'), 'transition_refused', GS7_scored_ref),
    ])

    def check(value):
        table.require('GS1_score_copy', value, context)
        table.require('GS2_threshold_copy', value, context)
        table.require('GS3_dispatch_ref_copy', value, context)
        table.require('GS4_dispatch_tuple_copy', value, context)
        table.require('GS5_scored_tuple', value, context)
        table.require('GS6_scored_node', value, context)
        table.require('GS7_scored_ref', value, context)
        return True
    return g.Case(table, check, context)
