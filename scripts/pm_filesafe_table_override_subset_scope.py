import pm_guard_isolation as g

FIELDS = ('granted_roots', 'requested_roots', 'requested_command', 'granted_command')


def SU12_roots(value, context):
    return 'grant_subset' if len([root for root in value['granted_roots'] if root not in value['requested_roots']]) != 0 else None


def SU13_command(value, context):
    return 'grant_subset' if value['requested_command'] is not None and value['granted_command'] != value['requested_command'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SU12_roots', g.Invariant('/granted_roots', 'every granted root is a requested root'), 'grant_subset', SU12_roots),
        g.Guard('SU13_command', g.Invariant('/granted_command', 'equals a requested command identity'), 'grant_subset', SU13_command),
    ])

    def check(value):
        table.require('SU12_roots', value, context)
        table.require('SU13_command', value, context)
        return True
    return g.Case(table, check, context)
