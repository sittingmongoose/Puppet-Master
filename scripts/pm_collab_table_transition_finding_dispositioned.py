"""DC guard table transition_finding_dispositioned: finding_dispositioned: a recorded open finding with its targets.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('finding_known', 'finding_disposition', 'target_hashes', 'finding_target_hashes')


def TR58_finding_known(value, context):
    return 'conflict:unknown_finding' if value['finding_known'] is not True else None


def TR59_finding_open(value, context):
    return 'conflict:already_dispositioned' if value['finding_known'] is True and value['finding_disposition'] is not None else None


def TR60_finding_targets(value, context):
    return 'conflict:target_hash_mismatch' if value['finding_known'] is True and value['target_hashes'] != value['finding_target_hashes'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR58_finding_known', g.Invariant('/finding_id', 'names a recorded finding'), 'conflict:unknown_finding', TR58_finding_known),
        g.Guard('TR59_finding_open', g.Invariant('/finding_id', 'is not dispositioned'), 'conflict:already_dispositioned', TR59_finding_open),
        g.Guard('TR60_finding_targets', g.Invariant('/target_hashes', 'equal the finding targets'), 'conflict:target_hash_mismatch', TR60_finding_targets),
    ])

    def check(value):
        table.require('TR58_finding_known', value, context)
        table.require('TR59_finding_open', value, context)
        table.require('TR60_finding_targets', value, context)
        return True
    return g.Case(table, check, context)
