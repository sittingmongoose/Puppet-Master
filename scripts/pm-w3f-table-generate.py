#!/usr/bin/env python3
"""Generate the W3F Method B guard-table modules from pm_w3f_event_oracles.ROWS.

Each module ``scripts/pm_w3f_table_<table>.py`` holds one table: a predicate per row that reads the one
boolean observation the checker derives for that row and returns its exact refusal code, a ``FIELDS``
tuple in table order, and ``case(value)`` building a fresh ``GuardTable`` whose check requires every row
in order. ``--check`` fails when a module is missing, stale or extra.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pm_w3f_event_oracles as W  # noqa: E402

SCRIPTS = W.ROOT / 'scripts'


def lit(text):
    return json.dumps(text, ensure_ascii=True)


def module_text(table, rows):
    lines = ['"""W3F guard table ' + table + '.', '',
             'Method B guard rows (scripts/pm_guard_isolation.py) for scripts/pm_w3f_event_oracles.py. Each predicate',
             'reads the one boolean observation the checker derives for its row from the complete scenario (True: the',
             'row\'s predicate holds or does not apply). Predicates never recompute, repair or call helpers. The checker',
             'refuses only through these rows, in this order.']
    if table.startswith('entailed_'):
        first, proof = W.ENTAILED[rows[0]['id']]
        lines += ['', 'Entailed row: never the first refusal. Rows that always refuse first: ' + ', '.join(first) + '.',
                  'Proof: ' + proof]
    lines += ['Generated by scripts/pm-w3f-table-generate.py from pm_w3f_event_oracles.ROWS; edit the spec there.', '"""',
              'import pm_guard_isolation as g',
              'FIELDS = (' + ''.join([lit(r['id']) + ', ' for r in rows]) + ')', '']
    for r in rows:
        lines += ['', 'def ' + r['id'] + '(value, context):',
                  '    return ' + lit(r['code']) + ' if value[' + lit(r['id']) + '] is not True else None', '']
    lines += ['', 'def case(value):', '    context = None', '    table = g.GuardTable([']
    for r in rows:
        lines.append('        g.Guard(' + lit(r['id']) + ', g.Invariant(' + lit(r['field']) + ', ' + lit(r['words']) + '), ' +
                     lit(r['code']) + ', ' + r['id'] + '),')
    lines += ['    ])', '', '    def check(value):']
    for r in rows:
        lines.append('        table.require(' + lit(r['id']) + ', value, context)')
    lines += ['        return True', '    return g.Case(table, check, context)', '']
    return '\n'.join(lines)


def expected():
    return {SCRIPTS / (W.TABLE_PREFIX + t + '.py'): module_text(t, W.TABLE_ROWS[t]) for t in W.TABLES}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    want = expected()
    present = set(SCRIPTS.glob(W.TABLE_PREFIX + '*.py'))
    stale = sorted([str(p.name) for p, t in want.items() if not p.exists() or p.read_text() != t])
    extra = sorted([str(p.name) for p in present - set(want)])
    if args.check:
        print(json.dumps({'tables': len(want), 'rows': len(W.ROWS), 'entailed': len(W.ENTAILED), 'stale': stale, 'extra': extra}))
        return 1 if stale or extra else 0
    for p in present - set(want):
        p.unlink()
    for p, t in want.items():
        if not p.exists() or p.read_text() != t:
            p.write_text(t)
    print(json.dumps({'tables': len(want), 'rows': len(W.ROWS), 'entailed': len(W.ENTAILED), 'written': stale, 'removed': extra}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
