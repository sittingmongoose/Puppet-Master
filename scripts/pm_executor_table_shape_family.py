"""DX guard table shape_family: Shape oracle: family source predicates (one row per family predicate).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('family', 'node_state', 'expected_node_state', 'fixed', 'child_success', 'child', 'parent', 'until', 'ts', 'graph_locked', 'packaging_passed', 'now', 'context_until')


def SX01_node_completion(value, context):
    return 'node completion source state' if value['family'] == 'node.completed' and value['node_state'] != value['expected_node_state'] else None


def SX02_fixed_child(value, context):
    return 'fixed without child success' if value['family'] == 'remediation.resolved' and value['fixed'] is True and value['child_success'] is not True else None


def SX03_child_parent(value, context):
    return 'child is parent' if value['family'] == 'remediation.spawned' and value['child'] == value['parent'] else None


def SX04_backoff_order(value, context):
    return 'backoff before recorded observation' if value['family'] == 'run.node_backoff_started' and value['until'][0] * value['ts'][1] < value['ts'][0] * value['until'][1] else None


def SX05_graph_unlocked(value, context):
    return 'graph already locked' if value['family'] == 'plan.decomposition_degraded' and value['graph_locked'] is not False else None


def SX06_packaging(value, context):
    return 'Document Set packaging' if value['family'] == 'run.completed' and value['packaging_passed'] is not True else None


def SX07_backoff_elapsed(value, context):
    return 'backoff not elapsed' if value['family'] == 'run.node_backoff_expired' and value['now'][0] * value['context_until'][1] < value['context_until'][0] * value['now'][1] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SX01_node_completion', g.Invariant('/context/source_facts/node_state', 'node.completed: verified for done, else verify_pending'), 'node completion source state', SX01_node_completion),
        g.Guard('SX02_fixed_child', g.Invariant('/context/source_child_success', 'remediation.resolved fixed: the child succeeded'), 'fixed without child success', SX02_fixed_child),
        g.Guard('SX03_child_parent', g.Invariant('/payload/child_attempt_id', 'remediation.spawned: differs from the parent'), 'child is parent', SX03_child_parent),
        g.Guard('SX04_backoff_order', g.Invariant('/payload/backoff_until_utc', 'run.node_backoff_started: not before ts'), 'backoff before recorded observation', SX04_backoff_order),
        g.Guard('SX05_graph_unlocked', g.Invariant('/context/graph_locked', 'plan.decomposition_degraded: is false'), 'graph already locked', SX05_graph_unlocked),
        g.Guard('SX06_packaging', g.Invariant('/context/packaging_passed', 'run.completed: is true'), 'Document Set packaging', SX06_packaging),
        g.Guard('SX07_backoff_elapsed', g.Invariant('/context/now_utc', 'run.node_backoff_expired: not before the deadline'), 'backoff not elapsed', SX07_backoff_elapsed),
    ])

    def check(value):
        table.require('SX01_node_completion', value, context)
        table.require('SX02_fixed_child', value, context)
        table.require('SX03_child_parent', value, context)
        table.require('SX04_backoff_order', value, context)
        table.require('SX05_graph_unlocked', value, context)
        table.require('SX06_packaging', value, context)
        table.require('SX07_backoff_elapsed', value, context)
        return True
    return g.Case(table, check, context)
