"""DT guard table denial: denial_emission: only a policy or user denial before dispatch emits tool.denied (DL-430).

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('denial_origin', 'policy_decision', 'dispatch_state')


def DE1_origin(value, context):
    return 'no_emission' if value['denial_origin'] not in ('policy', 'user') else None


def DE2_decision(value, context):
    return 'no_emission' if value['policy_decision'] != 'deny' else None


def DE3_not_dispatched(value, context):
    return 'no_emission' if value['dispatch_state'] != 'not_dispatched' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('DE1_origin', g.Invariant('/before/denial_origin', 'is policy or user'), 'no_emission', DE1_origin),
        g.Guard('DE2_decision', g.Invariant('/before/policy_decision', 'is deny'), 'no_emission', DE2_decision),
        g.Guard('DE3_not_dispatched', g.Invariant('/before/dispatch_state', 'is not_dispatched'), 'no_emission', DE3_not_dispatched),
    ])

    def check(value):
        table.require('DE1_origin', value, context)
        table.require('DE2_decision', value, context)
        table.require('DE3_not_dispatched', value, context)
        return True
    return g.Case(table, check, context)
