"""DX guard table retry_limit: Retry: owner provenance, exact limit, budget and ordinal.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('policy_owner_ref', 'policy_owner', 'limit_type', 'limit', 'expected_limit', 'used', 'has_retry_count', 'retry_count', 'next_count')


def RL01_policy_owner(value, context):
    return 'classified owner policy provenance' if value['policy_owner_ref'] != value['policy_owner'] else None


def RL02_limit_type(value, context):
    return 'exact classified retry limit' if value['limit_type'] != 'int' else None


def RL03_limit_value(value, context):
    return 'exact classified retry limit' if value['limit_type'] == 'int' and value['limit'] != value['expected_limit'] else None


def RL04_budget(value, context):
    return 'per-error retry budget' if value['limit_type'] == 'int' and value['limit'] == value['expected_limit'] and value['used'] >= value['limit'] else None


def RL05_ordinal(value, context):
    return 'classified retry ordinal' if value['has_retry_count'] is True and value['retry_count'] != value['next_count'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RL01_policy_owner', g.Invariant('/records/retry/body/policy_owner_ref', 'names the classified owner policy'), 'classified owner policy provenance', RL01_policy_owner),
        g.Guard('RL02_limit_type', g.Invariant('/records/retry/body/limit', 'is an integer'), 'exact classified retry limit', RL02_limit_type),
        g.Guard('RL03_limit_value', g.Invariant('/records/retry/body/limit', 'an integer limit equals the classified limit'), 'exact classified retry limit', RL03_limit_value),
        g.Guard('RL04_budget', g.Invariant('/records/retry/body/used', 'is below the limit'), 'per-error retry budget', RL04_budget),
        g.Guard('RL05_ordinal', g.Invariant('/payload/retry_count', 'equals used plus one when present'), 'classified retry ordinal', RL05_ordinal),
    ])

    def check(value):
        table.require('RL01_policy_owner', value, context)
        table.require('RL02_limit_type', value, context)
        table.require('RL03_limit_value', value, context)
        table.require('RL04_budget', value, context)
        table.require('RL05_ordinal', value, context)
        return True
    return g.Case(table, check, context)
