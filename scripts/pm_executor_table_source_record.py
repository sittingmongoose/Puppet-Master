"""DX guard table source_record: Capture source records: ref, owner, Project and Storage root of each slot.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('ref_type', 'ref_nonempty', 'owner', 'expected_owner', 'project', 'scope_project', 'storage', 'scope_storage')


def SR04_ref_type(value, context):
    return 'source ref' if value['ref_type'] != 'str' else None


def SR05_ref_nonempty(value, context):
    return 'source ref' if value['ref_type'] == 'str' and value['ref_nonempty'] is not True else None


def SR06_owner(value, context):
    return 'source owner' if value['owner'] != value['expected_owner'] else None


def SR07_project(value, context):
    return 'source Project' if value['project'] != value['scope_project'] else None


def SR08_storage(value, context):
    return 'source root' if value['storage'] != value['scope_storage'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SR04_ref_type', g.Invariant('/records/*/ref', 'is a string'), 'source ref', SR04_ref_type),
        g.Guard('SR05_ref_nonempty', g.Invariant('/records/*/ref', 'a string ref is nonempty'), 'source ref', SR05_ref_nonempty),
        g.Guard('SR06_owner', g.Invariant('/records/*/owner', 'equals the adapter owner for the slot'), 'source owner', SR06_owner),
        g.Guard('SR07_project', g.Invariant('/records/*/project_id', 'equals the scope Project'), 'source Project', SR07_project),
        g.Guard('SR08_storage', g.Invariant('/records/*/storage_instance_id', 'equals the scope Storage root'), 'source root', SR08_storage),
    ])

    def check(value):
        table.require('SR04_ref_type', value, context)
        table.require('SR05_ref_nonempty', value, context)
        table.require('SR06_owner', value, context)
        table.require('SR07_project', value, context)
        table.require('SR08_storage', value, context)
        return True
    return g.Case(table, check, context)
