"""DX guard table retry_storage: Retry storage_io: the SP-238 adapter class.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('failure_storage', 'retry_storage', 'new_attempt', 'successor')


def RS01_storage_join(value, context):
    return 'original Storage classification' if value['failure_storage'] != value['retry_storage'] else None


def RS02_storage_class(value, context):
    return 'Storage retry class' if value['failure_storage'] not in ('interrupted', 'transient_busy') else None


def RS03_no_new_attempt(value, context):
    return 'Storage adapter retry cannot create an Executor attempt' if value['new_attempt'] is not False else None


def RS04_no_successor(value, context):
    return 'Storage adapter retry cannot create an Executor attempt' if value['successor'] is not None else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RS01_storage_join', g.Invariant('/records/failure/body/storage_io_class', 'equals the retry Storage class'), 'original Storage classification', RS01_storage_join),
        g.Guard('RS02_storage_class', g.Invariant('/records/failure/body/storage_io_class', 'is interrupted or transient_busy'), 'Storage retry class', RS02_storage_class),
        g.Guard('RS03_no_new_attempt', g.Invariant('/records/retry/body/new_executor_attempt', 'is false'), 'Storage adapter retry cannot create an Executor attempt', RS03_no_new_attempt),
        g.Guard('RS04_no_successor', g.Invariant('/records/retry/body/successor_attempt_id', 'is null'), 'Storage adapter retry cannot create an Executor attempt', RS04_no_successor),
    ])

    def check(value):
        table.require('RS01_storage_join', value, context)
        table.require('RS02_storage_class', value, context)
        table.require('RS03_no_new_attempt', value, context)
        table.require('RS04_no_successor', value, context)
        return True
    return g.Case(table, check, context)
