"""DCH guard table rb_pack_a: resolve_body: SP-337 reference, pack key, size, media, Store and body copies.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('payload_ref', 'expected_payload_ref', 'pack_key', 'expected_pack_key', 'byte_size', 'raw_size', 'media_type', 'pack_store', 'store', 'pack_scope', 'body_scope', 'pack_computer_id', 'body_computer_id')


def RB05_payload_ref(value, context):
    return 'body_unavailable' if value['payload_ref'] != value['expected_payload_ref'] else None


def RB06_pack_key(value, context):
    return 'body_unavailable' if value['pack_key'] != value['expected_pack_key'] else None


def RB07_byte_size(value, context):
    return 'body_unavailable' if value['byte_size'] != value['raw_size'] else None


def RB08_media_type(value, context):
    return 'body_unavailable' if value['media_type'] != 'application/msgpack' else None


def RB09_pack_store(value, context):
    return 'body_unavailable' if value['pack_store'] != value['store'] else None


def RB10_scope_copy(value, context):
    return 'body_unavailable' if value['pack_scope'] != value['body_scope'] else None


def RB11_computer_copy(value, context):
    return 'body_unavailable' if value['pack_computer_id'] != value['body_computer_id'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RB05_payload_ref', g.Invariant('/payload_ref', 'equals the reference recomputed from the pack body bytes'), 'body_unavailable', RB05_payload_ref),
        g.Guard('RB06_pack_key', g.Invariant('/source/key', 'equals payload:v1: plus BLAKE3 of the pack body bytes'), 'body_unavailable', RB06_pack_key),
        g.Guard('RB07_byte_size', g.Invariant('/source/byte_size', 'equals the encoded pack body length'), 'body_unavailable', RB07_byte_size),
        g.Guard('RB08_media_type', g.Invariant('/source/media_type', 'is application/msgpack'), 'body_unavailable', RB08_media_type),
        g.Guard('RB09_pack_store', g.Invariant('/source/storage_instance_id', 'equals the reading Storage instance'), 'body_unavailable', RB09_pack_store),
        g.Guard('RB10_scope_copy', g.Invariant('/source/scope', 'equals the pack body scope'), 'body_unavailable', RB10_scope_copy),
        g.Guard('RB11_computer_copy', g.Invariant('/source/computer_id', 'equals the pack body computer_id'), 'body_unavailable', RB11_computer_copy),
    ])

    def check(value):
        table.require('RB05_payload_ref', value, context)
        table.require('RB06_pack_key', value, context)
        table.require('RB07_byte_size', value, context)
        table.require('RB08_media_type', value, context)
        table.require('RB09_pack_store', value, context)
        table.require('RB10_scope_copy', value, context)
        table.require('RB11_computer_copy', value, context)
        return True
    return g.Case(table, check, context)
