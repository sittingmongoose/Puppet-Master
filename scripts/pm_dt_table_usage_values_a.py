"""DT guard table usage_values_a: usage_values_valid: cost copies and cost visibility.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('payload_cost', 'record_cost', 'cost_mismatches', 'cost_status', 'amount_present', 'display_cost_policy')


def UV1_cost_amount_copy(value, context):
    return 'transition_refused' if value['payload_cost'] != value['record_cost'] else None


def UV2_cost_copies(value, context):
    return 'transition_refused' if value['cost_mismatches'] != [] else None


def UV3_unknown_cost(value, context):
    return 'transition_refused' if value['cost_status'] == 'unknown' and value['amount_present'] is True else None


def UV4_hidden_cost(value, context):
    return 'transition_refused' if value['cost_status'] in ('hidden_subscription', 'hidden_byok') and value['display_cost_policy'] == 'show' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('UV1_cost_amount_copy', g.Invariant('/payload/cost_microdollars', 'canonical bytes equal the cost record amount'), 'transition_refused', UV1_cost_amount_copy),
        g.Guard('UV2_cost_copies', g.Invariant('/payload', 'currency, status and pricing fields equal the cost record'), 'transition_refused', UV2_cost_copies),
        g.Guard('UV3_unknown_cost', g.Invariant('/payload/cost', 'an unknown cost has no amount'), 'transition_refused', UV3_unknown_cost),
        g.Guard('UV4_hidden_cost', g.Invariant('/payload/display_cost_policy', 'a hidden cost is never shown'), 'transition_refused', UV4_hidden_cost),
    ])

    def check(value):
        table.require('UV1_cost_amount_copy', value, context)
        table.require('UV2_cost_copies', value, context)
        table.require('UV3_unknown_cost', value, context)
        table.require('UV4_hidden_cost', value, context)
        return True
    return g.Case(table, check, context)
