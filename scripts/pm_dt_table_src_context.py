"""DT guard table src_context: source_valid: payload, occurrence, runtime, Usage and web-parent joins.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('payload_envelope_mismatches', 'occurred_at_utc', 'payload_time', 'runtime_mismatches', 'family', 'usage_event_ref', 'event_id', 'web_parent_applies', 'event_parent_event_id', 'web_parent_event_id')


def SV31_payload_envelope_ids(value, context):
    return 'join_refused' if value['payload_envelope_mismatches'] != [] else None


def SV32_occurrence_time(value, context):
    return 'join_refused' if value['occurred_at_utc'] != value['payload_time'] else None


def SV33_runtime_context(value, context):
    return 'join_refused' if value['runtime_mismatches'] != [] else None


def SV34_usage_event_ref(value, context):
    return 'join_refused' if value['family'] == 'usage.event' and value['usage_event_ref'] != value['event_id'] else None


def SV35_web_parent(value, context):
    return 'join_refused' if value['web_parent_applies'] is True and value['event_parent_event_id'] != value['web_parent_event_id'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SV31_payload_envelope_ids', g.Invariant('/completed/payload', 'every payload envelope id equals the event field'), 'join_refused', SV31_payload_envelope_ids),
        g.Guard('SV32_occurrence_time', g.Invariant('/event/occurred_at_utc', 'equals the payload occurrence time'), 'join_refused', SV32_occurrence_time),
        g.Guard('SV33_runtime_context', g.Invariant('/completed/runtime_context', 'every runtime context value equals its payload copy'), 'join_refused', SV33_runtime_context),
        g.Guard('SV34_usage_event_ref', g.Invariant('/completed/payload/usage_event_ref', 'a Usage payload names the event id'), 'join_refused', SV34_usage_event_ref),
        g.Guard('SV35_web_parent', g.Invariant('/event/parent_event_id', 'a web tool event names the web request parent'), 'join_refused', SV35_web_parent),
    ])

    def check(value):
        table.require('SV31_payload_envelope_ids', value, context)
        table.require('SV32_occurrence_time', value, context)
        table.require('SV33_runtime_context', value, context)
        table.require('SV34_usage_event_ref', value, context)
        table.require('SV35_web_parent', value, context)
        return True
    return g.Case(table, check, context)
