#!/usr/bin/env python3
"""Generate the W3D Method B guard-table modules from scripts/pm_w3d_bsd_rows.py.

Each predicate reads one observation the checker derives from the complete
boundary input; predicates never recompute, repair or call helpers. The
checker (scripts/pm_w3d_bsd_events.py) refuses only through these rows, in
row order. Edit the row inventory and regenerate; never edit a table module.
Usage: python3 scripts/pm-w3d-table-generate.py [--check]
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import pm_w3d_bsd_rows as rows_spec  # noqa: E402

PREFIX = 'pm_w3d_bsd_table_'


def render(phase, title, rows):
    fields = tuple(field for _, field, *_ in rows)
    lines = [
        f'"""W3D guard table {phase}: {title}.',
        '',
        'Method B guard rows (scripts/pm_guard_isolation.py) for the W3D BSD checker. Each predicate',
        'reads one observation the checker derives from the complete boundary input. Predicates never',
        'recompute, repair or call helpers. The checker refuses only through these rows, in this order.',
        'Generated by scripts/pm-w3d-table-generate.py; edit scripts/pm_w3d_bsd_rows.py instead.',
        '"""',
        'import pm_guard_isolation as g',
        '',
        f'FIELDS = {fields!r}',
        '',
    ]
    for name, field, _inv, code, *_ in rows:
        func = name.replace('.', '_').replace('-', '_')
        lines += [f'def {func}(value, context):',
                  f'    return {code!r} if value[{field!r}] is not True else None', '']
    lines += ['def case(value):', '    context = None', '    table = g.GuardTable([']
    for name, field, invariant, code, *_ in rows:
        func = name.replace('.', '_').replace('-', '_')
        lines.append(f'        g.Guard({name!r}, g.Invariant({"/" + field!r}, {invariant!r}), {code!r}, {func}),')
    lines += ['    ])', '', '    def check(value):']
    for name, *_ in rows:
        lines.append(f'        table.require({name!r}, value, context)')
    lines += ['        return True', '    return g.Case(table, check, context)', '']
    return '\n'.join(lines)


def main():
    check = '--check' in sys.argv[1:]
    stale = []
    phases = rows_spec.all_phases()
    expected = set()
    for phase, (title, rows) in phases.items():
        path = ROOT / 'scripts' / f'{PREFIX}{phase}.py'
        expected.add(path.name)
        text = render(phase, title, rows)
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.name)
        else:
            path.write_text(text)
    extra = sorted(p.name for p in (ROOT / 'scripts').glob(PREFIX + '*.py') if p.name not in expected)
    total = sum(len(r) for _, r in phases.values())
    print(f'{len(phases)} tables, {total} rows; stale {len(stale)}; extra {len(extra)}')
    if stale or extra:
        print('stale:', stale[:10], 'extra:', extra[:10])
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())