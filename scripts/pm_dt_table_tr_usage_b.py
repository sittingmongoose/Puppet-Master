"""DT guard table tr_usage_b: transition usage.event: parent run, record copies and provider observation.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('payload_parent_run_id', 'before_parent_run_id', 'copy_mismatches', 'raw_payload_ref', 'observation_ref', 'provider_payload_hash', 'observation_sha256')


def UE6_parent_run(value, context):
    return 'transition_refused' if value['payload_parent_run_id'] != value['before_parent_run_id'] else None


def UE7_record_copies(value, context):
    return 'transition_refused' if value['copy_mismatches'] != [] else None


def UE8_raw_payload_ref(value, context):
    return 'transition_refused' if value['raw_payload_ref'] != value['observation_ref'] else None


def UE9_provider_hash(value, context):
    return 'transition_refused' if value['provider_payload_hash'] != value['observation_sha256'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('UE6_parent_run', g.Invariant('/payload/parent_run_id', 'equals the observed parent run'), 'transition_refused', UE6_parent_run),
        g.Guard('UE7_record_copies', g.Invariant('/payload', 'every Usage record field equals the observed copy'), 'transition_refused', UE7_record_copies),
        g.Guard('UE8_raw_payload_ref', g.Invariant('/payload/raw_payload_ref', 'equals the observation ref'), 'transition_refused', UE8_raw_payload_ref),
        g.Guard('UE9_provider_hash', g.Invariant('/payload/provider_payload_hash', 'equals the observation digest'), 'transition_refused', UE9_provider_hash),
    ])

    def check(value):
        table.require('UE6_parent_run', value, context)
        table.require('UE7_record_copies', value, context)
        table.require('UE8_raw_payload_ref', value, context)
        table.require('UE9_provider_hash', value, context)
        return True
    return g.Case(table, check, context)
