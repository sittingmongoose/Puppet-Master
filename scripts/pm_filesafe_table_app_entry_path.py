"""DF guard table app_entry_path: Application original: manifest entry lexical root boundary.

Method B guard rows for the DF FileSafe checkers. Each predicate reads one
observation record that the lane checker derives from the complete boundary
input (recomputed digests, decoded values, resolved routes, presence);
predicates never recompute, repair or call helpers. The checkers refuse only
through these rows (pm_filesafe_tables.refusals), in this order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-filesafe-table-generate.py; do not edit by hand.
"""
import pm_guard_isolation as g

FIELDS = ('root', 'path', 'ignored', 'authorized_write_set')


def AE05_under_root(value, context):
    return 'application_entry_root' if value['root'] is None or not value['path'].startswith(value['root'] + '/') else None


def AE06_no_parent(value, context):
    return 'application_entry_root' if '..' in value['path'].split('/') else None


def AE07_no_git(value, context):
    return 'application_entry_root' if '/.git/' in value['path'] else None


def AE08_ignored_scope(value, context):
    return 'application_ignored_scope' if value['ignored'] and not value['authorized_write_set'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('AE05_under_root', g.Invariant('/entries/identity/canonical_absolute_path', 'starts with the (present) working directory and a slash'), 'application_entry_root', AE05_under_root),
        g.Guard('AE06_no_parent', g.Invariant('/entries/identity/canonical_absolute_path', 'has no .. segment'), 'application_entry_root', AE06_no_parent),
        g.Guard('AE07_no_git', g.Invariant('/entries/identity/canonical_absolute_path', 'does not enter /.git/'), 'application_entry_root', AE07_no_git),
        g.Guard('AE08_ignored_scope', g.Invariant('/entries/ignored', 'an ignored entry is in the authorized write set'), 'application_ignored_scope', AE08_ignored_scope),
    ])

    def check(value):
        table.require('AE05_under_root', value, context)
        table.require('AE06_no_parent', value, context)
        table.require('AE07_no_git', value, context)
        table.require('AE08_ignored_scope', value, context)
        return True
    return g.Case(table, check, context)
