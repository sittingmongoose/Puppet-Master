"""DCH guard table wt_merged: ACD-619 completed merge strategy under the owner lock and tests.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('lock', 'operation', 'strategy', 'payload_strategy', 'status', 'guard_mismatches', 'tests_enabled', 'tests', 'commit', 'payload_commit', 'rebase_steps')


def WM01_lock(value, context):
    return 'worktree_refused' if value['lock'] != value['operation'] else None


def WM02_strategy(value, context):
    return 'worktree_refused' if value['strategy'] != value['payload_strategy'] else None


def WM03_completed(value, context):
    return 'worktree_refused' if value['status'] != 'completed' else None


def WM04_guards(value, context):
    return 'worktree_refused' if value['guard_mismatches'] != [] else None


def WM05_tests(value, context):
    return 'worktree_refused' if value['tests_enabled'] is True and value['tests'] not in ('passed', 'explicit_override') else None


def WM06_commit(value, context):
    return 'worktree_refused' if value['commit'] != value['payload_commit'] else None


def WM07_rebase_steps(value, context):
    return 'worktree_refused' if value['strategy'] == 'rebase' and value['rebase_steps'] != ['worktree_rebase', 'main_ff_merge'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WM01_lock', g.Invariant('/operation/outcome/lock_owner', 'the same original operation holds the merge lock'), 'worktree_refused', WM01_lock),
        g.Guard('WM02_strategy', g.Invariant('/operation/outcome/strategy', 'equals the original strategy'), 'worktree_refused', WM02_strategy),
        g.Guard('WM03_completed', g.Invariant('/operation/outcome/status', 'git completed'), 'worktree_refused', WM03_completed),
        g.Guard('WM04_guards', g.Invariant('/operation/outcome/guards', 'dirty/conflict/active-run/detached-HEAD guards were rechecked and clear'), 'worktree_refused', WM04_guards),
        g.Guard('WM05_tests', g.Invariant('/operation/outcome/tests', 'tests passed or the existing explicit override was accepted'), 'worktree_refused', WM05_tests),
        g.Guard('WM06_commit', g.Invariant('/operation/outcome/result_commit_sha', 'equals the actual completed commit'), 'worktree_refused', WM06_commit),
        g.Guard('WM07_rebase_steps', g.Invariant('/operation/outcome/rebase_steps', 'rebase includes worktree rebase then main ff-merge under the lock'), 'worktree_refused', WM07_rebase_steps),
    ])

    def check(value):
        table.require('WM01_lock', value, context)
        table.require('WM02_strategy', value, context)
        table.require('WM03_completed', value, context)
        table.require('WM04_guards', value, context)
        table.require('WM05_tests', value, context)
        table.require('WM06_commit', value, context)
        table.require('WM07_rebase_steps', value, context)
        return True
    return g.Case(table, check, context)
