import pm_guard_isolation as g

FIELDS = ('ref_path', 'payload_path', 'ref_def_present', 'ref_schema_id', 'def_schema_id')


def IL10_ref_path(value, context):
    return 'payload_schema_ref_resolves' if value['ref_path'] != value['payload_path'] else None


def IL11_ref_def(value, context):
    return 'payload_schema_ref_resolves' if value['ref_def_present'] is not True else None


def IL12_ref_schema_id(value, context):
    return 'payload_schema_ref_resolves' if value['ref_def_present'] is True and value['ref_schema_id'] != value['def_schema_id'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IL10_ref_path', g.Invariant('/rows/<i>/registry_row/**/payload_schema_ref/path', 'is the payload schema path'), 'payload_schema_ref_resolves', IL10_ref_path),
        g.Guard('IL11_ref_def', g.Invariant('/rows/<i>/registry_row/**/payload_schema_ref/json_pointer', 'names a payload definition'), 'payload_schema_ref_resolves', IL11_ref_def),
        g.Guard('IL12_ref_schema_id', g.Invariant('/rows/<i>/registry_row/**/payload_schema_ref/schema_id', 'equals that definition $id'), 'payload_schema_ref_resolves', IL12_ref_schema_id),
    ])

    def check(value):
        table.require('IL10_ref_path', value, context)
        table.require('IL11_ref_def', value, context)
        table.require('IL12_ref_schema_id', value, context)
        return True
    return g.Case(table, check, context)
