"""DX guard table history_disclosure: Retained reader: current disclosure fences.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('reader_active', 'source_available', 'event_deleted_at')


def HD01_reader_active(value, context):
    return 'reader_withdrawn' if value['reader_active'] is not True else None


def HD02_source_available(value, context):
    return 'source_unavailable' if value['source_available'] is not True else None


def HD03_event_not_deleted(value, context):
    return 'event_deleted' if value['event_deleted_at'] is not None else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('HD01_reader_active', g.Invariant('/disclosure/reader_active', 'is true'), 'reader_withdrawn', HD01_reader_active),
        g.Guard('HD02_source_available', g.Invariant('/disclosure/source_available', 'is true'), 'source_unavailable', HD02_source_available),
        g.Guard('HD03_event_not_deleted', g.Invariant('/disclosure/event_deleted_at', 'is null'), 'event_deleted', HD03_event_not_deleted),
    ])

    def check(value):
        table.require('HD01_reader_active', value, context)
        table.require('HD02_source_available', value, context)
        table.require('HD03_event_not_deleted', value, context)
        return True
    return g.Case(table, check, context)
