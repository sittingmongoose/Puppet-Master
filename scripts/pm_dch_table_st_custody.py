"""DCH guard table st_custody: CH2 Stop sealed retained store: exactly one sealed receipt of the one Stop edition selects the original.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('store_in_custody', 'receipt_count', 'receipt_installed')


def SK01_custody_store(value, context):
    return 'original_unavailable' if value['store_in_custody'] is not True else None


def SK02_receipt_present(value, context):
    return 'original_unavailable' if value['store_in_custody'] is True and value['receipt_count'] == 0 else None


def SK03_receipt_unique(value, context):
    return 'recipe_unsupported' if value['store_in_custody'] is True and value['receipt_count'] != 0 and value['receipt_count'] != 1 else None


def SK04_receipt_edition(value, context):
    return 'recipe_unsupported' if value['receipt_count'] == 1 and value['receipt_installed'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SK01_custody_store', g.Invariant('/context/storage_instance_id', 'the sealed Stop custody holds this Store'), 'original_unavailable', SK01_custody_store),
        g.Guard('SK02_receipt_present', g.Invariant('/context/source_value_sha256', 'a sealed receipt exists for this exact original'), 'original_unavailable', SK02_receipt_present),
        g.Guard('SK03_receipt_unique', g.Invariant('/context/source_value_sha256', 'exactly one sealed receipt exists for this exact original'), 'recipe_unsupported', SK03_receipt_unique),
        g.Guard('SK04_receipt_edition', g.Invariant('/context/source_value_sha256', 'the receipt names the one installed Stop edition and its pinned resources'), 'recipe_unsupported', SK04_receipt_edition),
    ])

    def check(value):
        table.require('SK01_custody_store', value, context)
        table.require('SK02_receipt_present', value, context)
        table.require('SK03_receipt_unique', value, context)
        table.require('SK04_receipt_edition', value, context)
        return True
    return g.Case(table, check, context)
