"""DCH guard table st_index_frontier: stop index_read_valid: anchor, frontier and selection equal the node.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('token_anchor', 'node_anchor', 'token_frontier_revision', 'node_frontier_revision', 'token_frontier_sha256', 'node_frontier_sha256', 'token_selection', 'node_selection', 'current_selection')


def IX13_anchor(value, context):
    return 'stop_index_refused' if value['token_anchor'] != value['node_anchor'] else None


def IX14_frontier_revision(value, context):
    return 'stop_index_refused' if value['token_frontier_revision'] != value['node_frontier_revision'] else None


def IX15_frontier_sha256(value, context):
    return 'stop_index_refused' if value['token_frontier_sha256'] != value['node_frontier_sha256'] else None


def IX16_token_selection(value, context):
    return 'stop_index_refused' if value['token_selection'] != value['node_selection'] else None


def IX17_current_selection(value, context):
    return 'stop_index_refused' if value['current_selection'] != value['node_selection'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IX13_anchor', g.Invariant('/token/generation_anchor_sha256', 'equals the node anchor'), 'stop_index_refused', IX13_anchor),
        g.Guard('IX14_frontier_revision', g.Invariant('/token/frontier_revision', 'equals the node frontier revision'), 'stop_index_refused', IX14_frontier_revision),
        g.Guard('IX15_frontier_sha256', g.Invariant('/token/frontier_sha256', 'equals the node frontier digest'), 'stop_index_refused', IX15_frontier_sha256),
        g.Guard('IX16_token_selection', g.Invariant('/token/source_selection', 'equals the node selection'), 'stop_index_refused', IX16_token_selection),
        g.Guard('IX17_current_selection', g.Invariant('/source/current_source_selection', 'equals the node selection'), 'stop_index_refused', IX17_current_selection),
    ])

    def check(value):
        table.require('IX13_anchor', value, context)
        table.require('IX14_frontier_revision', value, context)
        table.require('IX15_frontier_sha256', value, context)
        table.require('IX16_token_selection', value, context)
        table.require('IX17_current_selection', value, context)
        return True
    return g.Case(table, check, context)
