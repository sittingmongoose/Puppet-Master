"""DCH guard table tj_start: test_joins: retained start identity and copies (W.9.2/W.9.3).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('payload_started_event_id', 'started_event_id', 'outcome_started_event_id', 'payload_copy_mismatches', 'outcome_copy_mismatches', 'payload_duration_ms', 'outcome_duration_ms')


def TJ01_payload_started_id(value, context):
    return 'test_join_refused' if value['payload_started_event_id'] != value['started_event_id'] else None


def TJ02_outcome_started_id(value, context):
    return 'test_join_refused' if value['outcome_started_event_id'] != value['started_event_id'] else None


def TJ03_payload_start_copies(value, context):
    return 'test_join_refused' if value['payload_copy_mismatches'] != [] else None


def TJ04_outcome_copies(value, context):
    return 'test_join_refused' if value['outcome_copy_mismatches'] != [] else None


def TJ05_duration_copy(value, context):
    return 'test_join_refused' if value['payload_duration_ms'] != value['outcome_duration_ms'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TJ01_payload_started_id', g.Invariant('/payload/started_event_id', 'names the retained start event'), 'test_join_refused', TJ01_payload_started_id),
        g.Guard('TJ02_outcome_started_id', g.Invariant('/source/outcome/started_event_id', 'names the retained start event'), 'test_join_refused', TJ02_outcome_started_id),
        g.Guard('TJ03_payload_start_copies', g.Invariant('/payload', 'every operation/scope/thread/worktree/command/strategy field equals the start body'), 'test_join_refused', TJ03_payload_start_copies),
        g.Guard('TJ04_outcome_copies', g.Invariant('/source/outcome', 'every operation/scope/thread/worktree/command/strategy field equals the terminal payload'), 'test_join_refused', TJ04_outcome_copies),
        g.Guard('TJ05_duration_copy', g.Invariant('/payload/duration_ms', 'equals the actual outcome duration'), 'test_join_refused', TJ05_duration_copy),
    ])

    def check(value):
        table.require('TJ01_payload_started_id', value, context)
        table.require('TJ02_outcome_started_id', value, context)
        table.require('TJ03_payload_start_copies', value, context)
        table.require('TJ04_outcome_copies', value, context)
        table.require('TJ05_duration_copy', value, context)
        return True
    return g.Case(table, check, context)
