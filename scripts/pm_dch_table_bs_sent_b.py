"""DCH guard table bs_sent_b: ACD-611 selection-to-chat: visible pending chip handoff, not a sent message.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('chip_state', 'chip_target', 'resolved', 'chip_mismatches', 'message_sent')


def BS06_chip_pending(value, context):
    return 'selection_refused' if value['chip_state'] != 'pending' else None


def BS07_chip_target(value, context):
    return 'selection_refused' if value['chip_target'] != value['resolved'] else None


def BS08_chip_copies(value, context):
    return 'selection_refused' if value['chip_mismatches'] != [] else None


def BS09_no_message(value, context):
    return 'selection_refused' if value['message_sent'] is not False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('BS06_chip_pending', g.Invariant('/operation/outcome/chip/state', 'the visible chip is pending'), 'selection_refused', BS06_chip_pending),
        g.Guard('BS07_chip_target', g.Invariant('/operation/outcome/chip/target', 'the chip records the effective target'), 'selection_refused', BS07_chip_target),
        g.Guard('BS08_chip_copies', g.Invariant('/operation/outcome/chip', 'selection, excerpt and provenance equal the payload'), 'selection_refused', BS08_chip_copies),
        g.Guard('BS09_no_message', g.Invariant('/operation/outcome/message_sent', 'chip handoff success sends no message'), 'selection_refused', BS09_no_message),
    ])

    def check(value):
        table.require('BS06_chip_pending', value, context)
        table.require('BS07_chip_target', value, context)
        table.require('BS08_chip_copies', value, context)
        table.require('BS09_no_message', value, context)
        return True
    return g.Case(table, check, context)
