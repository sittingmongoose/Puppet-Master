"""DCH guard table cs_pack_a: checkpoint_storage_valid: pack key, size, media, Store and domain copies.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('pack_key', 'expected_pack_key', 'byte_size', 'raw_size', 'media_type', 'pack_store', 'store', 'pack_domain_key', 'key', 'pack_partition', 'value_partition', 'pack_event_type', 'family')


def CS09_pack_key(value, context):
    return 'checkpoint_storage_refused' if value['pack_key'] != value['expected_pack_key'] else None


def CS10_pack_size(value, context):
    return 'checkpoint_storage_refused' if value['byte_size'] != value['raw_size'] else None


def CS11_pack_media(value, context):
    return 'checkpoint_storage_refused' if value['media_type'] != 'application/msgpack' else None


def CS12_pack_store(value, context):
    return 'checkpoint_storage_refused' if value['pack_store'] != value['store'] else None


def CS13_pack_domain_key(value, context):
    return 'checkpoint_storage_refused' if value['pack_domain_key'] != value['key'] else None


def CS14_pack_partition(value, context):
    return 'checkpoint_storage_refused' if value['pack_partition'] != value['value_partition'] else None


def CS15_pack_event_type(value, context):
    return 'checkpoint_storage_refused' if value['pack_event_type'] != value['family'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CS09_pack_key', g.Invariant('/source/checkpoint_storage/pack/key', 'equals payload:v1: plus BLAKE3 of the value bytes'), 'checkpoint_storage_refused', CS09_pack_key),
        g.Guard('CS10_pack_size', g.Invariant('/source/checkpoint_storage/pack/byte_size', 'equals the value byte length'), 'checkpoint_storage_refused', CS10_pack_size),
        g.Guard('CS11_pack_media', g.Invariant('/source/checkpoint_storage/pack/media_type', 'is application/msgpack'), 'checkpoint_storage_refused', CS11_pack_media),
        g.Guard('CS12_pack_store', g.Invariant('/source/checkpoint_storage/pack/storage_instance_id', 'equals the actual Store'), 'checkpoint_storage_refused', CS12_pack_store),
        g.Guard('CS13_pack_domain_key', g.Invariant('/source/checkpoint_storage/pack/domain_key', 'equals the domain checkpoint key'), 'checkpoint_storage_refused', CS13_pack_domain_key),
        g.Guard('CS14_pack_partition', g.Invariant('/source/checkpoint_storage/pack/scope_partition', 'equals the value partition'), 'checkpoint_storage_refused', CS14_pack_partition),
        g.Guard('CS15_pack_event_type', g.Invariant('/source/checkpoint_storage/pack/event_type', 'equals the family'), 'checkpoint_storage_refused', CS15_pack_event_type),
    ])

    def check(value):
        table.require('CS09_pack_key', value, context)
        table.require('CS10_pack_size', value, context)
        table.require('CS11_pack_media', value, context)
        table.require('CS12_pack_store', value, context)
        table.require('CS13_pack_domain_key', value, context)
        table.require('CS14_pack_partition', value, context)
        table.require('CS15_pack_event_type', value, context)
        return True
    return g.Case(table, check, context)
