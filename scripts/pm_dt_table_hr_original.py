"""DT guard table hr_original: historical_read: the authenticated retained original and its envelope.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('prepared_digest', 'original_prepared_digest', 'completed_digest', 'original_completed_digest', 'event_digest', 'original_event_digest', 'event_schema_errors')


def HR09_original_prepared(value, context):
    return 'unavailable' if value['prepared_digest'] != value['original_prepared_digest'] else None


def HR10_original_completed(value, context):
    return 'unavailable' if value['completed_digest'] != value['original_completed_digest'] else None


def HR11_original_event(value, context):
    return 'unavailable' if value['event_digest'] != value['original_event_digest'] else None


def HR12_event_schema(value, context):
    return 'unavailable' if value['event_schema_errors'] != 0 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('HR09_original_prepared', g.Invariant('/context/authenticated_original/prepared', 'source bytes equal the prepared stage bytes'), 'unavailable', HR09_original_prepared),
        g.Guard('HR10_original_completed', g.Invariant('/context/authenticated_original/completed', 'source bytes equal the completed stage bytes'), 'unavailable', HR10_original_completed),
        g.Guard('HR11_original_event', g.Invariant('/context/authenticated_original/event', 'canonical bytes equal the event'), 'unavailable', HR11_original_event),
        g.Guard('HR12_event_schema', g.Invariant('/event', 'the EventRecord schema reports no error'), 'unavailable', HR12_event_schema),
    ])

    def check(value):
        table.require('HR09_original_prepared', value, context)
        table.require('HR10_original_completed', value, context)
        table.require('HR11_original_event', value, context)
        table.require('HR12_event_schema', value, context)
        return True
    return g.Case(table, check, context)
