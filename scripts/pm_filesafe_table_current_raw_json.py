import pm_guard_isolation as g

FIELDS = ('reason',)


def CR01_integer_token(value, context):
    return 'current_raw_number' if value['reason'] == 'integer_token' else None


def CR02_json_syntax(value, context):
    return 'current_raw_number' if value['reason'] == 'json_syntax' else None


def CR03_other(value, context):
    return 'current_raw_number' if value['reason'] is not None and value['reason'] not in ('integer_token', 'json_syntax') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CR01_integer_token', g.Invariant('/', 'every integer token is 0 or -?[1-9][0-9]* (no -0, no plus)'), 'current_raw_number', CR01_integer_token),
        g.Guard('CR02_json_syntax', g.Invariant('/', 'the text is JSON (no leading zero, no bare word)'), 'current_raw_number', CR02_json_syntax),
        g.Guard('CR03_other', g.Invariant('/', 'no non-finite number, duplicate key or lone surrogate'), 'current_raw_number', CR03_other),
    ])

    def check(value):
        table.require('CR01_integer_token', value, context)
        table.require('CR02_json_syntax', value, context)
        table.require('CR03_other', value, context)
        return True
    return g.Case(table, check, context)
