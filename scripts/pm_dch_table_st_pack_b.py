"""DCH guard table st_pack_b: stop resolve_value: computer/thread copies and pack custody flags.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('pack_computer_id', 'body_computer_id', 'pack_thread_id', 'body_thread_id', 'authorized', 'hold_access_allowed', 'bytes_durable', 'index_durable', 'readback_verified')


def SV20_computer_copy(value, context):
    return 'stop_value_unavailable' if value['pack_computer_id'] != value['body_computer_id'] else None


def SV21_thread_copy(value, context):
    return 'stop_value_unavailable' if value['pack_thread_id'] != value['body_thread_id'] else None


def SV22_authorized(value, context):
    return 'stop_value_unavailable' if value['authorized'] is not True else None


def SV23_hold_access(value, context):
    return 'stop_value_unavailable' if value['hold_access_allowed'] is not True else None


def SV24_bytes_durable(value, context):
    return 'stop_value_unavailable' if value['bytes_durable'] is not True else None


def SV25_index_durable(value, context):
    return 'stop_value_unavailable' if value['index_durable'] is not True else None


def SV26_readback(value, context):
    return 'stop_value_unavailable' if value['readback_verified'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SV20_computer_copy', g.Invariant('/source/computer_id', 'equals the body computer_id'), 'stop_value_unavailable', SV20_computer_copy),
        g.Guard('SV21_thread_copy', g.Invariant('/source/thread_id', 'equals the body thread_id'), 'stop_value_unavailable', SV21_thread_copy),
        g.Guard('SV22_authorized', g.Invariant('/source/authorized', 'is exactly true'), 'stop_value_unavailable', SV22_authorized),
        g.Guard('SV23_hold_access', g.Invariant('/source/hold_access_allowed', 'is exactly true'), 'stop_value_unavailable', SV23_hold_access),
        g.Guard('SV24_bytes_durable', g.Invariant('/source/bytes_durable', 'is exactly true'), 'stop_value_unavailable', SV24_bytes_durable),
        g.Guard('SV25_index_durable', g.Invariant('/source/index_durable', 'is exactly true'), 'stop_value_unavailable', SV25_index_durable),
        g.Guard('SV26_readback', g.Invariant('/source/readback_verified', 'is exactly true'), 'stop_value_unavailable', SV26_readback),
    ])

    def check(value):
        table.require('SV20_computer_copy', value, context)
        table.require('SV21_thread_copy', value, context)
        table.require('SV22_authorized', value, context)
        table.require('SV23_hold_access', value, context)
        table.require('SV24_bytes_durable', value, context)
        table.require('SV25_index_durable', value, context)
        table.require('SV26_readback', value, context)
        return True
    return g.Case(table, check, context)
