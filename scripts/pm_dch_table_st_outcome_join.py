"""DCH guard table st_outcome_join: stop outcome_valid: saved result joins to the original request and decision.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('value_store', 'request_store', 'stop_request_event_id', 'request_event_id', 'join_mismatches', 'outcome', 'decided', 'outcome_at_utc', 'observed_outcome_at_utc', 'key', 'expected_key')


def OC10_store(value, context):
    return 'stop_outcome_refused' if value['value_store'] != value['request_store'] else None


def OC11_request_event(value, context):
    return 'stop_outcome_refused' if value['stop_request_event_id'] != value['request_event_id'] else None


def OC12_join_copies(value, context):
    return 'stop_outcome_refused' if value['join_mismatches'] != [] else None


def OC13_decided_outcome(value, context):
    return 'stop_outcome_refused' if value['outcome'] != value['decided'] else None


def OC14_outcome_time(value, context):
    return 'stop_outcome_refused' if value['outcome_at_utc'] != value['observed_outcome_at_utc'] else None


def OC15_outcome_key(value, context):
    return 'stop_outcome_refused' if value['key'] != value['expected_key'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('OC10_store', g.Invariant('/value/storage_instance_id', 'equals the request Store'), 'stop_outcome_refused', OC10_store),
        g.Guard('OC11_request_event', g.Invariant('/value/stop_request_event_id', 'equals the request event id'), 'stop_outcome_refused', OC11_request_event),
        g.Guard('OC12_join_copies', g.Invariant('/value', 'scope/computer/thread/turn/target work equal the request'), 'stop_outcome_refused', OC12_join_copies),
        g.Guard('OC13_decided_outcome', g.Invariant('/value/outcome', 'equals the decided cancelled/timeout outcome'), 'stop_outcome_refused', OC13_decided_outcome),
        g.Guard('OC14_outcome_time', g.Invariant('/value/outcome_at_utc', 'equals the observed decision time'), 'stop_outcome_refused', OC14_outcome_time),
        g.Guard('OC15_outcome_key', g.Invariant('/key', 'equals the outcome key of the saved value Store and request event id'), 'stop_outcome_refused', OC15_outcome_key),
    ])

    def check(value):
        table.require('OC10_store', value, context)
        table.require('OC11_request_event', value, context)
        table.require('OC12_join_copies', value, context)
        table.require('OC13_decided_outcome', value, context)
        table.require('OC14_outcome_time', value, context)
        table.require('OC15_outcome_key', value, context)
        return True
    return g.Case(table, check, context)
