"""DC guard table transition_run: Run families: run lineage, terminal state and definition revision.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('run_thread', 'thread_id', 'run_kind', 'kind', 'run_collaboration', 'collaboration_id', 'run_status', 'expected_revision', 'run_definition_revision', 'config_previous_revision', 'config_latest_revision')


def TR11_run_thread(value, context):
    return 'conflict:lineage_mismatch' if value['run_thread'] != value['thread_id'] else None


def TR12_run_kind(value, context):
    return 'conflict:lineage_mismatch' if value['run_kind'] != value['kind'] else None


def TR13_run_collaboration(value, context):
    return 'conflict:lineage_mismatch' if value['run_collaboration'] != value['collaboration_id'] else None


def TR14_not_terminal(value, context):
    return 'conflict:already_terminal' if value['run_status'] in ('completed', 'cancelled', 'failed') else None


def TR15_run_revision(value, context):
    return 'conflict:stale_definition_revision' if value['expected_revision'] != value['run_definition_revision'] else None


def TR16_latest_revision(value, context):
    return 'conflict:stale_definition_revision' if value['config_previous_revision'] != value['config_latest_revision'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR11_run_thread', g.Invariant('/thread_id', 'equals the run thread'), 'conflict:lineage_mismatch', TR11_run_thread),
        g.Guard('TR12_run_kind', g.Invariant('/kind', 'equals the run kind'), 'conflict:lineage_mismatch', TR12_run_kind),
        g.Guard('TR13_run_collaboration', g.Invariant('/collaboration_id', 'equals the run collaboration'), 'conflict:lineage_mismatch', TR13_run_collaboration),
        g.Guard('TR14_not_terminal', g.Invariant('/collaboration_run_id', 'the run is not terminal'), 'conflict:already_terminal', TR14_not_terminal),
        g.Guard('TR15_run_revision', g.Invariant('/definition_revision', 'the expected revision equals the run definition revision'), 'conflict:stale_definition_revision', TR15_run_revision),
        g.Guard('TR16_latest_revision', g.Invariant('/previous_definition_revision', 'configuration_changed: equals the latest definition revision'), 'conflict:stale_definition_revision', TR16_latest_revision),
    ])

    def check(value):
        table.require('TR11_run_thread', value, context)
        table.require('TR12_run_kind', value, context)
        table.require('TR13_run_collaboration', value, context)
        table.require('TR14_not_terminal', value, context)
        table.require('TR15_run_revision', value, context)
        table.require('TR16_latest_revision', value, context)
        return True
    return g.Case(table, check, context)
