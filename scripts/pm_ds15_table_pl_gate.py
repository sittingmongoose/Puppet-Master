import pm_guard_isolation as g

FIELDS = ('owner_command_authorized', 'unsafe_refs', 'context_scope', 'payload_scope', 'envelope_project_id', 'scope_project_id', 'payload_run_id', 'envelope_run_id', 'has_browser_session', 'session_security_class')


def PL01_owner_authorized(value, context):
    return 'transition_refused' if not value['owner_command_authorized'] else None


def PL02_safe_refs(value, context):
    return 'transition_refused' if value['unsafe_refs'] != [] else None


def PL03_scope(value, context):
    return 'transition_refused' if value['context_scope'] != value['payload_scope'] else None


def PL04_envelope_project(value, context):
    return 'transition_refused' if value['envelope_project_id'] != value['scope_project_id'] else None


def PL05_run(value, context):
    return 'transition_refused' if value['payload_run_id'] != value['envelope_run_id'] else None


def PL06_session_class(value, context):
    return 'transition_refused' if value['has_browser_session'] is True and value['session_security_class'] != 'ordinary' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('PL01_owner_authorized', g.Invariant('/owner_command_authorized', 'the owner command is authorized'), 'transition_refused', PL01_owner_authorized),
        g.Guard('PL02_safe_refs', g.Invariant('/unsafe_refs', 'no payload string is an absolute path, token-shaped or a forbidden ref'), 'transition_refused', PL02_safe_refs),
        g.Guard('PL03_scope', g.Invariant('/context_scope', 'the context scope equals the payload scope'), 'transition_refused', PL03_scope),
        g.Guard('PL04_envelope_project', g.Invariant('/envelope_project_id', 'the context envelope project equals the scope project'), 'transition_refused', PL04_envelope_project),
        g.Guard('PL05_run', g.Invariant('/envelope_run_id', 'the payload run_id equals the context envelope run'), 'transition_refused', PL05_run),
        g.Guard('PL06_session_class', g.Invariant('/session_security_class', 'a BrowserSession payload has an ordinary session'), 'transition_refused', PL06_session_class),
    ])

    def check(value):
        table.require('PL01_owner_authorized', value, context)
        table.require('PL02_safe_refs', value, context)
        table.require('PL03_scope', value, context)
        table.require('PL04_envelope_project', value, context)
        table.require('PL05_run', value, context)
        table.require('PL06_session_class', value, context)
        return True
    return g.Case(table, check, context)
