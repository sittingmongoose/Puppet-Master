"""DX guard table remediation_records: remediation.*: lineage records for parent, child and root.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('child', 'parent', 'parent_record', 'child_record', 'root', 'root_record')


def RM01_child_not_parent(value, context):
    return 'child is parent' if value['child'] == value['parent'] else None


def RM02_parent_record(value, context):
    return 'parent attempt record' if value['parent'] != value['parent_record'] else None


def RM03_child_record(value, context):
    return 'child attempt record' if value['child'] != value['child_record'] else None


def RM04_root_record(value, context):
    return 'remediation root record' if value['root'] != value['root_record'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RM01_child_not_parent', g.Invariant('/payload/child_attempt_id', 'differs from the parent attempt'), 'child is parent', RM01_child_not_parent),
        g.Guard('RM02_parent_record', g.Invariant('/records/parent_attempt/body/attempt_id', 'equals the payload parent attempt'), 'parent attempt record', RM02_parent_record),
        g.Guard('RM03_child_record', g.Invariant('/records/child_attempt/body/attempt_id', 'equals the payload child attempt'), 'child attempt record', RM03_child_record),
        g.Guard('RM04_root_record', g.Invariant('/records/root/body/remediation_root_id', 'equals the payload root'), 'remediation root record', RM04_root_record),
    ])

    def check(value):
        table.require('RM01_child_not_parent', value, context)
        table.require('RM02_parent_record', value, context)
        table.require('RM03_child_record', value, context)
        table.require('RM04_root_record', value, context)
        return True
    return g.Case(table, check, context)
