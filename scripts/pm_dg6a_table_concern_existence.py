import pm_guard_isolation as g

FIELDS = ('subject_bool', 'key_bool', 'prepared', 'subject_absent', 'key_absent')


def CE01_subject_bool(value, context):
    return 'invalid concern existence proof' if value['subject_bool'] is not True else None


def CE02_key_bool(value, context):
    return 'invalid concern existence proof' if value['subject_bool'] is True and value['key_bool'] is not True else None


def CE03_subject_absent(value, context):
    return 'existing concern cannot be recreated' if value['prepared'] is True and value['subject_absent'] is not True else None


def CE04_key_absent(value, context):
    return 'existing concern cannot be recreated' if value['prepared'] is True and value['subject_absent'] is True and value['key_absent'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CE01_subject_bool', g.Invariant('/subject_bool', 'subject_already_active is an exact boolean'), 'invalid concern existence proof', CE01_subject_bool),
        g.Guard('CE02_key_bool', g.Invariant('/key_bool', 'concern_key_exists is an exact boolean'), 'invalid concern existence proof', CE02_key_bool),
        g.Guard('CE03_subject_absent', g.Invariant('/subject_absent', 'a prepared creation has no active subject concern (exactly false)'), 'existing concern cannot be recreated', CE03_subject_absent),
        g.Guard('CE04_key_absent', g.Invariant('/key_absent', 'a prepared creation has no existing concern key (exactly false)'), 'existing concern cannot be recreated', CE04_key_absent),
    ])

    def check(value):
        table.require('CE01_subject_bool', value, context)
        table.require('CE02_key_bool', value, context)
        table.require('CE03_subject_absent', value, context)
        table.require('CE04_key_absent', value, context)
        return True
    return g.Case(table, check, context)
