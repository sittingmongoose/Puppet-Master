"""DCH guard table hr_flags: historical_read_valid: original edition schemas and current access custody.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('envelope_valid', 'payload_valid', 'retained', 'authorized', 'hold_access_allowed', 'deleted', 'event_withdrawn')


def HR02_envelope_schema(value, context):
    return 'history_refused' if value['envelope_valid'] is not True else None


def HR03_payload_schema(value, context):
    return 'history_refused' if value['payload_valid'] is not True else None


def HR04_retained(value, context):
    return 'history_refused' if value['retained'] is not True else None


def HR05_authorized(value, context):
    return 'history_refused' if value['authorized'] is not True else None


def HR06_hold_access(value, context):
    return 'history_refused' if value['hold_access_allowed'] is not True else None


def HR07_not_deleted(value, context):
    return 'history_refused' if value['deleted'] is not False else None


def HR08_not_withdrawn(value, context):
    return 'history_refused' if value['event_withdrawn'] is not False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('HR02_envelope_schema', g.Invariant('/record', 'satisfies the original EventRecord edition'), 'history_refused', HR02_envelope_schema),
        g.Guard('HR03_payload_schema', g.Invariant('/record/payload', 'the resolved body satisfies the original payload edition'), 'history_refused', HR03_payload_schema),
        g.Guard('HR04_retained', g.Invariant('/witness/retained', 'is exactly true'), 'history_refused', HR04_retained),
        g.Guard('HR05_authorized', g.Invariant('/witness/authorized', 'is exactly true'), 'history_refused', HR05_authorized),
        g.Guard('HR06_hold_access', g.Invariant('/witness/hold_access_allowed', 'is exactly true'), 'history_refused', HR06_hold_access),
        g.Guard('HR07_not_deleted', g.Invariant('/witness/deleted', 'is exactly false'), 'history_refused', HR07_not_deleted),
        g.Guard('HR08_not_withdrawn', g.Invariant('/witness/event_withdrawn', 'is exactly false'), 'history_refused', HR08_not_withdrawn),
    ])

    def check(value):
        table.require('HR02_envelope_schema', value, context)
        table.require('HR03_payload_schema', value, context)
        table.require('HR04_retained', value, context)
        table.require('HR05_authorized', value, context)
        table.require('HR06_hold_access', value, context)
        table.require('HR07_not_deleted', value, context)
        table.require('HR08_not_withdrawn', value, context)
        return True
    return g.Case(table, check, context)
