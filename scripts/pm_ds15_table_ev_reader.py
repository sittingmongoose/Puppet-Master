"""DS15 guard table ev_reader: Installed operating reader.

Method B guard rows (scripts/pm_guard_isolation.py) for the DS15 checkers. Each predicate reads one
observation the checker derives from the complete boundary input (recomputed hashes and identities,
canonical-byte sizes, resolved records, presence, typed copies). Predicates never recompute, repair or
call helpers. The checkers refuse only through these rows, in this order
(pm-ds15-event-contracts.py:refusal), and check that every factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-ds15-table-generate.py; edit the row spec there.
"""
import pm_guard_isolation as g

FIELDS = ('reader_withdrawn', 'reader_installed', 'consumer')


def RD01_reader_current(value, context):
    return 'reader_unavailable' if value['reader_withdrawn'] else None


def RD02_reader_version(value, context):
    return 'reader_unavailable' if value['reader_installed'] != value['consumer'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RD01_reader_current', g.Invariant('/reader_withdrawn', 'the reader is not withdrawn'), 'reader_unavailable', RD01_reader_current),
        g.Guard('RD02_reader_version', g.Invariant('/reader_installed', 'the installed reader is the family consumer'), 'reader_unavailable', RD02_reader_version),
    ])

    def check(value):
        table.require('RD01_reader_current', value, context)
        table.require('RD02_reader_version', value, context)
        return True
    return g.Case(table, check, context)
