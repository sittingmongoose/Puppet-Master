"""DCH guard table rt_semantic: retry_outcome: caller-semantic commitment (CV-317 projection, Storage metadata excluded).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('retained_differences', 'commitment_error', 'commitments_equal')


def RT12_retained_semantic_fields(value, context):
    return 'conflict' if value['retained_differences'] != [] else None


def RT13_commitment_encodable(value, context):
    return 'invalid_input_type' if value['retained_differences'] == [] and value['commitment_error'] is not None else None


def RT14_semantic_commitment(value, context):
    return 'conflict' if value['retained_differences'] == [] and value['commitment_error'] is None and value['commitments_equal'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RT12_retained_semantic_fields', g.Invariant('/retry/<semantic fields>', 'a retained-recipe original and the retry agree on every semantic field'), 'conflict', RT12_retained_semantic_fields),
        g.Guard('RT13_commitment_encodable', g.Invariant('/retry/<semantic fields>', 'both semantic projections have a JCS encoding'), 'invalid_input_type', RT13_commitment_encodable),
        g.Guard('RT14_semantic_commitment', g.Invariant('/retry/<semantic fields>', 'the retry semantic commitment equals the original'), 'conflict', RT14_semantic_commitment),
    ])

    def check(value):
        table.require('RT12_retained_semantic_fields', value, context)
        table.require('RT13_commitment_encodable', value, context)
        table.require('RT14_semantic_commitment', value, context)
        return True
    return g.Case(table, check, context)
