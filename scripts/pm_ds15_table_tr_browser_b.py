import pm_guard_isolation as g

FIELDS = ('chip_id', 'payload_chip_id', 'chip_thread_id', 'payload_thread_id', 'attachment_type', 'payload_attachment_type', 'source_ref', 'payload_source_ref', 'chip_committed', 'chip_status', 'payload_capture_status', 'provenance_ref', 'payload_provenance_ref')


def TB05_chip(value, context):
    return 'transition_refused' if value['chip_id'] != value['payload_chip_id'] else None


def TB06_chip_thread(value, context):
    return 'transition_refused' if value['chip_thread_id'] != value['payload_thread_id'] else None


def TB07_attachment(value, context):
    return 'transition_refused' if value['attachment_type'] != value['payload_attachment_type'] else None


def TB08_source(value, context):
    return 'transition_refused' if value['source_ref'] != value['payload_source_ref'] else None


def TB09_committed(value, context):
    return 'transition_refused' if not value['chip_committed'] else None


def TB10_status(value, context):
    return 'transition_refused' if value['chip_status'] != value['payload_capture_status'] else None


def TB11_provenance(value, context):
    return 'transition_refused' if value['provenance_ref'] != value['payload_provenance_ref'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TB05_chip', g.Invariant('/chip_id', 'the chip is the payload chip'), 'transition_refused', TB05_chip),
        g.Guard('TB06_chip_thread', g.Invariant('/chip_thread_id', 'the chip thread is the payload thread'), 'transition_refused', TB06_chip_thread),
        g.Guard('TB07_attachment', g.Invariant('/attachment_type', 'the chip attachment type is the payload type'), 'transition_refused', TB07_attachment),
        g.Guard('TB08_source', g.Invariant('/source_ref', 'the chip source is the payload source'), 'transition_refused', TB08_source),
        g.Guard('TB09_committed', g.Invariant('/chip_committed', 'the chip is committed'), 'transition_refused', TB09_committed),
        g.Guard('TB10_status', g.Invariant('/chip_status', 'the chip status is the payload capture status'), 'transition_refused', TB10_status),
        g.Guard('TB11_provenance', g.Invariant('/provenance_ref', 'the chip provenance is the payload provenance'), 'transition_refused', TB11_provenance),
    ])

    def check(value):
        table.require('TB05_chip', value, context)
        table.require('TB06_chip_thread', value, context)
        table.require('TB07_attachment', value, context)
        table.require('TB08_source', value, context)
        table.require('TB09_committed', value, context)
        table.require('TB10_status', value, context)
        table.require('TB11_provenance', value, context)
        return True
    return g.Case(table, check, context)
