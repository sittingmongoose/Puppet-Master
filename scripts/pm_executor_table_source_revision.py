"""DX guard table source_revision: Capture source records: exact revision and its expected owner read.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('revision_type', 'revision', 'expected_type', 'revision_canonical', 'expected_canonical')


def RV01_revision_type(value, context):
    return 'source revision' if value['revision_type'] != 'int' else None


def RV02_revision_nonnegative(value, context):
    return 'source revision' if value['revision_type'] == 'int' and value['revision'] < 0 else None


def RV03_expected_type(value, context):
    return 'source revision' if value['revision_type'] == 'int' and value['expected_type'] != 'int' else None


def RV04_revision_join(value, context):
    return 'source revision' if value['revision_type'] == 'int' and value['expected_type'] == 'int' and value['revision_canonical'] != value['expected_canonical'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RV01_revision_type', g.Invariant('/records/*/revision', 'is an integer'), 'source revision', RV01_revision_type),
        g.Guard('RV02_revision_nonnegative', g.Invariant('/records/*/revision', 'an integer revision is not negative'), 'source revision', RV02_revision_nonnegative),
        g.Guard('RV03_expected_type', g.Invariant('/expected_revisions/*', 'is an integer (for an integer revision)'), 'source revision', RV03_expected_type),
        g.Guard('RV04_revision_join', g.Invariant('/records/*/revision', 'equals the expected revision by exact typed value'), 'source revision', RV04_revision_join),
    ])

    def check(value):
        table.require('RV01_revision_type', value, context)
        table.require('RV02_revision_nonnegative', value, context)
        table.require('RV03_expected_type', value, context)
        table.require('RV04_revision_join', value, context)
        return True
    return g.Case(table, check, context)
