def table_order_errors(root=ROOT):
    """Each factory's check() requires its rows in exactly the table order."""
    errors = []
    for path in sorted((root / "scripts").glob("pm_collab_table_*.py")):
        phase = path.stem[len("pm_collab_table_"):]
        tree = ast.parse(read_owner("scripts/" + path.name, root))
