def envelope_rejection(event_type: str, record: dict[str, Any], storage_instance_id: str, recovery_epoch: int, root: Path = ROOT, payload_store: dict[str, str] | None = None, current_writer: bool = True, current_input: bool = True) -> str | None:
    """First failing EventRecord join of CV-460 rule 7, in the order the fixtures name them.

    current_writer=False skips the current-writer replay rule; current_input=False (the SP-1101 frozen v1 reading of a
    retained original) also skips CV-1100's current integer-token grammar (EV18, EV19, PN01). CV-1101 runs on both.
    """
    code = refusal("envelope_schema", {"record_schema_valid": validator(load(EVENT_RECORD_PATH, root)["$id"], "", root).is_valid(record)})
    if code:
        return code
    code = refusal("envelope_datetime", {"occurred_at_valid": shared_timestamp(record["occurred_at_utc"], EVENT_RECORD),
                                         "observed_at_valid": shared_timestamp(record["observed_at_utc"], STORAGE_UTC_Z),
                                         "persisted_at_valid": shared_timestamp(record["persisted_at_utc"], STORAGE_UTC_Z)})
    if code:
        return code
    if current_input:
        def exact(value, check):
            try:
                check(value)
            except Refusal:
                return False
            return True
        code = refusal("envelope_numbers", {"sequence_id_exact": exact(record["sequence_id"], storage_uint64),
                                            "producer_sequence_exact": record["producer_sequence_id"] is None or exact(record["producer_sequence_id"], lambda v: current_integer(v, minimum=0))})
        if code:
            return code
    code = refusal("envelope_family", {"record_event_type": record["event_type"], "boundary_event_type": event_type})
    if code:
        return code
    p, error = resolved_payload(record, payload_store)
    if error:
        return error
    if p is not None:
        code = refusal("envelope_scope", {"record_scope_kind": record["scope_kind"], "payload_scope_kind": p.get("scope_kind"),
                                          "record_project_id": record["project_id"], "payload_project_id": p.get("project_id"),
                                          "redaction_profile": record["redaction_profile"]})
        if code:
            return code
        # The current-writer replay rule is its own phase: a historical original never reaches it.
        if current_writer:
            code = refusal("envelope_replay", {"replay_policy": record["replay_policy"]})
            if code:
                return code
        code = refusal("envelope_joins", {
            "record_node_id": record["node_id"],
            "record_attempt_id": record["attempt_id"], "expected_attempt_id": p.get("attempt_id") if event_type in ATTEMPT_FAMILIES else None,
            "record_thread_id": record["thread_id"], "payload_thread_id": p.get("thread_id"),
            "record_run_id": record["run_id"], "payload_run_id": p.get("collaboration_run_id"),
            "record_idempotency_key": record["idempotency_key"], "payload_idempotency_key": p.get("idempotency_key"),
            "record_payload_schema_id": record["payload_schema_id"],
            "expected_payload_schema_id": f"pm.collaboration_event.{TOKEN[event_type]}." + ("v1" if p["scope_kind"] == "project" else "application.v1"),
            "record_occurred_at_utc": record["occurred_at_utc"], "payload_family_timestamp": p.get(FAMILY_TS[event_type])})
