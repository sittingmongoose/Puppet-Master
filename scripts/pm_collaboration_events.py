_TABLE_ROWS: dict[str, list] = {}
# Set to a list only by the guard-table suite builder (scripts/pm_collab_guard_suites.py); never by a checker path.
RECORDER = None


def table_module(phase):
    return importlib.import_module("pm_collab_table_" + phase)


def table_rows(phase):
    """The phase's (row, predicate, context) list in declared table order."""
    rows = _TABLE_ROWS.get(phase)
    if rows is None:
        built = table_module(phase).case(None)
        rows = _TABLE_ROWS[phase] = [(name, guard.predicate, built.context) for name, guard in built.table.guards.items()]
    return rows


def table_refusals(phase, facts, first=True):
    """Refusing (row, code) pairs of one phase in table order; the first only unless first=False.

    The observation passed to the rows holds exactly the module's FIELDS.
    """
    observed = {k: facts[k] for k in table_module(phase).FIELDS}
    found = []
    for name, predicate, context in table_rows(phase):
        code = predicate(observed, context)
        if code is not None:
            found.append((name, code))
            if first:
                break
    if RECORDER is not None:
        RECORDER.append((phase, copy.deepcopy(observed), found[0] if found else None))
    return found


def refusal(phase, facts):
    """The first refusing row's code, or None."""
    found = table_refusals(phase, facts)
    return found[0][1] if found else None


def collect(fails, phase, facts, detail=None):
    """Integrity collectors: append one failure per distinct refusing code, in table order."""
    seen = []
    for _, code in table_refusals(phase, facts, first=False):
        if code not in seen:
            seen.append(code)
            fails.append(dict({"check": code}, **(detail or {})))
    return seen


