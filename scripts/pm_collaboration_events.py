class Reducer:

    def __init__(self, admitted: list[str], storage_instance_id: str, recovery_epoch: int):
        self.admitted = set(admitted)
        self.siid = storage_instance_id
        self.epoch = recovery_epoch
        self.dedupe: dict[tuple[str, str, str], str] = {}
        self.defs: dict[tuple[str, str], dict[str, Any]] = {}
        self.runs: dict[tuple[str, str], dict[str, Any]] = {}

    def commit(self, et: str, p: dict[str, Any], sp: str) -> str:
        coll = (sp, p['collaboration_id'])
        rkey = (sp, p['collaboration_run_id'])
        if et == 'collaboration.created':
            self.defs[coll] = {'latest': 1, 'revs': {1}, 'kind': p['kind'], 'thread': p['thread_id'], 'required': set(p['required_slot_ids'])}
            return 'appended'
        if et == 'collaboration.configuration_changed':
            d = self.defs.get(coll)
            run = self.runs.get(rkey)
            if p['change_source'] == 'start_commit':
                pass
            d['required'] = set(p['required_slot_ids'])
            d['latest'] = p['definition_revision']
            d['revs'].add(p['definition_revision'])
            if run is not None and p['change_source'] == 'reconfigure':
                run['required'] = set(p['required_slot_ids'])
                run['def_rev'] = p['definition_revision']
                ck = set(p['change_kinds'])
                if 'add_participant' in ck:
                    for s in p['affected_slot_ids']:
                        if s not in run['roster']:
                            run['roster'].append(s)
                if 'remove_participant' in ck:
                    run['removed'] |= set(p['affected_slot_ids'])
                if 'waive_participant' in ck:
                    run['waivers'] |= set(p['affected_slot_ids'])
                if p['accept_stale_target']:
                    run['stale_accepted'] = True
            return 'appended'
        if et == 'collaboration.started':
            d = self.defs.get(coll)
            self.runs[rkey] = {'status': 'active', 'seq': 1, 'def_rev': p['definition_revision'], 'kind': p['kind'], 'thread': p['thread_id'], 'coll': p['collaboration_id'], 'roster': list(p['participant_slot_ids']), 'removed': set(), 'waivers': set(), 'target_hashes': list(p.get('target_hashes', [])), 'slots': {}, 'attempts': {}, 'last_msg': 0, 'msgs': set(), 'artifacts': set(), 'proposals': {}, 'votes': {}, 'synthesized': False, 'synthesized_plan_ref': None, 'synthesized_plan_version': None, 'findings': {}, 'finalized': None, 'stale_accepted': False, 'required': set(d['required'])}
            return 'appended'
        run = self.runs.get(rkey)
        short = et.split('.', 1)[1]
        handler = getattr(self, 'r_' + short)
        return handler(run, p)

    def slot(self, run, slot_id):
        return run['slots'].setdefault(slot_id, {'current_rev': 1, 'current_attempt': None, 'latest_outcome': None, 'no_attempt': {}, 'role': None})

    def open_attempts(self, run):
        return any((a['outcome'] is None for a in run['attempts'].values()))

    def r_paused(self, run, p):
        run['status'], run['seq'] = ('paused', p['lifecycle_seq'])
        return 'appended'

    def r_resumed(self, run, p):
        run['status'], run['seq'] = ('active', p['lifecycle_seq'])
        return 'appended'

    def r_cancelled(self, run, p):
        run['status'], run['seq'] = ('cancelled', p['lifecycle_seq'])
        return 'appended'

    def r_failed(self, run, p):
        run['status'], run['seq'] = ('failed', p['lifecycle_seq'])
        return 'appended'

    def r_completed(self, run, p):
        allowed = ('active', 'paused') if p['completion_trigger'] == 'chat_room_end' else ('active',)
        for s in p['required_slot_ids']:
            pass
        run['status'], run['seq'] = ('completed', p['lifecycle_seq'])
        return 'appended'

    def r_participant_started(self, run, p):
        s = p['participant_slot_id']
        st = self.slot(run, s)
        run['attempts'][p['attempt_id']] = {'slot': s, 'rev': p['assignment_revision'], 'outcome': None, 'role': p['additive_role_kind']}
        st.update(current_rev=p['assignment_revision'], current_attempt=p['attempt_id'], role=p['additive_role_kind'])
        self.recount(run)
        return 'appended'

    def r_participant_completed(self, run, p):
        s = p['participant_slot_id']
        a = p.get('attempt_id')
        if a is not None:
            att = run['attempts'].get(a)
        if a is not None:
            run['attempts'][a]['outcome'] = p['outcome']
        else:
            self.slot(run, s)['no_attempt'][p['assignment_revision']] = p['outcome']
        self.slot(run, s)['latest_outcome'] = p['outcome']
        self.recount(run)
        return 'appended'

    def r_message_added(self, run, p):
        if p['sender_kind'] == 'participant':
            a = p.get('attempt_id')
        run['msgs'].add(p['collaboration_message_id'])
        run['last_msg'] = p['sequence']
        return 'appended'

    def r_artifact_added(self, run, p):
        run['artifacts'].add(p['artifact_version_ref'])
        return 'appended'

    def r_proposal_added(self, run, p):
        att = run['attempts'].get(p['attempt_id'])
        run['proposals'][p['proposal_id']] = {'support': 0, 'oppose': 0, 'abstain': 0}
        return 'appended'

    def r_vote_added(self, run, p):
        att = run['attempts'].get(p['attempt_id'])
        st = self.slot(run, p['participant_slot_id'])
        run['votes'][p['vote_id']] = {'proposal': p['proposal_id'], 'slot': p['participant_slot_id'], 'attempt': p['attempt_id'], 'position': p['position']}
        self.recount(run)
        return 'appended'

    def recount(self, run):
        for t in run['proposals'].values():
            t.update(support=0, oppose=0, abstain=0)
        for v in run['votes'].values():
            att = run['attempts'][v['attempt']]
            if self.slot(run, v['slot'])['current_attempt'] == v['attempt'] and att['outcome'] in (None, 'completed'):
                run['proposals'][v['proposal']][v['position']] += 1

    def r_plan_synthesized(self, run, p):
        run['synthesized'] = True
        run['synthesized_plan_ref'] = 'assistant_plan:' + p['assistant_plan_id']
        run['synthesized_plan_version'] = p['plan_version']
        return 'appended'

    def r_finding_added(self, run, p):
        run['findings'][p['finding_id']] = {'disposition': None, 'target_hashes': p['target_hashes']}
        return 'appended'

    def r_finding_dispositioned(self, run, p):
        f = run['findings'].get(p['finding_id'])
        f['disposition'] = p['disposition']
        return 'appended'

    def r_artifact_finalized(self, run, p):
        run['finalized'] = p['artifact_version_ref']
        return 'appended'

    def final_state(self, sp: str, run_id: str) -> dict[str, Any]:
        run = self.runs[sp, run_id]
        return {'lifecycle_status': run['status'], 'lifecycle_seq': run['seq'], 'last_message_sequence': run['last_msg'], 'artifact_count': len(run['artifacts']), 'finalized_artifact_version_ref': run['finalized'], 'waived_slot_ids': sorted((s for s, st in run['slots'].items() if st['latest_outcome'] == 'explicitly_waived')), 'proposal_tallies': {k: dict(v) for k, v in run['proposals'].items()}, 'findings': {k: v['disposition'] for k, v in run['findings'].items()}}

    def apply(self, et, p, epoch=None):
        rejection = self.admission_rejection(et, p)
        if rejection is not None:
            return rejection
        result = self.commit(et, p, scope_partition(p))
        self.dedupe[scope_partition(p), et, p['idempotency_key']] = producer_digest(p)
        return result

    def admission_rejection(self, et, p):
        sp = scope_partition(p)
        key = (sp, et, p['idempotency_key'])
        code = refusal('transition_dedupe', {'recorded_digest': self.dedupe.get(key), 'producer_digest': producer_digest(p)})
        if code:
            return code
        if key in self.dedupe:
            return 'exact_retry'
        code = refusal('transition_admitted', {'family_admitted': et in self.admitted})
        if code:
            return code
        return self.transition_rejection(et, p, sp)

    def transition_rejection(self, et, p, sp):
        """Read-only admission predicates; effect application follows only an accepted decision.

        Dependent checks apply only in their actual domain: nonexistent owners, a wrong lineage
        or a terminal run never supplies a fabricated state to another family's rule. Each
        phase below is evaluated only on inputs that passed the phases before it.
        """
        coll = (sp, p['collaboration_id'])
        rkey = (sp, p['collaboration_run_id'])
        d = self.defs.get(coll)
        run = self.runs.get(rkey)
        if et == 'collaboration.created':
            return refusal('transition_created', {'definition_exists': d is not None})
        config = et == 'collaboration.configuration_changed'
        if et == 'collaboration.started' or config:
            code = refusal('transition_definition', {'definition_exists': d is not None,
                                                     'started_revision_recorded': p['definition_revision'] in d['revs'] if d is not None and not config else None})
            if code:
                return code
            code = refusal('transition_definition_lineage', {'definition_kind': d['kind'], 'kind': p['kind'], 'definition_thread': d['thread'], 'thread_id': p['thread_id']})
            if code:
                return code
            if not config or p['change_source'] == 'start_commit':
                return refusal('transition_start', {'run_exists': run is not None,
                                                    'start_previous_revision': p['previous_definition_revision'] if config else None,
                                                    'start_latest_revision': d['latest'] if config else None})
        code = refusal('transition_run_presence', {'run_exists': run is not None})
        if code:
            return code
        code = refusal('transition_run', {
            'run_thread': run['thread'], 'thread_id': p['thread_id'], 'run_kind': run['kind'], 'kind': p['kind'],
            'run_collaboration': run['coll'], 'collaboration_id': p['collaboration_id'], 'run_status': run['status'],
            'expected_revision': p['previous_definition_revision'] if config else p['definition_revision'], 'run_definition_revision': run['def_rev'],
            'config_previous_revision': p['previous_definition_revision'] if config else None, 'config_latest_revision': d['latest'] if config else None})
        if code:
            return code
        return self.family_rejection(et, p, run)

    def family_rejection(self, et, p, run):
        short = et.split('.', 1)[1]
        if short == 'configuration_changed':
            return None
        if short in ('paused', 'resumed', 'cancelled', 'failed', 'completed'):
            code = refusal('transition_lifecycle', {'short': short, 'completion_trigger': p.get('completion_trigger'), 'run_status': run['status'],
                                                    'lifecycle_seq': p['lifecycle_seq'], 'expected_lifecycle_seq': run['seq'] + 1,
                                                    'open_attempts': self.open_attempts(run) if short in ('cancelled', 'failed', 'completed') else None})
            if code or short != 'completed':
                return code
            return refusal('transition_completed', {
                'required_slot_ids': sorted(set(p['required_slot_ids'])), 'run_required_slot_ids': sorted(run['required']),
                'waived_slot_ids': sorted(set(p['waived_slot_ids'])),
                'run_waived_slot_ids': sorted(s for s, st in run['slots'].items() if st['latest_outcome'] == 'explicitly_waived'),
                'run_kind': run['kind'], 'completion_trigger': p['completion_trigger'],
                'required_outcomes': [run['slots'].get(s, {}).get('latest_outcome') for s in sorted(run['required'])],
                'synthesized': run['synthesized'], 'finalized_ref': run['finalized'], 'output_refs': p['output_refs'],
                'synthesized_plan_ref': run['synthesized_plan_ref']})
        if short in ('participant_started', 'proposal_added', 'vote_added', 'plan_synthesized', 'finding_added', 'finding_dispositioned', 'artifact_finalized'):
            code = refusal('transition_active', {'run_status': run['status']})
            if code:
                return code
        if short == 'participant_started':
            s = p['participant_slot_id']
            st = run['slots'].get(s, {'current_rev': 1})
            return refusal('transition_participant_started', {'slot_in_roster': s in run['roster'], 'slot_removed': s in run['removed'],
                                                              'attempt_known': p['attempt_id'] in run['attempts'],
                                                              'assignment_revision': p['assignment_revision'], 'slot_revision': st['current_rev']})
        if short == 'participant_completed':
            s = p['participant_slot_id']
            a = p.get('attempt_id')
            att = run['attempts'].get(a) if a is not None else None
            return refusal('transition_participant_completed', {
                'has_attempt': a is not None, 'attempt_known': att is not None, 'slot': s, 'assignment_revision': p['assignment_revision'],
                'attempt_slot': att['slot'] if att is not None else None, 'attempt_revision': att['rev'] if att is not None else None,
                'attempt_outcome': att['outcome'] if att is not None else None,
                'slot_in_roster': s in run['roster'] if a is None else None,
                'revision_closed': p['assignment_revision'] in run['slots'].get(s, {}).get('no_attempt', {}) if a is None else None,
                'outcome': p['outcome'], 'slot_waived': s in run['waivers']})
        if short == 'message_added':
            participant = p['sender_kind'] == 'participant'
            a = p.get('attempt_id') if participant else None
            att = run['attempts'].get(a) if a is not None else None
            return refusal('transition_message', {
                'message_known': p['collaboration_message_id'] in run['msgs'], 'sequence': p['sequence'], 'expected_sequence': run['last_msg'] + 1,
                'participant_sender': participant, 'sender_in_roster': p['sender_id'] in run['roster'] if participant else None,
                'has_attempt': a is not None, 'attempt_known': att is not None, 'attempt_slot': att['slot'] if att is not None else None,
                'sender_id': p['sender_id']})
        if short == 'artifact_added':
            return refusal('transition_artifact_added', {'artifact_known': p['artifact_version_ref'] in run['artifacts']})
        if short in ('proposal_added', 'vote_added'):
            att = run['attempts'].get(p['attempt_id'])
            matches = att is not None and att['slot'] == p['participant_slot_id']
            code = refusal('transition_contribution', {
                'short': short, 'proposal_known': p['proposal_id'] in run['proposals'], 'attempt_known': att is not None,
                'attempt_slot': att['slot'] if att is not None else None, 'slot': p['participant_slot_id'], 'attempt_matches': matches,
                'attempt_role': att['role'] if att is not None else None, 'attempt_id': p['attempt_id'],
                'slot_current_attempt': run['slots'][p['participant_slot_id']]['current_attempt'] if matches and short == 'vote_added' else None})
            if code or short == 'proposal_added':
                return code
            return refusal('transition_vote', {'attempt_outcome': att['outcome'], 'vote_known': p['vote_id'] in run['votes']})
        if short == 'plan_synthesized':
            return refusal('transition_synthesized', {'synthesized': run['synthesized']})
        if short == 'finding_added':
            return refusal('transition_finding_added', {'target_hashes': p['target_hashes'], 'run_target_hashes': run['target_hashes'],
                                                        'originating_reviewer_ids': p['originating_reviewer_ids'], 'roster': run['roster'],
                                                        'finding_known': p['finding_id'] in run['findings']})
        if short == 'finding_dispositioned':
            finding = run['findings'].get(p['finding_id'])
            return refusal('transition_finding_dispositioned', {'finding_known': finding is not None,
                                                                'finding_disposition': finding['disposition'] if finding is not None else None,
                                                                'target_hashes': p['target_hashes'],
                                                                'finding_target_hashes': finding['target_hashes'] if finding is not None else None})
        if short == 'artifact_finalized':
            return refusal('transition_finalized', {
                'finalized_ref': run['finalized'], 'open_findings': sum(1 for f in run['findings'].values() if f['disposition'] is None),
                'artifact_known': p['artifact_version_ref'] in run['artifacts'], 'target_hashes': p['target_hashes'], 'run_target_hashes': run['target_hashes'],
                'completed_reviewer_count': p['completed_reviewer_count'], 'requested_reviewer_count': p['requested_reviewer_count'],
                'partial_coverage_accepted': p['partial_coverage_accepted'], 'run_waiver_count': len(run['waivers']),
                'stale_target_accepted': p['stale_target_accepted'], 'run_stale_accepted': run['stale_accepted']})
        return None


