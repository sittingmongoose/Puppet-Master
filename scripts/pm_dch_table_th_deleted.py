"""DCH guard table th_deleted: ACD-615 delete: lifecycle source state and content-free storage-owned deletion record.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('command', 'before_state', 'previous_state', 'deletion_ref', 'payload_deletion_ref', 'content_free', 'storage_owned', 'hidden')


def TD01_producer(value, context):
    return 'thread_refused' if value['command'] != 'cmd.chat.thread.delete' else None


def TD02_deletable_state(value, context):
    return 'thread_refused' if value['before_state'] not in ('active', 'suspended', 'archived') else None


def TD03_previous_state(value, context):
    return 'thread_refused' if value['before_state'] in ('active', 'suspended', 'archived') and value['previous_state'] != value['before_state'] else None


def TD04_record_ref(value, context):
    return 'thread_refused' if value['deletion_ref'] != value['payload_deletion_ref'] else None


def TD05_content_free(value, context):
    return 'thread_refused' if value['content_free'] is not True else None


def TD06_storage_owned(value, context):
    return 'thread_refused' if value['storage_owned'] is not True else None


def TD07_hidden(value, context):
    return 'thread_refused' if value['hidden'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TD01_producer', g.Invariant('/operation/outcome/command', 'is the exact cmd.chat.thread.delete handler'), 'thread_refused', TD01_producer),
        g.Guard('TD02_deletable_state', g.Invariant('/before/thread_state', 'deletion starts from active, suspended or archived only'), 'thread_refused', TD02_deletable_state),
        g.Guard('TD03_previous_state', g.Invariant('/payload/previous_state', 'equals the observed before state'), 'thread_refused', TD03_previous_state),
        g.Guard('TD04_record_ref', g.Invariant('/operation/outcome/deletion_record/ref', 'equals the payload deletion_record_ref'), 'thread_refused', TD04_record_ref),
        g.Guard('TD05_content_free', g.Invariant('/operation/outcome/deletion_record/content_free', 'the deletion record carries no content'), 'thread_refused', TD05_content_free),
        g.Guard('TD06_storage_owned', g.Invariant('/operation/outcome/deletion_record/storage_owned', 'the deletion record is storage-owned'), 'thread_refused', TD06_storage_owned),
        g.Guard('TD07_hidden', g.Invariant('/operation/outcome/hidden', 'the thread is hidden immediately'), 'thread_refused', TD07_hidden),
    ])

    def check(value):
        table.require('TD01_producer', value, context)
        table.require('TD02_deletable_state', value, context)
        table.require('TD03_previous_state', value, context)
        table.require('TD04_record_ref', value, context)
        table.require('TD05_content_free', value, context)
        table.require('TD06_storage_owned', value, context)
        table.require('TD07_hidden', value, context)
        return True
    return g.Case(table, check, context)
