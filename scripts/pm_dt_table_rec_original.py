"""DT guard table rec_original: recovery: the frozen Storage/owner adapter originals.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('prepared_digest', 'original_prepared_digest', 'completed_digest', 'original_completed_digest', 'event_digest', 'original_event_digest', 'nonbool_stage_flags')


def RC13_original_prepared(value, context):
    return 'unavailable' if value['prepared_digest'] != value['original_prepared_digest'] else None


def RC14_original_completed(value, context):
    return 'unavailable' if value['completed_digest'] != value['original_completed_digest'] else None


def RC15_original_event(value, context):
    return 'unavailable' if value['event_digest'] != value['original_event_digest'] else None


def RC16_stage_flag_types(value, context):
    return 'unavailable' if value['nonbool_stage_flags'] != [] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RC13_original_prepared', g.Invariant('/recovery_original/prepared', 'source bytes equal the prepared stage bytes'), 'unavailable', RC13_original_prepared),
        g.Guard('RC14_original_completed', g.Invariant('/recovery_original/completed', 'source bytes equal the completed stage bytes'), 'unavailable', RC14_original_completed),
        g.Guard('RC15_original_event', g.Invariant('/recovery_original/event', 'canonical bytes equal the event'), 'unavailable', RC15_original_event),
        g.Guard('RC16_stage_flag_types', g.Invariant('/case', 'completed_present and append_issued are exactly bools'), 'unavailable', RC16_stage_flag_types),
    ])

    def check(value):
        table.require('RC13_original_prepared', value, context)
        table.require('RC14_original_completed', value, context)
        table.require('RC15_original_event', value, context)
        table.require('RC16_stage_flag_types', value, context)
        return True
    return g.Case(table, check, context)
