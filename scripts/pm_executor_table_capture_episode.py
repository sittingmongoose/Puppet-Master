"""DX guard table capture_episode: node.blocked/node.unblocked: the episode record and its attempt presence.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('episode_attempt_present', 'payload_attempt', 'episode_attempt')


def EP01_episode_record(value, context):
    return 'source record set' if value['episode_attempt_present'] is not True else None


def EP02_attempt_presence(value, context):
    return 'episode attempt presence' if value['episode_attempt_present'] is True and value['payload_attempt'] != value['episode_attempt'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('EP01_episode_record', g.Invariant('/records/episode/body/attempt_id', 'the episode record body names attempt_id'), 'source record set', EP01_episode_record),
        g.Guard('EP02_attempt_presence', g.Invariant('/payload/attempt_id', 'equals the episode attempt (absent when the episode has none)'), 'episode attempt presence', EP02_attempt_presence),
    ])

    def check(value):
        table.require('EP01_episode_record', value, context)
        table.require('EP02_attempt_presence', value, context)
        return True
    return g.Case(table, check, context)
