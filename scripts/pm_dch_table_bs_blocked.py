"""DCH guard table bs_blocked: ACD-610 selection-forward: a privacy/sensitivity, expired or scrubbed handoff is blocked.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('handler', 'blocked', 'block_class', 'reason', 'payload_reason', 'handoff_claimed', 'created')


def BB01_producer(value, context):
    return 'selection_refused' if value['handler'] != 'document_review.selection_forward' else None


def BB02_blocked(value, context):
    return 'selection_refused' if value['blocked'] is not True else None


def BB03_block_class(value, context):
    return 'selection_refused' if value['block_class'] not in ('privacy_sensitivity', 'expired', 'scrubbed') else None


def BB04_reason(value, context):
    return 'selection_refused' if value['reason'] != value['payload_reason'] else None


def BB05_no_success(value, context):
    return 'selection_refused' if value['handoff_claimed'] is not False else None


def BB06_no_creation(value, context):
    return 'selection_refused' if value['created'] != [] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('BB01_producer', g.Invariant('/operation/outcome/handler', 'is the Document review selection-forward handler'), 'selection_refused', BB01_producer),
        g.Guard('BB02_blocked', g.Invariant('/operation/outcome/blocked', 'the handoff was actually blocked'), 'selection_refused', BB02_blocked),
        g.Guard('BB03_block_class', g.Invariant('/operation/outcome/block_class', 'privacy/sensitivity, expired or scrubbed'), 'selection_refused', BB03_block_class),
        g.Guard('BB04_reason', g.Invariant('/payload/reason_code', 'equals the exact original block reason'), 'selection_refused', BB04_reason),
        g.Guard('BB05_no_success', g.Invariant('/operation/outcome/handoff_claimed', 'never claims a successful handoff'), 'selection_refused', BB05_no_success),
        g.Guard('BB06_no_creation', g.Invariant('/operation/outcome/created', 'no message or annotation is created'), 'selection_refused', BB06_no_creation),
    ])

    def check(value):
        table.require('BB01_producer', value, context)
        table.require('BB02_blocked', value, context)
        table.require('BB03_block_class', value, context)
        table.require('BB04_reason', value, context)
        table.require('BB05_no_success', value, context)
        table.require('BB06_no_creation', value, context)
        return True
    return g.Case(table, check, context)
