"""DCH guard table wt_bound: ACD-616 successful creation/binding completion.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('status', 'inflight', 'worktree', 'payload_worktree', 'path', 'payload_path', 'branch', 'payload_branch')


def WB01_created(value, context):
    return 'worktree_refused' if value['status'] != 'created' else None


def WB02_no_inflight(value, context):
    return 'worktree_refused' if value['inflight'] is not False else None


def WB03_worktree(value, context):
    return 'worktree_refused' if value['worktree'] != value['payload_worktree'] else None


def WB04_path(value, context):
    return 'worktree_refused' if value['path'] != value['payload_path'] else None


def WB05_branch(value, context):
    return 'worktree_refused' if value['branch'] != value['payload_branch'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WB01_created', g.Invariant('/operation/outcome/status', 'the actual creation completed'), 'worktree_refused', WB01_created),
        g.Guard('WB02_no_inflight', g.Invariant('/operation/outcome/inflight_turn', 'binding changes are refused during an in-flight turn'), 'worktree_refused', WB02_no_inflight),
        g.Guard('WB03_worktree', g.Invariant('/after/worktree/worktree_id', 'equals the committed result worktree'), 'worktree_refused', WB03_worktree),
        g.Guard('WB04_path', g.Invariant('/after/worktree/worktree_path', 'equals the committed result path'), 'worktree_refused', WB04_path),
        g.Guard('WB05_branch', g.Invariant('/after/worktree/branch_name', 'equals the committed result branch'), 'worktree_refused', WB05_branch),
    ])

    def check(value):
        table.require('WB01_created', value, context)
        table.require('WB02_no_inflight', value, context)
        table.require('WB03_worktree', value, context)
        table.require('WB04_path', value, context)
        table.require('WB05_branch', value, context)
        return True
    return g.Case(table, check, context)
