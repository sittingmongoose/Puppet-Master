"""DCH guard table cp_family_entailed: checkpoint_joins: value family, reader and projector (the checkpoint schema consts decide first, CP01) and the retained event family (JN02 decides first); defence in depth.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('value_event_type', 'family', 'event_event_type', 'consumer_id', 'reader', 'projector_id', 'domain_projector')


def CP29_value_event_type(value, context):
    return 'checkpoint_refused' if value['value_event_type'] != value['family'] else None


def CP30_event_event_type(value, context):
    return 'checkpoint_refused' if value['event_event_type'] != value['family'] else None


def CP32_consumer(value, context):
    return 'checkpoint_refused' if value['consumer_id'] != value['reader'] else None


def CP33_projector(value, context):
    return 'checkpoint_refused' if value['projector_id'] != value['domain_projector'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP29_value_event_type', g.Invariant('/value/event_type', 'equals the family'), 'checkpoint_refused', CP29_value_event_type),
        g.Guard('CP30_event_event_type', g.Invariant('/source/event_record/event_type', 'equals the family'), 'checkpoint_refused', CP30_event_event_type),
        g.Guard('CP32_consumer', g.Invariant('/value/consumer_id', 'equals the family reader'), 'checkpoint_refused', CP32_consumer),
        g.Guard('CP33_projector', g.Invariant('/value/projector_id', 'equals the family domain projector'), 'checkpoint_refused', CP33_projector),
    ])

    def check(value):
        table.require('CP29_value_event_type', value, context)
        table.require('CP30_event_event_type', value, context)
        table.require('CP32_consumer', value, context)
        table.require('CP33_projector', value, context)
        return True
    return g.Case(table, check, context)
