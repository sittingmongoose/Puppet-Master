"""DCH guard table ar_request: archive_joins: manual origin, command and request authority.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('archive_origin', 'command_id', 'request_origin', 'request_command_id', 'permission_allowed', 'thread_selected', 'active_run')


def AR01_manual_origin(value, context):
    return 'archive_refused' if value['archive_origin'] != 'manual' else None


def AR02_command_id(value, context):
    return 'archive_refused' if value['command_id'] != 'cmd.chat.archive' else None


def AR03_request_origin(value, context):
    return 'archive_refused' if value['request_origin'] != 'manual' else None


def AR04_request_command(value, context):
    return 'archive_refused' if value['request_command_id'] != 'cmd.chat.archive' else None


def AR05_permission(value, context):
    return 'archive_refused' if value['permission_allowed'] is not True else None


def AR06_thread_selected(value, context):
    return 'archive_refused' if value['thread_selected'] is not True else None


def AR07_no_active_run(value, context):
    return 'archive_refused' if value['active_run'] is not False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('AR01_manual_origin', g.Invariant('/payload/archive_origin', 'is manual'), 'archive_refused', AR01_manual_origin),
        g.Guard('AR02_command_id', g.Invariant('/payload/command_id', 'is cmd.chat.archive'), 'archive_refused', AR02_command_id),
        g.Guard('AR03_request_origin', g.Invariant('/source/request/origin', 'is manual'), 'archive_refused', AR03_request_origin),
        g.Guard('AR04_request_command', g.Invariant('/source/request/command_id', 'is cmd.chat.archive (the payload command)'), 'archive_refused', AR04_request_command),
        g.Guard('AR05_permission', g.Invariant('/source/request/permission_allowed', 'is exactly true'), 'archive_refused', AR05_permission),
        g.Guard('AR06_thread_selected', g.Invariant('/source/request/thread_selected', 'is exactly true'), 'archive_refused', AR06_thread_selected),
        g.Guard('AR07_no_active_run', g.Invariant('/source/before/active_run', 'is exactly false'), 'archive_refused', AR07_no_active_run),
    ])

    def check(value):
        table.require('AR01_manual_origin', value, context)
        table.require('AR02_command_id', value, context)
        table.require('AR03_request_origin', value, context)
        table.require('AR04_request_command', value, context)
        table.require('AR05_permission', value, context)
        table.require('AR06_thread_selected', value, context)
        table.require('AR07_no_active_run', value, context)
        return True
    return g.Case(table, check, context)
