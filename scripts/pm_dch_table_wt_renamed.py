"""DCH guard table wt_renamed: ACD-625 original successful rename and old/new branch copies.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('status', 'old_branch', 'payload_old', 'new_branch', 'payload_new')


def WR01_renamed(value, context):
    return 'worktree_refused' if value['status'] != 'renamed' else None


def WR02_old_branch(value, context):
    return 'worktree_refused' if value['old_branch'] != value['payload_old'] else None


def WR03_new_branch(value, context):
    return 'worktree_refused' if value['new_branch'] != value['payload_new'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WR01_renamed', g.Invariant('/operation/outcome/status', 'the actual rename succeeded'), 'worktree_refused', WR01_renamed),
        g.Guard('WR02_old_branch', g.Invariant('/before/worktree/branch_name', 'equals the original old branch'), 'worktree_refused', WR02_old_branch),
        g.Guard('WR03_new_branch', g.Invariant('/after/worktree/branch_name', 'equals the committed new branch'), 'worktree_refused', WR03_new_branch),
    ])

    def check(value):
        table.require('WR01_renamed', value, context)
        table.require('WR02_old_branch', value, context)
        table.require('WR03_new_branch', value, context)
        return True
    return g.Case(table, check, context)
