"""DFM guard table creation_container: Creation: the exact original container (validate_snapshot_subjects).

Method B guard rows for scripts/pm-filemanager-event-contracts.py, generated by
scripts/pm-filemanager-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(recomputed keys, identities and digests, exact types, resolved rows); a
predicate never recomputes, repairs or calls helpers. The checker refuses
only through these rows, in this order (table_refusals in the checker).
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('container_count', 'container_folder', 'settled_ref_equal', 'settled_folder', 'computer_equal', 'root_equal', 'parent_equal')


def CC01_container_unique(value, context):
    return 'creation exact container' if value['container_count'] != 1 else None


def CC02_container_folder(value, context):
    return 'creation exact container' if value['container_folder'] is False else None


def CC03_settled_container_ref(value, context):
    return 'creation settled container' if value['settled_ref_equal'] is False else None


def CC04_settled_container_folder(value, context):
    return 'creation settled container' if value['settled_folder'] is False else None


def CC05_container_computer(value, context):
    return 'creation container location' if value['computer_equal'] is False else None


def CC06_container_root(value, context):
    return 'creation container location' if value['root_equal'] is False else None


def CC07_container_parent(value, context):
    return 'creation container location' if value['parent_equal'] is False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CC01_container_unique', g.Invariant('/accepted_path_snapshots', 'exactly one accepted snapshot is the destination container'), 'creation exact container', CC01_container_unique),
        g.Guard('CC02_container_folder', g.Invariant('/accepted_path_snapshots/{container}/node_kind', 'the unique container is a folder'), 'creation exact container', CC02_container_folder),
        g.Guard('CC03_settled_container_ref', g.Invariant('/settlement/path_snapshots/{container}/node_ref', 'still names the container'), 'creation settled container', CC03_settled_container_ref),
        g.Guard('CC04_settled_container_folder', g.Invariant('/settlement/path_snapshots/{container}/node_kind', 'is still a folder'), 'creation settled container', CC04_settled_container_folder),
        g.Guard('CC05_container_computer', g.Invariant('/accepted_path_snapshots/{destination}/computer_id', 'equals the container computer'), 'creation container location', CC05_container_computer),
        g.Guard('CC06_container_root', g.Invariant('/accepted_path_snapshots/{destination}/root_identity_ref', 'equals the container root'), 'creation container location', CC06_container_root),
        g.Guard('CC07_container_parent', g.Invariant('/accepted_path_snapshots/{destination}/relative_components', 'parent equals the container components'), 'creation container location', CC07_container_parent),
    ])

    def check(value):
        table.require('CC01_container_unique', value, context)
        table.require('CC02_container_folder', value, context)
        table.require('CC03_settled_container_ref', value, context)
        table.require('CC04_settled_container_folder', value, context)
        table.require('CC05_container_computer', value, context)
        table.require('CC06_container_root', value, context)
        table.require('CC07_container_parent', value, context)
        return True
    return g.Case(table, check, context)
