"""DCH guard table th_message_a: ACD-612 transcript commit: one canonical typed message at a durable boundary.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('handler', 'boundary', 'copy_mismatches', 'commit_count')


def TM01_producer(value, context):
    return 'thread_refused' if value['handler'] != 'assistant_chat.transcript_commit' else None


def TM02_durable_boundary(value, context):
    return 'thread_refused' if value['boundary'] != 'durable_message' else None


def TM03_message_copies(value, context):
    return 'thread_refused' if value['copy_mismatches'] != [] else None


def TM04_commit_once(value, context):
    return 'thread_refused' if value['commit_count'] != 1 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TM01_producer', g.Invariant('/operation/outcome/handler', 'is the Assistant Chat transcript commit handler'), 'thread_refused', TM01_producer),
        g.Guard('TM02_durable_boundary', g.Invariant('/operation/outcome/boundary', 'commits at a durable message boundary, never a stream delta'), 'thread_refused', TM02_durable_boundary),
        g.Guard('TM03_message_copies', g.Invariant('/operation/outcome/message', 'id, type, role, content and attachments equal the payload'), 'thread_refused', TM03_message_copies),
        g.Guard('TM04_commit_once', g.Invariant('/operation/outcome/commit_count', 'the canonical message commits exactly once'), 'thread_refused', TM04_commit_once),
    ])

    def check(value):
        table.require('TM01_producer', value, context)
        table.require('TM02_durable_boundary', value, context)
        table.require('TM03_message_copies', value, context)
        table.require('TM04_commit_once', value, context)
        return True
    return g.Case(table, check, context)
