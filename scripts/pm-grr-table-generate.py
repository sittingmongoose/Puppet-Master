#!/usr/bin/env python3
"""Generate the PNC-019 rv8b Method B guard-table modules from pm_goal_run_replan_oracles.ROWS.

Each predicate reads one boolean observation the checker (scripts/pm_goal_run_replan_oracles.py) derives from the
complete boundary input; predicates never recompute, repair or call helpers. The checker refuses only through
these rows, in spec order. A phase of more than eight rows is rendered as consecutive part tables
(<phase>__1, <phase>__2, ...; at most eight rows each, evaluated in row order). Edit ROWS in the checker and
regenerate; never edit a table module. --check exits 1 when a committed table differs from what ROWS renders.
The renderer is the PNC-019 S2 generator's (scripts/pm-s2-table-generate.py on plans/ea-pnc-s2-20261114).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import pm_goal_run_replan_oracles as m  # noqa: E402


def render(table, code, title, rows):
    fields = tuple(row[1] for row in rows)
    lines = [
        f'"""rv8b guard table {table}: {title}.',
        '',
        'Method B guard rows (scripts/pm_guard_isolation.py) for the PNC-019 rv8b goal_run.replanned checker. Each',
        'predicate reads one observation the checker derives from the complete boundary input. Predicates never',
        'recompute, repair or call helpers. The checker refuses only through these rows, in this order.',
        'Generated by scripts/pm-grr-table-generate.py from pm_goal_run_replan_oracles.ROWS; edit the spec there.',
        '"""',
        'import pm_guard_isolation as g',
        '',
        f'FIELDS = {fields!r}',
        '',
    ]
    for row in rows:
        name, field = row[0], row[1]
        row_code = row[3] if len(row) > 3 else code
        lines += [f'def {name}(value, context):',
                  f'    return {row_code!r} if value[{field!r}] is not True else None', '']
    lines += ['def case(value):', '    context = None', '    table = g.GuardTable([']
    for row in rows:
        name, field, invariant = row[0], row[1], row[2]
        row_code = row[3] if len(row) > 3 else code
        lines.append(f"        g.Guard({name!r}, g.Invariant({'/' + field!r}, {invariant!r}), {row_code!r}, {name}),")
    lines += ['    ])', '', '    def check(value):']
    for row in rows:
        lines.append(f'        table.require({row[0]!r}, value, context)')
    lines += ['        return True', '    return g.Case(table, check, context)', '']
    return '\n'.join(lines)


def main():
    check = '--check' in sys.argv[1:]
    stale, expected = [], set()
    for phase, (code, title, _rows) in m.ROWS.items():
        for table, rows in m.part_rows(phase).items():
            assert len(rows) <= m.MAX_ROWS, (table, len(rows))
            path = ROOT / 'scripts' / f'{m.TABLE_PREFIX}{table}.py'
            expected.add(path.name)
            text = render(table, code, title, rows)
            if check:
                if not path.exists() or path.read_text() != text:
                    stale.append(path.name)
            else:
                path.write_text(text)
    extra = sorted(p.name for p in (ROOT / 'scripts').glob(m.TABLE_PREFIX + '*.py') if p.name not in expected)
    rows = sum(len(r[2]) for r in m.ROWS.values())
    out = {'status': 'pass' if not stale and not extra else 'fail', 'tables': len(expected), 'rows': rows, 'stale': stale, 'unexpected': extra}
    print(out if check else {'tables': len(expected), 'rows': rows})
    return 1 if check and (stale or extra) else 0


if __name__ == '__main__':
    sys.exit(main())
