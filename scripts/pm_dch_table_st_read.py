"""DCH guard table st_read: stop read_outcome: committed result and verified readback.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('result_committed', 'readback_verified', 'outcome_value_sha256', 'value_commitment')


def RD02_committed(value, context):
    return 'stop_outcome_refused' if value['result_committed'] is not True else None


def RD03_readback(value, context):
    return 'stop_outcome_refused' if value['readback_verified'] is not True else None


def RD04_value_commitment(value, context):
    return 'stop_outcome_refused' if value['outcome_value_sha256'] != value['value_commitment'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RD02_committed', g.Invariant('/context/result_committed', 'is exactly true'), 'stop_outcome_refused', RD02_committed),
        g.Guard('RD03_readback', g.Invariant('/context/readback_verified', 'is exactly true'), 'stop_outcome_refused', RD03_readback),
        g.Guard('RD04_value_commitment', g.Invariant('/context/outcome_value_sha256', 'equals SHA-256 of the saved value bytes'), 'stop_outcome_refused', RD04_value_commitment),
    ])

    def check(value):
        table.require('RD02_committed', value, context)
        table.require('RD03_readback', value, context)
        table.require('RD04_value_commitment', value, context)
        return True
    return g.Case(table, check, context)
