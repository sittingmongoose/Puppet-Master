"""DX guard table trace_rebuild: Trace model: rebuild needs every first-receipt custody.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('row_count', 'all_custody')


def TB01_rows_present(value, context):
    return 'source_unavailable' if value['row_count'] < 1 else None


def TB02_custody_complete(value, context):
    return 'source_unavailable' if value['row_count'] >= 1 and value['all_custody'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TB01_rows_present', g.Invariant('/rows', 'is not empty'), 'source_unavailable', TB01_rows_present),
        g.Guard('TB02_custody_complete', g.Invariant('/rows/*', 'every row has custody'), 'source_unavailable', TB02_custody_complete),
    ])

    def check(value):
        table.require('TB01_rows_present', value, context)
        table.require('TB02_custody_complete', value, context)
        return True
    return g.Case(table, check, context)
