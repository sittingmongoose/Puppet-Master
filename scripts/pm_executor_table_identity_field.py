"""DX guard table identity_field: Identity inputs: each identity field in its declared payload schema domain.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('domain_type', 'value_type', 'length', 'bound', 'integer_refusal')


def ID01_domain_declared(value, context):
    return 'identity declared field domain' if value['domain_type'] not in ('string', 'integer') else None


def ID02_string_type(value, context):
    return 'identity declared field domain' if value['domain_type'] == 'string' and value['value_type'] != 'str' else None


def ID03_string_length(value, context):
    return 'identity declared field domain' if value['domain_type'] == 'string' and value['value_type'] == 'str' and value['length'] < value['bound'] else None


def ID04_integer_type(value, context):
    return 'identity declared field domain' if value['domain_type'] == 'integer' and value['integer_refusal'] == 'integer_type' else None


def ID05_integer_minimum(value, context):
    return 'identity declared field domain' if value['domain_type'] == 'integer' and value['integer_refusal'] == 'integer_range' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('ID01_domain_declared', g.Invariant('/identity_fields/*', 'the field schema declares a string or integer domain'), 'identity declared field domain', ID01_domain_declared),
        g.Guard('ID02_string_type', g.Invariant('/identity_fields/*', 'a string-domain value is a string'), 'identity declared field domain', ID02_string_type),
        g.Guard('ID03_string_length', g.Invariant('/identity_fields/*', 'a string value meets minLength'), 'identity declared field domain', ID03_string_length),
        g.Guard('ID04_integer_type', g.Invariant('/identity_fields/*', 'an integer-domain value passes CV-1100 current_integer type admission'), 'identity declared field domain', ID04_integer_type),
        g.Guard('ID05_integer_minimum', g.Invariant('/identity_fields/*', 'an integer value is within the schema minimum/maximum (current_integer range)'), 'identity declared field domain', ID05_integer_minimum),
    ])

    def check(value):
        table.require('ID01_domain_declared', value, context)
        table.require('ID02_string_type', value, context)
        table.require('ID03_string_length', value, context)
        table.require('ID04_integer_type', value, context)
        table.require('ID05_integer_minimum', value, context)
        return True
    return g.Case(table, check, context)
