"""DCH guard table st_index_entailed: stop index_read_valid: request family (the request joins decide first, JN02) and index sequence type (the source type walk decides first, TY03); defence in depth.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('record_event_type', 'row_sequence_type')


def IX22_record_event_type(value, context):
    return 'stop_index_refused' if value['record_event_type'] != 'chat.response_stop_requested' else None


def IX24_row_sequence_type(value, context):
    return 'stop_index_refused' if value['row_sequence_type'] != 'int' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IX22_record_event_type', g.Invariant('/record/event_type', 'is chat.response_stop_requested'), 'stop_index_refused', IX22_record_event_type),
        g.Guard('IX24_row_sequence_type', g.Invariant('/source/index_row/sequence_id', 'is exactly an integer'), 'stop_index_refused', IX24_row_sequence_type),
    ])

    def check(value):
        table.require('IX22_record_event_type', value, context)
        table.require('IX24_row_sequence_type', value, context)
        return True
    return g.Case(table, check, context)
