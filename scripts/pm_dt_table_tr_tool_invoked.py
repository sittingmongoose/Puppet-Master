"""DT guard table tr_tool_invoked: transition tool.invoked, including the web request join.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('request_present', 'meta_present', 'tool_name', 'meta_tool_id', 'web_mismatches', 'dispatch_state', 'outcome_dispatch_state', 'copy_mismatches')


def TI1_web_presence(value, context):
    return 'transition_refused' if value['request_present'] is not value['meta_present'] else None


def TI2_web_tool(value, context):
    return 'transition_refused' if value['request_present'] is True and value['meta_present'] is True and value['tool_name'] != value['meta_tool_id'] else None


def TI3_web_copies(value, context):
    return 'transition_refused' if value['web_mismatches'] != [] else None


def TI4_dispatch_started(value, context):
    return 'transition_refused' if value['dispatch_state'] != 'started' else None


def TI5_attempted(value, context):
    return 'transition_refused' if value['outcome_dispatch_state'] != 'attempted_completed' else None


def TI6_copies(value, context):
    return 'transition_refused' if value['copy_mismatches'] != [] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TI1_web_presence', g.Invariant('/payload/meta', 'is present exactly when a web request was dispatched'), 'transition_refused', TI1_web_presence),
        g.Guard('TI2_web_tool', g.Invariant('/payload/tool_name', 'equals the web meta tool_id'), 'transition_refused', TI2_web_tool),
        g.Guard('TI3_web_copies', g.Invariant('/payload/meta', 'every web request field but parent_event_id equals its meta copy'), 'transition_refused', TI3_web_copies),
        g.Guard('TI4_dispatch_started', g.Invariant('/before/dispatch_state', 'is started'), 'transition_refused', TI4_dispatch_started),
        g.Guard('TI5_attempted', g.Invariant('/owner_result/dispatch_state', 'is attempted_completed'), 'transition_refused', TI5_attempted),
        g.Guard('TI6_copies', g.Invariant('/payload', 'success, latency_ms, index_used and meta equal the owner result'), 'transition_refused', TI6_copies),
    ])

    def check(value):
        table.require('TI1_web_presence', value, context)
        table.require('TI2_web_tool', value, context)
        table.require('TI3_web_copies', value, context)
        table.require('TI4_dispatch_started', value, context)
        table.require('TI5_attempted', value, context)
        table.require('TI6_copies', value, context)
        return True
    return g.Case(table, check, context)
