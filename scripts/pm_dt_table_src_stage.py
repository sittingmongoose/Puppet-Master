import pm_guard_isolation as g

FIELDS = ('prepared_stage', 'completed_stage')


def SV12_prepared_stage(value, context):
    return 'original_source_refused' if value['prepared_stage'] != 'prepared' else None


def SV13_completed_stage(value, context):
    return 'original_source_refused' if value['completed_stage'] != 'completed' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SV12_prepared_stage', g.Invariant('/prepared/stage', 'is prepared'), 'original_source_refused', SV12_prepared_stage),
        g.Guard('SV13_completed_stage', g.Invariant('/completed/stage', 'is completed'), 'original_source_refused', SV13_completed_stage),
    ])

    def check(value):
        table.require('SV12_prepared_stage', value, context)
        table.require('SV13_completed_stage', value, context)
        return True
    return g.Case(table, check, context)
