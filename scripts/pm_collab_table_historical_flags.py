"""DC guard table historical_flags: Retained-history controls and the original record join.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('withdrawn_type', 'withdrawn', 'retained_type', 'retained', 'write_epoch_type', 'write_epoch_negative', 'record_sha256', 'original_record_sha256')


def HI02_withdrawn_type(value, context):
    return 'historical_withdrawn' if value['withdrawn_type'] != 'bool' else None


def HI03_not_withdrawn(value, context):
    return 'historical_withdrawn' if value['withdrawn'] is True else None


def HI04_retained_type(value, context):
    return 'historical_not_retained' if value['retained_type'] != 'bool' else None


def HI05_retained(value, context):
    return 'historical_not_retained' if value['retained'] is False else None


def HI06_epoch_type(value, context):
    return 'historical_epoch_type' if value['write_epoch_type'] != 'int' else None


def HI07_epoch_nonnegative(value, context):
    return 'historical_epoch_type' if value['write_epoch_negative'] is True else None


def HI08_original(value, context):
    return 'historical_forged' if value['record_sha256'] is None or value['record_sha256'] != value['original_record_sha256'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('HI02_withdrawn_type', g.Invariant('/<context>/withdrawn', 'is exactly bool'), 'historical_withdrawn', HI02_withdrawn_type),
        g.Guard('HI03_not_withdrawn', g.Invariant('/<context>/withdrawn', 'is not true'), 'historical_withdrawn', HI03_not_withdrawn),
        g.Guard('HI04_retained_type', g.Invariant('/<context>/retained', 'is exactly bool'), 'historical_not_retained', HI04_retained_type),
        g.Guard('HI05_retained', g.Invariant('/<context>/retained', 'is not false'), 'historical_not_retained', HI05_retained),
        g.Guard('HI06_epoch_type', g.Invariant('/<context>/write_epoch', 'is an exact int'), 'historical_epoch_type', HI06_epoch_type),
        g.Guard('HI07_epoch_nonnegative', g.Invariant('/<context>/write_epoch', 'an int write epoch is not negative'), 'historical_epoch_type', HI07_epoch_nonnegative),
        g.Guard('HI08_original', g.Invariant('/', 'equals the captured original record'), 'historical_forged', HI08_original),
    ])

    def check(value):
        table.require('HI02_withdrawn_type', value, context)
        table.require('HI03_not_withdrawn', value, context)
        table.require('HI04_retained_type', value, context)
        table.require('HI05_retained', value, context)
        table.require('HI06_epoch_type', value, context)
        table.require('HI07_epoch_nonnegative', value, context)
        table.require('HI08_original', value, context)
        return True
    return g.Case(table, check, context)
