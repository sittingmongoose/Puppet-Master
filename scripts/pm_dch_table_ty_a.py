"""DCH guard table ty_a: input_types_valid: map keys, Storage descriptors and integer slots (strict recipes).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('nonstring_keys', 'store_descriptors', 'integer_types', 'uint64_ranges')


def TY01_key_type(value, context):
    return 'type_refused' if value['nonstring_keys'] != [] else None


def TY02_store_descriptor(value, context):
    return 'type_refused' if value['store_descriptors'] != [] else None


def TY03_integer_type(value, context):
    return 'type_refused' if value['integer_types'] != [] else None


def TY04_uint64_range(value, context):
    return 'type_refused' if value['uint64_ranges'] != [] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TY01_key_type', g.Invariant('/**', 'every map key is exactly a string'), 'type_refused', TY01_key_type),
        g.Guard('TY02_store_descriptor', g.Invariant('/**/storage_instance_id', 'every Storage instance id satisfies the Storage descriptor'), 'type_refused', TY02_store_descriptor),
        g.Guard('TY03_integer_type', g.Invariant('/**/<integer slot>', 'every integer slot holds an exact integer (producer_sequence_id may be null)'), 'type_refused', TY03_integer_type),
        g.Guard('TY04_uint64_range', g.Invariant('/**/<Storage uint64 slot>', 'every current Storage uint64 slot is within 0..2^64-1'), 'type_refused', TY04_uint64_range),
    ])

    def check(value):
        table.require('TY01_key_type', value, context)
        table.require('TY02_store_descriptor', value, context)
        table.require('TY03_integer_type', value, context)
        table.require('TY04_uint64_range', value, context)
        return True
    return g.Case(table, check, context)
