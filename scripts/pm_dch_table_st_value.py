"""DCH guard table st_value: stop resolve_value: record shape and Storage descriptor.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('record_type', 'payload_type', 'store_valid')


def SV01_record_object(value, context):
    return 'stop_value_unavailable' if value['record_type'] != 'dict' else None


def SV02_payload_object(value, context):
    return 'stop_value_unavailable' if value['record_type'] == 'dict' and value['payload_type'] != 'dict' else None


def SV03_store_descriptor(value, context):
    return 'stop_value_unavailable' if value['store_valid'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SV01_record_object', g.Invariant('/record', 'is exactly a JSON object'), 'stop_value_unavailable', SV01_record_object),
        g.Guard('SV02_payload_object', g.Invariant('/record/payload', 'is exactly a JSON object'), 'stop_value_unavailable', SV02_payload_object),
        g.Guard('SV03_store_descriptor', g.Invariant('/storage_instance', 'satisfies the Storage descriptor'), 'stop_value_unavailable', SV03_store_descriptor),
    ])

    def check(value):
        table.require('SV01_record_object', value, context)
        table.require('SV02_payload_object', value, context)
        table.require('SV03_store_descriptor', value, context)
        return True
    return g.Case(table, check, context)
