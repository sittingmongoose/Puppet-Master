"""DT guard table cp_coverage: checkpoint_result: examined cursor, last applied event and filter.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('examined_through', 'through', 'last_applied_event_id', 'last_matching_event_id', 'filter_complete_truthy')


def CP30_examined_through(value, context):
    return 'coverage_refused' if value['examined_through'] != value['through'] else None


def CP31_last_applied(value, context):
    return 'coverage_refused' if value['last_applied_event_id'] != value['last_matching_event_id'] else None


def CP32_filter_complete(value, context):
    return 'coverage_refused' if value['filter_complete_truthy'] is False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP30_examined_through', g.Invariant('/proposed/examined_through_sequence_id', 'canonical bytes equal the global row cursor'), 'coverage_refused', CP30_examined_through),
        g.Guard('CP31_last_applied', g.Invariant('/proposed/last_applied_event_id', 'equals the last matching row event id'), 'coverage_refused', CP31_last_applied),
        g.Guard('CP32_filter_complete', g.Invariant('/proposed/filter_complete', 'is truthy'), 'coverage_refused', CP32_filter_complete),
    ])

    def check(value):
        table.require('CP30_examined_through', value, context)
        table.require('CP31_last_applied', value, context)
        table.require('CP32_filter_complete', value, context)
        return True
    return g.Case(table, check, context)
