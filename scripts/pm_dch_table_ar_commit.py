"""DCH guard table ar_commit: archive_joins: committed revision, record ref and original identity copies.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('committed_thread_revision', 'after_revision', 'next_revision', 'thread_record_ref', 'after_record_ref', 'payload_copy_mismatches', 'before_copy_mismatches', 'after_copy_mismatches')


def AR15_committed_revision(value, context):
    return 'archive_refused' if value['committed_thread_revision'] != value['after_revision'] else None


def AR16_after_revision(value, context):
    return 'archive_refused' if value['after_revision'] != value['next_revision'] else None


def AR17_record_ref(value, context):
    return 'archive_refused' if value['thread_record_ref'] != value['after_record_ref'] else None


def AR18_payload_copies(value, context):
    return 'archive_refused' if value['payload_copy_mismatches'] != [] else None


def AR19_before_copies(value, context):
    return 'archive_refused' if value['before_copy_mismatches'] != [] else None


def AR20_after_copies(value, context):
    return 'archive_refused' if value['after_copy_mismatches'] != [] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('AR15_committed_revision', g.Invariant('/payload/committed_thread_revision', 'equals the committed after revision'), 'archive_refused', AR15_committed_revision),
        g.Guard('AR16_after_revision', g.Invariant('/source/after/revision', 'is the before revision plus one'), 'archive_refused', AR16_after_revision),
        g.Guard('AR17_record_ref', g.Invariant('/payload/thread_record_ref', 'equals the committed record ref'), 'archive_refused', AR17_record_ref),
        g.Guard('AR18_payload_copies', g.Invariant('/payload', 'thread_id, computer_id, scope and operation_id equal the original request'), 'archive_refused', AR18_payload_copies),
        g.Guard('AR19_before_copies', g.Invariant('/source/before', 'thread_id, computer_id, scope and operation_id equal the original request'), 'archive_refused', AR19_before_copies),
        g.Guard('AR20_after_copies', g.Invariant('/source/after', 'thread_id, computer_id, scope and operation_id equal the original request'), 'archive_refused', AR20_after_copies),
    ])

    def check(value):
        table.require('AR15_committed_revision', value, context)
        table.require('AR16_after_revision', value, context)
        table.require('AR17_record_ref', value, context)
        table.require('AR18_payload_copies', value, context)
        table.require('AR19_before_copies', value, context)
        table.require('AR20_after_copies', value, context)
        return True
    return g.Case(table, check, context)
