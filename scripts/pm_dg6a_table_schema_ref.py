"""DG6A guard table schema_ref: Every local $ref of a schema document resolves, unused definitions included (one call per reference).

Method B guard rows (scripts/pm_guard_isolation.py) for the DG6A checkers. Each predicate reads one
observation the checker derives from the complete boundary input (recomputed digests and identities,
canonical-byte sizes, typed joins, presence). Predicates never recompute, repair or call helpers.
The checkers refuse only through these rows, in this order (scripts/pm_dg6a_tables.py).
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-dg6a-table-generate.py; edit the row spec there.
"""
import pm_guard_isolation as g

FIELDS = ('local', 'resolves', 'target_schema')


def SR01_local(value, context):
    return 'unresolved schema reference' if value['local'] is not True else None


def SR02_resolves(value, context):
    return 'unresolved schema reference' if value['local'] is True and value['resolves'] is not True else None


def SR03_target_schema(value, context):
    return 'unresolved schema reference' if value['local'] is True and value['resolves'] is True and value['target_schema'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SR01_local', g.Invariant('/local', "the reference is '#' or a '#/' JSON pointer"), 'unresolved schema reference', SR01_local),
        g.Guard('SR02_resolves', g.Invariant('/resolves', 'every pointer token names an existing member or index'), 'unresolved schema reference', SR02_resolves),
        g.Guard('SR03_target_schema', g.Invariant('/target_schema', 'the target is a schema (object or boolean)'), 'unresolved schema reference', SR03_target_schema),
    ])

    def check(value):
        table.require('SR01_local', value, context)
        table.require('SR02_resolves', value, context)
        table.require('SR03_target_schema', value, context)
        return True
    return g.Case(table, check, context)
