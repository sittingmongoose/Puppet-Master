"""DCH guard table tj_failed_b: test_joins: failed terminal outcome kinds (success is never a failure).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('kind', 'exit_code_type', 'exit_code', 'payload_error_ref')


def TJ12_exit_type(value, context):
    return 'test_join_refused' if value['kind'] == 'exit' and value['exit_code_type'] != 'int' else None


def TJ13_exit_nonzero(value, context):
    return 'test_join_refused' if value['kind'] == 'exit' and value['exit_code_type'] == 'int' and value['exit_code'] == 0 else None


def TJ14_exit_no_error_ref(value, context):
    return 'test_join_refused' if value['kind'] == 'exit' and value['payload_error_ref'] is not None else None


def TJ15_terminal_kind(value, context):
    return 'test_join_refused' if value['kind'] not in ('exit', 'timeout', 'process_error') else None


def TJ16_nonexit_no_code(value, context):
    return 'test_join_refused' if value['kind'] in ('timeout', 'process_error') and value['exit_code'] is not None else None


def TJ17_process_error_ref(value, context):
    return 'test_join_refused' if value['kind'] == 'process_error' and value['payload_error_ref'] is None else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TJ12_exit_type', g.Invariant('/source/outcome/exit_code', 'a failed exit code is exactly an integer'), 'test_join_refused', TJ12_exit_type),
        g.Guard('TJ13_exit_nonzero', g.Invariant('/source/outcome/exit_code', 'a failed exit code is nonzero'), 'test_join_refused', TJ13_exit_nonzero),
        g.Guard('TJ14_exit_no_error_ref', g.Invariant('/payload/error_ref', 'a failed exit carries no error_ref'), 'test_join_refused', TJ14_exit_no_error_ref),
        g.Guard('TJ15_terminal_kind', g.Invariant('/source/outcome/kind', 'is exit, timeout or process_error'), 'test_join_refused', TJ15_terminal_kind),
        g.Guard('TJ16_nonexit_no_code', g.Invariant('/source/outcome/exit_code', 'a timeout or process error has no exit code'), 'test_join_refused', TJ16_nonexit_no_code),
        g.Guard('TJ17_process_error_ref', g.Invariant('/payload/error_ref', 'a process error names its error_ref'), 'test_join_refused', TJ17_process_error_ref),
    ])

    def check(value):
        table.require('TJ12_exit_type', value, context)
        table.require('TJ13_exit_nonzero', value, context)
        table.require('TJ14_exit_no_error_ref', value, context)
        table.require('TJ15_terminal_kind', value, context)
        table.require('TJ16_nonexit_no_code', value, context)
        table.require('TJ17_process_error_ref', value, context)
        return True
    return g.Case(table, check, context)
