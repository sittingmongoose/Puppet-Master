"""DX guard table capture_scope: Capture scope: Project, encoded partition and Storage root.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('scope_project', 'payload_project', 'scope_partition', 'expected_partition', 'scope_storage', 'envelope_storage')


def SC01_project(value, context):
    return 'scope Project' if value['scope_project'] != value['payload_project'] else None


def SC02_partition(value, context):
    return 'scope partition' if value['scope_partition'] != value['expected_partition'] else None


def SC03_storage(value, context):
    return 'storage root' if value['scope_storage'] != value['envelope_storage'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SC01_project', g.Invariant('/capture/scope/project_id', 'equals the payload Project'), 'scope Project', SC01_project),
        g.Guard('SC02_partition', g.Invariant('/capture/scope/scope_partition', 'equals project~ plus the unpadded urlsafe base64 Project id'), 'scope partition', SC02_partition),
        g.Guard('SC03_storage', g.Invariant('/capture/scope/storage_instance_id', 'equals the envelope Storage instance'), 'storage root', SC03_storage),
    ])

    def check(value):
        table.require('SC01_project', value, context)
        table.require('SC02_partition', value, context)
        table.require('SC03_storage', value, context)
        return True
    return g.Case(table, check, context)
