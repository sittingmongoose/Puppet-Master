"""DCH guard table st_request_access: stop request_valid: retained access custody and original byte commitment.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('retained', 'authorized', 'hold_access_allowed', 'deleted', 'withdrawn', 'source_commitment', 'record_commitment')


def RQ05_retained(value, context):
    return 'stop_request_refused' if value['retained'] is not True else None


def RQ06_authorized(value, context):
    return 'stop_request_refused' if value['authorized'] is not True else None


def RQ07_hold_access(value, context):
    return 'stop_request_refused' if value['hold_access_allowed'] is not True else None


def RQ08_not_deleted(value, context):
    return 'stop_request_refused' if value['deleted'] is not False else None


def RQ09_not_withdrawn(value, context):
    return 'stop_request_refused' if value['withdrawn'] is not False else None


def RQ10_source_commitment(value, context):
    return 'stop_request_refused' if value['source_commitment'] != value['record_commitment'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RQ05_retained', g.Invariant('/context/retained', 'is exactly true'), 'stop_request_refused', RQ05_retained),
        g.Guard('RQ06_authorized', g.Invariant('/context/authorized', 'is exactly true'), 'stop_request_refused', RQ06_authorized),
        g.Guard('RQ07_hold_access', g.Invariant('/context/hold_access_allowed', 'is exactly true'), 'stop_request_refused', RQ07_hold_access),
        g.Guard('RQ08_not_deleted', g.Invariant('/context/deleted', 'is exactly false'), 'stop_request_refused', RQ08_not_deleted),
        g.Guard('RQ09_not_withdrawn', g.Invariant('/context/withdrawn', 'is exactly false'), 'stop_request_refused', RQ09_not_withdrawn),
        g.Guard('RQ10_source_commitment', g.Invariant('/context/source_value_sha256', 'equals SHA-256 of the record bytes'), 'stop_request_refused', RQ10_source_commitment),
    ])

    def check(value):
        table.require('RQ05_retained', value, context)
        table.require('RQ06_authorized', value, context)
        table.require('RQ07_hold_access', value, context)
        table.require('RQ08_not_deleted', value, context)
        table.require('RQ09_not_withdrawn', value, context)
        table.require('RQ10_source_commitment', value, context)
        return True
    return g.Case(table, check, context)
