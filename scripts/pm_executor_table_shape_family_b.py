"""DX guard table shape_family_b: Shape oracle: retry, terminal and restore-anchor family predicates.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('retry_family', 'failure_class', 'family', 'terminal_done', 'success', 'restore_required', 'safe_point_present', 'anchor_present')


def SX08_retryable(value, context):
    return 'non-retryable failure' if value['retry_family'] is True and value['failure_class'] in ('graph_integrity', 'verification_failed', 'reviewer_findings', 'quota_exceeded') else None


def SX09_terminal(value, context):
    return 'terminal success/failure mismatch' if value['family'] == 'attempt.completed' and value['terminal_done'] != value['success'] else None


def SX10_restore_safe_point(value, context):
    return 'missing restore anchor' if value['family'] == 'node.blocked' and value['restore_required'] is True and value['safe_point_present'] is not True else None


def SX11_restore_anchor(value, context):
    return 'missing restore anchor' if value['family'] == 'node.blocked' and value['restore_required'] is True and value['anchor_present'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SX08_retryable', g.Invariant('/payload/failure_class', 'backoff_started/retry_scheduled: a retryable class'), 'non-retryable failure', SX08_retryable),
        g.Guard('SX09_terminal', g.Invariant('/payload/terminal_state', 'attempt.completed: done exactly when success'), 'terminal success/failure mismatch', SX09_terminal),
        g.Guard('SX10_restore_safe_point', g.Invariant('/payload/safe_point_id', 'node.blocked restore: a safe point is named'), 'missing restore anchor', SX10_restore_safe_point),
        g.Guard('SX11_restore_anchor', g.Invariant('/payload/anchor_ref', 'node.blocked restore: an anchor is named'), 'missing restore anchor', SX11_restore_anchor),
    ])

    def check(value):
        table.require('SX08_retryable', value, context)
        table.require('SX09_terminal', value, context)
        table.require('SX10_restore_safe_point', value, context)
        table.require('SX11_restore_anchor', value, context)
        return True
    return g.Case(table, check, context)
