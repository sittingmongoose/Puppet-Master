"""DX guard table retry_deadline: Retry: the classified deadline, timed backoff and timer joins.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('until', 'expected_until', 'backoff_family', 'delay', 'expired_family', 'observed', 'started_family', 'payload_until')


def RE01_deadline(value, context):
    return 'original classified retry deadline' if value['until'] != value['expected_until'] else None


def RE02_timed_backoff(value, context):
    return 'classified policy has no timed backoff' if value['backoff_family'] is True and value['delay'][0] <= 0 else None


def RE03_timer_elapsed(value, context):
    return 'early timer' if value['expired_family'] is True and value['observed'][0] * value['until'][1] < value['until'][0] * value['observed'][1] else None


def RE04_start_timer_join(value, context):
    return 'original start timer join' if value['started_family'] is True and value['payload_until'] != value['until'] else None


def RE05_deadline_after_observed(value, context):
    return 'backoff deadline' if value['started_family'] is True and value['payload_until'] == value['until'] and value['until'][0] * value['observed'][1] < value['observed'][0] * value['until'][1] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RE01_deadline', g.Invariant('/records/retry/body/backoff_until_utc', 'equals scheduled plus the classified delay'), 'original classified retry deadline', RE01_deadline),
        g.Guard('RE02_timed_backoff', g.Invariant('/records/retry/body/backoff_until_utc', 'backoff families have a positive delay'), 'classified policy has no timed backoff', RE02_timed_backoff),
        g.Guard('RE03_timer_elapsed', g.Invariant('/payload/ts', 'run.node_backoff_expired: is not before the deadline'), 'early timer', RE03_timer_elapsed),
        g.Guard('RE04_start_timer_join', g.Invariant('/payload/backoff_until_utc', 'run.node_backoff_started: equals the original deadline'), 'original start timer join', RE04_start_timer_join),
        g.Guard('RE05_deadline_after_observed', g.Invariant('/payload/backoff_until_utc', 'run.node_backoff_started: is not before the observation'), 'backoff deadline', RE05_deadline_after_observed),
    ])

    def check(value):
        table.require('RE01_deadline', value, context)
        table.require('RE02_timed_backoff', value, context)
        table.require('RE03_timer_elapsed', value, context)
        table.require('RE04_start_timer_join', value, context)
        table.require('RE05_deadline_after_observed', value, context)
        return True
    return g.Case(table, check, context)
