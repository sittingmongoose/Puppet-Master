def source_facts(snapshot):
    """snapshot: {'files': {relpath: sha256}, 'manifest': {...}, 'preimage': {...}, 'digest_file': str,
    'descriptor': {...}, 'adoption': {...}}. Nothing here reads the filesystem."""
    files, man, pre = snapshot['files'], snapshot['manifest'], snapshot['preimage']
    man_map = {m['path']: m['sha256'] for m in man.get('members', [])} if type(man) is dict else {}
    pre_map = {m['path']: m['sha256'] for m in pre.get('whole_members', [])} if type(pre) is dict else {}
    placed = {p: h for p, h in files.items() if p.startswith(SOURCE)}
    rel = {p[len(SOURCE):]: h for p, h in placed.items()}
    desc = snapshot['descriptor']
    corrections = snapshot['adoption'].get('corrections', []) if type(snapshot['adoption']) is dict else []
    return dict(
        manifest_sha=files.get(SOURCE + 'manifest.json') == MANIFEST_SHA,
        preimage_sha=files.get(SOURCE + 'installed-profile-preimage.json') == FROZEN_DIGEST,
        placed_manifest=bool(rel) and all(man_map.get(p) == h for p, h in rel.items() if p != 'manifest.json'),
        placed_preimage=all(pre_map[p] == h for p, h in rel.items() if p in pre_map),
        canon_members=_ok(lambda: all(files.get(m['path']) == m['sha256'] for m in desc['canon_members'])),
        digest_recorded=_ok(lambda: snapshot['digest_file'] == adoption_digest(desc)),
        corrections_named=[c.get('id') for c in corrections] == ['C%d' % i for i in range(1, 10)]
                          and all(c.get('frozen') and c.get('canon') and c.get('owner') for c in corrections),
    )


