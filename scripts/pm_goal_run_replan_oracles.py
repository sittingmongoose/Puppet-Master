def retained_read(w):
    """('available', event) or ('unavailable'|'unsupported', refusal). Never creates a receipt or alters bytes."""
    facts = retained_facts(w)
    first = refusal('rr', facts) or refusal('rv', facts)
    if first is not None:
        return ('unsupported' if first[2] in ('recipe_unsupported', 'recipe_ambiguous') else 'unavailable', first)
    dispatcher = RetainedDispatcher(ReplanOriginalOwner(w), {RECIPE: frozen_verify(w)})
    try:
        custody = dispatcher.resolve(w['storage']['locator'], binding_of(w), disclose=lambda b: True)
    except Refusal as exc:   # the shared dispatcher is a second, independent line; reached only if a row was weakened
        return ('unavailable', ('dispatcher', 'dispatcher_' + exc.reason, exc.reason))
    assert custody.binding == binding_of(w)
    return ('available', w['event'])


