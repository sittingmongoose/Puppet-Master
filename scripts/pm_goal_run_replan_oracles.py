# --- Method B tables ------------------------------------------------------------------------------------
TABLE_PREFIX = 'pm_grr_table_'
MAX_ROWS = 8
RECORDER = None
_ROWS = {}
_FIELDS = {}


def parts(phase):
    rows = ROWS[phase][2]
    if len(rows) <= MAX_ROWS:
        return [phase]
    return [f'{phase}__{i + 1}' for i in range((len(rows) + MAX_ROWS - 1) // MAX_ROWS)]


def part_rows(phase):
    rows = ROWS[phase][2]
    return {name: rows[i * MAX_ROWS:(i + 1) * MAX_ROWS] for i, name in enumerate(parts(phase))}


def table_rows(table):
    rows = _ROWS.get(table)
    if rows is None:
        module = importlib.import_module(TABLE_PREFIX + table)
        case = module.case(None)
        rows = _ROWS[table] = [(name, guard.predicate, case.context) for name, guard in case.table.guards.items()]
        _FIELDS[table] = module.FIELDS
        spec = [r[1] for r in part_rows(table.split('__')[0])[table]]
        assert list(module.FIELDS) == spec, ('table out of date; run scripts/pm-grr-table-generate.py', table)
    return rows


def refusal(phase, facts):
    """First refusing row of one phase (its part tables in order) as (table, row, code), or None."""
    for table in parts(phase):
        rows = table_rows(table)
        missing = set(_FIELDS[table]) - set(facts)
        assert not missing, (table, sorted(missing))
        observed = {k: facts[k] is True for k in _FIELDS[table]}
        first = None
        for name, predicate, context in rows:
            code = predicate(observed, context)
            if code is not None:
                first = (table, name, code)
                break
        if RECORDER is not None:
            RECORDER.append((table, dict(observed), first))
        if first is not None:
            return first
    return None


