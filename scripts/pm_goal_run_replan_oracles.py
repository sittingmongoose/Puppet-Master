    numbers = number_corpus() if corpus else dict(status='pass', counts={}, mismatch_count=0, mismatches=[], skipped=True)
    static = schema_correspondence()
    status = 'pass' if not (failures or witnessless or numbers['status'] != 'pass' or corr['problems'] or static) else 'fail'
    summary = {'status': status, 'cases': len(results), 'positives': sum(1 for r in results if r['expected'] is None),
               'negatives': sum(1 for r in results if r['expected']), 'rows': len(rows), 'tables': sum(len(parts(p)) for p in ROWS),
               'witnessed_rows': len(targeted & rows), 'rows_without_witness': witnessless, 'not_rows_entailed': sorted(ENTAILED),
               'failures': failures[:40], 'numbers': {k: numbers[k] for k in ('status', 'counts', 'mismatch_count', 'mismatches')},
               'correspondence': corr, 'schema_correspondence_problems': static,
               'adoption_digest': adoption_digest(), 'recorded_digest': recorded_digest(), 'native': 'NOT_RUN'}
    return summary, results


