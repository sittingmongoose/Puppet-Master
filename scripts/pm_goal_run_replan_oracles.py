    for case in doc['cases']:
        if case['op'] not in NUMBER_OPS or 'date_time_profile' in case:
            continue
        spelling, raw = None, case.get('raw')
        if case['op'] in ('token', 'parse', 'slot', 'jcs', 'parse_token') and type(raw) is str:
            spelling = raw
        elif case['op'] in ('integer', 'uint64', 'physical', 'jcs_value') and type(case.get('value')) is dict and set(case['value']) == {'@int'}:
            spelling = case['value']['@int']
