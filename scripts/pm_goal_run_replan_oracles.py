def schema_correspondence():
    """Static: canon v3 = draft grammar with exactly the recorded member changes; graph-patch defs equal the draft source."""
    problems = []
    canon, draft = PAYLOAD_SCHEMA, DRAFT
    removed = set(draft['properties']) - set(canon['properties'])
    if removed != {'expected_goal_revision', 'parent_goal_id'} or set(canon['properties']) - set(draft['properties']):
        problems.append(('properties', sorted(removed)))
    if set(canon['required']) != (set(draft['required']) - {'expected_goal_revision'}) | {'idempotency_key'}:
        problems.append(('required', sorted(set(canon['required']) ^ set(draft['required']))))
    for k in canon['properties']:
        if k in ('schema_version', 'expected_goal_run_revision', 'goal_run_revision', 'payload'):
            continue
        if canon['properties'][k] != draft['properties'][k]:
            problems.append(('property', k))
    for k, v in draft['$defs'].items():
        if k != 'event_payload' and canon['$defs'].get(k) != v:
            problems.append(('def', k))
    src = DRAFT_SOURCE['$defs']
    sid = DRAFT_SOURCE['$id']

    def relocate(node):
        if type(node) is dict:
            out = {}
            for kk, vv in node.items():
                if kk == '$ref' and type(vv) is str:
                    name = vv.split('/')[-1]
                    vv = '#/$defs/graph_patch_' + ('OwnerIdentity' if vv.startswith(_COMPOSED_OWNER) else name)
                out[kk] = relocate(vv)
            return out
        if type(node) is list:
            return [relocate(x) for x in node]
        return node
    for name in ('AppliedGraphPatch', 'AppliedGraphPatchSnapshot', 'GraphPatchOriginalHistory', 'RequestedGraphPatch',
                 'RequestedGraphPatchSnapshot', 'ValidatedGraphPatch', 'ValidatedGraphPatchSnapshot'):
        want = {kk: vv for kk, vv in relocate(src[name]).items() if kk != '$comment'}
        if canon['$defs'].get('graph_patch_' + name) != want:
            problems.append(('graph_patch', name))
    if canon['$defs'].get('graph_patch_OwnerIdentity') != ACTIVATION['$defs']['OwnerIdentity']:
        problems.append(('graph_patch', 'OwnerIdentity'))
    if sha_file(OWNER_IDENTITY_URI['path']) != OWNER_IDENTITY_URI['sha256']:
        problems.append(('owner_identity_source', OWNER_IDENTITY_URI['path']))
    ev_c, ev_d = canon['$defs']['event_payload'], draft['$defs']['event_payload']
    if set(ev_c['properties']) != set(ev_d['properties']) or ev_c['required'] != ev_d['required']:
        problems.append(('event_payload', 'members'))
    if sid not in json.dumps(ev_d):
        problems.append(('event_payload', 'draft source ref'))
    if V2_SCHEMA['$id'] != V2_SCHEMA_ID or sha_file('Plans/event_payloads/goal_runtime/goal_run_replanned.schema.json') != V2_SHA:
        problems.append(('v2', 'bytes changed'))
    return problems



