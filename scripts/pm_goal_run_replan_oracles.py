def evaluate(boundary, value):
    """First refusal (table, row, code) across the boundary's phases, or None when every row passes."""
    if boundary == 'source':
        return refusal('sr', source_facts(value))
    if boundary == 'retention':
        return refusal('rt', retention_facts(value))
    if boundary == 'retained':
        out = retained_read(value)
        return None if out[0] == 'available' else out[1]
    for phase in BOUNDARIES[boundary]:
        first = refusal(phase, FACTS[phase](value))
        if first is not None:
            return first
    return None


