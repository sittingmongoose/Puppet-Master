    ap.add_argument('--outcomes', type=Path)
    ap.add_argument('--write-digest', action='store_true')
    ap.add_argument('--no-corpus', action='store_true', help='skip the shared number corpus (mutation-proof detector runs only)')
    args = ap.parse_args()
    if args.write_digest:
        (ROOT / CONTRACTS / 'adoption-digest.txt').write_text(adoption_digest() + '\n', encoding='utf-8')
        print(adoption_digest())
        return 0
    summary, results = run_all(corpus=not args.no_corpus)
    if args.outcomes:
        args.outcomes.write_text(json.dumps(results, indent=1, sort_keys=True) + '\n')
    print(json.dumps(summary, indent=1, sort_keys=True))
    return 0 if summary['status'] == 'pass' else 1


