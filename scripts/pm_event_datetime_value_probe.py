"""Source-only timestamp trigger, using the runtime's closed resolver graph.

The battery supplies a trigger, never authority for a timestamp role. Reviewed
roles live in a separate committed record whose schema fingerprint is not
regenerated by source_inventory_projection().

Graph discovery and role authority are separate. Discovery may walk everything
it needs to preload the resolver. Authority is an allowlist: a citation counts
for a non-timestamp role only through keywords that prove every accepted value
satisfies it (the value schema, $ref, allOf, or a union in which every branch
carries the same citation). Every other keyword earns no credit, including
$dynamicRef: an outer document can rebind its anchor, so a row-level proof
through it does not hold for every evaluation of the same field.

Conjunction is not enough. The cited definition must also decide the string:
on its own it must refuse every battery timestamp and every fixed non-timestamp
control, so a description-only, member-only or otherwise unconstrained
definition never authorizes a value.
"""
from __future__ import annotations

import json
import re
from urllib.parse import unquote, urlsplit

BATTERY = "scripts/pm_event_datetime_timestamp_battery.json"
ROLES = "scripts/pm_event_datetime_roles.json"

# Keywords that neither route to a schema nor constrain a value.
ANNOTATIONS = frozenset(("$schema", "$id", "$anchor", "$dynamicAnchor", "$recursiveAnchor", "$comment",
                         "$vocabulary", "$defs", "definitions", "title", "description", "default",
                         "examples", "deprecated", "readOnly", "writeOnly"))
# Same-instance assertions with no subschema. They can narrow a value, never
# route authority to another definition.
ASSERTIONS = frozenset(("type", "const", "enum", "format", "pattern", "minLength", "maxLength",
                        "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "multipleOf",
                        "minItems", "maxItems", "uniqueItems", "minContains", "maxContains",
                        "minProperties", "maxProperties", "required",
                        "contentEncoding", "contentMediaType"))
# Positive-path references. $dynamicRef is deliberately absent: its target
# depends on the dynamic scope of each evaluation, not on the row's source.
REFERENCES = ("$ref",)
UNIONS = ("anyOf", "oneOf")
# These apply only to an object's or array's members or sibling structure. They
# never decide whether a string value is accepted. They still earn no credit:
# automatic credit is withheld, and a citation never routes through them.
MEMBER_ONLY = frozenset(("properties", "patternProperties", "additionalProperties", "propertyNames",
                         "unevaluatedProperties", "items", "prefixItems", "additionalItems", "contains",
                         "unevaluatedItems", "dependentSchemas", "dependentRequired", "dependencies"))
# Fixed non-timestamp strings. They never classify a value. They serve two
# refusal-only checks: FIX11's timestamp-only guard (a proven node that accepts
# a timestamp and refuses all 16 refuses the role), and the deciding rule (a
# cited definition that accepts any of them, or any battery timestamp, does not
# decide the string and earns no non-timestamp credit).
NON_TIMESTAMP_CONTROLS = ("", "a", "1", "x.y.z", "resource-id", "abc123", "2026", "2026-01-01", "12:00:00",
                          "2026-01-01T00:00:00", "2026-01-01 00:00:00Z", "deadbeef", "Plans/x.schema.json",
                          "https://example.invalid/a", "a" * 30, "0" * 30)


def timestamp_battery(root, cache):
    from pm_event_datetime import date_time
    from pm_event_datetime_inventory import digest
    key = ("timestamp_battery",)
    if key not in cache:
        battery = json.loads((root / BATTERY).read_text())
        samples = battery["samples"]
        if (battery["schema_id"] != "pm.datetime_timestamp_battery.v1" or
                len(samples) < 300 or len({s["value"] for s in samples}) != len(samples)):
            raise ValueError("invalid committed timestamp battery")
        for sample in samples:
            if not sample["features"] or date_time(sample["value"]) != sample["value"]:
                raise ValueError("invalid timestamp battery sample")
        cache[key] = battery, digest(battery)
    return cache[key]


def wildcard_probe(row, document, root, cache):
    """Validate every sample at each declared key in its real map context.

    In particular, propertyNames and intersecting patternProperties apply.
    A key the source actually forbids cannot turn a setting-ID map into a
    timestamp field. Reference traversal discovers/preloads dependencies only;
    acceptance uses jsonschema's real keywords, resolver and format checker.
    """
    import pm_event_datetime_inventory as inv
    from pm_event_datetime import _closed_datetime_graph, _dialect_validator, format_checker
    from referencing import Registry, Resource
    from referencing.jsonschema import specification_with

    key = ("wildcard_probe", *inv.node_key(row))
    if key in cache:
        return cache[key]
    resource = inv.at(document, row["resource_pointer"])
    base = _dialect_validator(resource)
    spec = specification_with(base.META_SCHEMA["$id"])
    bank, locations, sources, references = {}, {}, {}, {}

    def register(path, pointer, value, aliases=()):
        res = Resource.from_contents(value, default_specification=spec)
        uri = res.id() or "https://puppetmaster.local/" + path
        for alias in (uri, *aliases):
            if alias in bank and inv.digest(bank[alias].contents) != inv.digest(value):
                raise ValueError("source resource URI conflict: " + alias)
            bank[alias] = res
        for relative, node in inv.walk(value):
            locations[id(node)] = (path, pointer + relative)
        return uri

    uri = register(row["path"], row["resource_pointer"], resource)

    def offline_load(requested):
        # This callback constructs the offline bank. It is never installed in
        # the validator that executes the battery.
        path = unquote(urlsplit(requested).path).lstrip("/")
        if not path.startswith("Plans/") or ".." in path.split("/"):
            raise ValueError("source reference is not an offline Plans resource: " + requested)
        target = {"path": path, "origin": "json"}
        value = inv._source_document(root, target, cache)
        register(path, "", value, (requested,))
        return bank[requested]

    discovery = Registry(retrieve=offline_load).with_resources(bank.items()).crawl()
    relative = row["pointer"][len(row["resource_pointer"]):]
    resolved = discovery.resolver(uri).lookup("#" + relative)
    visited = set()

    def visit(value, resolver):
        identity = (id(value), resolver._base_uri)
        if identity in visited:
            return
        visited.add(identity)
        if not isinstance(value, dict):
            return
        path, pointer = locations[id(value)]
        sources[path, pointer] = {"path": path, "pointer": pointer, "value": value}
        for keyword in ("$ref", "$dynamicRef", "$recursiveRef"):
            if keyword in value:
                target = resolver.lookup(value[keyword])
                references[resolver._base_uri, keyword, value[keyword]] = target.contents
                visit(target.contents, target.resolver)
        dialect = _dialect_validator(value, default=base)
        res = Resource.from_contents(value, default_specification=specification_with(dialect.META_SCHEMA["$id"]))
        for child in res.subresources():
            visit(child.contents, resolver.in_subresource(child))

    visit(resolved.contents, resolved.resolver)
    selector = {"$schema": base.META_SCHEMA["$id"], "$ref": uri + "#" + relative}
    selected, registry = _closed_datetime_graph(selector, Registry().with_resources(bank.items()))
    validator = selected(selector, registry=registry, format_checker=format_checker())
    # Discovery above intentionally preloads *all* subresources. Value paths are
    # narrower: follow same-instance applicators, then the actual value selector
    # for this key. Key schemas, sibling values, items and $defs never appear.
    # A timestamp review may cite any such path, because that class claims no
    # exemption. A non-timestamp role needs _PositivePaths below.
    paths, dependencies, contexts = [], [], []
    applicators = ("allOf", "anyOf", "oneOf", "not", "if", "then", "else")

    def location(value):
        path, pointer = locations[id(value)]
        return {"path": path, "pointer": pointer}

    def constraint_paths(value, resolver, field, chain=(), mode="map", seen=frozenset()):
        if not isinstance(value, dict):
            return
        identity = (id(value), resolver._base_uri, mode)
        if identity in seen:
            return
        seen = seen | {identity}
        here = location(value)
        chain = (*chain, here)
        if mode == "value":
            paths.append({"field": field, "path": list(chain)})
        else:
            # Be conservative at object scope. Singleton rejection is not a
            # proof in the presence of sibling cardinality/conditions or a
            # same-instance combinator (including through references).
            for keyword in ("required", "dependentRequired", "dependentSchemas", "dependencies",
                            "minProperties", "maxProperties", "unevaluatedProperties", "const", "enum",
                            *applicators):
                if keyword in value:
                    dependency = {**here, "keyword": keyword}
                    if dependency not in dependencies:
                        dependencies.append(dependency)
            context = {}
            for name, child in value.get("properties", {}).items():
                if name in inv.FIELDS:
                    continue
                if isinstance(child, dict):
                    if "const" in child:
                        context[name] = child["const"]
                    elif child.get("enum"):
                        context[name] = child["enum"][0]
                    else:
                        context[name] = "timestamp"
            if context and context not in contexts:
                contexts.append(context)
            matched = field in value.get("properties", {})
            selectors = []
            if matched:
                selectors.append(value["properties"][field])
            for pattern, child in value.get("patternProperties", {}).items():
                if re.search(pattern, field):
                    matched = True
                    selectors.append(child)
            if not matched and "additionalProperties" in value:
                selectors.append(value["additionalProperties"])
            if "unevaluatedProperties" in value:
                selectors.append(value["unevaluatedProperties"])
            for child in selectors:
                subresource = Resource.from_contents(child, default_specification=spec)
                constraint_paths(child, resolver.in_subresource(subresource), field, chain, "value", seen)
            if (not matched and "additionalProperties" not in value and
                    "propertyNames" in value):
                # An absent additionalProperties is the map's implicit true
                # value constraint. It has no child pointer to cite.
                paths.append({"field": field, "path": list(chain), "implicit_additional_properties": True})
        for keyword in ("$ref", "$dynamicRef", "$recursiveRef"):
            if keyword in value:
                target = resolver.lookup(value[keyword])
                constraint_paths(target.contents, target.resolver, field, chain, mode, seen)
        children = []
        for keyword in applicators:
            child = value.get(keyword)
            children.extend(child if isinstance(child, list) else [child] if isinstance(child, dict) else [])
        if mode == "map":
            children.extend(value.get("dependentSchemas", {}).values())
            children.extend(c for c in value.get("dependencies", {}).values() if isinstance(c, dict))
        for child in children:
            subresource = Resource.from_contents(child, default_specification=spec)
            constraint_paths(child, resolver.in_subresource(subresource), field, chain, mode, seen)

    for field in inv.declarations(inv.at(document, row["pointer"])):
        constraint_paths(resolved.contents, resolved.resolver, field)
    record = _role_records(root, cache).get(inv.node_key(row), {})
    for context in record.get("sibling_contexts", []):
        if not isinstance(context, dict) or set(context).intersection(inv.FIELDS):
            raise ValueError("reviewed sibling context must contain only sibling properties")
        if context not in contexts:
            contexts.append(context)
    if record.get("sibling_contexts"):
        dependencies.append({**location(resolved.contents), "keyword": "reviewed_sibling_context"})

    positive = _PositivePaths(location, base)
    authority = [positive.field(resolved.contents, resolved.resolver, field)
                 for field in inv.declarations(inv.at(document, row["pointer"]))]

    battery, fingerprint = timestamp_battery(root, cache)
    results = []
    for field in inv.declarations(inv.at(document, row["pointer"])):
        for context in ({}, *contexts):
            accepted = [s["value"] for s in battery["samples"]
                        if validator.is_valid({**context, field: s["value"]})]
            result = {"field": field, "accepted": len(accepted),
                      "first_accepted": accepted[0] if accepted else None}
            if context:
                result["context"] = context
            results.append(result)
    citations = [sources[k] for k in sorted(sources)]
    all_refused = all(r["accepted"] == 0 for r in results)
    timestamp_only = []
    if not all_refused:
        # Each proven conjunct or branch through the real validator, closed graph.
        for (path, pointer), (node, resolver, _) in sorted(positive.nodes.items(), key=lambda i: i[0]):
            check = selected(node, registry=registry, format_checker=format_checker(),
                             _resolver=registry.resolver(resolver._base_uri))
            if (any(check.is_valid(s["value"]) for s in battery["samples"]) and
                    not any(check.is_valid(c) for c in NON_TIMESTAMP_CONTROLS)):
                timestamp_only.append({"path": path, "pointer": pointer})
    # The deciding rule. Every proven value node, on its own, through the real
    # validator of its own dialect and the same closed graph: it decides the
    # string only if it refuses every battery sample and every fixed control.
    # An implicit endpoint (an absent additionalProperties) is the unconstrained
    # true schema, so it never decides, even where the same map node is also
    # reached as a value node for another field.
    deciding = []
    for (path, pointer), (node, resolver, dialect) in sorted(positive.nodes.items(), key=lambda i: i[0]):
        if (path, pointer) in positive.implicit:
            continue
        check = dialect(node, registry=registry, format_checker=format_checker(),
                        _resolver=registry.resolver(resolver._base_uri))
        if not (any(check.is_valid(s["value"]) for s in battery["samples"]) or
                any(check.is_valid(c) for c in NON_TIMESTAMP_CONTROLS)):
            deciding.append({"path": path, "pointer": pointer})
    evidence = {"battery_sha256": fingerprint, "samples": len(battery["samples"]),
                "value_schema_sha256": inv.digest({"schemas": citations, "references": [
                    {"base": k[0], "keyword": k[1], "ref": k[2], "value": references[k]}
                    for k in sorted(references)]}),
                "all_refused": all_refused, "results": results,
                "singleton_probes_complete": not dependencies,
                "sibling_dependencies": dependencies, "value_constraint_paths": paths,
                "role_authority": authority, "timestamp_only_nodes": timestamp_only,
                "deciding_nodes": deciding,
                "automatic_credit": (all_refused and not dependencies and
                                     not any(a["unproven"] for a in authority))}
    cache[key] = evidence, citations
    return cache[key]


def _applied_keywords(node, dialect):
    """What the real validator applies: draft 7 and earlier ignore $ref siblings."""
    from jsonschema import Draft201909Validator, Draft202012Validator
    if "$ref" in node and dialect not in (Draft201909Validator, Draft202012Validator):
        return {"$ref": node["$ref"]}
    return node


class _PositivePaths:
    """Definitions every accepted value must satisfy, proven by keyword allowlist.

    Conjunctive paths only. A union counts only for the definitions all of its
    branches carry. Anything unrecognised is recorded as unproven, never walked.
    Reference cycles prove nothing. Only keywords the dialect implements count.
    """

    def __init__(self, location, dialect):
        self.location, self.dialect, self.nodes, self.implicit = location, dialect, {}, set()

    def _enter(self, child, resolver, dialect):
        from referencing import Resource
        from referencing.jsonschema import specification_with
        return resolver.in_subresource(Resource.from_contents(
            child, default_specification=specification_with(dialect.META_SCHEMA["$id"])))

    def field(self, node, resolver, field):
        endpoints, unproven, selected, implicit = self._map(node, resolver, self.dialect, field, frozenset())
        # An absent additionalProperties is the map's implicit true value, but
        # only when no other same-instance schema selects a value for this key.
        if not selected:
            endpoints = endpoints | implicit
            self.implicit.update(implicit)
        return {"field": field,
                "endpoints": [{"path": p, "pointer": q} for p, q in sorted(endpoints)],
                "unproven": [{"path": p, "pointer": q, "keyword": k, "scope": s}
                             for p, q, k, s in sorted(unproven)]}

    def _map(self, node, resolver, dialect, field, stack):
        from pm_event_datetime import _dialect_validator
        if not isinstance(node, dict):
            return frozenset(), frozenset(), False, frozenset()
        dialect = _dialect_validator(node, default=dialect)
        identity = (id(node), resolver._base_uri)
        if identity in stack:
            return frozenset(), frozenset(), False, frozenset()
        stack = stack | {identity}
        here = self.location(node)
        here = here["path"], here["pointer"]
        view = _applied_keywords(node, dialect)
        endpoints, unproven, selected, implicit = set(), set(), False, set()

        def merge(result):
            nonlocal selected
            endpoints.update(result[0])
            unproven.update(result[1])
            selected = selected or result[2]
            implicit.update(result[3])

        for keyword, argument in view.items():
            if (keyword in ANNOTATIONS or keyword in ASSERTIONS or
                    keyword in ("properties", "patternProperties", "additionalProperties", "propertyNames")):
                continue
            if keyword in REFERENCES and keyword in dialect.VALIDATORS:
                target = resolver.lookup(argument)
                merge(self._map(target.contents, target.resolver, dialect, field, stack))
            elif keyword == "allOf":
                for child in argument:
                    merge(self._map(child, self._enter(child, resolver, dialect), dialect, field, stack))
            elif keyword in UNIONS:
                branches = [self._map(c, self._enter(c, resolver, dialect), dialect, field, stack)
                            for c in argument]
                merge((frozenset.intersection(*(b[0] for b in branches)) if branches else frozenset(),
                       frozenset().union(*(b[1] for b in branches)),
                       any(b[2] for b in branches), frozenset()))
            else:
                unproven.add((*here, keyword, "map"))
        children, matched = [], False
        if field in view.get("properties", {}):
            matched = True
            children.append(view["properties"][field])
        for pattern, child in view.get("patternProperties", {}).items():
            if re.search(pattern, field):
                matched = True
                children.append(child)
        if not matched and "additionalProperties" in view:
            children.append(view["additionalProperties"])
        for child in children:
            selected = True
            found, still_open = self._value(child, self._enter(child, resolver, dialect), dialect, frozenset())
            endpoints.update(found)
            unproven.update(still_open)
        if not matched and "additionalProperties" not in view and "propertyNames" in view:
            implicit.add(here)
        return frozenset(endpoints), frozenset(unproven), selected, frozenset(implicit)

    def _value(self, node, resolver, dialect, stack):
        from pm_event_datetime import _dialect_validator
        if not isinstance(node, dict):
            return frozenset(), frozenset()
        dialect = _dialect_validator(node, default=dialect)
        identity = (id(node), resolver._base_uri)
        if identity in stack:
            return frozenset(), frozenset()
        stack = stack | {identity}
        here = self.location(node)
        here = here["path"], here["pointer"]
        self.nodes.setdefault(here, (node, resolver, dialect))
        endpoints, unproven = {here}, set()
        for keyword, argument in _applied_keywords(node, dialect).items():
            if keyword in ANNOTATIONS or keyword in ASSERTIONS:
                continue
            if keyword in REFERENCES and keyword in dialect.VALIDATORS:
                target = resolver.lookup(argument)
                found, still_open = self._value(target.contents, target.resolver, dialect, stack)
                endpoints.update(found)
                unproven.update(still_open)
            elif keyword == "allOf":
                for child in argument:
                    found, still_open = self._value(child, self._enter(child, resolver, dialect), dialect, stack)
                    endpoints.update(found)
                    unproven.update(still_open)
            elif keyword in UNIONS:
                branches = [self._value(c, self._enter(c, resolver, dialect), dialect, stack) for c in argument]
                if branches:
                    endpoints.update(frozenset.intersection(*(b[0] for b in branches)))
                    unproven.update(frozenset().union(*(b[1] for b in branches)))
            else:
                unproven.add((*here, keyword, "value"))
        return frozenset(endpoints), frozenset(unproven)


def _role_records(root, cache):
    key = ("reviewed_wildcard_roles",)
    if key not in cache:
        records = json.loads((root / ROLES).read_text())
        roles = {}
        for record in records:
            selector = tuple(record["node"])
            if selector in roles:
                raise ValueError("duplicate reviewed wildcard role")
            roles[selector] = record
        cache[key] = roles
    return cache[key]


def reviewed_role(row, evidence, citations, root, cache):
    """Return (accepted record or None, tuple of gate errors) for this wildcard row.

    A timestamp review claims no exemption, so any actual value path may carry
    its citation. A non-timestamp role needs a positive path for every field,
    and the cited definition must decide the string on its own: it refuses every
    battery timestamp and every fixed control. Through a positive path every
    accepted value satisfies the citation, so a deciding citation implies the
    value refuses every battery timestamp. The timestamp-accepting checks below
    are kept as a second, independent refusal.
    """
    from pm_event_datetime_inventory import node_key
    review = "wildcard_role_review_required"
    changed = "wildcard_role_evidence_changed"
    record = _role_records(root, cache).get(node_key(row))
    if record is None:
        credited = evidence["singleton_probes_complete"] and (
            evidence["automatic_credit"] or not evidence["all_refused"])
        return None, (() if credited else (review,))
    if record["value_schema_sha256"] != evidence["value_schema_sha256"]:
        return None, ("wildcard_role_schema_changed",)
    citation = record.get("citation", {})
    cited = {k: citation.get(k) for k in ("path", "pointer")}
    fields = {r["field"] for r in evidence["results"]}
    on_value_path = all(any(p["field"] == field and p["path"][-1] == cited
                            for p in evidence["value_constraint_paths"]) for field in fields)
    classification = record.get("classification", "wildcard_non_timestamp_role")
    if (not record.get("role", "").strip() or not record.get("reason", "").strip() or
            citation not in citations or
            classification not in ("wildcard_non_timestamp_role", "other_owner_observation") or
            (classification == "other_owner_observation" and not on_value_path)):
        return None, (changed, review)
    if classification == "other_owner_observation":
        return record, ()
    if not all(cited in a["endpoints"] for a in evidence["role_authority"]):
        return None, ((review,) if on_value_path else (changed, review))
    if cited not in evidence["deciding_nodes"]:
        return None, (review,)
    if not evidence["all_refused"] and (evidence["timestamp_only_nodes"] or any(
            u["scope"] == "map" or u["keyword"] not in MEMBER_ONLY
            for a in evidence["role_authority"] for u in a["unproven"])):
        return None, (review,)
    return record, ()
