"""Source-only timestamp trigger, using the runtime's closed resolver graph.

The battery supplies a trigger, never authority for a timestamp role. Reviewed
roles live in a separate committed record whose schema fingerprint is not
regenerated by source_inventory_projection().
"""
from __future__ import annotations

import json
import re
from urllib.parse import unquote, urlsplit

BATTERY = "scripts/pm_event_datetime_timestamp_battery.json"
ROLES = "scripts/pm_event_datetime_roles.json"


def timestamp_battery(root, cache):
    from pm_event_datetime import date_time
    from pm_event_datetime_inventory import digest
    key = ("timestamp_battery",)
    if key not in cache:
        battery = json.loads((root / BATTERY).read_text())
        samples = battery["samples"]
        if (battery["schema_id"] != "pm.datetime_timestamp_battery.v1" or
                len(samples) < 300 or len({s["value"] for s in samples}) != len(samples)):
            raise ValueError("invalid committed timestamp battery")
        for sample in samples:
            if not sample["features"] or date_time(sample["value"]) != sample["value"]:
                raise ValueError("invalid timestamp battery sample")
        cache[key] = battery, digest(battery)
    return cache[key]


def wildcard_probe(row, document, root, cache):
    """Validate every sample at each declared key in its real map context.

    In particular, propertyNames and intersecting patternProperties apply.
    A key the source actually forbids cannot turn a setting-ID map into a
    timestamp field. Reference traversal discovers/preloads dependencies only;
    acceptance uses jsonschema's real keywords, resolver and format checker.
    """
    import pm_event_datetime_inventory as inv
    from pm_event_datetime import _closed_datetime_graph, _dialect_validator, format_checker
    from referencing import Registry, Resource
    from referencing.jsonschema import specification_with

    key = ("wildcard_probe", *inv.node_key(row))
    if key in cache:
        return cache[key]
    resource = inv.at(document, row["resource_pointer"])
    base = _dialect_validator(resource)
    spec = specification_with(base.META_SCHEMA["$id"])
    bank, locations, sources, references = {}, {}, {}, {}

    def register(path, pointer, value, aliases=()):
        res = Resource.from_contents(value, default_specification=spec)
        uri = res.id() or "https://puppetmaster.local/" + path
        for alias in (uri, *aliases):
            if alias in bank and inv.digest(bank[alias].contents) != inv.digest(value):
                raise ValueError("source resource URI conflict: " + alias)
            bank[alias] = res
        for relative, node in inv.walk(value):
            locations[id(node)] = (path, pointer + relative)
        return uri

    uri = register(row["path"], row["resource_pointer"], resource)

    def offline_load(requested):
        # This callback constructs the offline bank. It is never installed in
        # the validator that executes the battery.
        path = unquote(urlsplit(requested).path).lstrip("/")
        if not path.startswith("Plans/") or ".." in path.split("/"):
            raise ValueError("source reference is not an offline Plans resource: " + requested)
        target = {"path": path, "origin": "json"}
        value = inv._source_document(root, target, cache)
        register(path, "", value, (requested,))
        return bank[requested]

    discovery = Registry(retrieve=offline_load).with_resources(bank.items()).crawl()
    relative = row["pointer"][len(row["resource_pointer"]):]
    resolved = discovery.resolver(uri).lookup("#" + relative)
    visited = set()

    def visit(value, resolver):
        identity = (id(value), resolver._base_uri)
        if identity in visited:
            return
        visited.add(identity)
        if not isinstance(value, dict):
            return
        path, pointer = locations[id(value)]
        sources[path, pointer] = {"path": path, "pointer": pointer, "value": value}
        for keyword in ("$ref", "$dynamicRef", "$recursiveRef"):
            if keyword in value:
                target = resolver.lookup(value[keyword])
                references[resolver._base_uri, keyword, value[keyword]] = target.contents
                visit(target.contents, target.resolver)
        dialect = _dialect_validator(value, default=base)
        res = Resource.from_contents(value, default_specification=specification_with(dialect.META_SCHEMA["$id"]))
        for child in res.subresources():
            visit(child.contents, resolver.in_subresource(child))

    visit(resolved.contents, resolved.resolver)
    selector = {"$schema": base.META_SCHEMA["$id"], "$ref": uri + "#" + relative}
    selected, registry = _closed_datetime_graph(selector, Registry().with_resources(bank.items()))
    validator = selected(selector, registry=registry, format_checker=format_checker())
    # Discovery above intentionally preloads *all* subresources. Authority is
    # narrower: follow only same-instance applicators, then the actual value
    # selector for this key. Key schemas, sibling values, items and $defs are
    # never value-role evidence just because discovery happened to see them.
    paths, dependencies, contexts = [], [], []
    applicators = ("allOf", "anyOf", "oneOf", "not", "if", "then", "else")

    def location(value):
        path, pointer = locations[id(value)]
        return {"path": path, "pointer": pointer}

    def constraint_paths(value, resolver, field, chain=(), mode="map", seen=frozenset()):
        if not isinstance(value, dict):
            return
        identity = (id(value), resolver._base_uri, mode)
        if identity in seen:
            return
        seen = seen | {identity}
        here = location(value)
        chain = (*chain, here)
        if mode == "value":
            paths.append({"field": field, "path": list(chain)})
        else:
            # Be conservative at object scope. Singleton rejection is not a
            # proof in the presence of sibling cardinality/conditions or a
            # same-instance combinator (including through references).
            for keyword in ("required", "dependentRequired", "dependentSchemas", "dependencies",
                            "minProperties", "maxProperties", "unevaluatedProperties", "const", "enum",
                            *applicators):
                if keyword in value:
                    dependency = {**here, "keyword": keyword}
                    if dependency not in dependencies:
                        dependencies.append(dependency)
            context = {}
            for name, child in value.get("properties", {}).items():
                if name in inv.FIELDS:
                    continue
                if isinstance(child, dict):
                    if "const" in child:
                        context[name] = child["const"]
                    elif child.get("enum"):
                        context[name] = child["enum"][0]
                    else:
                        context[name] = "timestamp"
            if context and context not in contexts:
                contexts.append(context)
            matched = field in value.get("properties", {})
            selectors = []
            if matched:
                selectors.append(value["properties"][field])
            for pattern, child in value.get("patternProperties", {}).items():
                if re.search(pattern, field):
                    matched = True
                    selectors.append(child)
            if not matched and "additionalProperties" in value:
                selectors.append(value["additionalProperties"])
            if "unevaluatedProperties" in value:
                selectors.append(value["unevaluatedProperties"])
            for child in selectors:
                subresource = Resource.from_contents(child, default_specification=spec)
                constraint_paths(child, resolver.in_subresource(subresource), field, chain, "value", seen)
            if (not matched and "additionalProperties" not in value and
                    "propertyNames" in value):
                # An absent additionalProperties is the map's implicit true
                # value constraint. It has no child pointer to cite.
                paths.append({"field": field, "path": list(chain), "implicit_additional_properties": True})
        for keyword in ("$ref", "$dynamicRef", "$recursiveRef"):
            if keyword in value:
                target = resolver.lookup(value[keyword])
                constraint_paths(target.contents, target.resolver, field, chain, mode, seen)
        children = []
        for keyword in applicators:
            child = value.get(keyword)
            children.extend(child if isinstance(child, list) else [child] if isinstance(child, dict) else [])
        if mode == "map":
            children.extend(value.get("dependentSchemas", {}).values())
            children.extend(c for c in value.get("dependencies", {}).values() if isinstance(c, dict))
        for child in children:
            subresource = Resource.from_contents(child, default_specification=spec)
            constraint_paths(child, resolver.in_subresource(subresource), field, chain, mode, seen)

    for field in inv.declarations(inv.at(document, row["pointer"])):
        constraint_paths(resolved.contents, resolved.resolver, field)
    record = _role_records(root, cache).get(inv.node_key(row), {})
    for context in record.get("sibling_contexts", []):
        if not isinstance(context, dict) or set(context).intersection(inv.FIELDS):
            raise ValueError("reviewed sibling context must contain only sibling properties")
        if context not in contexts:
            contexts.append(context)
    if record.get("sibling_contexts"):
        dependencies.append({**location(resolved.contents), "keyword": "reviewed_sibling_context"})

    battery, fingerprint = timestamp_battery(root, cache)
    results = []
    for field in inv.declarations(inv.at(document, row["pointer"])):
        for context in ({}, *contexts):
            accepted = [s["value"] for s in battery["samples"]
                        if validator.is_valid({**context, field: s["value"]})]
            result = {"field": field, "accepted": len(accepted),
                      "first_accepted": accepted[0] if accepted else None}
            if context:
                result["context"] = context
            results.append(result)
    citations = [sources[k] for k in sorted(sources)]
    evidence = {"battery_sha256": fingerprint, "samples": len(battery["samples"]),
                "value_schema_sha256": inv.digest({"schemas": citations, "references": [
                    {"base": k[0], "keyword": k[1], "ref": k[2], "value": references[k]}
                    for k in sorted(references)]}),
                "all_refused": all(r["accepted"] == 0 for r in results), "results": results,
                "singleton_probes_complete": not dependencies,
                "sibling_dependencies": dependencies, "value_constraint_paths": paths}
    cache[key] = evidence, citations
    return cache[key]


def _role_records(root, cache):
    key = ("reviewed_wildcard_roles",)
    if key not in cache:
        records = json.loads((root / ROLES).read_text())
        roles = {}
        for record in records:
            selector = tuple(record["node"])
            if selector in roles:
                raise ValueError("duplicate reviewed wildcard role")
            roles[selector] = record
        cache[key] = roles
    return cache[key]


def reviewed_role(row, evidence, citations, root, cache):
    """Require the exact citation at the end of an actual value-constraint path."""
    from pm_event_datetime_inventory import node_key
    record = _role_records(root, cache).get(node_key(row))
    if record is None:
        return None, (None if evidence["singleton_probes_complete"] else "wildcard_role_review_required")
    if record["value_schema_sha256"] != evidence["value_schema_sha256"]:
        return None, "wildcard_role_schema_changed"
    citation = record.get("citation", {})
    cited_location = {k: citation.get(k) for k in ("path", "pointer")}
    fields = {r["field"] for r in evidence["results"]}
    value_bound = all(any(p["field"] == field and p["path"][-1] == cited_location
                         for p in evidence["value_constraint_paths"]) for field in fields)
    if (not record.get("role", "").strip() or not record.get("reason", "").strip() or
            citation not in citations or
            not value_bound or
            record.get("classification", "wildcard_non_timestamp_role") not in
            ("wildcard_non_timestamp_role", "other_owner_observation")):
        return None, "wildcard_role_evidence_changed"
    return record, None
