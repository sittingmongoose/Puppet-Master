"""DX guard table pack_bytes: SP-337 pack bytes: hex, BLAKE3 and byte sizes.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('hex_decodes', 'hex_normalized', 'stored_blake3', 'ref_blake3', 'pack_size_type', 'stored_size', 'pack_size', 'ref_size')


def PK01_hex_decodes(value, context):
    return 'exact normalized pack bytes' if value['hex_decodes'] is not True else None


def PK02_hex_normalized(value, context):
    return 'exact normalized pack bytes' if value['hex_decodes'] is True and value['hex_normalized'] is not True else None


def PK03_blake3(value, context):
    return 'payload pack BLAKE3' if value['hex_decodes'] is True and value['stored_blake3'] != value['ref_blake3'] else None


def PK04_pack_size_type(value, context):
    return 'payload pack byte size' if value['pack_size_type'] != 'int' else None


def PK05_pack_size_bytes(value, context):
    return 'payload pack byte size' if value['hex_decodes'] is True and value['pack_size_type'] == 'int' and value['stored_size'] != value['pack_size'] else None


def PK06_pack_size_ref(value, context):
    return 'payload pack byte size' if value['hex_decodes'] is True and value['pack_size_type'] == 'int' and value['stored_size'] == value['pack_size'] and value['pack_size'] != value['ref_size'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('PK01_hex_decodes', g.Invariant('/payload_packs/*/bytes_hex', 'is a hex string'), 'exact normalized pack bytes', PK01_hex_decodes),
        g.Guard('PK02_hex_normalized', g.Invariant('/payload_packs/*/bytes_hex', 'decoded hex is its own lowercase normal form'), 'exact normalized pack bytes', PK02_hex_normalized),
        g.Guard('PK03_blake3', g.Invariant('/payload_packs/*', 'BLAKE3 of the pack bytes equals the descriptor'), 'payload pack BLAKE3', PK03_blake3),
        g.Guard('PK04_pack_size_type', g.Invariant('/payload_packs/*/byte_size', 'is an integer'), 'payload pack byte size', PK04_pack_size_type),
        g.Guard('PK05_pack_size_bytes', g.Invariant('/payload_packs/*/byte_size', 'an integer pack size equals the pack byte length'), 'payload pack byte size', PK05_pack_size_bytes),
        g.Guard('PK06_pack_size_ref', g.Invariant('/payload_packs/*/byte_size', 'a pack size equal to its byte length equals the descriptor size'), 'payload pack byte size', PK06_pack_size_ref),
    ])

    def check(value):
        table.require('PK01_hex_decodes', value, context)
        table.require('PK02_hex_normalized', value, context)
        table.require('PK03_blake3', value, context)
        table.require('PK04_pack_size_type', value, context)
        table.require('PK05_pack_size_bytes', value, context)
        table.require('PK06_pack_size_ref', value, context)
        return True
    return g.Case(table, check, context)
