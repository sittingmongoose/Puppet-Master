"""DT guard table cp_rows: checkpoint_result: the verified global source rows are well formed.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('rows_type', 'non_object_rows', 'bad_sequence_rows', 'bad_string_rows')


def CP25_rows_list(value, context):
    return 'unavailable' if value['rows_type'] != 'list' else None


def CP26_rows_objects(value, context):
    return 'unavailable' if value['non_object_rows'] != 0 else None


def CP27_rows_sequence(value, context):
    return 'unavailable' if value['bad_sequence_rows'] != 0 else None


def CP28_rows_strings(value, context):
    return 'unavailable' if value['bad_string_rows'] != 0 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP25_rows_list', g.Invariant('/context/source_rows', 'is exactly a list'), 'unavailable', CP25_rows_list),
        g.Guard('CP26_rows_objects', g.Invariant('/context/source_rows', 'every row is exactly an object'), 'unavailable', CP26_rows_objects),
        g.Guard('CP27_rows_sequence', g.Invariant('/context/source_rows/sequence_id', 'every row sequence_id is an exact Storage uint64 (shared storage_uint64, SP-1100)'), 'unavailable', CP27_rows_sequence),
        g.Guard('CP28_rows_strings', g.Invariant('/context/source_rows', 'every row event_type, event_id and scope_partition is a nonempty str'), 'unavailable', CP28_rows_strings),
    ])

    def check(value):
        table.require('CP25_rows_list', value, context)
        table.require('CP26_rows_objects', value, context)
        table.require('CP27_rows_sequence', value, context)
        table.require('CP28_rows_strings', value, context)
        return True
    return g.Case(table, check, context)
