"""DC guard table transition_participant_completed: participant_completed: the attempt or slot outcome is open and waivers are recorded.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('has_attempt', 'attempt_known', 'attempt_slot', 'slot', 'attempt_revision', 'assignment_revision', 'attempt_outcome', 'slot_in_roster', 'revision_closed', 'outcome', 'slot_waived')


def TR32_attempt_known(value, context):
    return 'conflict:unknown_attempt' if value['has_attempt'] is True and value['attempt_known'] is not True else None


def TR33_attempt_slot(value, context):
    return 'conflict:unknown_attempt' if value['attempt_known'] is True and value['attempt_slot'] != value['slot'] else None


def TR34_attempt_revision(value, context):
    return 'conflict:unknown_attempt' if value['attempt_known'] is True and value['attempt_revision'] != value['assignment_revision'] else None


def TR35_attempt_open(value, context):
    return 'conflict:attempt_already_closed' if value['attempt_known'] is True and value['attempt_slot'] == value['slot'] and value['attempt_revision'] == value['assignment_revision'] and value['attempt_outcome'] is not None else None


def TR36_slot_in_roster(value, context):
    return 'conflict:slot_not_in_roster' if value['has_attempt'] is False and value['slot_in_roster'] is not True else None


def TR37_revision_open(value, context):
    return 'conflict:attempt_already_closed' if value['has_attempt'] is False and value['revision_closed'] is True else None


def TR38_waiver_recorded(value, context):
    return 'conflict:waiver_not_recorded' if value['outcome'] == 'explicitly_waived' and value['slot_waived'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR32_attempt_known', g.Invariant('/attempt_id', 'names a started attempt'), 'conflict:unknown_attempt', TR32_attempt_known),
        g.Guard('TR33_attempt_slot', g.Invariant('/participant_slot_id', 'equals the attempt slot'), 'conflict:unknown_attempt', TR33_attempt_slot),
        g.Guard('TR34_attempt_revision', g.Invariant('/assignment_revision', 'equals the attempt revision'), 'conflict:unknown_attempt', TR34_attempt_revision),
        g.Guard('TR35_attempt_open', g.Invariant('/attempt_id', 'the matching attempt has no outcome'), 'conflict:attempt_already_closed', TR35_attempt_open),
        g.Guard('TR36_slot_in_roster', g.Invariant('/participant_slot_id', 'without an attempt: is in the roster'), 'conflict:slot_not_in_roster', TR36_slot_in_roster),
        g.Guard('TR37_revision_open', g.Invariant('/assignment_revision', 'without an attempt: no outcome is recorded for the revision'), 'conflict:attempt_already_closed', TR37_revision_open),
        g.Guard('TR38_waiver_recorded', g.Invariant('/outcome', 'explicitly_waived: the slot waiver is recorded'), 'conflict:waiver_not_recorded', TR38_waiver_recorded),
    ])

    def check(value):
        table.require('TR32_attempt_known', value, context)
        table.require('TR33_attempt_slot', value, context)
        table.require('TR34_attempt_revision', value, context)
        table.require('TR35_attempt_open', value, context)
        table.require('TR36_slot_in_roster', value, context)
        table.require('TR37_revision_open', value, context)
        table.require('TR38_waiver_recorded', value, context)
        return True
    return g.Case(table, check, context)
