def independent_number_expected(raw, js_spelling):
    """Test-only route oracle: independent JSON/Decimal and ECMAScript serialization.

    The product checker still uses only the gated Python helpers. No lane cap or
    new serialization is introduced by this expected-result computation.
    """
    token=raw.strip()
    if token=='-0':
        return ['parser:integer_token']
    def pairs(values):
        result={}
        for key,value in values:
            if key in result:
                raise ValueError('duplicate_key')
            result[key]=value
        return result
    def constant(_):
        raise ValueError('json_nonfinite')
    def integer(text):
        if text=='-0':
            raise ValueError('integer_token')
        return Decimal(text)
    try:
        parsed=json.loads(raw,parse_int=integer,parse_float=Decimal,parse_constant=constant,object_pairs_hook=pairs)
    except json.JSONDecodeError:
        return ['parser:json_syntax']
    except ValueError as error:
        return ['parser:'+str(error)]
    def unicode_bad(value):
        if isinstance(value,str):
            return any(0xD800<=ord(ch)<=0xDFFF for ch in value)
        if isinstance(value,dict):
            return any(unicode_bad(k) or unicode_bad(v) for k,v in value.items())
        if isinstance(value,list):
            return any(unicode_bad(v) for v in value)
        return False
    if unicode_bad(parsed):
        return ['parser:unicode_scalar']
    integer_lexeme=re.fullmatch(r'-?(?:0|[1-9][0-9]*)',token,re.ASCII) is not None
    if not integer_lexeme:
        errors=['payload_occurrence_type']
        if isinstance(parsed,Decimal) and parsed<1:
            errors.append('payload_occurrence_minimum')
        return errors
    if parsed<1:
        return ['payload_occurrence_minimum']
    if js_spelling is None or Decimal(js_spelling)!=parsed:
        return ['occurrence_number']
    return []


def collect():
    controls, negatives = W.all_cases()
    slots = {table: {'controls': [], 'negatives': []} for table in W.TABLES}
    failures = []
    for cid, case in controls:
        refused, values = W.evaluate(case)
        if refused:
            failures.append({'case': cid, 'expected': [], 'actual': refused})
        for table in W.TABLES:
            value = {r['id']: values[r['id']] for r in W.TABLE_ROWS[table]}
            slots[table]['controls'].append({'id': cid, 'value': value})
    for negative in negatives:
        refused, values = W.evaluate(negative['case'])
        expected = [(negative['target'], negative['code'])]
        if refused != expected:
            failures.append({'case': negative['id'], 'expected': expected, 'actual': refused})
        table = W.ROW_TABLE[negative['target']]
        slot = dict(negative)
        slot['control_id'] = negative['case']['boundary'] + ':' + negative['family']
        slot.pop('case')
        slot['value'] = {r['id']: values[r['id']] for r in W.TABLE_ROWS[table]}
        slots[table]['negatives'].append(slot)
    missing = [row['id'] for table in W.TABLES for row in W.TABLE_ROWS[table]
               if not any(n['target'] == row['id'] for n in slots[table]['negatives'])]
    return slots, failures, missing, len(controls), len(negatives)


