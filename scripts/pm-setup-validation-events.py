def run_check(out):
    slots, failures, missing, controls, negatives = collect()
    extras = extra_checks()
    summary = {'status': 'pass' if not failures and not missing and all(r['pass'] for r in extras) else 'fail',
               'families': list(W.FAMILIES), 'tables': len(W.TABLES), 'rows': len(W.ROWS),
               'controls': controls, 'single_defect_negatives': negatives, 'missing_witnesses': missing,
               'failures': failures, 'extra_checks': len(extras), 'extra_failures': [r for r in extras if not r['pass']],
               'native_status': 'NOT_RUN', 'retention': 'RP-RUNTIME-365D@1.0.0', 'decision': 'E9-2 A; DL-086'}
    out.mkdir(parents=True, exist_ok=True)
    (out / 'checks.json').write_text(json.dumps(summary, indent=2, default=str)+'\n')
    with gzip.open(out/'whole-path-vectors.json.gz', 'wt') as handle:
        json.dump(extras, handle, default=str)
    print(json.dumps(summary, indent=2, default=str)[:14000], flush=True)
    return int(summary['status'] != 'pass')


def run_table(table, out):
    slots, failures, missing, _, _ = collect()
    if failures or missing:
        print(json.dumps({'failures': failures[:20], 'missing': missing})); return 1
    slot = slots[table]
    path = 'scripts/' + W.TABLE_PREFIX + table + '.py'
    controls = [g.Control(c['id'], c['value'], 'synthetic') for c in slot['controls']]
    negatives = [g.Negative(n['id'], n['value'], n['target'], n['code'], n['control_id'],
                            n['defect']+'; complete checker gives only this refusal') for n in slot['negatives']]
    suite = g.Suite('s6v '+table, W.table_module(table).case, controls, negatives, (path,), W.ROOT,
                    non_guards=[g.NonGuard(path, 'case', 'return', 'return g.Case(table, check, context)',
                    'Return a fresh engine Case; no acceptance or refusal is computed by this constructor return.')])
    report = g.run(suite, memory=g.MemoryGate(1800, 12, 12, 10, 2700))
    out.mkdir(parents=True, exist_ok=True)
    with gzip.open(out/(table+'.json.gz'), 'wt') as handle:
        json.dump(report, handle, default=str)
    summary = {'table':table, 'status':report['status'], 'rows':len(W.TABLE_ROWS[table]),
               'proved':[r['id'] for r in report.get('rows',[]) if r.get('proved')],
               'unproved':report.get('unproved_guards',[]), 'failures':report.get('failures',[])}
    (out/(table+'.summary.json')).write_text(json.dumps(summary,indent=2,default=str)+'\n')
    print(json.dumps(summary,default=str)[:3500],flush=True)
    return int(report['status']!='PASS')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['generate','generated-check','fixtures','check','guards','guard-table'])
    parser.add_argument('--out',type=Path)
    parser.add_argument('--table',choices=W.TABLES)
    args=parser.parse_args()
    if args.command=='fixtures':
        fixtures();return 0
    if args.command in ('generate','generated-check'):
        changed=generate(args.command=='generated-check')
        print(json.dumps({'tables':len(W.TABLES),'rows':len(W.ROWS),'changed':changed}))
        return int(bool(changed) and args.command=='generated-check')
    if not args.out:
        parser.error('--out is required for evidence')
    if args.command=='check':
        return run_check(args.out)
    if args.command=='guard-table':
        return run_table(args.table,args.out)
    code=0
    for table in W.TABLES:
        result=subprocess.call([sys.executable,'-B',__file__,'guard-table','--table',table,'--out',str(args.out)])
        code=max(code,result)
        if result:
            break
    summaries=[json.loads((args.out/(t+'.summary.json')).read_text()) for t in W.TABLES if (args.out/(t+'.summary.json')).exists()]
    report={'status':'pass' if code==0 and len(summaries)==len(W.TABLES) else 'fail','tables':summaries,
            'proved':sum(len(s['proved']) for s in summaries),'rows':len(W.ROWS)}
    (args.out/'guard-summary.json').write_text(json.dumps(report,indent=2)+'\n')
    return code


if __name__=='__main__':
    sys.exit(main())
