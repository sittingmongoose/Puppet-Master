def module_text(table):
    rows = W.TABLE_ROWS[table]
    lines = ['"""s6v actual checker predicates; generated by pm-setup-validation-events.py generate.',
             'Inputs are original data/copies or named shared-helper results, never row verdicts.',
             'Method B proves only this declared relational static boundary; native custody is NOT_RUN.',
             '"""', 'import pm_guard_isolation as g']
    for row in rows:
        lines += ['', '', 'def ' + row['id'] + '(value, context):',
                  '    record = value[' + repr(row['id']) + ']',
                  "    if record['applies'] is not True:", '        return None',
                  '    if ' + TEMPLATES[row['kind']] + ':', '        return ' + repr(row['code']), '    return None']
    lines += ['', '', 'def case(value):', '    context = None', '    table = g.GuardTable([']
    for row in rows:
        lines += ['        g.Guard(' + repr(row['id']) + ', g.Invariant(' + repr(row['field']) + ', ' + repr(row['words']) +
                  '), ' + repr(row['code']) + ', ' + row['id'] + '),']
    lines += ['    ])', '', '    def check(value):']
    for row in rows:
        lines += ['        table.require(' + repr(row['id']) + ', value, context)']
    lines += ['        return True', '    return g.Case(table, check, context)', '']
    return '\n'.join(lines)


def generate(check=False):
    changed = []
    for table in W.TABLES:
        path = W.ROOT / 'scripts' / (W.TABLE_PREFIX + table + '.py')
        expected = module_text(table)
        if not path.exists() or path.read_text() != expected:
            changed.append(str(path.relative_to(W.ROOT)))
            if not check:
                path.write_text(expected)
    return changed


