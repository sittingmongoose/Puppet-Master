"""DCH guard table hr_source: historical_read_valid: original byte commitment and retained replay policies.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('source_commitment', 'witness_commitment', 'replay_policy')


def HR09_source_commitment(value, context):
    return 'history_refused' if value['source_commitment'] != value['witness_commitment'] else None


def HR10_replay_policy(value, context):
    return 'history_refused' if value['replay_policy'] not in ('dedupe_by_idempotency_key', 'projector_replay_only') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('HR09_source_commitment', g.Invariant('/witness/source_value_sha256', 'equals SHA-256 of the retained record bytes'), 'history_refused', HR09_source_commitment),
        g.Guard('HR10_replay_policy', g.Invariant('/record/replay_policy', 'is dedupe_by_idempotency_key or the compatibility projector_replay_only'), 'history_refused', HR10_replay_policy),
    ])

    def check(value):
        table.require('HR09_source_commitment', value, context)
        table.require('HR10_replay_policy', value, context)
        return True
    return g.Case(table, check, context)
