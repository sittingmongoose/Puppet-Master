"""DS15 guard table cp_row: One matching source row resolved to its own original.

Method B guard rows (scripts/pm_guard_isolation.py) for the DS15 checkers. Each predicate reads one
observation the checker derives from the complete boundary input (recomputed hashes and identities,
canonical-byte sizes, resolved records, presence, typed copies). Predicates never recompute, repair or
call helpers. The checkers refuse only through these rows, in this order
(pm-ds15-event-contracts.py:refusal), and check that every factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-ds15-table-generate.py; edit the row spec there.
"""
import pm_guard_isolation as g

FIELDS = ('original_object', 'row', 'expected_row')


def CR01_row_original(value, context):
    return 'checkpoint_refused' if value['original_object'] is not True else None


def CR02_row_fields(value, context):
    return 'checkpoint_refused' if value['original_object'] is True and value['row'] != value['expected_row'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CR01_row_original', g.Invariant('/original_object', 'the matching row resolves an original record'), 'checkpoint_refused', CR01_row_original),
        g.Guard('CR02_row_fields', g.Invariant('/row', 'every row field equals its own original'), 'checkpoint_refused', CR02_row_fields),
    ])

    def check(value):
        table.require('CR01_row_original', value, context)
        table.require('CR02_row_fields', value, context)
        return True
    return g.Case(table, check, context)
