"""DT guard table tr_gate_passed_b: transition gate.passed: questions, predicates and evidence.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('questions_truthy', 'all_predicates_pass', 'evidence_truthy', 'payload_evidence', 'outcome_evidence')


def GP5_no_questions(value, context):
    return 'transition_refused' if value['questions_truthy'] is True else None


def GP6_all_predicates(value, context):
    return 'transition_refused' if value['all_predicates_pass'] is not True else None


def GP7_evidence_present(value, context):
    return 'transition_refused' if value['evidence_truthy'] is False else None


def GP8_evidence_copy(value, context):
    return 'transition_refused' if value['payload_evidence'] != value['outcome_evidence'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('GP5_no_questions', g.Invariant('/owner_result/question_ids', 'is empty'), 'transition_refused', GP5_no_questions),
        g.Guard('GP6_all_predicates', g.Invariant('/owner_result/all_predicates_pass', 'is True'), 'transition_refused', GP6_all_predicates),
        g.Guard('GP7_evidence_present', g.Invariant('/payload/evidence_refs', 'is nonempty'), 'transition_refused', GP7_evidence_present),
        g.Guard('GP8_evidence_copy', g.Invariant('/payload/evidence_refs', 'equals the report evidence'), 'transition_refused', GP8_evidence_copy),
    ])

    def check(value):
        table.require('GP5_no_questions', value, context)
        table.require('GP6_all_predicates', value, context)
        table.require('GP7_evidence_present', value, context)
        table.require('GP8_evidence_copy', value, context)
        return True
    return g.Case(table, check, context)
