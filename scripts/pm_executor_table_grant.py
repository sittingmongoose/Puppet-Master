"""DX guard table grant: String-list grants: subject and grant list types, then exact membership (string_list_contains).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('subject_type', 'subject_nonempty', 'grant_type', 'items_nonempty_strings', 'member')


def GR01_subject_type(value, context):
    return 'grant subject string' if value['subject_type'] != 'str' else None


def GR02_subject_nonempty(value, context):
    return 'grant subject nonempty' if value['subject_type'] == 'str' and value['subject_nonempty'] is not True else None


def GR03_grant_list(value, context):
    return 'grant list' if value['grant_type'] != 'list' else None


def GR04_grant_items(value, context):
    return 'grant items' if value['grant_type'] == 'list' and value['items_nonempty_strings'] is not True else None


def GR05_membership(value, context):
    return 'grant membership' if value['subject_type'] == 'str' and value['subject_nonempty'] is True and value['grant_type'] == 'list' and value['items_nonempty_strings'] is True and value['member'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('GR01_subject_type', g.Invariant('/viewer', 'the subject is a string'), 'grant subject string', GR01_subject_type),
        g.Guard('GR02_subject_nonempty', g.Invariant('/viewer', 'a string subject is nonempty'), 'grant subject nonempty', GR02_subject_nonempty),
        g.Guard('GR03_grant_list', g.Invariant('/readers', 'the grant is a list'), 'grant list', GR03_grant_list),
        g.Guard('GR04_grant_items', g.Invariant('/readers/*', 'every grant item is a nonempty string'), 'grant items', GR04_grant_items),
        g.Guard('GR05_membership', g.Invariant('/readers', 'a well-typed subject is a member of a well-typed grant'), 'grant membership', GR05_membership),
    ])

    def check(value):
        table.require('GR01_subject_type', value, context)
        table.require('GR02_subject_nonempty', value, context)
        table.require('GR03_grant_list', value, context)
        table.require('GR04_grant_items', value, context)
        table.require('GR05_membership', value, context)
        return True
    return g.Case(table, check, context)
