import pm_guard_isolation as g

FIELDS = ('uses', 'stage', 'expected_stage', 'installed_available', 'expected_installed')


def TC17_no_uses(value, context):
    return 'transition_refused' if value['uses'] != [] else None


def TC18_stage(value, context):
    return 'transition_refused' if value['stage'] != value['expected_stage'] else None


def TC19_installed(value, context):
    return 'transition_refused' if value['installed_available'] is not value['expected_installed'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TC17_no_uses', g.Invariant('/uses', 'removal proceeds only with no use left'), 'transition_refused', TC17_no_uses),
        g.Guard('TC18_stage', g.Invariant('/stage', 'the stage is removing (started) or removed (completed)'), 'transition_refused', TC18_stage),
        g.Guard('TC19_installed', g.Invariant('/installed_available', 'the item is installed until completed'), 'transition_refused', TC19_installed),
    ])

    def check(value):
        table.require('TC17_no_uses', value, context)
        table.require('TC18_stage', value, context)
        table.require('TC19_installed', value, context)
        return True
    return g.Case(table, check, context)
