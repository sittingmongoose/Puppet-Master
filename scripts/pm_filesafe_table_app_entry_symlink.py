import pm_guard_isolation as g

FIELDS = ('present_symlink', 'symlink_target_present', 'payload_id_present')


def AS01_symlink_target(value, context):
    return 'application_symlink_value' if value['present_symlink'] is True and value['symlink_target_present'] is not True else None


def AS02_symlink_payload(value, context):
    return 'application_symlink_value' if value['present_symlink'] is True and value['payload_id_present'] is not False else None


def AS03_nonfile_payload(value, context):
    return 'application_nonfile_payload' if value['present_symlink'] is not True and value['payload_id_present'] is not False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('AS01_symlink_target', g.Invariant('/entries/symlink_target_hex', 'a present symlink names its target'), 'application_symlink_value', AS01_symlink_target),
        g.Guard('AS02_symlink_payload', g.Invariant('/entries/payload_id', 'a present symlink has no payload_id'), 'application_symlink_value', AS02_symlink_payload),
        g.Guard('AS03_nonfile_payload', g.Invariant('/entries/payload_id', 'an absent or non-file, non-symlink entry has no payload_id'), 'application_nonfile_payload', AS03_nonfile_payload),
    ])

    def check(value):
        table.require('AS01_symlink_target', value, context)
        table.require('AS02_symlink_payload', value, context)
        table.require('AS03_nonfile_payload', value, context)
        return True
    return g.Case(table, check, context)
