"""DX guard table integrity_contract: Contract integrity: unadmitted draft, closed schema, paired fixtures.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('admitted', 'additional_properties', 'accept_cases', 'reject_cases')


def IC03_unadmitted(value, context):
    return 'Draft must remain unadmitted' if value['admitted'] is True else None


def IC05_closed_schema(value, context):
    return 'closed payload schema' if value['additional_properties'] is not False else None


def IC06_accept_fixture(value, context):
    return 'paired shape fixtures' if value['accept_cases'] < 1 else None


def IC07_reject_fixture(value, context):
    return 'paired shape fixtures' if value['reject_cases'] < 1 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IC03_unadmitted', g.Invariant('/families/*/event_type', 'is not on the event family registry'), 'Draft must remain unadmitted', IC03_unadmitted),
        g.Guard('IC05_closed_schema', g.Invariant('/schema_ref/additionalProperties', 'is exactly false'), 'closed payload schema', IC05_closed_schema),
        g.Guard('IC06_accept_fixture', g.Invariant('/fixtures', 'has an accepted shape case'), 'paired shape fixtures', IC06_accept_fixture),
        g.Guard('IC07_reject_fixture', g.Invariant('/fixtures', 'has a rejected shape case'), 'paired shape fixtures', IC07_reject_fixture),
    ])

    def check(value):
        table.require('IC03_unadmitted', value, context)
        table.require('IC05_closed_schema', value, context)
        table.require('IC06_accept_fixture', value, context)
        table.require('IC07_reject_fixture', value, context)
        return True
    return g.Case(table, check, context)
