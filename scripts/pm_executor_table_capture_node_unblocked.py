"""DX guard table capture_node_unblocked: node.unblocked: resolution evidence and barrier.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('body_resolution', 'payload_resolution', 'restore_result', 'prerequisite_state')


def NU01_resolution(value, context):
    return 'resolution evidence' if value['body_resolution'] != value['payload_resolution'] else None


def NU02_restore_barrier(value, context):
    return 'resolution barrier' if value['payload_resolution'] == 'safe_point_restored' and value['restore_result'] != 'committed' else None


def NU03_prerequisite_barrier(value, context):
    return 'resolution barrier' if value['payload_resolution'] != 'safe_point_restored' and value['prerequisite_state'] != 'resolved' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('NU01_resolution', g.Invariant('/records/episode/body/resolution', 'equals the payload resolution'), 'resolution evidence', NU01_resolution),
        g.Guard('NU02_restore_barrier', g.Invariant('/records/episode/body/restore_result', 'a safe-point restore is committed'), 'resolution barrier', NU02_restore_barrier),
        g.Guard('NU03_prerequisite_barrier', g.Invariant('/records/episode/body/prerequisite_state', 'any other resolution has a resolved prerequisite'), 'resolution barrier', NU03_prerequisite_barrier),
    ])

    def check(value):
        table.require('NU01_resolution', value, context)
        table.require('NU02_restore_barrier', value, context)
        table.require('NU03_prerequisite_barrier', value, context)
        return True
    return g.Case(table, check, context)
