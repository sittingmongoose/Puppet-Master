"""DCH guard table st_pack_a: stop resolve_value: pack size, exact reference, key, media, Store and scope copy.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('byte_size_type', 'byte_size', 'raw_size', 'reference', 'expected_reference', 'key', 'expected_key', 'media_type', 'pack_store', 'store', 'pack_scope', 'body_scope')


def SV13_byte_size_type(value, context):
    return 'stop_value_unavailable' if value['byte_size_type'] != 'int' else None


def SV14_byte_size(value, context):
    return 'stop_value_unavailable' if value['byte_size_type'] == 'int' and value['byte_size'] != value['raw_size'] else None


def SV15_reference_exact(value, context):
    return 'stop_value_unavailable' if value['reference'] != value['expected_reference'] else None


def SV16_pack_key(value, context):
    return 'stop_value_unavailable' if value['key'] != value['expected_key'] else None


def SV17_media_type(value, context):
    return 'stop_value_unavailable' if value['media_type'] != 'application/msgpack' else None


def SV18_pack_store(value, context):
    return 'stop_value_unavailable' if value['pack_store'] != value['store'] else None


def SV19_scope_copy(value, context):
    return 'stop_value_unavailable' if value['pack_scope'] != value['body_scope'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SV13_byte_size_type', g.Invariant('/source/byte_size', 'is exactly an integer'), 'stop_value_unavailable', SV13_byte_size_type),
        g.Guard('SV14_byte_size', g.Invariant('/source/byte_size', 'equals the encoded body length'), 'stop_value_unavailable', SV14_byte_size),
        g.Guard('SV15_reference_exact', g.Invariant('/record/payload_ref', 'equals the reference recomputed from the body bytes'), 'stop_value_unavailable', SV15_reference_exact),
        g.Guard('SV16_pack_key', g.Invariant('/source/key', 'equals payload:v1: plus BLAKE3 of the body bytes'), 'stop_value_unavailable', SV16_pack_key),
        g.Guard('SV17_media_type', g.Invariant('/source/media_type', 'is application/msgpack'), 'stop_value_unavailable', SV17_media_type),
        g.Guard('SV18_pack_store', g.Invariant('/source/storage_instance_id', 'equals the reading Store'), 'stop_value_unavailable', SV18_pack_store),
        g.Guard('SV19_scope_copy', g.Invariant('/source/scope', 'equals the body scope'), 'stop_value_unavailable', SV19_scope_copy),
    ])

    def check(value):
        table.require('SV13_byte_size_type', value, context)
        table.require('SV14_byte_size', value, context)
        table.require('SV15_reference_exact', value, context)
        table.require('SV16_pack_key', value, context)
        table.require('SV17_media_type', value, context)
        table.require('SV18_pack_store', value, context)
        table.require('SV19_scope_copy', value, context)
        return True
    return g.Case(table, check, context)
