"""DT guard table cp_state: checkpoint_result: publication state, withdrawn and rollback cursors.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('state', 'health', 'withdrawn_at_utc', 'previous_truthy', 'previous_state', 'governed_rebuild', 'previous_examined', 'global_through')


def CP33_state_current(value, context):
    return 'unavailable' if value['state'] != 'current' else None


def CP34_health(value, context):
    return 'unavailable' if value['health'] != 'healthy' else None


def CP35_not_withdrawn_at(value, context):
    return 'unavailable' if value['withdrawn_at_utc'] is not None else None


def CP36_withdrawn_resume(value, context):
    return 'unavailable' if value['previous_truthy'] is True and value['previous_state'] == 'withdrawn' and value['governed_rebuild'] is False else None


def CP37_rollback(value, context):
    return 'coverage_refused' if value['previous_truthy'] is True and value['previous_examined'] is not None and (value['global_through'] is None or value['global_through'] < value['previous_examined']) and value['governed_rebuild'] is False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP33_state_current', g.Invariant('/proposed/state', 'is current'), 'unavailable', CP33_state_current),
        g.Guard('CP34_health', g.Invariant('/proposed/health', 'is healthy'), 'unavailable', CP34_health),
        g.Guard('CP35_not_withdrawn_at', g.Invariant('/proposed/withdrawn_at_utc', 'is null'), 'unavailable', CP35_not_withdrawn_at),
        g.Guard('CP36_withdrawn_resume', g.Invariant('/previous/state', 'a withdrawn prior resumes only by governed rebuild'), 'unavailable', CP36_withdrawn_resume),
        g.Guard('CP37_rollback', g.Invariant('/previous/examined_through_sequence_id', 'the cursor never moves back without governed rebuild'), 'coverage_refused', CP37_rollback),
    ])

    def check(value):
        table.require('CP33_state_current', value, context)
        table.require('CP34_health', value, context)
        table.require('CP35_not_withdrawn_at', value, context)
        table.require('CP36_withdrawn_resume', value, context)
        table.require('CP37_rollback', value, context)
        return True
    return g.Case(table, check, context)
