def ST01_stage(value, context):
    return 'application_operation_staging' if value['kind'] in ('create', 'replace') and not value['stage_ref'] else None


def ST02_create_tombstone(value, context):
    return 'application_operation_staging' if value['kind'] == 'create' and value['tombstone_ref'] is not None else None


def ST03_delete_stage(value, context):
    return 'application_operation_staging' if value['kind'] == 'delete' and value['stage_ref'] is not None else None


def ST04_delete_tombstone(value, context):
    return 'application_operation_staging' if value['kind'] == 'delete' and not value['tombstone_ref'] else None


