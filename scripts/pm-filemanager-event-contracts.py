def slot_values(value, path, location=""):
    if not path:
        yield location, value
        return
    head, rest = path[0], path[1:]
    if head == "*":
        if type(value) is list:
            for index, item in enumerate(value):
                yield from slot_values(item, rest, location + "/" + str(index))
    elif type(value) is dict and head in value:
        yield from slot_values(value[head], rest, location + "/" + head)


def admit_slots(slots, value, root):
    """CV-1100: current_integer at every declared schema integer slot of a current write (never history)."""
    for path, minimum, maximum, nullable in slots:
        for location, slot in slot_values(value, path):
            if nullable and slot is None:
                continue
            reason = integer_refusal(slot, minimum=minimum, maximum=maximum)
            refuse("integer_slot", {"slot_refusal": reason}, message=f"{reason} at {root}{location}")
            refuse("integer_slot_range", {"slot_refusal": reason}, message=f"{reason} at {root}{location}")


def validate_path_coverage(paths, required_paths, label):
    # Accepted and settled snapshots obey the same coverage invariant. Keep one
    # enforcement point so an isolated coverage mutation tests that invariant.
    count = len(paths) == len(required_paths)
    refuse("path_coverage", {"count_matches": count,
                             "members_match": {p["path_ref"] for p in paths} == required_paths if count else None},
           message=label + " path coverage")


LOCATION_FIELDS = (("project_equal", "project_id"), ("revision_equal", "path_snapshot_revision"),
                   ("computer_equal", "computer_id"), ("root_equal", "root_identity_ref"),
                   ("components_equal", "relative_components"))


def validate_path_custody(payload, row):
    """Authenticate complete settled coverage against the accepted path source."""
    paths = row["settlement"]["path_snapshots"]
    required_paths = set(payload["affected_path_refs"] +
                         [payload[k] for k in ("source_path_ref", "destination_path_ref") if k in payload])
    validate_path_coverage(paths, required_paths, "original")
    for p in paths:
        refuse("path_join", {"project_equal": p["project_id"] == payload["project_id"],
                             "revision_equal": p["path_snapshot_revision"] == payload["path_snapshot_revision"],
                             "absence_consistent": (p["node_ref"] is None) == (p["node_kind"] == "absent")})
    accepted_paths = row["accepted_path_snapshots"]
    validate_path_coverage(accepted_paths, required_paths, "accepted")
    for p in paths:
        original = next(a for a in accepted_paths if a["path_ref"] == p["path_ref"])
        refuse("path_location", {fact: original[k] == p[k] for fact, k in LOCATION_FIELDS})


