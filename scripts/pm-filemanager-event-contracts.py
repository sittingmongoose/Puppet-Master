def validate_owner_adoption(name, owner_unit, owner):
    start = owner.find("### " + owner_unit + " - ")
    refuse("owner_unit", {"unit_present": start >= 0}, message=name + ": missing owner unit " + owner_unit)
    section = owner[start:].split("\n### ", 1)[0]
    for token in owner_tokens(name):
        refuse("owner_adoption", {"token_present": token in section}, message=name + ": missing owner adoption " + token)


def validate_registry_contracts(registry, registry_schema, schema):
    with exact_integer_text():
        error = next(jsonschema.Draft202012Validator(registry_schema).iter_errors(registry), None)
        message = None if error is None else str(error)
    refuse("schema_storage_registry", {"schema_valid": error is None}, message=message,
           schema=None if error is None else {"validator": error.validator, "path": list(error.absolute_path)})
    check_schema_document(schema)
    for family, definition in [("filemanager_operation_custody", "operation_custody"),
                               ("filemanager_family_control", "family_control")]:
        entry = next(f for f in registry["families"] if f["family_id"] == family)
        check_schema_document(entry["value_schema"])
        validate_schema_graph({**schema_documents(), "embedded/" + family + ".schema.json": entry["value_schema"]})
        companion = schema["$defs"][definition + "_value"]
        refuse("registry_drift", {fact: entry["value_schema"][k] == companion[k] for fact, k in (
            ("properties_equal", "properties"), ("required_equal", "required"),
            ("additional_equal", "additionalProperties"), ("one_of_equal", "oneOf"))},
            message=family + ": registry/schema drift")
        refuse("registry_custody", {"required_fields_equal": entry["required_fields"] == companion["required"],
                                    "backup_required": bool(entry["recovery_disposition"]["backup_required"]),
                                    "mutation_fence": bool(entry["restore_disposition"]["mutation_fence_on_unresolved"])},
               message=family + ": incomplete registered custody")
        refuse("registry_defs", {"defs_equal": entry["value_schema"]["$defs"] == schema["$defs"]},
               message=family + ": embedded logical schema drift")
        validate_profile(registry, family)
    failures = _codec.storage_value_registry_data_failures(registry, path_label="Plans/storage_value_registry.json")
    refuse("registry_failures", {"no_failures": not failures},
           message="Storage registry contract failures: " + json.dumps(failures))


def integrity_inputs():
    return dict(
        fixtures=json.loads((ROOT / "Plans/filemanager_event_contract_fixtures.json").read_text()),
        owner=(ROOT / "Plans/FileManager.md").read_text(),
        registry=json.loads((ROOT / "Plans/storage_value_registry.json").read_text()),
        registry_schema=json.loads((ROOT / "Plans/storage_value_registry.schema.json").read_text()),
        schema=json.loads((ROOT / "Plans/filemanager_operation_contracts.schema.json").read_text()))


def integrity_witnesses(inputs):
    """Checker-integrity witnesses: one accepting control per route and single-fact negatives.

    Each negative changes exactly one fact of a deep copy of the loaded inputs and names the row
    that must refuse it. main() runs them through the same validators; the guard-table suite
    builder uses them as the integrity rows' controls and negatives.
    """
    fixtures, owner, registry = inputs["fixtures"], inputs["owner"], inputs["registry"]
    registry_schema, schema = inputs["registry_schema"], inputs["schema"]

    def registry_case(edit):
        def action():
            changed = copy.deepcopy(registry)
            edit(changed)
            validate_registry_contracts(changed, registry_schema, schema)
        return action

    def entry(changed, family="filemanager_operation_custody"):
        return next(f for f in changed["families"] if f["family_id"] == family)

    def schema_case(edit):
        def action():
            changed = copy.deepcopy(schema)
            edit(changed)
            validate_registry_contracts(registry, registry_schema, changed)
        return action

    def fixture_case(edit, family=None):
        def action():
            changed = {"rows": [{"event_type": r["event_type"]} for r in fixtures["rows"]]}
            edit(changed)
            validate_fixture_set(changed, family)
        return action

    first = fixtures["rows"][0]
    cases = [
        ("integrity/control/fixture_set", None, fixture_case(lambda c: None)),
        ("integrity/control/fixture_set_family", None, fixture_case(lambda c: None, "file.copied")),
        ("integrity/fixture-unknown-family", "FX01_family_known", fixture_case(lambda c: None, "file.unknown")),
        ("integrity/fixture-extra-row", "FX02_twelve_rows", fixture_case(lambda c: c["rows"].append(dict(c["rows"][0])))),
        ("integrity/fixture-foreign-family", "FX03_family_set",
         fixture_case(lambda c: c["rows"][0].update(event_type="file.unknown"))),
        ("integrity/control/owner", None, lambda: validate_owner_adoption(first["event_type"], first["owner_unit"], owner)),
        ("integrity/owner-unit-missing", "OU01_owner_unit_present",
         lambda: validate_owner_adoption(first["event_type"], first["owner_unit"],
                                         owner.replace("### " + first["owner_unit"] + " - ", "### X-" + first["owner_unit"] + " - "))),
        ("integrity/owner-token-missing", "OA01_owner_token",
         lambda: validate_owner_adoption(first["event_type"], first["owner_unit"],
                                         owner.replace("PENDING_RETENTION_DECISION", "PENDING-RETENTION"))),
        ("integrity/control/registry", None, registry_case(lambda c: None)),
        ("integrity/registry-schema", "RG01_storage_registry", registry_case(lambda c: c.update(unexpected_top_level=True))),
        ("integrity/registry-properties-drift", "RD01_properties",
         registry_case(lambda c: entry(c)["value_schema"]["properties"].update(extra_probe={"type": "string"}))),
        ("integrity/registry-required-drift", "RD02_required",
         registry_case(lambda c: entry(c)["value_schema"]["required"].pop())),
        ("integrity/registry-additional-drift", "RD03_additional",
         registry_case(lambda c: entry(c)["value_schema"].update(additionalProperties=True))),
        ("integrity/registry-oneof-drift", "RD04_one_of",
         registry_case(lambda c: entry(c)["value_schema"].update(oneOf=entry(c)["value_schema"]["oneOf"][:1]))),
        ("integrity/registry-required-fields", "RC01_required_fields",
         registry_case(lambda c: entry(c).update(required_fields=entry(c)["required_fields"][:-1]))),
        ("integrity/registry-backup-required", "RC02_backup_required",
         registry_case(lambda c: entry(c)["recovery_disposition"].update(backup_required=False))),
        ("integrity/registry-mutation-fence", "RC03_mutation_fence",
         registry_case(lambda c: entry(c)["restore_disposition"].update(mutation_fence_on_unresolved=False))),
        ("integrity/registry-defs-drift", "RX01_embedded_defs",
         registry_case(lambda c: entry(c)["value_schema"]["$defs"].update(extra_probe={"type": "string"}))),
        ("integrity/registry-data-failure", "RF01_registry_data",
         registry_case(lambda c: c["families"].append(copy.deepcopy(entry(c))))),
        ("integrity/schema-meta", "SM01_meta_schema", schema_case(lambda c: c.update(type=5))),
        ("integrity/registry-dormant-ref", "SR01_ref_resolves",
         registry_case(lambda c: entry(c)["value_schema"]["$defs"].update(
             unexercised_probe={"$ref": "#/$defs/unresolvable_probe"}))),
    ]
    return cases


def run_integrity_witnesses(inputs):
    count = 0
    for case_id, row, action in integrity_witnesses(inputs):
        try:
            action()
        except TableRefusal as error:
            if row is None or error.row != row:
                raise AssertionError(case_id + ": refused by " + error.row + ", expected " + str(row)) from error
        else:
            if row is not None:
                raise AssertionError(case_id + ": accepted, expected " + row)
        count += 1
    return count


def p2a_cases():
    return json.loads((ROOT / P2A_CASES).read_text())["rows"]


def run_p2a_case(row, case):
    """A sweep part 2A witness: a control must accept; a negative must refuse at exactly its row."""
    try:
        boundary_case(row, case)
    except TableRefusal as error:
        if case["valid"] or error.row != case["expected_row"]:
            raise AssertionError(row["event_type"] + ": p2a witness " + case["name"] + " refused by " + error.row) from error
        check_negative_reason(case, error)
    else:
        if not case["valid"]:
            raise AssertionError(row["event_type"] + ": accepted p2a witness " + case["name"])


def main(family=None):
    global SCHEMAS
    SCHEMAS = schema_registry()  # Fail before instances, even if no fixture visits a broken ref.
    inputs = integrity_inputs()
    fixtures = inputs["fixtures"]
    validate_fixture_set(fixtures, family)
    witnesses = p2a_cases()
    p2a = 0
    count = 0
    assessed_families = 0
    for row in fixtures["rows"]:
        if family is not None and row["event_type"] != family:
            continue
        assessed_families += 1
        name, payload, trace = row["event_type"], row["payload"], row["trace"]
        validate_case(name, payload, trace)
        count += 1
        for case in row["negative_cases"]:
            try:
                negative_case(row, case)
            except (ValueError, KeyError, jsonschema.ValidationError) as error:
                check_negative_reason(case, error)
                count += 1
            else:
                raise AssertionError(name + ": accepted negative " + case["name"])
        for case in row["transition_cases"]:
            try:
                transition_case(row, case)
            except (ValueError, KeyError, jsonschema.ValidationError) as error:
                if case["valid"]:
                    raise AssertionError(name + ": rejected positive transition " + case["name"])
                check_negative_reason(case, error)
            else:
                if not case["valid"]:
                    raise AssertionError(name + ": accepted negative transition " + case["name"])
            count += 1
        for case in row["boundary_cases"]:
            try:
                boundary_case(row, case)
            except (ValueError, KeyError, jsonschema.ValidationError) as error:
                if case["valid"]:
                    raise AssertionError(name + ": rejected positive boundary " + case["name"]) from error
                check_negative_reason(case, error)
            else:
                if not case["valid"]:
                    raise AssertionError(name + ": accepted negative boundary " + case["name"])
            count += 1
        for case in witnesses.get(name, []):
            run_p2a_case(row, case)
            p2a += 1
        validate_owner_adoption(name, row["owner_unit"], inputs["owner"])
    validate_registry_contracts(inputs["registry"], inputs["registry_schema"], inputs["schema"])
    integrity = run_integrity_witnesses(inputs)
    print(json.dumps({"status": "pass", "families": assessed_families,
                      "oracle_cases": count, "sweep_p2a_witnesses": p2a, "integrity_witnesses": integrity,
                      "native_execution": "NOT_RUN"}))
    return 0


