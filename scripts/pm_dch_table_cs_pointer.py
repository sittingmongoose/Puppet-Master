"""DCH guard table cs_pointer: checkpoint_storage_valid: exact SP-337 pointer and pack body bytes.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('pointer', 'expected_pointer', 'pack_body_encoding_error', 'pack_body_equal')


def CS06_pointer_exact(value, context):
    return 'checkpoint_storage_refused' if value['pointer'] != value['expected_pointer'] else None


def CS07_pack_body_encodable(value, context):
    return 'checkpoint_storage_refused' if value['pack_body_encoding_error'] is not None else None


def CS08_pack_body_bytes(value, context):
    return 'checkpoint_storage_refused' if value['pack_body_encoding_error'] is None and value['pack_body_equal'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CS06_pointer_exact', g.Invariant('/source/checkpoint_storage/pointer', 'is exactly {payload_ref: reference of the value bytes}'), 'checkpoint_storage_refused', CS06_pointer_exact),
        g.Guard('CS07_pack_body_encodable', g.Invariant('/source/checkpoint_storage/pack/body', 'encodes under the value recipe'), 'checkpoint_storage_refused', CS07_pack_body_encodable),
        g.Guard('CS08_pack_body_bytes', g.Invariant('/source/checkpoint_storage/pack/body', 'has exactly the checkpoint value bytes'), 'checkpoint_storage_refused', CS08_pack_body_bytes),
    ])

    def check(value):
        table.require('CS06_pointer_exact', value, context)
        table.require('CS07_pack_body_encodable', value, context)
        table.require('CS08_pack_body_bytes', value, context)
        return True
    return g.Case(table, check, context)
