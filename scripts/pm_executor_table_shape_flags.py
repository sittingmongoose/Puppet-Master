"""DX guard table shape_flags: Shape oracle: synthetic predicate flags are exactly true.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('admitted', 'source_refs_valid', 'read_authorized', 'receipt_available', 'predicate_valid')


def SF02_admitted(value, context):
    return 'admitted' if value['admitted'] is not True else None


def SF03_source_refs(value, context):
    return 'source_refs_valid' if value['source_refs_valid'] is not True else None


def SF04_read_authorized(value, context):
    return 'read_authorized' if value['read_authorized'] is not True else None


def SF05_receipt(value, context):
    return 'receipt_available' if value['receipt_available'] is not True else None


def SF06_predicate(value, context):
    return 'predicate_valid' if value['predicate_valid'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SF02_admitted', g.Invariant('/context/admitted', 'is true'), 'admitted', SF02_admitted),
        g.Guard('SF03_source_refs', g.Invariant('/context/source_refs_valid', 'is true'), 'source_refs_valid', SF03_source_refs),
        g.Guard('SF04_read_authorized', g.Invariant('/context/read_authorized', 'is true'), 'read_authorized', SF04_read_authorized),
        g.Guard('SF05_receipt', g.Invariant('/context/receipt_available', 'is true'), 'receipt_available', SF05_receipt),
        g.Guard('SF06_predicate', g.Invariant('/context/predicate_valid', 'is true'), 'predicate_valid', SF06_predicate),
    ])

    def check(value):
        table.require('SF02_admitted', value, context)
        table.require('SF03_source_refs', value, context)
        table.require('SF04_read_authorized', value, context)
        table.require('SF05_receipt', value, context)
        table.require('SF06_predicate', value, context)
        return True
    return g.Case(table, check, context)
