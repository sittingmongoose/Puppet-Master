def TC01_producer(value, context):
    return 'thread_refused' if value['command'] != 'cmd.chat.thread.commit_first_message' else None


def TC02_user_message(value, context):
    return 'thread_refused' if value['role'] != 'user' else None


def TC03_message_committed(value, context):
    return 'thread_refused' if value['message_committed'] is not True else None


def TC04_first_message(value, context):
    return 'thread_refused' if value['message_id'] != value['payload_first_message_id'] else None


def TC05_joint_commit(value, context):
    return 'thread_refused' if value['message_commit_group'] != value['thread_commit_group'] else None


def TC06_record_ref(value, context):
    return 'thread_refused' if value['record_ref'] != value['payload_record_ref'] else None


def TC07_not_discarded(value, context):
    return 'thread_refused' if value['discard_empty_draft'] is not False else None


