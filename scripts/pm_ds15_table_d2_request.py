import pm_guard_isolation as g

FIELDS = ('owner_rules_satisfied', 'remove', 'listed_uses_present', 'installed_available', 'queued', 'effective_version', 'previous_version')


def CQ01_owner_rules(value, context):
    return 'request_refused' if not value['owner_rules_satisfied'] else None


def CQ02_remove_installed(value, context):
    return 'request_refused' if value['remove'] is True and value['listed_uses_present'] is True and not value['installed_available'] else None


def CQ03_remove_not_queued(value, context):
    return 'request_refused' if value['remove'] is True and value['listed_uses_present'] is True and value['installed_available'] and value['queued'] else None


def CQ04_update_verified(value, context):
    return 'request_refused' if value['remove'] is False and value['listed_uses_present'] is True and value['effective_version'] != value['previous_version'] else None


def CQ05_update_installed(value, context):
    return 'request_refused' if value['remove'] is False and value['listed_uses_present'] is True and value['effective_version'] == value['previous_version'] and not value['installed_available'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CQ01_owner_rules', g.Invariant('/owner_rules_satisfied', 'the existing owner rules are satisfied'), 'request_refused', CQ01_owner_rules),
        g.Guard('CQ02_remove_installed', g.Invariant('/installed_available', 'a refused removal keeps the item installed'), 'request_refused', CQ02_remove_installed),
        g.Guard('CQ03_remove_not_queued', g.Invariant('/queued', 'a refused removal queues nothing'), 'request_refused', CQ03_remove_not_queued),
        g.Guard('CQ04_update_verified', g.Invariant('/effective_version', 'a deferred update keeps the verified version effective'), 'request_refused', CQ04_update_verified),
        g.Guard('CQ05_update_installed', g.Invariant('/installed_available', 'a deferred update keeps the item installed'), 'request_refused', CQ05_update_installed),
    ])

    def check(value):
        table.require('CQ01_owner_rules', value, context)
        table.require('CQ02_remove_installed', value, context)
        table.require('CQ03_remove_not_queued', value, context)
        table.require('CQ04_update_verified', value, context)
        table.require('CQ05_update_installed', value, context)
        return True
    return g.Case(table, check, context)
