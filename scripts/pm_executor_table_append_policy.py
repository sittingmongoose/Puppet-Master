"""DX guard table append_policy: Current writer replay policy (standing check 1).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('policy', 'contract_policy')


def AP01_replay_only(value, context):
    return 'replay_only_not_appendable' if value['policy'] == 'projector_replay_only' else None


def AP02_family_policy(value, context):
    return 'family append replay policy' if value['policy'] != 'projector_replay_only' and (value['contract_policy'] != 'dedupe_by_idempotency_key' or value['policy'] != 'dedupe_by_idempotency_key') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('AP01_replay_only', g.Invariant('/replay_policy', 'a current writer never uses projector_replay_only'), 'replay_only_not_appendable', AP01_replay_only),
        g.Guard('AP02_family_policy', g.Invariant('/replay_policy', 'equals the family dedupe_by_idempotency_key policy'), 'family append replay policy', AP02_family_policy),
    ])

    def check(value):
        table.require('AP01_replay_only', value, context)
        table.require('AP02_family_policy', value, context)
        return True
    return g.Case(table, check, context)
