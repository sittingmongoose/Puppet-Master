"""DCH guard table rb_route: resolve_body: selected body encoding, inline limit and reference route shape.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('encoding_error', 'route', 'inline_size', 'payload_empty', 'source_truthy')


def RB01_body_encodable(value, context):
    return 'body_unavailable' if value['encoding_error'] is not None else None


def RB02_inline_limit(value, context):
    return 'body_unavailable' if value['route'] == 'inline' and value['encoding_error'] is None and value['inline_size'] > 16384 else None


def RB03_ref_payload_empty(value, context):
    return 'body_unavailable' if value['route'] == 'ref' and value['payload_empty'] is not True else None


def RB04_ref_source_present(value, context):
    return 'body_unavailable' if value['route'] == 'ref' and value['source_truthy'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RB01_body_encodable', g.Invariant('/payload | source/body', 'the selected body encodes under the selected recipe'), 'body_unavailable', RB01_body_encodable),
        g.Guard('RB02_inline_limit', g.Invariant('/payload', 'an inline body encodes to at most 16384 bytes'), 'body_unavailable', RB02_inline_limit),
        g.Guard('RB03_ref_payload_empty', g.Invariant('/payload', 'a referenced record carries the empty inline payload'), 'body_unavailable', RB03_ref_payload_empty),
        g.Guard('RB04_ref_source_present', g.Invariant('/source', 'a referenced record has a nonempty pack source'), 'body_unavailable', RB04_ref_source_present),
    ])

    def check(value):
        table.require('RB01_body_encodable', value, context)
        table.require('RB02_inline_limit', value, context)
        table.require('RB03_ref_payload_empty', value, context)
        table.require('RB04_ref_source_present', value, context)
        return True
    return g.Case(table, check, context)
