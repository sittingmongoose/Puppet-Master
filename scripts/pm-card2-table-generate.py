#!/usr/bin/env python3
"""Generate the DCN Method B guard-table modules from pm_card2_events.ROWS.

Each table module (scripts/pm_card2_table_<table>.py) holds one predicate per row.
A predicate reads the single boolean observation its row names and returns the
row's refusal code when the observation is not True. The checker derives the
observations; predicates never recompute, repair or call helpers.

  python3 scripts/pm-card2-table-generate.py           # write the modules
  python3 scripts/pm-card2-table-generate.py --check   # exit 1 if any module is stale or extra
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import pm_card2_events as dcn  # noqa: E402

HEADER = '''"""DCN guard table {table}.

Method B guard rows (scripts/pm_guard_isolation.py) for scripts/pm_card2_events.py. Each predicate
reads the one boolean observation the checker derives for its row from the complete scenario
(True: the row's predicate holds or does not apply). Predicates never recompute, repair or call
helpers. The checker refuses only through these rows, in this order.
Generated by scripts/pm-card2-table-generate.py from pm_card2_events.ROWS; edit the spec there.
{entailed}"""
import pm_guard_isolation as g
'''


def literal(text):
    return repr(text)


def module(table, rows):
    entailed = ''
    if table.startswith('entailed_'):
        rid = rows[0]['id']
        first, proof = dcn.ENTAILED[rid]
        entailed = ('\nUnprovable by construction: always refused first by ' + ', '.join(first) +
                    '.\nProof: ' + proof + '\n')
    out = [HEADER.format(table=table, entailed=entailed)]
    out.append('FIELDS = (' + ''.join(literal(r['id']) + ', ' for r in rows) + ')\n')
    for r in rows:
        out.append('\ndef {0}(value, context):\n    return {1} if value[{2}] is not True else None\n'.format(
            r['id'], literal(r['code']), literal(r['id'])))
    out.append('\ndef case(value):\n    context = None\n    table = g.GuardTable([\n')
    for r in rows:
        out.append('        g.Guard({0}, g.Invariant({1}, {2}), {3}, {4}),\n'.format(
            literal(r['id']), literal(r['field']), literal(r['words']), literal(r['code']), r['id']))
    out.append('    ])\n\n    def check(value):\n')
    for r in rows:
        out.append('        table.require({0}, value, context)\n'.format(literal(r['id'])))
    out.append('        return True\n    return g.Case(table, check, context)\n')
    return ''.join(out)


def expected():
    files = {}
    for table in dcn.TABLES:
        rows = [r for r in dcn.ROWS if r['table'] == table]
        files[ROOT / 'scripts' / (dcn.TABLE_PREFIX + table + '.py')] = module(table, rows)
    return files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = expected()
    existing = set((ROOT / 'scripts').glob(dcn.TABLE_PREFIX + '*.py'))
    stale = sorted(str(p.name) for p, text in files.items() if not p.exists() or p.read_text() != text)
    extra = sorted(str(p.name) for p in existing - set(files))
    if args.check:
        print({'tables': len(files), 'rows': len(dcn.ROWS), 'stale': stale, 'extra': extra})
        return 1 if stale or extra else 0
    for path, text in files.items():
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    for path in existing - set(files):
        path.unlink()
    print({'tables': len(files), 'rows': len(dcn.ROWS), 'written': len(stale), 'removed': len(extra)})
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
