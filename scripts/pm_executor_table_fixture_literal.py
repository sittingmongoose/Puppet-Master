"""DX guard table fixture_literal: Fixture authoring notation: explicit repetition parts.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('part_type', 'part_keys', 'text_type', 'repeat_type', 'repeat')


def FL01_part_object(value, context):
    return 'fixture repetition syntax' if value['part_type'] != 'dict' else None


def FL02_part_keys(value, context):
    return 'fixture repetition syntax' if value['part_type'] == 'dict' and value['part_keys'] != ['repeat', 'text'] else None


def FL03_text_type(value, context):
    return 'fixture repetition syntax' if value['part_type'] == 'dict' and value['part_keys'] == ['repeat', 'text'] and value['text_type'] != 'str' else None


def FL04_repeat_type(value, context):
    return 'fixture repetition syntax' if value['part_type'] == 'dict' and value['part_keys'] == ['repeat', 'text'] and value['repeat_type'] != 'int' else None


def FL05_repeat_nonnegative(value, context):
    return 'fixture repetition syntax' if value['part_type'] == 'dict' and value['part_keys'] == ['repeat', 'text'] and value['repeat_type'] == 'int' and value['repeat'] < 0 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('FL01_part_object', g.Invariant('/fixture_text_parts/*', 'a non-string part is an object'), 'fixture repetition syntax', FL01_part_object),
        g.Guard('FL02_part_keys', g.Invariant('/fixture_text_parts/*', 'an object part has exactly text and repeat'), 'fixture repetition syntax', FL02_part_keys),
        g.Guard('FL03_text_type', g.Invariant('/fixture_text_parts/*/text', 'is a string'), 'fixture repetition syntax', FL03_text_type),
        g.Guard('FL04_repeat_type', g.Invariant('/fixture_text_parts/*/repeat', 'is an integer'), 'fixture repetition syntax', FL04_repeat_type),
        g.Guard('FL05_repeat_nonnegative', g.Invariant('/fixture_text_parts/*/repeat', 'an integer repeat is not negative'), 'fixture repetition syntax', FL05_repeat_nonnegative),
    ])

    def check(value):
        table.require('FL01_part_object', value, context)
        table.require('FL02_part_keys', value, context)
        table.require('FL03_text_type', value, context)
        table.require('FL04_repeat_type', value, context)
        table.require('FL05_repeat_nonnegative', value, context)
        return True
    return g.Case(table, check, context)
