"""DCH guard table st_ref: stop resolve_value: reference route shape.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('reference_type', 'payload_empty', 'source_type', 'body_type')


def SV06_reference_string(value, context):
    return 'stop_value_unavailable' if value['reference_type'] != 'str' else None


def SV07_payload_empty(value, context):
    return 'stop_value_unavailable' if value['payload_empty'] is not True else None


def SV08_source_object(value, context):
    return 'stop_value_unavailable' if value['source_type'] != 'dict' else None


def SV09_source_body_object(value, context):
    return 'stop_value_unavailable' if value['source_type'] == 'dict' and value['body_type'] != 'dict' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SV06_reference_string', g.Invariant('/record/payload_ref', 'is exactly a string'), 'stop_value_unavailable', SV06_reference_string),
        g.Guard('SV07_payload_empty', g.Invariant('/record/payload', 'a referenced record carries the empty inline payload'), 'stop_value_unavailable', SV07_payload_empty),
        g.Guard('SV08_source_object', g.Invariant('/source', 'is exactly a JSON object'), 'stop_value_unavailable', SV08_source_object),
        g.Guard('SV09_source_body_object', g.Invariant('/source/body', 'is exactly a JSON object'), 'stop_value_unavailable', SV09_source_body_object),
    ])

    def check(value):
        table.require('SV06_reference_string', value, context)
        table.require('SV07_payload_empty', value, context)
        table.require('SV08_source_object', value, context)
        table.require('SV09_source_body_object', value, context)
        return True
    return g.Case(table, check, context)
