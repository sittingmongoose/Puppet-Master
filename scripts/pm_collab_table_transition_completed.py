"""DC guard table transition_completed: collaboration.completed: owner-derived requiredness, waivers and outputs (CWR-031).

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('required_slot_ids', 'run_required_slot_ids', 'waived_slot_ids', 'run_waived_slot_ids', 'run_kind', 'completion_trigger', 'required_outcomes', 'synthesized', 'finalized_ref', 'output_refs', 'synthesized_plan_ref')


def TR20_required_set(value, context):
    return 'conflict:required_slot_set_mismatch' if value['required_slot_ids'] != value['run_required_slot_ids'] else None


def TR21_waived_set(value, context):
    return 'conflict:waived_slot_set_mismatch' if value['waived_slot_ids'] != value['run_waived_slot_ids'] else None


def TR22_required_resolved(value, context):
    return 'conflict:unresolved_required_slots' if not (value['run_kind'] == 'chat_room' and value['completion_trigger'] == 'chat_room_end') and set(value['required_outcomes']) - {'completed', 'explicitly_waived'} else None


def TR23_brainstorm_output(value, context):
    return 'conflict:missing_output' if value['run_kind'] == 'brainstorm' and value['synthesized'] is not True else None


def TR24_review_output(value, context):
    return 'conflict:missing_output' if value['run_kind'] == 'review' and value['finalized_ref'] is None else None


def TR25_brainstorm_refs(value, context):
    return 'conflict:output_refs_mismatch' if value['run_kind'] == 'brainstorm' and value['synthesized'] is True and value['output_refs'] != [value['synthesized_plan_ref']] else None


def TR26_review_refs(value, context):
    return 'conflict:output_refs_mismatch' if value['run_kind'] == 'review' and value['finalized_ref'] is not None and value['output_refs'] != [value['finalized_ref']] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR20_required_set', g.Invariant('/required_slot_ids', 'equals the run required set'), 'conflict:required_slot_set_mismatch', TR20_required_set),
        g.Guard('TR21_waived_set', g.Invariant('/waived_slot_ids', 'equals the recorded waived slots'), 'conflict:waived_slot_set_mismatch', TR21_waived_set),
        g.Guard('TR22_required_resolved', g.Invariant('/required_slot_ids', 'every required slot is completed or waived unless Chat Room End'), 'conflict:unresolved_required_slots', TR22_required_resolved),
        g.Guard('TR23_brainstorm_output', g.Invariant('/output_refs', 'BrainStorm: a Plan is synthesized'), 'conflict:missing_output', TR23_brainstorm_output),
        g.Guard('TR24_review_output', g.Invariant('/output_refs', 'Review: an artifact is finalized'), 'conflict:missing_output', TR24_review_output),
        g.Guard('TR25_brainstorm_refs', g.Invariant('/output_refs', 'BrainStorm: names the synthesized Plan'), 'conflict:output_refs_mismatch', TR25_brainstorm_refs),
        g.Guard('TR26_review_refs', g.Invariant('/output_refs', 'Review: names the finalized artifact'), 'conflict:output_refs_mismatch', TR26_review_refs),
    ])

    def check(value):
        table.require('TR20_required_set', value, context)
        table.require('TR21_waived_set', value, context)
        table.require('TR22_required_resolved', value, context)
        table.require('TR23_brainstorm_output', value, context)
        table.require('TR24_review_output', value, context)
        table.require('TR25_brainstorm_refs', value, context)
        table.require('TR26_review_refs', value, context)
        return True
    return g.Case(table, check, context)
