"""DT guard table tr_gate_failed_b: transition gate.failed: questions, evidence and failure code.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('questions_truthy', 'evidence_truthy', 'payload_evidence', 'outcome_evidence', 'payload_failure_code', 'outcome_failure_code')


def GF5_no_questions(value, context):
    return 'transition_refused' if value['questions_truthy'] is True else None


def GF6_evidence_present(value, context):
    return 'transition_refused' if value['evidence_truthy'] is False else None


def GF7_evidence_copy(value, context):
    return 'transition_refused' if value['payload_evidence'] != value['outcome_evidence'] else None


def GF8_failure_code(value, context):
    return 'transition_refused' if value['payload_failure_code'] != value['outcome_failure_code'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('GF5_no_questions', g.Invariant('/owner_result/question_ids', 'is empty'), 'transition_refused', GF5_no_questions),
        g.Guard('GF6_evidence_present', g.Invariant('/payload/evidence_refs', 'is nonempty'), 'transition_refused', GF6_evidence_present),
        g.Guard('GF7_evidence_copy', g.Invariant('/payload/evidence_refs', 'equals the report evidence'), 'transition_refused', GF7_evidence_copy),
        g.Guard('GF8_failure_code', g.Invariant('/payload/failure_reason_code', 'equals the report failure code'), 'transition_refused', GF8_failure_code),
    ])

    def check(value):
        table.require('GF5_no_questions', value, context)
        table.require('GF6_evidence_present', value, context)
        table.require('GF7_evidence_copy', value, context)
        table.require('GF8_failure_code', value, context)
        return True
    return g.Case(table, check, context)
