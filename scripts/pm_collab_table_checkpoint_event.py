"""DC guard table checkpoint_event: Checkpoint last-event scope joins (the event then passes the historical envelope).

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('event_scope_kind', 'checkpoint_scope_kind', 'event_project_id', 'checkpoint_project_id')


def CK17_event_scope(value, context):
    return 'checkpoint_event' if value['event_scope_kind'] != value['checkpoint_scope_kind'] else None


def CK18_event_project(value, context):
    return 'checkpoint_event' if value['event_project_id'] != value['checkpoint_project_id'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CK17_event_scope', g.Invariant('/<last_event>/scope_kind', 'equals the checkpoint scope_kind'), 'checkpoint_event', CK17_event_scope),
        g.Guard('CK18_event_project', g.Invariant('/<last_event>/project_id', 'equals the checkpoint project_id'), 'checkpoint_event', CK18_event_project),
    ])

    def check(value):
        table.require('CK17_event_scope', value, context)
        table.require('CK18_event_project', value, context)
        return True
    return g.Case(table, check, context)
