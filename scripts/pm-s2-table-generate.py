#!/usr/bin/env python3
"""Generate the PNC-019 S2 Method B guard-table modules from pm_s2_dl300_events.ROWS.

Each predicate reads one boolean observation the checker (scripts/pm_s2_dl300_events.py) derives from the
complete boundary input; predicates never recompute, repair or call helpers. The checker refuses only through
these rows, in spec order. A phase of more than eight rows is rendered as consecutive part tables
(<phase>__1, <phase>__2, ...; at most eight rows each, evaluated in row order); the checker's result is the
same as for the whole phase. Edit ROWS in pm_s2_dl300_events.py and regenerate; never edit a table module.
--check exits 1 when a committed table differs from what ROWS renders.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import pm_s2_dl300_events as s2  # noqa: E402


def render(table, code, title, rows):
    fields = tuple(row[1] for row in rows)
    lines = [
        f'"""S2 guard table {table}: {title}.',
        '',
        'Method B guard rows (scripts/pm_guard_isolation.py) for the PNC-019 S2 DL-300 checker. Each predicate reads',
        'one observation the checker derives from the complete boundary input. Predicates never recompute,',
        'repair or call helpers. The checker refuses only through these rows, in this order.',
        'Generated by scripts/pm-s2-table-generate.py from pm_s2_dl300_events.ROWS; edit the spec there.',
        '"""',
        'import pm_guard_isolation as g',
        '',
        f'FIELDS = {fields!r}',
        '',
    ]
    for row in rows:
        name, field = row[0], row[1]
        row_code = row[3] if len(row) > 3 else code
        lines += [f'def {name}(value, context):',
                  f'    return {row_code!r} if value[{field!r}] is not True else None', '']
    lines += ['def case(value):', '    context = None', '    table = g.GuardTable([']
    for row in rows:
        name, field, invariant = row[0], row[1], row[2]
        row_code = row[3] if len(row) > 3 else code
        lines.append(f"        g.Guard({name!r}, g.Invariant({'/' + field!r}, {invariant!r}), {row_code!r}, {name}),")
    lines += ['    ])', '', '    def check(value):']
    for row in rows:
        lines.append(f'        table.require({row[0]!r}, value, context)')
    lines += ['        return True', '    return g.Case(table, check, context)', '']
    return '\n'.join(lines)


def main():
    check = '--check' in sys.argv[1:]
    stale, expected = [], set()
    for phase, (code, title, _rows) in s2.ROWS.items():
        for table, rows in s2.part_rows(phase).items():
            assert len(rows) <= s2.MAX_ROWS, (table, len(rows))
            path = ROOT / 'scripts' / f'{s2.TABLE_PREFIX}{table}.py'
            expected.add(path.name)
            text = render(table, code, title, rows)
            if check:
                if not path.exists() or path.read_text() != text:
                    stale.append(path.name)
            else:
                path.write_text(text)
                print(path.name, len(rows))
    extra = sorted(p.name for p in (ROOT / 'scripts').glob(s2.TABLE_PREFIX + '*.py') if p.name not in expected)
    tables = len(expected)
    rows = sum(len(r[2]) for r in s2.ROWS.values())
    if check:
        print({'status': 'pass' if not stale and not extra else 'fail', 'tables': tables, 'rows': rows, 'stale': stale, 'unexpected': extra})
        return 1 if stale or extra else 0
    print({'tables': tables, 'rows': rows})
    return 0


if __name__ == '__main__':
    sys.exit(main())
