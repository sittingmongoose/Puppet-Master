"""DX guard table graph_join: Installed graph: node and run revisions, graph join and materialization request.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('node_revision_type', 'node_revision', 'run_revision_type', 'run_revision', 'node_graph', 'run_graph', 'node_request', 'operation_request')


def GJ01_node_revision_type(value, context):
    return 'installed graph join' if value['node_revision_type'] != 'int' else None


def GJ02_node_revision_min(value, context):
    return 'installed graph join' if value['node_revision_type'] == 'int' and value['node_revision'] < 1 else None


def GJ03_run_revision_type(value, context):
    return 'installed graph join' if value['run_revision_type'] != 'int' else None


def GJ04_run_revision_min(value, context):
    return 'installed graph join' if value['run_revision_type'] == 'int' and value['run_revision'] < 1 else None


def GJ05_graph_id_join(value, context):
    return 'installed graph join' if value['node_graph'] != value['run_graph'] else None


def GJ06_graph_revision_join(value, context):
    return 'installed graph join' if value['node_revision_type'] == 'int' and value['run_revision_type'] == 'int' and value['node_revision'] >= 1 and value['run_revision'] >= 1 and value['node_revision'] != value['run_revision'] else None


def GJ07_request_join(value, context):
    return 'materialization request join' if value['node_request'] != value['operation_request'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('GJ01_node_revision_type', g.Invariant('/records/node/body/workgraph_revision', 'is an integer'), 'installed graph join', GJ01_node_revision_type),
        g.Guard('GJ02_node_revision_min', g.Invariant('/records/node/body/workgraph_revision', 'an integer revision is at least 1'), 'installed graph join', GJ02_node_revision_min),
        g.Guard('GJ03_run_revision_type', g.Invariant('/records/run/body/workgraph_revision', 'is an integer'), 'installed graph join', GJ03_run_revision_type),
        g.Guard('GJ04_run_revision_min', g.Invariant('/records/run/body/workgraph_revision', 'an integer revision is at least 1'), 'installed graph join', GJ04_run_revision_min),
        g.Guard('GJ05_graph_id_join', g.Invariant('/records/node/body/workgraph_id', 'equals the run graph id'), 'installed graph join', GJ05_graph_id_join),
        g.Guard('GJ06_graph_revision_join', g.Invariant('/records/node/body/workgraph_revision', 'a valid node revision equals the valid run revision'), 'installed graph join', GJ06_graph_revision_join),
        g.Guard('GJ07_request_join', g.Invariant('/records/node/body/source_request_id', 'equals the operation source request'), 'materialization request join', GJ07_request_join),
    ])

    def check(value):
        table.require('GJ01_node_revision_type', value, context)
        table.require('GJ02_node_revision_min', value, context)
        table.require('GJ03_run_revision_type', value, context)
        table.require('GJ04_run_revision_min', value, context)
        table.require('GJ05_graph_id_join', value, context)
        table.require('GJ06_graph_revision_join', value, context)
        table.require('GJ07_request_join', value, context)
        return True
    return g.Case(table, check, context)
