"""DCH guard table wt_pr_failed: ACD-621 distinguishes push failure from failure after successful push.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('error', 'payload_error', 'push', 'expected_push', 'phase', 'api_present', 'api_status')


def WX01_error(value, context):
    return 'worktree_refused' if value['error'] != value['payload_error'] else None


def WX02_push(value, context):
    return 'worktree_refused' if value['push'] != value['expected_push'] else None


def WX03_api_absent(value, context):
    return 'worktree_refused' if value['phase'] == 'push' and value['api_present'] is not False else None


def WX04_api_failed(value, context):
    return 'worktree_refused' if value['phase'] == 'api' and value['api_status'] != 'failed' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WX01_error', g.Invariant('/operation/outcome/error', 'equals the original sanitized error'), 'worktree_refused', WX01_error),
        g.Guard('WX02_push', g.Invariant('/operation/outcome/push', 'the original push failed in push phase and succeeded before api phase'), 'worktree_refused', WX02_push),
        g.Guard('WX03_api_absent', g.Invariant('/operation/outcome/api', 'push failure has no API outcome'), 'worktree_refused', WX03_api_absent),
        g.Guard('WX04_api_failed', g.Invariant('/operation/outcome/api/status', 'api phase has an actual failed API result'), 'worktree_refused', WX04_api_failed),
    ])

    def check(value):
        table.require('WX01_error', value, context)
        table.require('WX02_push', value, context)
        table.require('WX03_api_absent', value, context)
        table.require('WX04_api_failed', value, context)
        return True
    return g.Case(table, check, context)
