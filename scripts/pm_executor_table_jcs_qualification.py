"""DX guard table jcs_qualification: CV-1100 qualified JCS of an actual identity/digest preimage under the current recipe (shared qualified_jcs).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('jcs_refusal',)


def JQ01_binary64(value, context):
    return 'jcs_binary64' if value['jcs_refusal'] == 'jcs_binary64' else None


def JQ02_emitted_decimal(value, context):
    return 'jcs_decimal' if value['jcs_refusal'] == 'jcs_decimal' else None


def JQ03_jcs_other(value, context):
    return 'jcs_preimage' if value['jcs_refusal'] not in (None, 'jcs_binary64', 'jcs_decimal') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('JQ01_binary64', g.Invariant('/**', 'every integer has an exact finite binary64 value'), 'jcs_binary64', JQ01_binary64),
        g.Guard('JQ02_emitted_decimal', g.Invariant('/**', 'every emitted JCS decimal equals the original integer'), 'jcs_decimal', JQ02_emitted_decimal),
        g.Guard('JQ03_jcs_other', g.Invariant('/**', 'the preimage has no other JCS refusal (Unicode scalar strings, supported kinds)'), 'jcs_preimage', JQ03_jcs_other),
    ])

    def check(value):
        table.require('JQ01_binary64', value, context)
        table.require('JQ02_emitted_decimal', value, context)
        table.require('JQ03_jcs_other', value, context)
        return True
    return g.Case(table, check, context)
