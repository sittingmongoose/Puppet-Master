#!/usr/bin/env python3
"""Generate the W3E Method B guard-table modules from pm_w3e_event_oracles.ROWS.

Each module ``scripts/pm_w3e_table_<table>.py`` holds one table: one predicate per row whose body is that row's
decision (its template from pm_w3e_event_oracles.TEMPLATES over the row's projected inputs), a ``FIELDS`` tuple in
table order, and ``case(value)`` building a fresh ``GuardTable`` whose check requires every row in order. The complete
checker (pm_w3e_event_oracles.evaluate) refuses only through these predicates. ``--check`` fails when a module is
missing, stale or extra.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pm_w3e_event_oracles as W  # noqa: E402

SCRIPTS = W.ROOT / 'scripts'


def lit(text):
    return json.dumps(text, ensure_ascii=True)


def predicate_lines(r):
    _keys, condition = W.TEMPLATES[r['kind']]
    return ['', '', 'def ' + r['id'] + '(value, context):',
            '    record = value[' + lit(r['id']) + ']',
            "    if record['applies'] is not True:",
            '        return None',
            '    if ' + condition + ':',
            '        return ' + lit(r['code']),
            '    return None']


def module_text(table, rows):
    lines = ['"""W3E guard table ' + table + ' (boundary ' + rows[0]['boundary'] + ').', '',
             'Method B guard rows (scripts/pm_guard_isolation.py) for scripts/pm_w3e_event_oracles.py. Each',
             'predicate is its row\'s decision over the inputs the checker projects for that row: the presented value',
             'and the independent reference it must equal, or a shared helper\'s own result where the rule is that',
             'helper. `applies` is the row\'s family and readiness precondition. The checker refuses only through',
             'these predicates, in this order.']
    if table.startswith('entailed_'):
        first, proof = W.ENTAILED[rows[0]['id']]
        lines += ['', 'Entailed row: never the first refusal. Rows that always refuse first: ' + ', '.join(first) + '.',
                  'Proof: ' + proof]
    lines += ['Generated by scripts/pm-w3e-table-generate.py from pm_w3e_event_oracles.ROWS; edit the spec there.',
              '"""', 'import pm_guard_isolation as g', '',
              'FIELDS = (' + ''.join(lit(r['id']) + ', ' for r in rows) + ')']
    for r in rows:
        lines += predicate_lines(r)
    lines += ['', '', 'def case(value):', '    context = None', '    table = g.GuardTable([']
    for r in rows:
        lines.append('        g.Guard(' + lit(r['id']) + ', g.Invariant(' + lit(r['field']) + ', ' + lit(r['words']) +
                     '), ' + lit(r['code']) + ', ' + r['id'] + '),')
    lines += ['    ])', '', '    def check(value):']
    for r in rows:
        lines.append('        table.require(' + lit(r['id']) + ', value, context)')
    lines += ['        return True', '    return g.Case(table, check, context)', '']
    return '\n'.join(lines)


def expected():
    return {SCRIPTS / (W.TABLE_PREFIX + t + '.py'): module_text(t, W.TABLE_ROWS[t]) for t in W.TABLES}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    want = expected()
    present = set(SCRIPTS.glob(W.TABLE_PREFIX + '*.py'))
    stale = sorted(p.name for p, t in want.items() if not p.exists() or p.read_text() != t)
    extra = sorted(p.name for p in present - set(want))
    summary = {'tables': len(want), 'rows': len(W.ROWS), 'entailed': len(W.ENTAILED), 'stale': stale, 'extra': extra}
    if args.check:
        print(json.dumps(summary))
        return 1 if stale or extra else 0
    for p in present - set(want):
        p.unlink()
    for p, t in want.items():
        if not p.exists() or p.read_text() != t:
            p.write_text(t)
    print(json.dumps({k: (len(v) if type(v) is list else v) for k, v in summary.items()}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
