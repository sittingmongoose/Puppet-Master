"""DFM guard table control_authority: Control reader and drain authority (validate_control_transition).

Method B guard rows for scripts/pm-filemanager-event-contracts.py, generated by
scripts/pm-filemanager-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(recomputed keys, identities and digests, exact types, resolved rows); a
predicate never recomputes, repairs or calls helpers. The checker refuses
only through these rows, in this order (table_refusals in the checker).
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('issuance_reader_kept', 'issuance_drain_kept', 'drain_members_equal', 'drain_reader_kept', 'withdraw_drained', 'withdraw_cutoff_equal')


def CA01_issuance_reader(value, context):
    return 'issuance changed control authority' if value['issuance_reader_kept'] is False else None


def CA02_issuance_drain(value, context):
    return 'issuance changed control authority' if value['issuance_drain_kept'] is False else None


def CA03_drain_membership(value, context):
    return 'drain membership' if value['drain_members_equal'] is False else None


def CA04_drain_reader(value, context):
    return 'drain changed reader authority' if value['drain_reader_kept'] is False else None


def CA05_withdraw_drained(value, context):
    return 'cutoff before original drain' if value['withdraw_drained'] is False else None


def CA06_withdraw_cutoff(value, context):
    return 'cutoff before original drain' if value['withdraw_cutoff_equal'] is False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CA01_issuance_reader', g.Invariant('/reader_enabled', 'an issuance edge keeps reader authority'), 'issuance changed control authority', CA01_issuance_reader),
        g.Guard('CA02_issuance_drain', g.Invariant('/drain_operation_keys', 'an issuance edge keeps the drain set'), 'issuance changed control authority', CA02_issuance_drain),
        g.Guard('CA03_drain_membership', g.Invariant('/drain_operation_keys', 'the drain edge records exactly the given drain keys'), 'drain membership', CA03_drain_membership),
        g.Guard('CA04_drain_reader', g.Invariant('/reader_enabled', 'the drain edge keeps reader authority'), 'drain changed reader authority', CA04_drain_reader),
        g.Guard('CA05_withdraw_drained', g.Invariant('/drain_keys', 'withdrawal has no open drain key'), 'cutoff before original drain', CA05_withdraw_drained),
        g.Guard('CA06_withdraw_cutoff', g.Invariant('/writer_cutoff_sequence', 'withdrawal cuts off at the issued sequence'), 'cutoff before original drain', CA06_withdraw_cutoff),
    ])

    def check(value):
        table.require('CA01_issuance_reader', value, context)
        table.require('CA02_issuance_drain', value, context)
        table.require('CA03_drain_membership', value, context)
        table.require('CA04_drain_reader', value, context)
        table.require('CA05_withdraw_drained', value, context)
        table.require('CA06_withdraw_cutoff', value, context)
        return True
    return g.Case(table, check, context)
