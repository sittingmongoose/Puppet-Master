"""DC guard table fix_payload: Fixture: positive payloads accept in their edition; negatives refuse at their layer.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('positive_rejection', 'positive_edition', 'declared_edition', 'negative_rejection', 'expected_layer')


def IF04_positive_payload(value, context):
    return 'positive_payload' if value['positive_rejection'] is not None else None


def IF05_positive_edition(value, context):
    return 'positive_payload' if value['positive_edition'] != value['declared_edition'] else None


def IF06_negative_layer(value, context):
    return 'negative_payload_layer' if value['negative_rejection'] != value['expected_layer'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IF04_positive_payload', g.Invariant('/payloads/<i>', 'accepts'), 'positive_payload', IF04_positive_payload),
        g.Guard('IF05_positive_edition', g.Invariant('/payloads/<i>', 'is in its declared edition'), 'positive_payload', IF05_positive_edition),
        g.Guard('IF06_negative_layer', g.Invariant('/invalid_payloads/<i>', 'refuses at its first failing layer'), 'negative_payload_layer', IF06_negative_layer),
    ])

    def check(value):
        table.require('IF04_positive_payload', value, context)
        table.require('IF05_positive_edition', value, context)
        table.require('IF06_negative_layer', value, context)
        return True
    return g.Case(table, check, context)
