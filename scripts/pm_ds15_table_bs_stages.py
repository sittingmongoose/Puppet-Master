"""DS15 guard table bs_stages: Browser stage custody, every stage.

Method B guard rows (scripts/pm_guard_isolation.py) for the DS15 checkers. Each predicate reads one
observation the checker derives from the complete boundary input (recomputed hashes and identities,
canonical-byte sizes, resolved records, presence, typed copies). Predicates never recompute, repair or
call helpers. The checkers refuse only through these rows, in this order
(pm-ds15-event-contracts.py:refusal), and check that every factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-ds15-table-generate.py; edit the row spec there.
"""
import pm_guard_isolation as g

FIELDS = ('stage_statuses', 'record_original_operation_id', 'stage_operations', 'record_interface_id', 'stage_methods', 'record_request_ref', 'stage_requests', 'record_result_ref', 'stage_results', 'expected_evidence', 'stage_evidence')


def BS27_stage_status(value, context):
    return 'browser_stage_custody' if any([s != 'accepted' for s in value['stage_statuses']]) else None


def BS28_stage_operation(value, context):
    return 'browser_stage_custody' if any([s != value['record_original_operation_id'] for s in value['stage_operations']]) else None


def BS29_stage_method(value, context):
    return 'browser_stage_custody' if any([s != value['record_interface_id'] for s in value['stage_methods']]) else None


def BS30_stage_request(value, context):
    return 'browser_stage_custody' if any([s != value['record_request_ref'] for s in value['stage_requests']]) else None


def BS31_stage_result(value, context):
    return 'browser_stage_custody' if any([s != value['record_result_ref'] for s in value['stage_results']]) else None


def BS32_stage_evidence(value, context):
    return 'browser_stage_custody' if any([s != value['expected_evidence'] for s in value['stage_evidence']]) else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('BS27_stage_status', g.Invariant('/stage_statuses', 'every stage status is accepted'), 'browser_stage_custody', BS27_stage_status),
        g.Guard('BS28_stage_operation', g.Invariant('/stage_operations', 'every stage original_operation_id is the record operation'), 'browser_stage_custody', BS28_stage_operation),
        g.Guard('BS29_stage_method', g.Invariant('/stage_methods', 'every stage owner_method_id is the record interface'), 'browser_stage_custody', BS29_stage_method),
        g.Guard('BS30_stage_request', g.Invariant('/stage_requests', 'every stage request_ref is the record request'), 'browser_stage_custody', BS30_stage_request),
        g.Guard('BS31_stage_result', g.Invariant('/stage_results', 'every stage result_ref is the record result'), 'browser_stage_custody', BS31_stage_result),
        g.Guard('BS32_stage_evidence', g.Invariant('/stage_evidence', 'every stage custody evidence equals the derived evidence'), 'browser_stage_custody', BS32_stage_evidence),
    ])

    def check(value):
        table.require('BS27_stage_status', value, context)
        table.require('BS28_stage_operation', value, context)
        table.require('BS29_stage_method', value, context)
        table.require('BS30_stage_request', value, context)
        table.require('BS31_stage_result', value, context)
        table.require('BS32_stage_evidence', value, context)
        return True
    return g.Case(table, check, context)
