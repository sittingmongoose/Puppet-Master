"""DCH guard table cp_generation: checkpoint_joins: current generation, checkpoint key and reference.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('current_generation', 'generation', 'node_state', 'token_key', 'generic_key', 'source_key', 'token_ref', 'expected_ref')


def CP08_current_generation(value, context):
    return 'checkpoint_refused' if value['current_generation'] != value['generation'] else None


def CP09_node_current(value, context):
    return 'checkpoint_refused' if value['node_state'] != 'current' else None


def CP10_token_key(value, context):
    return 'checkpoint_refused' if value['token_key'] != value['generic_key'] else None


def CP11_source_key(value, context):
    return 'checkpoint_refused' if value['source_key'] != value['generic_key'] else None


def CP12_token_ref(value, context):
    return 'checkpoint_refused' if value['token_ref'] != value['expected_ref'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP08_current_generation', g.Invariant('/source/checkpoint/current_generation_id', 'equals the token generation'), 'checkpoint_refused', CP08_current_generation),
        g.Guard('CP09_node_current', g.Invariant('/source/checkpoint/generations/<g>/state', 'is current'), 'checkpoint_refused', CP09_node_current),
        g.Guard('CP10_token_key', g.Invariant('/value/source_token/checkpoint_key', 'equals the generic SP-278 checkpoint key'), 'checkpoint_refused', CP10_token_key),
        g.Guard('CP11_source_key', g.Invariant('/source/checkpoint_key', 'equals the generic SP-278 checkpoint key'), 'checkpoint_refused', CP11_source_key),
        g.Guard('CP12_token_ref', g.Invariant('/value/source_token/checkpoint_ref', 'equals the generic key plus the generation pointer'), 'checkpoint_refused', CP12_token_ref),
    ])

    def check(value):
        table.require('CP08_current_generation', value, context)
        table.require('CP09_node_current', value, context)
        table.require('CP10_token_key', value, context)
        table.require('CP11_source_key', value, context)
        table.require('CP12_token_ref', value, context)
        return True
    return g.Case(table, check, context)
