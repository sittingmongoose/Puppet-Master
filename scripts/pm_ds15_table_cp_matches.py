import pm_guard_isolation as g

FIELDS = ('prior_present', 'earlier', 'prior_last_event_id', 'last', 'matches', 'selected_matches', 'checkpoint_last_event_id')


def CE01_prior_earlier(value, context):
    return 'checkpoint_refused' if value['prior_present'] is True and value['earlier'] == [] else None


def CE02_prior_last(value, context):
    return 'checkpoint_refused' if value['prior_present'] is True and value['earlier'] != [] and value['prior_last_event_id'] != value['earlier'][-1] else None


def CE03_last_exists(value, context):
    return 'checkpoint_refused' if value['last'] is None else None


def CE04_selected_matches(value, context):
    return 'checkpoint_refused' if value['last'] is not None and value['matches'] != value['selected_matches'] else None


def CE05_last_event(value, context):
    return 'checkpoint_refused' if value['last'] is not None and value['checkpoint_last_event_id'] != value['last'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CE01_prior_earlier', g.Invariant('/earlier', 'a prior checkpoint follows an earlier match'), 'checkpoint_refused', CE01_prior_earlier),
        g.Guard('CE02_prior_last', g.Invariant('/prior_last_event_id', 'the prior last event is the last earlier match'), 'checkpoint_refused', CE02_prior_last),
        g.Guard('CE03_last_exists', g.Invariant('/last', 'a checkpoint has a first match'), 'checkpoint_refused', CE03_last_exists),
        g.Guard('CE04_selected_matches', g.Invariant('/matches', 'the matches are the selected matches'), 'checkpoint_refused', CE04_selected_matches),
        g.Guard('CE05_last_event', g.Invariant('/checkpoint_last_event_id', 'the checkpoint last event is the last match'), 'checkpoint_refused', CE05_last_event),
    ])

    def check(value):
        table.require('CE01_prior_earlier', value, context)
        table.require('CE02_prior_last', value, context)
        table.require('CE03_last_exists', value, context)
        table.require('CE04_selected_matches', value, context)
        table.require('CE05_last_event', value, context)
        return True
    return g.Case(table, check, context)
