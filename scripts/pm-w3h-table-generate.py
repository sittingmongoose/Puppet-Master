#!/usr/bin/env python3
"""Generate the W3H Method B guard-table modules from pm_w3h_events.ROWS.

Each predicate reads one boolean observation the checker (scripts/pm_w3h_events.py) derives from
the complete boundary input; predicates never recompute, repair or call helpers. The checker refuses
only through these rows, in spec order. Edit ROWS in pm_w3h_events.py and regenerate; never edit a
table module. --check exits 1 when a committed table differs from what ROWS renders.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import pm_w3h_events as w3h  # noqa: E402


def render(phase, code, title, rows):
    fields = tuple(row[1] for row in rows)
    lines = [
        f'"""W3H guard table {phase}: {title}.',
        '',
        'Method B guard rows (scripts/pm_guard_isolation.py) for the W3H checker. Each predicate reads one',
        'observation the checker derives from the complete boundary input. Predicates never recompute,',
        'repair or call helpers. The checker refuses only through these rows, in this order.',
        'Generated by scripts/pm-w3h-table-generate.py from pm_w3h_events.ROWS; edit the spec there.',
        '"""',
        'import pm_guard_isolation as g',
        '',
        f'FIELDS = {fields!r}',
        '',
    ]
    for row in rows:
        name, field = row[0], row[1]
        row_code = row[3] if len(row) > 3 else code
        lines += [f'def {name}(value, context):',
                  f'    return {row_code!r} if value[{field!r}] is not True else None', '']
    lines += ['def case(value):', '    context = None', '    table = g.GuardTable([']
    for row in rows:
        name, field, invariant = row[0], row[1], row[2]
        row_code = row[3] if len(row) > 3 else code
        lines.append(f"        g.Guard({name!r}, g.Invariant({'/' + field!r}, {invariant!r}), {row_code!r}, {name}),")
    lines += ['    ])', '', '    def check(value):']
    for row in rows:
        lines.append(f'        table.require({row[0]!r}, value, context)')
    lines += ['        return True', '    return g.Case(table, check, context)', '']
    return '\n'.join(lines)


def main():
    check = '--check' in sys.argv[1:]
    stale = []
    for phase, (code, title, rows) in w3h.ROWS.items():
        path = ROOT / 'scripts' / f'{w3h.TABLE_PREFIX}{phase}.py'
        text = render(phase, code, title, rows)
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.name)
        else:
            path.write_text(text)
            print(path.name, len(rows))
    expected = {f'{w3h.TABLE_PREFIX}{p}.py' for p in w3h.ROWS}
    extra = sorted(p.name for p in (ROOT / 'scripts').glob(w3h.TABLE_PREFIX + '*.py') if p.name not in expected)
    if check:
        print({'stale': stale, 'unexpected': extra})
        return 1 if stale or extra else 0
    return 0


if __name__ == '__main__':
    sys.exit(main())
