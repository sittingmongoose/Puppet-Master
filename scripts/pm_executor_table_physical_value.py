"""DX guard table physical_value: SP-1100 EVENT_VALUE canonical MessagePack of the logical payload (shared storage_value_bytes).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('physical_refusal',)


def PV01_integer_range(value, context):
    return 'physical_integer_range' if value['physical_refusal'] == 'physical_integer_range' else None


def PV02_physical_other(value, context):
    return 'physical_value' if value['physical_refusal'] not in (None, 'physical_integer_range') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('PV01_integer_range', g.Invariant('/payload/**', 'every integer is within -2^63..2^64-1'), 'physical_integer_range', PV01_integer_range),
        g.Guard('PV02_physical_other', g.Invariant('/payload/**', 'the value has no other EVENT_VALUE refusal (Unicode scalar strings, supported types)'), 'physical_value', PV02_physical_other),
    ])

    def check(value):
        table.require('PV01_integer_range', value, context)
        table.require('PV02_physical_other', value, context)
        return True
    return g.Case(table, check, context)
