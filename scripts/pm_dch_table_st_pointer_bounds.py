"""DCH guard table st_pointer_bounds: stop resolve_value: inline pointer encodability and size (entailed by SV15: an exact pointer is at most 131 bytes; defence in depth).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('pointer_encoding_error', 'pointer_size')


def SV11_pointer_encodable(value, context):
    return 'stop_value_unavailable' if value['pointer_encoding_error'] is not None else None


def SV12_pointer_size(value, context):
    return 'stop_value_unavailable' if value['pointer_encoding_error'] is None and value['pointer_size'] > 16384 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SV11_pointer_encodable', g.Invariant('/record/payload_ref', 'the inline pointer encodes'), 'stop_value_unavailable', SV11_pointer_encodable),
        g.Guard('SV12_pointer_size', g.Invariant('/record/payload_ref', 'the inline pointer encodes to at most 16384 bytes'), 'stop_value_unavailable', SV12_pointer_size),
    ])

    def check(value):
        table.require('SV11_pointer_encodable', value, context)
        table.require('SV12_pointer_size', value, context)
        return True
    return g.Case(table, check, context)
