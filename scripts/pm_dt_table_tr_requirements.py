"""DT guard table tr_requirements: transition requirements.clarification_requested.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('report_status', 'questions_truthy', 'copy_mismatches')


def RQ1_blocked(value, context):
    return 'transition_refused' if value['report_status'] != 'BLOCKED' else None


def RQ2_questions(value, context):
    return 'transition_refused' if value['questions_truthy'] is False else None


def RQ3_copies(value, context):
    return 'transition_refused' if value['copy_mismatches'] != [] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RQ1_blocked', g.Invariant('/before/report_status', 'is BLOCKED'), 'transition_refused', RQ1_blocked),
        g.Guard('RQ2_questions', g.Invariant('/before/question_ids', 'is nonempty'), 'transition_refused', RQ2_questions),
        g.Guard('RQ3_copies', g.Invariant('/payload', 'question_ids, report_ref, wizard_id and thread_id equal the blocked report'), 'transition_refused', RQ3_copies),
    ])

    def check(value):
        table.require('RQ1_blocked', value, context)
        table.require('RQ2_questions', value, context)
        table.require('RQ3_copies', value, context)
        return True
    return g.Case(table, check, context)
