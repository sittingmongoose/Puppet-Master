"""DCH guard table ar_state: archive_joins: lifecycle state and expected revision.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('before_state', 'previous_state', 'payload_state', 'after_state', 'readback_available', 'expected_thread_revision', 'before_revision', 'request_expected_revision')


def AR08_before_state(value, context):
    return 'archive_refused' if value['before_state'] not in ('active', 'suspended') else None


def AR09_previous_state(value, context):
    return 'archive_refused' if value['previous_state'] != value['before_state'] else None


def AR10_payload_state(value, context):
    return 'archive_refused' if value['payload_state'] != 'archived' else None


def AR11_after_state(value, context):
    return 'archive_refused' if value['after_state'] != 'archived' else None


def AR12_readback(value, context):
    return 'archive_refused' if value['readback_available'] is not True else None


def AR13_expected_revision(value, context):
    return 'archive_refused' if value['expected_thread_revision'] != value['before_revision'] else None


def AR14_request_revision(value, context):
    return 'archive_refused' if value['request_expected_revision'] != value['before_revision'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('AR08_before_state', g.Invariant('/source/before/state', 'is active or suspended'), 'archive_refused', AR08_before_state),
        g.Guard('AR09_previous_state', g.Invariant('/payload/previous_state', 'equals the before state'), 'archive_refused', AR09_previous_state),
        g.Guard('AR10_payload_state', g.Invariant('/payload/state', 'is archived'), 'archive_refused', AR10_payload_state),
        g.Guard('AR11_after_state', g.Invariant('/source/after/state', 'is archived'), 'archive_refused', AR11_after_state),
        g.Guard('AR12_readback', g.Invariant('/source/after/readback_available', 'is exactly true'), 'archive_refused', AR12_readback),
        g.Guard('AR13_expected_revision', g.Invariant('/payload/expected_thread_revision', 'equals the before revision'), 'archive_refused', AR13_expected_revision),
        g.Guard('AR14_request_revision', g.Invariant('/source/request/expected_revision', 'equals the before revision'), 'archive_refused', AR14_request_revision),
    ])

    def check(value):
        table.require('AR08_before_state', value, context)
        table.require('AR09_previous_state', value, context)
        table.require('AR10_payload_state', value, context)
        table.require('AR11_after_state', value, context)
        table.require('AR12_readback', value, context)
        table.require('AR13_expected_revision', value, context)
        table.require('AR14_request_revision', value, context)
        return True
    return g.Case(table, check, context)
