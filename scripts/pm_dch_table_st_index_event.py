"""DCH guard table st_index_event: stop index_read_valid: the index row names the retained request.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('row_event_type', 'row_event_id', 'record_event_id', 'row_sequence_type', 'row_sequence_id', 'record_sequence_id', 'row_partition', 'body_partition', 'row_commitment', 'context_commitment')


def IX21_row_event_type(value, context):
    return 'stop_index_refused' if value['row_event_type'] != 'chat.response_stop_requested' else None


def IX23_row_event_id(value, context):
    return 'stop_index_refused' if value['row_event_id'] != value['record_event_id'] else None


def IX25_row_sequence(value, context):
    return 'stop_index_refused' if value['row_sequence_type'] == 'int' and value['row_sequence_id'] != value['record_sequence_id'] else None


def IX26_row_partition(value, context):
    return 'stop_index_refused' if value['row_partition'] != value['body_partition'] else None


def IX27_row_commitment(value, context):
    return 'stop_index_refused' if value['row_commitment'] != value['context_commitment'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IX21_row_event_type', g.Invariant('/source/index_row/event_type', 'is chat.response_stop_requested'), 'stop_index_refused', IX21_row_event_type),
        g.Guard('IX23_row_event_id', g.Invariant('/source/index_row/event_id', 'equals the request event id'), 'stop_index_refused', IX23_row_event_id),
        g.Guard('IX25_row_sequence', g.Invariant('/source/index_row/sequence_id', 'equals the request sequence'), 'stop_index_refused', IX25_row_sequence),
        g.Guard('IX26_row_partition', g.Invariant('/source/index_row/scope_partition', 'equals the request body partition'), 'stop_index_refused', IX26_row_partition),
        g.Guard('IX27_row_commitment', g.Invariant('/source/index_row/source_value_sha256', 'equals the request source commitment'), 'stop_index_refused', IX27_row_commitment),
    ])

    def check(value):
        table.require('IX21_row_event_type', value, context)
        table.require('IX23_row_event_id', value, context)
        table.require('IX25_row_sequence', value, context)
        table.require('IX26_row_partition', value, context)
        table.require('IX27_row_commitment', value, context)
        return True
    return g.Case(table, check, context)
