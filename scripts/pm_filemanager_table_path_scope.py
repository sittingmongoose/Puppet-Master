import pm_guard_isolation as g

FIELDS = ('source_scoped', 'destination_scoped', 'affected_scoped')


def PA01_source_scope(value, context):
    return 'foreign path scope' if value['source_scoped'] is False else None


def PA02_destination_scope(value, context):
    return 'foreign path scope' if value['destination_scoped'] is False else None


def PA03_affected_scope(value, context):
    return 'foreign affected path scope' if value['affected_scoped'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('PA01_source_scope', g.Invariant('/source_path_ref', 'is a project path ref when present'), 'foreign path scope', PA01_source_scope),
        g.Guard('PA02_destination_scope', g.Invariant('/destination_path_ref', 'is a project path ref when present'), 'foreign path scope', PA02_destination_scope),
        g.Guard('PA03_affected_scope', g.Invariant('/affected_path_refs/*', 'every affected ref is a project path ref'), 'foreign affected path scope', PA03_affected_scope),
    ])

    def check(value):
        table.require('PA01_source_scope', value, context)
        table.require('PA02_destination_scope', value, context)
        table.require('PA03_affected_scope', value, context)
        return True
    return g.Case(table, check, context)
