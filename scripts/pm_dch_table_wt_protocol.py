"""DCH guard table wt_protocol: W.8/W.9 original guard, target, override and process trace evidence.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('context_refusals', 'target', 'original_target', 'override_requested', 'override_authorized', 'guard_conflicts', 'payload_conflicts', 'trace', 'expected_trace')


def WG01_context(value, context):
    return 'worktree_refused' if value['context_refusals'] != [] else None


def WG02_target(value, context):
    return 'worktree_refused' if value['target'] != value['original_target'] else None


def WG03_override(value, context):
    return 'worktree_refused' if value['override_requested'] is True and value['override_authorized'] is not True else None


def WG05_guard_conflicts(value, context):
    return 'worktree_refused' if value['guard_conflicts'] is True and value['payload_conflicts'] is not True else None


def WG04_trace(value, context):
    return 'worktree_refused' if value['trace'] != value['expected_trace'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WG01_context', g.Invariant('/operation/owner_context', 'owner-specific prerequisites or actual guard failure are evidenced'), 'worktree_refused', WG01_context),
        g.Guard('WG02_target', g.Invariant('/operation/owner_context/test_target', 'equals the independently retained original test target'), 'worktree_refused', WG02_target),
        g.Guard('WG03_override', g.Invariant('/operation/owner_context/override_authorized', 'an override is an independently authorized original choice'), 'worktree_refused', WG03_override),
        g.Guard('WG05_guard_conflicts', g.Invariant('/operation/outcome/guards/conflicts', 'a pre-existing conflict refused before mutation is preserved in the failure payload'), 'worktree_refused', WG05_guard_conflicts),
        g.Guard('WG04_trace', g.Invariant('/operation/execution_trace', 'matches original owner ordering, working root, shell, no-commit, hooks and cleanup'), 'worktree_refused', WG04_trace),
    ])

    def check(value):
        table.require('WG01_context', value, context)
        table.require('WG02_target', value, context)
        table.require('WG03_override', value, context)
        table.require('WG05_guard_conflicts', value, context)
        table.require('WG04_trace', value, context)
        return True
    return g.Case(table, check, context)
