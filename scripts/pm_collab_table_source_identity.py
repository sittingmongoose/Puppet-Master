"""DC guard table source_identity: Source custody: instance, epoch, key and identity recomputation.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('value_instance', 'context_instance', 'write_epoch_type', 'recovery_epoch', 'write_epoch', 'physical_key', 'expected_physical_key', 'scope_partition', 'expected_scope_partition', 'owner_operation_id', 'expected_owner_operation_id', 'event_id', 'expected_event_id')


def SF01_instance(value, context):
    return 'source_instance' if value['value_instance'] != value['context_instance'] else None


def SF02_epoch_type(value, context):
    return 'source_epoch' if value['write_epoch_type'] != 'int' else None


def SF03_epoch(value, context):
    return 'source_epoch' if value['write_epoch_type'] == 'int' and value['recovery_epoch'] != value['write_epoch'] else None


def SF04_key(value, context):
    return 'source_key' if value['physical_key'] != value['expected_physical_key'] else None


def SF05_partition(value, context):
    return 'source_partition' if value['scope_partition'] != value['expected_scope_partition'] else None


def SF06_operation(value, context):
    return 'source_operation' if value['owner_operation_id'] != value['expected_owner_operation_id'] else None


def SF07_event_id(value, context):
    return 'source_event_id' if value['event_id'] != value['expected_event_id'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SF01_instance', g.Invariant('/storage_instance_id', 'equals the captured storage instance'), 'source_instance', SF01_instance),
        g.Guard('SF02_epoch_type', g.Invariant('/<context>/write_epoch', 'is an exact int'), 'source_epoch', SF02_epoch_type),
        g.Guard('SF03_epoch', g.Invariant('/recovery_epoch', 'equals the captured write epoch'), 'source_epoch', SF03_epoch),
        g.Guard('SF04_key', g.Invariant('/<physical key>', 'equals the recomputed prepared-source key'), 'source_key', SF04_key),
        g.Guard('SF05_partition', g.Invariant('/scope_partition', 'equals the Storage scope_partition of the body'), 'source_partition', SF05_partition),
        g.Guard('SF06_operation', g.Invariant('/owner_operation_id', 'equals the recomputed owner operation id'), 'source_operation', SF06_operation),
        g.Guard('SF07_event_id', g.Invariant('/event_id', 'equals the recomputed event id'), 'source_event_id', SF07_event_id),
    ])

    def check(value):
        table.require('SF01_instance', value, context)
        table.require('SF02_epoch_type', value, context)
        table.require('SF03_epoch', value, context)
        table.require('SF04_key', value, context)
        table.require('SF05_partition', value, context)
        table.require('SF06_operation', value, context)
        table.require('SF07_event_id', value, context)
        return True
    return g.Case(table, check, context)
