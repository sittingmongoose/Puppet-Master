"""DX guard table clock_owner: Owner clocks, current edition: the shared CV-1101 date_time predicate (storage_utc_z) and the DX owner profile of CV-500..515 (instant).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('shared_refusal', 'leap_second', 'backoff', 'upper_t')


def TC01_shared_syntax(value, context):
    return 'whole-string source timestamp' if value['shared_refusal'] in ('date_time_type', 'date_time_syntax') else None


def TC02_shared_utc_z(value, context):
    return 'whole-string source timestamp' if value['shared_refusal'] == 'date_time_utc_z' else None


def TC03_shared_calendar(value, context):
    return 'whole-string source timestamp' if value['shared_refusal'] not in (None, 'date_time_type', 'date_time_syntax', 'date_time_utc_z') else None


def TC04_owner_no_leap_second(value, context):
    return 'whole-string source timestamp' if value['shared_refusal'] is None and value['leap_second'] is True else None


def TC05_backoff_upper_t(value, context):
    return 'whole-string source timestamp' if value['shared_refusal'] is None and value['leap_second'] is not True and value['backoff'] is True and value['upper_t'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TC01_shared_syntax', g.Invariant('/**/*_utc', 'the whole string is an RFC 3339 date-time (shared date_time: type and syntax)'), 'whole-string source timestamp', TC01_shared_syntax),
        g.Guard('TC02_shared_utc_z', g.Invariant('/**/*_utc', 'the zone is a terminal uppercase Z (shared date_time, storage_utc_z profile)'), 'whole-string source timestamp', TC02_shared_utc_z),
        g.Guard('TC03_shared_calendar', g.Invariant('/**/*_utc', 'the date, time and any second 60 are real (shared date_time: calendar, ranges, announced leap seconds)'), 'whole-string source timestamp', TC03_shared_calendar),
        g.Guard('TC04_owner_no_leap_second', g.Invariant('/**/*_utc', 'a DX owner timestamp has no second 60, even an announced one (CV-500..515)'), 'whole-string source timestamp', TC04_owner_no_leap_second),
        g.Guard('TC05_backoff_upper_t', g.Invariant('/**/*_utc', 'a backoff clock observation has an uppercase T (CV-500..515)'), 'whole-string source timestamp', TC05_backoff_upper_t),
    ])

    def check(value):
        table.require('TC01_shared_syntax', value, context)
        table.require('TC02_shared_utc_z', value, context)
        table.require('TC03_shared_calendar', value, context)
        table.require('TC04_owner_no_leap_second', value, context)
        table.require('TC05_backoff_upper_t', value, context)
        return True
    return g.Case(table, check, context)
