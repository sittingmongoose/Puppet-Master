"""DX guard table recipe_binding: SP-5xx: one authenticated write-time recipe per stored record (record_rules).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('edition', 'retained', 'entry_present', 'entry_source', 'key', 'claimed_kind', 'claimed')


def RB01_edition_known(value, context):
    return 'authenticated retained recipe binding' if value['edition'] not in ('executor-jcs-binary64-v1', 'executor-json-integer-v0') else None


def RB02_retained_entry(value, context):
    return 'authenticated retained recipe binding' if value['retained'] is True and value['entry_present'] is not True else None


def RB03_entry_source(value, context):
    return 'authenticated retained recipe binding' if value['entry_source'] != value['key'] else None


def RB04_claim_type(value, context):
    return 'authenticated retained recipe binding' if value['claimed_kind'] == 'other' else None


def RB05_claim_edition(value, context):
    return 'authenticated retained recipe binding' if value['claimed_kind'] == 'str' and value['edition'] in ('executor-jcs-binary64-v1', 'executor-json-integer-v0') and value['claimed'] != value['edition'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RB01_edition_known', g.Invariant('/recipe_version', 'the custody edition is one of the two DX recipes'), 'authenticated retained recipe binding', RB01_edition_known),
        g.Guard('RB02_retained_entry', g.Invariant('/custody', 'a retained original has an authenticated custody entry'), 'authenticated retained recipe binding', RB02_retained_entry),
        g.Guard('RB03_entry_source', g.Invariant('/custody/source_sha256', 'the custody entry pins the same complete original'), 'authenticated retained recipe binding', RB03_entry_source),
        g.Guard('RB04_claim_type', g.Invariant('/disclosure/recipe_version', 'a claimed recipe is a string'), 'authenticated retained recipe binding', RB04_claim_type),
        g.Guard('RB05_claim_edition', g.Invariant('/disclosure/recipe_version', 'a string claim equals the authenticated edition'), 'authenticated retained recipe binding', RB05_claim_edition),
    ])

    def check(value):
        table.require('RB01_edition_known', value, context)
        table.require('RB02_retained_entry', value, context)
        table.require('RB03_entry_source', value, context)
        table.require('RB04_claim_type', value, context)
        table.require('RB05_claim_edition', value, context)
        return True
    return g.Case(table, check, context)
