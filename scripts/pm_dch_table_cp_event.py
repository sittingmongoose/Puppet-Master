import pm_guard_isolation as g

FIELDS = ('index_event_id', 'event_id', 'last_event_id', 'index_sequence_id', 'event_sequence_id', 'last_sequence_id', 'index_partition', 'body_partition', 'value_partition')


def CP22_index_event_id(value, context):
    return 'checkpoint_refused' if value['index_event_id'] != value['event_id'] else None


def CP23_last_event_id(value, context):
    return 'checkpoint_refused' if value['last_event_id'] != value['event_id'] else None


def CP24_index_sequence(value, context):
    return 'checkpoint_refused' if value['index_sequence_id'] != value['event_sequence_id'] else None


def CP25_last_sequence(value, context):
    return 'checkpoint_refused' if value['last_sequence_id'] != value['event_sequence_id'] else None


def CP26_index_partition(value, context):
    return 'checkpoint_refused' if value['index_partition'] != value['body_partition'] else None


def CP27_value_partition(value, context):
    return 'checkpoint_refused' if value['value_partition'] != value['body_partition'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP22_index_event_id', g.Invariant('/source/index_row/event_id', 'equals the retained event id'), 'checkpoint_refused', CP22_index_event_id),
        g.Guard('CP23_last_event_id', g.Invariant('/value/last_event_id', 'equals the retained event id'), 'checkpoint_refused', CP23_last_event_id),
        g.Guard('CP24_index_sequence', g.Invariant('/source/index_row/sequence_id', 'equals the retained event sequence'), 'checkpoint_refused', CP24_index_sequence),
        g.Guard('CP25_last_sequence', g.Invariant('/value/last_sequence_id', 'equals the retained event sequence'), 'checkpoint_refused', CP25_last_sequence),
        g.Guard('CP26_index_partition', g.Invariant('/source/index_row/scope_partition', 'equals the retained body partition'), 'checkpoint_refused', CP26_index_partition),
        g.Guard('CP27_value_partition', g.Invariant('/value/scope_partition', 'equals the retained body partition'), 'checkpoint_refused', CP27_value_partition),
    ])

    def check(value):
        table.require('CP22_index_event_id', value, context)
        table.require('CP23_last_event_id', value, context)
        table.require('CP24_index_sequence', value, context)
        table.require('CP25_last_sequence', value, context)
        table.require('CP26_index_partition', value, context)
        table.require('CP27_value_partition', value, context)
        return True
    return g.Case(table, check, context)
