"""DX guard table history_custody: Retained reader: original source custody and identity.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('original_digest', 'retained_sha256', 'custody_identity', 'identity', 'disclosure_identity')


def HI01_source_custody(value, context):
    return 'retained original source custody' if value['original_digest'] != value['retained_sha256'] else None


def HI02_custody_identity(value, context):
    return 'retained original identity' if value['custody_identity'] != value['identity'] else None


def HI03_disclosure_identity(value, context):
    return 'retained original identity' if value['disclosure_identity'] != value['identity'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('HI01_source_custody', g.Invariant('/retained_source_sha256', 'equals the digest of the complete original'), 'retained original source custody', HI01_source_custody),
        g.Guard('HI02_custody_identity', g.Invariant('/custody/stored_identity', 'equals the recomputed original identity'), 'retained original identity', HI02_custody_identity),
        g.Guard('HI03_disclosure_identity', g.Invariant('/disclosure/stored_identity', 'equals the recomputed original identity'), 'retained original identity', HI03_disclosure_identity),
    ])

    def check(value):
        table.require('HI01_source_custody', value, context)
        table.require('HI02_custody_identity', value, context)
        table.require('HI03_disclosure_identity', value, context)
        return True
    return g.Case(table, check, context)
