def outputs():
    files = {}
    tables = sorted({r['table'] for r in ROWS})
    imports = []
    mapping = []
    for number in tables:
        name = 'pm_dcw_table_%03d' % number
        imports.append('import ' + name)
        selected = [r for r in ROWS if r['table'] == number]
        text = ['"""DCW phase rows. Generated by pm-dcw-table-generate.py; see its scope note."""', 'import pm_guard_isolation as g', '']
        for row in selected:
            text += ['def ' + row['id'] + '(value, context):', "    if value['site'] != " + repr(row['id']) + ':', '        return None', '    return None if (' + row['predicate'] + ") else value['code']", '']
            mapping.append(repr(row['id']) + ': ' + name + '.case')
        text += ['def case(value):', '    context = None', '    table = g.GuardTable([']
        for row in selected:
            text += ['        g.Guard(' + repr(row['id']) + ', g.Invariant(' + repr('/v0') + ', ' + repr(row['source']) + "), 'refused', " + row['id'] + '),']
        text += ['    ])', '', '    def check(value):']
        for row in selected:
            text += ['        table.require(' + repr(row['id']) + ', value, context)']
        text += ['        return True', '    return g.Case(table, check, context)', '']
        files['scripts/' + name + '.py'] = '\n'.join(text)
    return (files, imports, mapping)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    files, _, _ = outputs()
    stale = []
    for name, text in files.items():
        p = root / name
        if args.check:
            if not p.exists() or p.read_text() != text:
                stale.append(name)
        else:
            p.write_text(text)
    if stale:
        raise SystemExit('stale DCW tables: ' + repr(stale))
    print(str(len(ROWS)) + ' rows in ' + str(len(files)) + ' tables; ' + ('current' if args.check else 'generated'))
if __name__ == '__main__':
    main()
