"""DT guard table tr_usage_a: transition usage.event: settlement order and settlement times.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('previous', 'state', 'prior_ref_truthy', 'settled_at_truthy', 'adjusted_at_truthy')


def UE1_settled_not_reopened(value, context):
    return 'transition_refused' if value['previous'] in ('settled', 'adjusted', 'failed') and value['state'] in ('observed', 'streaming_partial', 'unknown') else None


def UE2_adjusted_after_settled(value, context):
    return 'transition_refused' if value['state'] == 'adjusted' and value['previous'] not in ('settled', 'adjusted') else None


def UE3_prior_ref(value, context):
    return 'transition_refused' if value['previous'] is not None and value['prior_ref_truthy'] is False else None


def UE4_settled_at(value, context):
    return 'transition_refused' if value['state'] == 'settled' and value['settled_at_truthy'] is False else None


def UE5_adjusted_at(value, context):
    return 'transition_refused' if value['state'] == 'adjusted' and value['adjusted_at_truthy'] is False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('UE1_settled_not_reopened', g.Invariant('/payload/settlement_status', 'a settled, adjusted or failed record never returns to observed, partial or unknown'), 'transition_refused', UE1_settled_not_reopened),
        g.Guard('UE2_adjusted_after_settled', g.Invariant('/payload/settlement_status', 'adjusted follows settled or adjusted only'), 'transition_refused', UE2_adjusted_after_settled),
        g.Guard('UE3_prior_ref', g.Invariant('/before/prior_usage_event_ref', 'a revision names its prior Usage event'), 'transition_refused', UE3_prior_ref),
        g.Guard('UE4_settled_at', g.Invariant('/payload/settled_at_utc', 'a settled record carries settled_at_utc'), 'transition_refused', UE4_settled_at),
        g.Guard('UE5_adjusted_at', g.Invariant('/payload/adjusted_at_utc', 'an adjusted record carries adjusted_at_utc'), 'transition_refused', UE5_adjusted_at),
    ])

    def check(value):
        table.require('UE1_settled_not_reopened', value, context)
        table.require('UE2_adjusted_after_settled', value, context)
        table.require('UE3_prior_ref', value, context)
        table.require('UE4_settled_at', value, context)
        table.require('UE5_adjusted_at', value, context)
        return True
    return g.Case(table, check, context)
