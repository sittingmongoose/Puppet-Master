"""DCH guard table ty_b: input_types_valid: object, array and string slots and untyped leaves (strict recipes).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('object_types', 'array_types', 'string_types', 'leaf_types')


def TY05_object_type(value, context):
    return 'type_refused' if value['object_types'] != [] else None


def TY06_array_type(value, context):
    return 'type_refused' if value['array_types'] != [] else None


def TY07_string_type(value, context):
    return 'type_refused' if value['string_types'] != [] else None


def TY08_leaf_type(value, context):
    return 'type_refused' if value['leaf_types'] != [] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TY05_object_type', g.Invariant('/**/<object slot>', 'every object slot holds a JSON object'), 'type_refused', TY05_object_type),
        g.Guard('TY06_array_type', g.Invariant('/**/<array slot>', 'every array slot holds a JSON array'), 'type_refused', TY06_array_type),
        g.Guard('TY07_string_type', g.Invariant('/**/<string slot>', 'every string slot holds a string'), 'type_refused', TY07_string_type),
        g.Guard('TY08_leaf_type', g.Invariant('/**/<untyped leaf>', 'every untyped leaf is a string, boolean, integer or null'), 'type_refused', TY08_leaf_type),
    ])

    def check(value):
        table.require('TY05_object_type', value, context)
        table.require('TY06_array_type', value, context)
        table.require('TY07_string_type', value, context)
        table.require('TY08_leaf_type', value, context)
        return True
    return g.Case(table, check, context)
