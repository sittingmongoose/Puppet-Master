"""DC guard table transition_contribution: proposal_added/vote_added: proposal, attempt and role.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('short', 'proposal_known', 'attempt_known', 'attempt_slot', 'slot', 'attempt_matches', 'attempt_role', 'slot_current_attempt', 'attempt_id')


def TR45_vote_proposal(value, context):
    return 'conflict:unknown_proposal' if value['short'] == 'vote_added' and value['proposal_known'] is not True else None


def TR46_attempt_known(value, context):
    return 'conflict:unknown_attempt' if value['attempt_known'] is not True else None


def TR47_attempt_slot(value, context):
    return 'conflict:unknown_attempt' if value['attempt_known'] is True and value['attempt_slot'] != value['slot'] else None


def TR48_core_proposer(value, context):
    return 'conflict:not_core_participant' if value['short'] == 'proposal_added' and value['attempt_matches'] is True and value['attempt_role'] != 'none' else None


def TR49_proposal_new(value, context):
    return 'conflict:proposal_already_added' if value['short'] == 'proposal_added' and value['attempt_matches'] is True and value['proposal_known'] is True else None


def TR50_not_wonderer(value, context):
    return 'conflict:wonderer_cannot_vote' if value['short'] == 'vote_added' and value['attempt_matches'] is True and value['attempt_role'] == 'wonderer' else None


def TR51_current_attempt(value, context):
    return 'conflict:attempt_not_current' if value['short'] == 'vote_added' and value['attempt_matches'] is True and value['slot_current_attempt'] != value['attempt_id'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR45_vote_proposal', g.Invariant('/proposal_id', 'vote: names a recorded proposal'), 'conflict:unknown_proposal', TR45_vote_proposal),
        g.Guard('TR46_attempt_known', g.Invariant('/attempt_id', 'names a started attempt'), 'conflict:unknown_attempt', TR46_attempt_known),
        g.Guard('TR47_attempt_slot', g.Invariant('/participant_slot_id', 'equals the attempt slot'), 'conflict:unknown_attempt', TR47_attempt_slot),
        g.Guard('TR48_core_proposer', g.Invariant('/attempt_id', 'proposal: a core attempt'), 'conflict:not_core_participant', TR48_core_proposer),
        g.Guard('TR49_proposal_new', g.Invariant('/proposal_id', 'proposal: not already added'), 'conflict:proposal_already_added', TR49_proposal_new),
        g.Guard('TR50_not_wonderer', g.Invariant('/attempt_id', 'vote: not a Wonderer attempt'), 'conflict:wonderer_cannot_vote', TR50_not_wonderer),
        g.Guard('TR51_current_attempt', g.Invariant('/attempt_id', 'vote: the slot current attempt'), 'conflict:attempt_not_current', TR51_current_attempt),
    ])

    def check(value):
        table.require('TR45_vote_proposal', value, context)
        table.require('TR46_attempt_known', value, context)
        table.require('TR47_attempt_slot', value, context)
        table.require('TR48_core_proposer', value, context)
        table.require('TR49_proposal_new', value, context)
        table.require('TR50_not_wonderer', value, context)
        table.require('TR51_current_attempt', value, context)
        return True
    return g.Case(table, check, context)
