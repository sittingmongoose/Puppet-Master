"""DX guard table dependency_custody: Dependencies: scope, Storage root, recomputed digest and deletion.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('project', 'payload_project', 'storage', 'scope_storage', 'declared_sha256', 'recomputed_sha256', 'deleted_at')


def DC01_scope(value, context):
    return 'dependency scope' if value['project'] != value['payload_project'] else None


def DC02_root(value, context):
    return 'dependency root' if value['storage'] != value['scope_storage'] else None


def DC03_digest(value, context):
    return 'dependency hash' if value['declared_sha256'] != value['recomputed_sha256'] else None


def DC04_not_deleted(value, context):
    return 'deleted dependency' if value['deleted_at'] is not None else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('DC01_scope', g.Invariant('/dependencies/*/project_id', 'equals the payload Project'), 'dependency scope', DC01_scope),
        g.Guard('DC02_root', g.Invariant('/dependencies/*/storage_instance_id', 'equals the scope Storage root'), 'dependency root', DC02_root),
        g.Guard('DC03_digest', g.Invariant('/dependencies/*/sha256', 'equals the recomputed body digest'), 'dependency hash', DC03_digest),
        g.Guard('DC04_not_deleted', g.Invariant('/dependencies/*/deleted_at', 'is null'), 'deleted dependency', DC04_not_deleted),
    ])

    def check(value):
        table.require('DC01_scope', value, context)
        table.require('DC02_root', value, context)
        table.require('DC03_digest', value, context)
        table.require('DC04_not_deleted', value, context)
        return True
    return g.Case(table, check, context)
