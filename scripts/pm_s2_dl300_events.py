@contextmanager
def exact_integer_digits():
    """CV-1100 sets no global cap: a 4,400-digit integer must reach a refusal row, never crash."""
    previous = sys.get_int_max_str_digits()
    sys.set_int_max_str_digits(0)
    try:
        yield
    finally:
        sys.set_int_max_str_digits(previous)


def exact(value, expected):
    """Typed equality: bool is never a number, 1.0 is never 1, key sets must agree."""
    if type(value) is not type(expected):
        return False
    if type(expected) is dict:
        return value.keys() == expected.keys() and all(exact(value[k], v) for k, v in expected.items())
    if type(expected) is list:
        return len(value) == len(expected) and all(exact(a, b) for a, b in zip(value, expected))
    return value == expected


def number(value):
    return type(value) in (int, float)


def _ok(fn):
    """One observation clause: True only when it evaluates truthy; an exception never passes."""
    try:
        with exact_integer_digits():
            return bool(fn())
    except Exception:
        return False


def clock(value, profile):
    """The shared CV-1101 predicate accepts the exact string and returns it unchanged."""
    if type(value) is not str:
        return True       # a non-string is the schema row's defect
    try:
        return date_time(value, profile=profile) == value
    except Refusal:
        return False


def at(node, path):
    for part in path:
        node = node[part]
    return node


def slot_values(payload, path):
    """Every (value, concrete path) at one declared slot path; '*' fans out over a map's values."""
    out = [((), payload)]
    for part in path:
        nxt = []
        for p, node in out:
            if type(node) is not dict:
                continue
            if part == '*':
                nxt += [(p + (k,), v) for k, v in node.items()]
            elif part in node:
                nxt.append((p + (part,), node[part]))
        out = nxt
    return out


def payload_numbers(f, payload):
    """current_integer at every integer slot the schema admits as a number (CV-1100)."""
    for path, uri, minimum in INT_SLOTS[f]:
        for _p, value in slot_values(payload, path):
            if number(value) and type(value) is not bool and _ok(lambda: V_SLOT[uri].is_valid(value)):
                current_integer(value, minimum=minimum)
    return True


# --- Method B tables -------------------------------------------------------------------------------------
TABLE_PREFIX = 'pm_s2_table_'
MAX_ROWS = 8
RECORDER = None
_ROWS = {}
_FIELDS = {}


def parts(phase):
    """The generated table modules of one phase, in order: one module, or consecutive parts of at most MAX_ROWS."""
    rows = ROWS[phase][2]
    if len(rows) <= MAX_ROWS:
        return [phase]
    return [f'{phase}__{i + 1}' for i in range((len(rows) + MAX_ROWS - 1) // MAX_ROWS)]


def part_rows(phase):
    rows = ROWS[phase][2]
    names = parts(phase)
    return {name: rows[i * MAX_ROWS:(i + 1) * MAX_ROWS] for i, name in enumerate(names)}


def table_rows(table):
    rows = _ROWS.get(table)
    if rows is None:
        module = importlib.import_module(TABLE_PREFIX + table)
        case = module.case(None)
        rows = _ROWS[table] = [(name, guard.predicate, case.context) for name, guard in case.table.guards.items()]
        _FIELDS[table] = module.FIELDS
        phase = table.split('__')[0]
        spec = [r[1] for r in part_rows(phase)[table]]
        assert list(module.FIELDS) == spec, ('table out of date; run scripts/pm-s2-table-generate.py', table)
    return rows


def refusal(phase, facts):
    """First refusing row of one phase (its part tables in order) as (table, row, code), or None."""
    for table in parts(phase):
        rows = table_rows(table)
        missing = set(_FIELDS[table]) - set(facts)
        assert not missing, (table, sorted(missing))
        observed = {k: facts[k] is True for k in _FIELDS[table]}
        first = None
        for name, predicate, context in rows:
            code = predicate(observed, context)
            if code is not None:
                first = (table, name, code)
                break
        if RECORDER is not None:
            RECORDER.append((table, dict(observed), first))
        if first is not None:
            return first
    return None


