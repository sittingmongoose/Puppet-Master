def _resolve(node, base):
    while isinstance(node, dict) and '$ref' in node:
        ref = node['$ref']
        resolved = REGISTRY.resolver(base_uri=base).lookup(ref)
        base = ref.split('#')[0] or base
        node = resolved.contents
    return node, base


def assert_schema_closure():
    """Every $ref reachable from the lane resources resolves eagerly, including branches no fixture visits
    (check 9); the logical_event / publication definitions keep the structure the rows decompose; every declared
    integer slot is an integer-typed subschema of the registered payload."""
    count, seen = 0, set()

    def walk(node, base):
        nonlocal count
        if isinstance(node, dict):
            if '$ref' in node:
                try:
                    target = REGISTRY.resolver(base_uri=base).lookup(node['$ref'])
                except Unresolvable as error:
                    raise AssertionError(('unresolved schema reference', base, node['$ref'])) from error
                count += 1
                key = (node['$ref'].split('#')[0] or base, node['$ref'].partition('#')[2])
                if key not in seen:
                    seen.add(key)
                    walk(target.contents, key[0])
            for child in node.values():
                walk(child, base)
        elif isinstance(node, list):
            for child in node:
                walk(child, base)
    for schema in [ENVELOPE, RECEIPTS] + list(SCHEMAS.values()):
        Draft202012Validator.check_schema(schema)
        walk(schema, schema['$id'])
    for f in FAMILIES:
        logical = SCHEMAS[f]['$defs']['logical_event']['allOf']
        assert logical[0] == {'$ref': ENVELOPE['$id']}, f
        assert set(logical[1]['properties']) == {'event_type', 'payload_schema_id', 'payload'}, f
        pub = PUB_DEF[f]
        assert tuple(pub['required']) == JOURNAL_SCALARS + ('prepared_event', 'first_append_receipt', 'full_value_commitment'), f
        assert pub['additionalProperties'] is False and set(pub['properties']) == set(pub['required']), f
        row = REGISTRY_ROWS[f]
        assert row['payload_schema_id'] == FAMILY_ROWS[f]['payload_schema_id'], f
        assert sorted(v['scope_kind'] for v in row['payload_versions']) == sorted(SCOPES[f]), f
        for _path, uri, _minimum in INT_SLOTS[f]:
            node, _ = _resolve({'$ref': uri}, SCHEMAS[f]['$id'])
            assert node.get('type') == 'integer', (f, uri)
    return count


def _formats(node, base, path=(), seen=None):
    """(path, format) of every formatted string reachable from a definition (item 12 inventory)."""
    out = []
    seen = set() if seen is None else seen
    if isinstance(node, dict):
        if 'format' in node:
            out.append((path, node['format']))
        if '$ref' in node:
            resolved = REGISTRY.resolver(base_uri=base).lookup(node['$ref'])
            target_base = node['$ref'].split('#')[0] or base
            key = (path, target_base, node['$ref'])
            if key not in seen:
                seen.add(key)
                out += _formats(resolved.contents, target_base, path, seen)
        for k, v in node.items():
            if k == 'properties':
                for name, sub in v.items():
                    out += _formats(sub, base, path + (name,), seen)
            elif k in ('allOf', 'anyOf', 'oneOf'):
                for sub in v:
                    out += _formats(sub, base, path, seen)
            elif k in ('if', 'then', 'else', 'items', 'not', 'additionalProperties') and isinstance(v, dict):
                out += _formats(v, base, path, seen)
    return out


