def retention_facts(f, registry, event_registry_rows):
    row = next((r for r in registry['families'] if r.get('family_id') == FAMILY_ROWS[f]['storage_family_id']), None)
    objects = [p for p in registry['retention_policies'] if p.get('policy_id') == JOURNAL_POLICY]
    obj = objects[0] if len(objects) == 1 else None
    event_row = event_registry_rows.get(f) or {}
    return dict(row_present=row is not None,
                policy_ref=row is None or row.get('retention_policy_ref') == JOURNAL_POLICY,
                registry_agrees=(event_row.get('retention_policy_ref') or {}).get('policy_id') == JOURNAL_POLICY,
                policy_object=len(objects) == 1,
                policy_terms=obj is None or (obj.get('retain_indefinitely') is True and obj.get('ttl_seconds') is None),
                canonical_class=row is None or (row.get('recovery_disposition', {}).get('authority_class') == 'canonical_non_rebuildable'
                                                and row['recovery_disposition'].get('backup_required') is True),
                decision_named=row is None or 'DL-300' in str(row.get('retention_compaction')))


def retention_cell(f, registry, event_registry_rows=None):
    first = refusal('rt', retention_facts(f, registry, REGISTRY_ROWS if event_registry_rows is None else event_registry_rows))
    return 'bound' if first is None else ('refused', first)
