"""DX guard table schema_reference: Whole-document schema admission: every $ref resolves to a schema.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('resolves', 'target_type')


def SR02_ref_resolves(value, context):
    return 'unresolved schema $ref' if value['resolves'] is not True else None


def SR03_ref_target(value, context):
    return 'non-schema $ref target' if value['resolves'] is True and value['target_type'] not in ('dict', 'bool') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SR02_ref_resolves', g.Invariant('/**/$ref', 'the reference resolves offline'), 'unresolved schema $ref', SR02_ref_resolves),
        g.Guard('SR03_ref_target', g.Invariant('/**/$ref', 'a resolved reference names an object or boolean schema'), 'non-schema $ref target', SR03_ref_target),
    ])

    def check(value):
        table.require('SR02_ref_resolves', value, context)
        table.require('SR03_ref_target', value, context)
        return True
    return g.Case(table, check, context)
