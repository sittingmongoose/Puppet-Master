def _validate_history(contract, payload, original, retained_source_sha256, disclosure):
    """Finite retained-source read oracle, independent of today's live lifecycle.

    The hash is a test observation of immutable retained-source custody, not a new
    persisted event field or native admission proof. Original transition predicates
    use the original owner reads; disclosure uses current access/withdrawal fences.
    The original resolves through the shared SP-1101 RetainedDispatcher: one authenticated
    recipe selection, its frozen verifier, then current disclosure.
    """
    original_digest = digest(original)
    from pm_executor_event_contracts import identity
    stored_identity = identity(contract, payload, original['capture']['scope']['storage_instance_id'])
    refuse('history_custody', {
        'original_digest': original_digest, 'retained_sha256': retained_source_sha256,
        'custody_identity': copy.deepcopy(custody_entry(retained_source_sha256).get('stored_identity', list(stored_identity))),
        'disclosure_identity': copy.deepcopy(disclosure.get('stored_identity', list(stored_identity))),
        'identity': list(stored_identity)})
    refuse('history_scope', {'project': copy.deepcopy(disclosure['project_id']), 'payload_project': payload['project_id'],
                             'storage': copy.deepcopy(disclosure['storage_instance_id']),
                             'original_storage': copy.deepcopy(original['capture']['scope']['storage_instance_id'])})

    def verify(custody):
        # The frozen verifier: the complete original and its then-valid lifecycle under its own recipe.
        # The recorded viewer is evidence of original disclosure, never a current grant. Every stored body
        # of the pinned original is read under its own custody entry (_PINNED), never a default recipe.
        token = _PINNED.set(True)
        try:
            validate_capture(contract, payload, original['capture'], historical=True)
        finally:
            _PINNED.reset(token)
        return True

    def disclose(binding):
        refuse('history_disclosure', {'reader_active': copy.deepcopy(disclosure['reader_active']),
                                      'source_available': copy.deepcopy(disclosure['source_available']),
                                      'event_deleted_at': copy.deepcopy(disclosure['event_deleted_at'])})
        refuse('grant', grant_facts(disclosure['viewer'], disclosure['event_readers']), message='event access')
        # These are fresh owner read observations, separate from the pinned original.
        current = {**original['capture'], 'viewer': disclosure['viewer'],
                   'payload_packs': disclosure['payload_packs'],
                   'dependencies': disclosure['dependencies']}
        validate_payload_transport(payload, current['envelope'], current['payload_packs'], current['viewer'])
        validate_dependencies(contract, payload, current)
        return True
    try:
        expected = OriginalBinding(
            storage_instance_id=disclosure['storage_instance_id'], scope_kind='project', server_id=EXECUTOR_SERVER,
            project_id=payload['project_id'], event_type=contract['event_type'], event_id=stored_identity[1],
            idempotency_key=stored_identity[0], owner_operation_id=HISTORY_OPERATION, source_commitment=retained_source_sha256)
        dispatcher = RetainedDispatcher(CustodyOwner(contract, original, list(stored_identity)), installed_recipes(contract, verify))
        dispatcher.resolve(retained_source_sha256, expected, disclose=disclose)
        reason = None
    except Refusal as error:
        reason = error.reason
    refuse('retained_dispatch', {'dispatch_refusal': reason})
    return {'result': 'history_only', 'effects': 0}


def run_trace(contract, payload, scenario):
    """Small deterministic model of receipt custody, restart and reader fences."""
    from pm_executor_event_contracts import identity
    rows, effects, first = {}, 0, None
    writer, reader, generation, frontier = True, True, 1, 0
    token = (generation, frontier)
    outputs = []
    for operation in scenario['operations']:
        action = operation['op']
        refuse('trace_operation', {'op': copy.deepcopy(action)}, ' ' + str(action))
        if action in ('append', 'replay'):
            try:
                validate_append_policy(contract, operation.get('replay_policy', contract['replay_policy']))
            except ValueError as error:
                outputs.append(str(error))
                continue
            p = copy.deepcopy(payload)
            p.update(operation.get('payload_changes', {}))
            try:
                schema_validate(contract['schema_ref'], p)
                admit_integer_slots(contract['schema_ref'], p)
            except (ValueError, jsonschema.ValidationError):
                outputs.append('invalid_payload')
                continue
            try:
                validate_payload_transport(p, {
                    'payload': operation.get('inline_payload', p),
                    'payload_ref': operation.get('payload_ref'),
                    'storage_instance_id': 'store-001',
                }, operation.get('payload_packs', {}), operation.get('viewer', 'viewer-001'))
            except ValueError as error:
                outputs.append(str(error))
                continue
            key = identity(contract, p, 'store-001')
            if key in rows:
                prior = rows[key]
                code = refusal('trace_existing', {'custody_available': prior is not None,
                                                  'prior_digest': prior['digest'] if prior is not None else None,
                                                  'digest': digest(p) if prior is not None else None})
                outputs.append(code if code is not None else prior['receipt'])
            else:
                code = refusal('trace_new', {'writer_open': writer, 'op': action})
                if code is not None:
                    outputs.append(code)
                else:
                    first = 'first-receipt-001'
                    rows[key] = {'digest': digest(p), 'receipt': first, 'result': copy.deepcopy(p)}
                    effects += 1
                    frontier += 1
                    outputs.append('ack_lost' if operation.get('lose_ack') else first)
        elif action == 'crash':
            outputs.append('restarted')
        elif action == 'lose_custody':
            rows[identity(contract, payload, 'store-001')] = None
            outputs.append('custody_unavailable')
        elif action == 'withdraw_writer':
            writer = False
            outputs.append('writer_closed')
        elif action == 'withdraw_reader':
            reader = False
            outputs.append('reader_closed')
        elif action == 'compact':
            generation += 1
            outputs.append('source_generation_changed')
        elif action == 'refresh_token':
            token = (generation, frontier)
            outputs.append('token_refreshed')
        elif action == 'read':
            code = refusal('trace_read', {'reader_active': reader, 'token': list(token), 'current': [generation, frontier]})
            outputs.append(code if code is not None else 'history_only')
        else:  # rebuild; trace_operation admits no other operation
            code = refusal('trace_rebuild', {'row_count': len(rows), 'all_custody': all([x is not None for x in rows.values()])})
            outputs.append(code if code is not None else 'rebuilt')
    return {'outputs': outputs, 'effects': effects}


def mutate(value, changes):
    result = copy.deepcopy(value)
    for change in changes:
        parts = change['path'].split('/')
        target = result
        for part in parts[:-1]:
            target = target[int(part)] if isinstance(target, list) else target[part]
        key = int(parts[-1]) if isinstance(target, list) else parts[-1]
        if change.get('delete'):
            del target[key]
        else:
            target[key] = change['value']
    return result


