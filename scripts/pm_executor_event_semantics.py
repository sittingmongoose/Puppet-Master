# --- Method B guard tables (sweep part 2A) ------------------------------------------------------------------
# Every refusal of the DX checkers is one named row of one phase table (scripts/pm_executor_table_*.py,
# generated by scripts/pm-executor-table-generate.py), evaluated in the table's declared order. The code below
# only derives observations (recomputed digests and identities, canonical bytes, resolved routes, presence)
# for the phase it is about to evaluate; it never decides acceptance. A derivation that depends on an earlier
# row of the same phase is computed only when that row passes, so an observation never carries a second defect
# the checker would not have reached. A caller that reports a reused boundary (grants, dependency custody)
# under its own legacy message still refuses through that boundary's row.
TABLE_PREFIX = 'pm_executor_table_'
_TABLE_MODULES = {}
_TABLE_ROWS = {}
# Set only by the guard-table suite builder (scripts/pm_executor_guard_suites.py); never by a checker path.
RECORDER = None


class TableRefusal(ValueError):
    """A refusal issued by one table row; str() is the legacy refusal message."""

    def __init__(self, phase, row, code, message):
        super().__init__(message)
        self.phase, self.row, self.code = phase, row, code


def table_module(phase):
    module = _TABLE_MODULES.get(phase)
    if module is None:
        module = _TABLE_MODULES[phase] = importlib.import_module(TABLE_PREFIX + phase)
    return module


def table_rows(phase):
    """The phase's (row, predicate, context) list in declared table order."""
    rows = _TABLE_ROWS.get(phase)
    if rows is None:
        built = table_module(phase).case(None)
        rows = _TABLE_ROWS[phase] = [(name, guard.predicate, built.context) for name, guard in built.table.guards.items()]
    return rows


def table_refusals(phase, facts, first=True):
    """Refusing (row, code) pairs of one phase in table order; the first only unless first=False."""
    fields = table_module(phase).FIELDS
    if set(facts) != set(fields):
        raise RuntimeError(f'observation for {phase} must hold exactly {fields}, got {sorted(facts)}')
    observed = {key: facts[key] for key in fields}
    found = []
    for name, predicate, context in table_rows(phase):
        code = predicate(observed, context)
        if code is not None:
            found.append((name, code))
            if first:
                break
    if RECORDER is not None:
        RECORDER.record(phase, observed, found[0] if found else None)
    return found


def refusal(phase, facts):
    """The first refusing row's code, or None (refusals that the trace model returns as outputs)."""
    found = table_refusals(phase, facts)
    return found[0][1] if found else None


def refuse(phase, facts, suffix='', message=None):
    """Raise the first refusing row of the phase. The legacy message is code + suffix unless given."""
    found = table_refusals(phase, facts)
    if found:
        row, code = found[0]
        if type(message) is dict:
            message = message.get(row)
        raise TableRefusal(phase, row, code, (code + suffix) if message is None else message)


def tname(value):
    return type(value).__name__


def q(value):
    """An exact rational observation [numerator, positive denominator]."""
    value = Fraction(value)
    return [value.numerator, value.denominator]


