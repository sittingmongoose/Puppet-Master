def type_case_specimens(family, shapes, case):
    """Resolve a named valid fixture, then change exactly one typed observation."""
    route = case['route']
    refuse('fixture_route', {'kind': 'type_route', 'name': copy.deepcopy(route)}, ' ' + str(route))
    if route == 'capture':
        if case['seed'] == 'baseline':
            seed = copy.deepcopy(family['baseline'])
        else:
            source = next(row for row in family['cases'] if row['case'] == case['seed'])
            seed = mutate(family['baseline'], source['changes'])
    elif route == 'history':
        source = next(row for row in family['history_cases'] if row['case'] == case['seed'])
        seed = {
            'original': mutate(family['baseline'], source['original_changes']),
            'payload': {**copy.deepcopy(family['baseline']['payload']), **source['event_changes']},
            'retained_source_sha256': source.get('retained_source_sha256', family['retained_source_sha256']),
            'disclosure': copy.deepcopy(source['disclosure']),
        }
    else:
        seed = copy.deepcopy(next(row for row in shapes if row['case'] == case['seed']))
    return seed, mutate(seed, case['changes'])


def validate_type_case(contract, route, specimen):
    refuse('fixture_route', {'kind': 'type_route', 'name': copy.deepcopy(route)}, ' ' + str(route))
    if route == 'capture':
        return validate_capture(contract, specimen['payload'], specimen['capture'])
    if route == 'history':
        return validate_history(contract, specimen['payload'], specimen['original'],
                                specimen['retained_source_sha256'], specimen['disclosure'])
    from pm_executor_event_contracts import validate
    return validate(contract, specimen['payload'], specimen['context'])


def numeric_observation(value):
    """A numeric-case result as plain data: bytes as hex, tuples as lists."""
    if type(value) is bytes:
        return {'bytes_hex': value.hex()}
    if type(value) is tuple:
        return list(value)
    return value


def stock_schema_validate(path, value):
    """Isolated schema cases: the exact-end guard under the stock format checker (one table row)."""
    schema = _load_schema(path)
    error = next(iter(jsonschema.Draft202012Validator(schema, format_checker=jsonschema.FormatChecker()).iter_errors(value)), None)
    refuse('payload_schema_stock', {'schema_valid': error is None}, '' if error is None else ': ' + error.message)


def table_order_facts(phase, swap=None):
    """The require order of a generated factory's check() (optionally with two require lines swapped) and its table order."""
    import ast
    lines = (ROOT / 'scripts' / (TABLE_PREFIX + phase + '.py')).read_text().splitlines(keepends=True)
    if swap is not None:
        requires = [i for i, line in enumerate(lines) if line.strip().startswith('table.require(')]
        a, b = requires[swap[0]], requires[swap[1]]
        lines[a], lines[b] = lines[b], lines[a]
    tree = ast.parse(''.join(lines))
    factory = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == 'case')
    check = next(n for n in factory.body if isinstance(n, ast.FunctionDef) and n.name == 'check')
    required = [c.args[0].value for c in ast.walk(check) if isinstance(c, ast.Call) and ast.unparse(c.func) == 'table.require']
    return {'require_order': required, 'table_order': [name for name, _, _ in table_rows(phase)]}


def check_table_order_text(phase, swap=None):
    refuse('integrity_table_order', table_order_facts(phase, swap), ' ' + phase)
    return True


def table_phases(root=ROOT):
    return sorted(path.stem[len(TABLE_PREFIX):] for path in (root / 'scripts').glob(TABLE_PREFIX + '*.py'))


def check_table_order(root=ROOT):
    """Refuse the first generated factory whose check() does not require its rows in table order."""
    for phase in table_phases(root):
        check_table_order_text(phase)
    return True


def table_order_errors(root=ROOT):
    """Each generated factory's check() requires its rows in exactly the table order."""
    return [['table_require_order', phase] for phase in table_phases(root)
            if refusal('integrity_table_order', table_order_facts(phase))]


def check_family_closure(fixture_families, contract_families):
    refuse('integrity_closure', {'fixture_families': sorted(fixture_families), 'contract_families': sorted(contract_families)})
    return True


def check_contract_set(event_types):
    refuse('integrity_contract_set', {'family_count': len(event_types), 'distinct_count': len(set(event_types))})
    return True


def check_type_case(case):
    refuse('integrity_type_case', {'change_count': len(case['changes'])}, ' ' + case['case'])
    return True


def check_capture_seed(family, case):
    seed = mutate(family['baseline'], case['seed_changes'])
    specimen = mutate(family['baseline'], case['changes'])
    refuse('integrity_seed', {'kind': 'capture', 'rebuilt': fixture_encoding(mutate(seed, case['defect_changes'])),
                              'specimen': fixture_encoding(specimen)}, ' ' + case['case'])
    return True


def check_disclosure_seed(case):
    refuse('integrity_seed', {'kind': 'disclosure', 'rebuilt': fixture_encoding(mutate(case['seed_disclosure'], case['disclosure_changes'])),
                              'specimen': fixture_encoding(case['disclosure'])}, ' ' + case['case'])
    return True


def check_shape_seed(case):
    rebuilt = mutate(case['seed'], case['defect_changes'])
    refuse('integrity_seed', {'kind': 'shape', 'rebuilt': fixture_encoding([rebuilt['payload'], rebuilt['context']]),
                              'specimen': fixture_encoding([case['payload'], case['context']])}, ' ' + case['case'])
    return True


def numeric_case(contract, baseline, case):
    """A numeric boundary case: the result, then its canonical-spelling control and golden value."""
    actual = run_numeric_case(contract, baseline, case)
    observed = list(actual) if type(actual) is tuple else actual
    # JSON -0 decodes to integer zero. It must have exactly the same
    # identity/digest/bytes as 0, never a second spelling downstream.
    control = run_numeric_case(contract, baseline, {**case, 'spelling': fixture_encoding(json.loads(case['spelling']))})
    refuse('integrity_numeric', {
        'has_golden': 'expected_value' in case, 'observed': numeric_observation(observed),
        'golden': copy.deepcopy(case.get('expected_value')),
        'actual': numeric_observation(actual), 'control': numeric_observation(control)})
    return actual


def main(family_name=None):
    contracts = json.loads((ROOT / 'Plans/executor_event_contracts.json').read_text())['families']
    if family_name is not None:
        contracts = [contract for contract in contracts if contract['event_type'] == family_name]
        if not contracts:
            raise SystemExit('unknown Executor family ' + family_name)
    failures = check_lane_schemas(contracts)
    if failures:
        print(json.dumps({'status': 'fail', 'schema_reference_failures': failures, 'native_execution': 'NOT_RUN'}, indent=2))
        return 1
    failures.extend(table_order_errors())
    fixture_doc = json.loads((ROOT / 'Plans/executor_event_semantic_fixtures.json').read_text())
    # Deliberately invalid authoring literals are only expanded by their own case.
    selected = {contract['event_type'] for contract in contracts}
    families = expand_fixture_literals({name: family for name, family in fixture_doc['families'].items()
                                        if name in selected})
    helper_cases = fixture_doc.get('helper_cases', [])
    for case in fixture_doc.get('canonical_golden_cases', []):
        try:
            value = json.loads(case['json'])
            actual = canonical(value)
            result = 'accept'
            if (actual != case.get('canonical') or digest(value) != case.get('sha256')):
                failures.append(['canonical_golden', case['case'], 'canonical bytes/hash mismatch'])
        except ValueError:
            result = 'reject'
        if result != case['expected']:
            failures.append(['canonical_golden', case['case'], result])
    ref_fixtures = json.loads((ROOT / 'Plans/executor_event_schema_reference_fixtures.json').read_text())['families']
    type_fixtures = json.loads((ROOT / 'Plans/executor_event_type_fixtures.json').read_text())['families']
    shapes = expand_fixture_literals(json.loads((ROOT / 'Plans/executor_event_contract_fixtures.json').read_text()))['cases']
    for case in helper_cases:
        try:
            run_helper_case(case)
            result, reason = 'accept', None
        except ValueError as error:
            result, reason = 'reject', str(error)
        if result != case['expected'] or reason != case.get('reason'):
            failures.append(['helper', case['case'], result, reason])
    count, traces, score_cases, schema_cases, ref_cases, history_cases, numeric_cases, type_cases = 0, 0, 0, 0, 0, 0, 0, 0
    workgraph_id_cases = 0
    check_family_closure(families, {c['event_type'] for c in contracts})
    for contract in contracts:
        family = families[contract['event_type']]
        for case in family.get('workgraph_id_cases', []):
            workgraph_id_cases += 1
            # These are owner-read boundary cases, not full-capture negatives.
            # The valid seed comes from the real capture's named owner record.
            seed = family['baseline']['capture']['records'][case['slot']]['body']['workgraph_id']
            validate_workgraph_id(seed, case['slot'])
            try:
                validate_workgraph_id(case['value'], case['slot'])
                result, reason = 'accept', None
            except ValueError as error:
                result, reason = 'reject', str(error)
            if result != case['expected'] or reason != case.get('reason'):
                failures.append([contract['event_type'], case['case'], result, reason])
        for case in type_fixtures[contract['event_type']]:
            type_cases += 1
            seed, specimen = type_case_specimens(family, [row for row in shapes if row['event_type'] == contract['event_type']], case)
            validate_type_case(contract, case['route'], seed)
            check_type_case(case)
            try:
                validate_type_case(contract, case['route'], specimen)
                result = 'accept'
            except (ValueError, jsonschema.ValidationError):
                result = 'reject'
            if result != case['expected']:
                failures.append([contract['event_type'], case['case'], result])
        failures.extend(reference_cases(contract, ref_fixtures[contract['event_type']]))
        ref_cases += len(ref_fixtures[contract['event_type']])
        for case in family.get('numeric_cases', []):
            numeric_cases += 1
            try:
                numeric_case(contract, family['baseline'], case)
                result = 'accept'
            except ValueError:
                result = 'reject'
            if result != case['expected']:
                failures.append([contract['event_type'], case['case'], result])
        for case in family['cases']:
            count += 1
            specimen = mutate(family['baseline'], case['changes'])
            if 'seed_changes' in case:
                seed = mutate(family['baseline'], case['seed_changes'])
                validate_capture(contract, seed['payload'], seed['capture'])
                check_capture_seed(family, case)
            try:
                validate_capture(contract, specimen['payload'], specimen['capture'])
                result = 'accept'
            except (ValueError, KeyError, jsonschema.ValidationError):
                result = 'reject'
            if result != case['expected']:
                failures.append([contract['event_type'], case['case'], result])
        for case in family.get('history_cases', []):
            history_cases += 1
            original = mutate(family['baseline'], case['original_changes'])
            payload = copy.deepcopy(family['baseline']['payload'])
            payload.update(case['event_changes'])
            if 'seed_disclosure' in case:
                validate_history(contract, payload, original, case['retained_source_sha256'],
                                 case['seed_disclosure'])
                check_disclosure_seed(case)
            try:
                actual = validate_history(contract, payload, original,
                                          case.get('retained_source_sha256', family['retained_source_sha256']), case['disclosure'])
                result, reason = ('accept' if actual == {'result': 'history_only', 'effects': 0} else 'invalid_effects'), None
            except (ValueError, KeyError, jsonschema.ValidationError) as error:
                result, reason = 'reject', str(error)
            if result != case['expected']:
                failures.append([contract['event_type'], case['case'], result])
            if 'reason' in case and (reason is None or not reason.startswith(case['reason'])):
                failures.append([contract['event_type'], case['case'], reason])
            # The same event must fail current-writer predicates using the later
            # live source; passing history cannot be an accidental ignored check.
            live = mutate(family['baseline'], case['live_changes'])
            try:
                validate_capture(contract, payload, live['capture'])
                current_result = 'accept'
            except (ValueError, KeyError, jsonschema.ValidationError):
                current_result = 'reject'
            if current_result != 'reject':
                failures.append([contract['event_type'], case['case'] + '-live-control', current_result])
        for scenario in family['traces']:
            traces += 1
            actual = run_trace(contract, family['baseline']['payload'], scenario)
            if actual != scenario['expected']:
                failures.append([contract['event_type'], scenario['case'], actual])
        for case in family.get('score_domain_cases', []):
            score_cases += 1
            try:
                validate_score_domain(case['ready_nodes'], case['selected_nodes'])
                result = 'accept'
            except (ValueError, KeyError):
                result = 'reject'
            if result != case['expected']:
                failures.append([contract['event_type'], case['case'], result])
        for case in family.get('schema_cases', []):
            schema_cases += 1
            if 'valid_seed' in case:
                schema_validate(contract['schema_ref'], case['valid_seed'])
            try:
                # Test each schema's exact-end guard independently of our stricter
                # format checker and of every relational/source comparison.
                if case.get('format_route') == 'strict':
                    schema_validate(contract['schema_ref'], case['payload'])
                else:
                    stock_schema_validate(contract['schema_ref'], case['payload'])
                result = 'accept'
            except (ValueError, jsonschema.ValidationError):
                result = 'reject'
            if result != case['expected']:
                failures.append([contract['event_type'], case['case'], result])
    p2a_cases = 0
    if (ROOT / 'Plans/executor_event_p2a_cases.json').exists():
        import pm_executor_p2a_cases as p2a
        registry = json.loads((ROOT / 'Plans/event_family_registry.json').read_text())
        p2a_failures, p2a_cases = p2a.run(json.loads((ROOT / 'Plans/executor_event_p2a_cases.json').read_text()),
                                          {c['event_type']: c for c in contracts}, families, shapes,
                                          {f['event_type'] for f in registry['families']}, ROOT)
        failures.extend(p2a_failures)
    print(json.dumps({'status': 'fail' if failures else 'pass', 'families': len(families), 'sweep_p2a_witnesses': p2a_cases, 'source_transition_cases': count, 'receipt_replay_withdrawal_traces': traces, 'source_score_domain_cases': score_cases, 'isolated_schema_cases': schema_cases, 'schema_reference_cases': ref_cases, 'historical_read_cases': history_cases, 'numeric_boundary_cases': numeric_cases, 'exact_type_cases': type_cases, 'workgraph_id_boundary_cases': workgraph_id_cases, 'canonical_golden_cases': len(fixture_doc.get('canonical_golden_cases', [])), 'helper_cases': len(helper_cases), 'failures': failures, 'native_execution': 'NOT_RUN'}, indent=2))
    return bool(failures)


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--family', help='Check one family in a memory-bounded process; default checks all.')
    raise SystemExit(main(parser.parse_args().family))
