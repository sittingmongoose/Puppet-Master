"""DCH guard table cp_frontier: checkpoint_joins: token anchor, frontier and source selection equal the current node.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('token_anchor', 'node_anchor', 'token_frontier_revision', 'node_frontier_revision', 'token_frontier_sha256', 'node_frontier_sha256', 'token_selection', 'node_selection', 'current_selection')


def CP13_anchor(value, context):
    return 'checkpoint_refused' if value['token_anchor'] != value['node_anchor'] else None


def CP14_frontier_revision(value, context):
    return 'checkpoint_refused' if value['token_frontier_revision'] != value['node_frontier_revision'] else None


def CP15_frontier_sha256(value, context):
    return 'checkpoint_refused' if value['token_frontier_sha256'] != value['node_frontier_sha256'] else None


def CP16_token_selection(value, context):
    return 'checkpoint_refused' if value['token_selection'] != value['node_selection'] else None


def CP17_current_selection(value, context):
    return 'checkpoint_refused' if value['current_selection'] != value['node_selection'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP13_anchor', g.Invariant('/value/source_token/generation_anchor_sha256', 'equals the node anchor'), 'checkpoint_refused', CP13_anchor),
        g.Guard('CP14_frontier_revision', g.Invariant('/value/source_token/frontier_revision', 'equals the node frontier revision'), 'checkpoint_refused', CP14_frontier_revision),
        g.Guard('CP15_frontier_sha256', g.Invariant('/value/source_token/frontier_sha256', 'equals the node frontier digest'), 'checkpoint_refused', CP15_frontier_sha256),
        g.Guard('CP16_token_selection', g.Invariant('/value/source_token/source_selection', 'equals the node source selection'), 'checkpoint_refused', CP16_token_selection),
        g.Guard('CP17_current_selection', g.Invariant('/source/current_source_selection', 'equals the node source selection'), 'checkpoint_refused', CP17_current_selection),
    ])

    def check(value):
        table.require('CP13_anchor', value, context)
        table.require('CP14_frontier_revision', value, context)
        table.require('CP15_frontier_sha256', value, context)
        table.require('CP16_token_selection', value, context)
        table.require('CP17_current_selection', value, context)
        return True
    return g.Case(table, check, context)
