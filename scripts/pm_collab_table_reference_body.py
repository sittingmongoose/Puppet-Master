"""DC guard table reference_body: SP-337 reference: size, hash, JSON object and canonical bytes.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('declared_size', 'body_size', 'declared_blake3', 'body_blake3', 'body_is_object', 'canonical_sha256', 'body_sha256')


def RF03_size(value, context):
    return 'reference_size' if value['declared_size'] != value['body_size'] else None


def RF04_hash(value, context):
    return 'reference_hash' if value['declared_blake3'] != value['body_blake3'] else None


def RF05_json_object(value, context):
    return 'reference_json' if value['body_is_object'] is not True else None


def RF06_canonical(value, context):
    return 'reference_canonical' if value['canonical_sha256'] != value['body_sha256'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RF03_size', g.Invariant('/payload_ref', 'declared size equals the body byte length'), 'reference_size', RF03_size),
        g.Guard('RF04_hash', g.Invariant('/payload_ref', 'declared BLAKE3 equals the body hash'), 'reference_hash', RF04_hash),
        g.Guard('RF05_json_object', g.Invariant('/payload_ref', 'the body decodes to a JSON object'), 'reference_json', RF05_json_object),
        g.Guard('RF06_canonical', g.Invariant('/payload_ref', 'the body is its own canonical JSON (a body with no lossless canonical form has none)'), 'reference_canonical', RF06_canonical),
    ])

    def check(value):
        table.require('RF03_size', value, context)
        table.require('RF04_hash', value, context)
        table.require('RF05_json_object', value, context)
        table.require('RF06_canonical', value, context)
        return True
    return g.Case(table, check, context)
