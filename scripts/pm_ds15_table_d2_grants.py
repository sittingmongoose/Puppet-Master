import pm_guard_isolation as g

FIELDS = ('before_threads', 'after_threads')


def G01_before_unique(value, context):
    return 'transition_refused' if len(value['before_threads']) != len(set(value['before_threads'])) else None


def G02_after_unique(value, context):
    return 'transition_refused' if len(value['after_threads']) != len(set(value['after_threads'])) else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('G01_before_unique', g.Invariant('/before_threads', 'the grants before have distinct threads'), 'transition_refused', G01_before_unique),
        g.Guard('G02_after_unique', g.Invariant('/after_threads', 'the grants after have distinct threads'), 'transition_refused', G02_after_unique),
    ])

    def check(value):
        table.require('G01_before_unique', value, context)
        table.require('G02_after_unique', value, context)
        return True
    return g.Case(table, check, context)
