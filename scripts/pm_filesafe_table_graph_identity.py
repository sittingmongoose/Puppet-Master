"""DF guard table graph_identity: Source graph: family and graph hash.

Method B guard rows for the DF FileSafe checkers. Each predicate reads one
observation record that the lane checker derives from the complete boundary
input (recomputed digests, decoded values, resolved routes, presence);
predicates never recompute, repair or call helpers. The checkers refuse only
through these rows (pm_filesafe_tables.refusals), in this order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-filesafe-table-generate.py; do not edit by hand.
"""
import pm_guard_isolation as g

FIELDS = ('event_type', 'family', 'graph_sha256', 'computed_sha256')


def GR01_family(value, context):
    return 'graph_family' if value['event_type'] != value['family'] else None


def GR02_hash(value, context):
    return 'graph_hash' if value['graph_sha256'] != value['computed_sha256'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('GR01_family', g.Invariant('/event_type', 'equals the checked family'), 'graph_family', GR01_family),
        g.Guard('GR02_hash', g.Invariant('/graph_sha256', 'equals the CV-366 source_graph hash of the graph without graph_sha256'), 'graph_hash', GR02_hash),
    ])

    def check(value):
        table.require('GR01_family', value, context)
        table.require('GR02_hash', value, context)
        return True
    return g.Case(table, check, context)
