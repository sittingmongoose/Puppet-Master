"""DCH guard table st_index_key: stop index_read_valid: checkpoint key, references and current generation.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('token_key', 'key', 'source_key', 'token_ref', 'expected_ref', 'row_ref', 'current_generation', 'generation', 'node_state')


def IX07_token_key(value, context):
    return 'stop_index_refused' if value['token_key'] != value['key'] else None


def IX08_source_key(value, context):
    return 'stop_index_refused' if value['source_key'] != value['key'] else None


def IX09_token_ref(value, context):
    return 'stop_index_refused' if value['token_ref'] != value['expected_ref'] else None


def IX10_row_ref(value, context):
    return 'stop_index_refused' if value['row_ref'] != value['expected_ref'] else None


def IX11_current_generation(value, context):
    return 'stop_index_refused' if value['current_generation'] != value['generation'] else None


def IX12_node_current(value, context):
    return 'stop_index_refused' if value['node_state'] != 'current' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IX07_token_key', g.Invariant('/token/checkpoint_key', 'equals the generic SP-278 key'), 'stop_index_refused', IX07_token_key),
        g.Guard('IX08_source_key', g.Invariant('/source/checkpoint_key', 'equals the generic SP-278 key'), 'stop_index_refused', IX08_source_key),
        g.Guard('IX09_token_ref', g.Invariant('/token/checkpoint_ref', 'equals the key plus the generation pointer'), 'stop_index_refused', IX09_token_ref),
        g.Guard('IX10_row_ref', g.Invariant('/source/index_row/checkpoint_ref', 'equals the key plus the generation pointer'), 'stop_index_refused', IX10_row_ref),
        g.Guard('IX11_current_generation', g.Invariant('/source/checkpoint/current_generation_id', 'equals the token generation'), 'stop_index_refused', IX11_current_generation),
        g.Guard('IX12_node_current', g.Invariant('/source/checkpoint/generations/<g>/state', 'is current'), 'stop_index_refused', IX12_node_current),
    ])

    def check(value):
        table.require('IX07_token_key', value, context)
        table.require('IX08_source_key', value, context)
        table.require('IX09_token_ref', value, context)
        table.require('IX10_row_ref', value, context)
        table.require('IX11_current_generation', value, context)
        table.require('IX12_node_current', value, context)
        return True
    return g.Case(table, check, context)
