import pm_guard_isolation as g

FIELDS = ('degradation_revision', 'previous_revision', 'visible_dependency_available', 'launch_outcome', 'expected_launch_outcome')


def TLD01_revision(value, context):
    return 'transition_refused' if not value['degradation_revision'] > value['previous_revision'] else None


def TLD02_dependency(value, context):
    return 'transition_refused' if value['visible_dependency_available'] else None


def TLD03_launch(value, context):
    return 'transition_refused' if value['launch_outcome'] != value['expected_launch_outcome'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TLD01_revision', g.Invariant('/degradation_revision', 'the degradation revision is above the previous revision'), 'transition_refused', TLD01_revision),
        g.Guard('TLD02_dependency', g.Invariant('/visible_dependency_available', 'the visible dependency is unavailable'), 'transition_refused', TLD02_dependency),
        g.Guard('TLD03_launch', g.Invariant('/launch_outcome', 'the launch outcome is refused for forced_visible, else headless'), 'transition_refused', TLD03_launch),
    ])

    def check(value):
        table.require('TLD01_revision', value, context)
        table.require('TLD02_dependency', value, context)
        table.require('TLD03_launch', value, context)
        return True
    return g.Case(table, check, context)
