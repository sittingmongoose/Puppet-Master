import pm_guard_isolation as g

FIELDS = ('source_thread_id', 'evidence_thread_id', 'source_scope', 'evidence_scope')


def MG10_thread(value, context):
    return 'migration_refused' if value['source_thread_id'] != value['evidence_thread_id'] else None


def MG11_scope(value, context):
    return 'migration_refused' if value['source_scope'] != value['evidence_scope'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('MG10_thread', g.Invariant('/source_thread_id', 'the chip thread is the evidence thread'), 'migration_refused', MG10_thread),
        g.Guard('MG11_scope', g.Invariant('/source_scope', 'the chip scope is the evidence scope'), 'migration_refused', MG11_scope),
    ])

    def check(value):
        table.require('MG10_thread', value, context)
        table.require('MG11_scope', value, context)
        return True
    return g.Case(table, check, context)
