#!/usr/bin/env python3
"""Generate the W3C Method B guard-table modules from pm_w3c_event_oracles.ROWS.

Each module ``scripts/pm_w3c_table_<table>.py`` holds one table (at most eight rows): per row, a predicate that
compares the raw facts the checker observed for it (``pm_w3c_event_oracles.TEMPLATES``) and returns its exact
refusal code, a ``FIELDS`` tuple in table order, and ``case(value)`` building a fresh ``GuardTable`` whose check
requires every row in order. ``--check`` fails when a module is missing, stale or extra.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pm_w3c_event_oracles as W  # noqa: E402

SCRIPTS = W.ROOT / 'scripts'


def lit(text):
    return json.dumps(text, ensure_ascii=True)


def literal(value):
    """A Python literal tuple for an 'in'/'notin' row (strings and integers only) or a 'reason' string."""
    if type(value) is str:
        return lit(value)
    items = []
    for v in value:
        if type(v) is str:
            items.append(lit(v))
        elif type(v) is int:
            items.append(str(v))
        else:
            raise ValueError('unsupported literal ' + repr(v))
    return '(' + ', '.join(items) + (',)' if len(items) == 1 else ')')


def predicate_lines(r):
    condition, _ = W.TEMPLATES[r['template']]
    if 'LIT' in condition:
        condition = condition.replace('LIT', literal(r['lit']))
    lines = ['def ' + r['id'] + '(value, context):', '    v = value[' + lit(r['id']) + ']']
    if r['template'] not in ('ok', 'reason'):
        lines.append('    if v is True:')
        lines.append('        return None')
    lines.append('    return ' + lit(r['code']) + ' if ' + condition + ' else None')
    return lines


def module_text(table, rows):
    lines = ['"""W3C guard table ' + table + '.', '',
             'Method B guard rows (scripts/pm_guard_isolation.py) for scripts/pm_w3c_event_oracles.py. Each predicate is the',
             'row\'s comparison over the raw facts the checker observed for it (True: the row does not apply). The checker',
             'refuses only through these rows, in this order.',
             'Generated by scripts/pm-w3c-table-generate.py from pm_w3c_event_oracles.ROWS; edit the spec there.', '"""',
             'import pm_guard_isolation as g',
             'FIELDS = (' + ''.join([lit(r['id']) + ', ' for r in rows]) + ')', '']
    for r in rows:
        lines += [''] + predicate_lines(r) + ['']
    lines += ['', 'def case(value):', '    context = None', '    table = g.GuardTable([']
    for r in rows:
        lines.append('        g.Guard(' + lit(r['id']) + ', g.Invariant(' + lit(r['field']) + ', ' + lit(r['words']) + '), ' +
                     lit(r['code']) + ', ' + r['id'] + '),')
    lines += ['    ])', '', '    def check(value):']
    for r in rows:
        lines.append('        table.require(' + lit(r['id']) + ', value, context)')
    lines += ['        return True', '    return g.Case(table, check, context)', '']
    return '\n'.join(lines)


def expected():
    return {SCRIPTS / (W.TABLE_PREFIX + t + '.py'): module_text(t, W.TABLE_ROWS[t]) for t in W.TABLES}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    want = expected()
    present = set(SCRIPTS.glob(W.TABLE_PREFIX + '*.py'))
    stale = sorted([str(p.name) for p, t in want.items() if not p.exists() or p.read_text() != t])
    extra = sorted([str(p.name) for p in present - set(want)])
    summary = {'tables': len(want), 'rows': len(W.ROWS), 'entailed': len(W.ENTAILED)}
    if args.check:
        print(json.dumps(dict(summary, stale=stale, extra=extra)))
        return 1 if stale or extra else 0
    for p in present - set(want):
        p.unlink()
    for p, t in want.items():
        if not p.exists() or p.read_text() != t:
            p.write_text(t)
    print(json.dumps(dict(summary, written=len(stale), removed=extra)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
