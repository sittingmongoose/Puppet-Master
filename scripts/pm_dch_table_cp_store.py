"""DCH guard table cp_store: checkpoint_joins: every Storage instance copy equals the actual Store.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('value_store', 'store', 'token_store', 'selection_store', 'root_store')


def CP04_value_store(value, context):
    return 'checkpoint_refused' if value['value_store'] != value['store'] else None


def CP05_token_store(value, context):
    return 'checkpoint_refused' if value['token_store'] != value['store'] else None


def CP06_selection_store(value, context):
    return 'checkpoint_refused' if value['selection_store'] != value['store'] else None


def CP07_root_store(value, context):
    return 'checkpoint_refused' if value['root_store'] != value['store'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP04_value_store', g.Invariant('/value/storage_instance_id', 'equals the actual Store'), 'checkpoint_refused', CP04_value_store),
        g.Guard('CP05_token_store', g.Invariant('/value/source_token/storage_instance_id', 'equals the actual Store'), 'checkpoint_refused', CP05_token_store),
        g.Guard('CP06_selection_store', g.Invariant('/value/source_token/source_selection/storage_instance_id', 'equals the actual Store'), 'checkpoint_refused', CP06_selection_store),
        g.Guard('CP07_root_store', g.Invariant('/source/checkpoint/storage_instance_id', 'equals the actual Store'), 'checkpoint_refused', CP07_root_store),
    ])

    def check(value):
        table.require('CP04_value_store', value, context)
        table.require('CP05_token_store', value, context)
        table.require('CP06_selection_store', value, context)
        table.require('CP07_root_store', value, context)
        return True
    return g.Case(table, check, context)
