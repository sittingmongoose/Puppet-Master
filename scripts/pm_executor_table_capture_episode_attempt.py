"""DX guard table capture_episode_attempt: node.blocked/node.unblocked: the envelope omission or the joined attempt record.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('episode_has_attempt', 'envelope_has_attempt', 'attempt_record_present', 'record_attempt', 'episode_attempt')


def EP03_envelope_omission(value, context):
    return 'pre-attempt envelope omission' if value['episode_has_attempt'] is not True and value['envelope_has_attempt'] is True else None


def EP04_attempt_record(value, context):
    return 'source record set' if value['episode_has_attempt'] is True and value['attempt_record_present'] is not True else None


def EP05_attempt_join(value, context):
    return 'episode attempt record' if value['episode_has_attempt'] is True and value['attempt_record_present'] is True and value['record_attempt'] != value['episode_attempt'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('EP03_envelope_omission', g.Invariant('/capture/envelope/attempt_id', 'is absent before an attempt exists'), 'pre-attempt envelope omission', EP03_envelope_omission),
        g.Guard('EP04_attempt_record', g.Invariant('/records/attempt/body/attempt_id', 'an attempt record is present when the episode names one'), 'source record set', EP04_attempt_record),
        g.Guard('EP05_attempt_join', g.Invariant('/records/attempt/body/attempt_id', 'equals the episode attempt'), 'episode attempt record', EP05_attempt_join),
    ])

    def check(value):
        table.require('EP03_envelope_omission', value, context)
        table.require('EP04_attempt_record', value, context)
        table.require('EP05_attempt_join', value, context)
        return True
    return g.Case(table, check, context)
