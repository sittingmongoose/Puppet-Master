"""DCH guard table cp_family: checkpoint_joins: family, domain key, reader and projector.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('index_event_type', 'family', 'key', 'expected_key')


def CP28_index_event_type(value, context):
    return 'checkpoint_refused' if value['index_event_type'] != value['family'] else None


def CP31_domain_key(value, context):
    return 'checkpoint_refused' if value['key'] != value['expected_key'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP28_index_event_type', g.Invariant('/source/index_row/event_type', 'equals the family'), 'checkpoint_refused', CP28_index_event_type),
        g.Guard('CP31_domain_key', g.Invariant('/key', 'equals the family domain checkpoint key for the Store and body partition'), 'checkpoint_refused', CP31_domain_key),
    ])

    def check(value):
        table.require('CP28_index_event_type', value, context)
        table.require('CP31_domain_key', value, context)
        return True
    return g.Case(table, check, context)
