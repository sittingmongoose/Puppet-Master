FIELDS = ('prepared_commitment', 'recomputed_commitment', 'immutable_mismatches', 'envelope_mismatches')


def SV14_prepare_commitment(value, context):
    return 'original_source_refused' if value['prepared_commitment'] != value['recomputed_commitment'] else None


def SV15_immutable_closure(value, context):
    return 'original_source_refused' if value['immutable_mismatches'] != [] else None


def SV16_envelope_closure(value, context):
    return 'original_source_refused' if value['envelope_mismatches'] != [] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SV14_prepare_commitment', g.Invariant('/completed/prepared_sha256', 'equals SHA-256 of the prepared stage source bytes'), 'original_source_refused', SV14_prepare_commitment),
        g.Guard('SV15_immutable_closure', g.Invariant('/completed', 'every immutable field equals its prepared copy'), 'original_source_refused', SV15_immutable_closure),
        g.Guard('SV16_envelope_closure', g.Invariant('/completed/envelope_context', 'every envelope field but occurred_at_utc equals its prepared copy'), 'original_source_refused', SV16_envelope_closure),
    ])

    def check(value):
        table.require('SV14_prepare_commitment', value, context)
        table.require('SV15_immutable_closure', value, context)
        table.require('SV16_envelope_closure', value, context)
        return True
    return g.Case(table, check, context)
