"""DX guard table post_effects: Transition: committed post-state effects equal the adapter effects.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('observed_type', 'observed_keys', 'expected_keys', 'observed_all_int', 'observed_min', 'expected_all_int', 'expected_min', 'observed_pairs', 'expected_pairs')


def EF01_effects_object(value, context):
    return 'post-state effects' if value['observed_type'] != 'dict' else None


def EF02_effects_keys(value, context):
    return 'post-state effects' if value['observed_type'] == 'dict' and value['observed_keys'] != value['expected_keys'] else None


def EF03_observed_types(value, context):
    return 'post-state effects' if value['observed_type'] == 'dict' and value['observed_all_int'] is not True else None


def EF04_observed_nonnegative(value, context):
    return 'post-state effects' if value['observed_type'] == 'dict' and value['observed_all_int'] is True and value['observed_min'] < 0 else None


def EF05_expected_types(value, context):
    return 'post-state effects' if value['expected_all_int'] is not True else None


def EF06_expected_nonnegative(value, context):
    return 'post-state effects' if value['expected_all_int'] is True and value['expected_min'] < 0 else None


def EF07_effects_equal(value, context):
    return 'post-state effects' if value['observed_type'] == 'dict' and value['observed_keys'] == value['expected_keys'] and value['observed_all_int'] is True and value['expected_all_int'] is True and value['observed_pairs'] != value['expected_pairs'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('EF01_effects_object', g.Invariant('/post_state/effects', 'is an object'), 'post-state effects', EF01_effects_object),
        g.Guard('EF02_effects_keys', g.Invariant('/post_state/effects', 'has exactly the adapter effect names'), 'post-state effects', EF02_effects_keys),
        g.Guard('EF03_observed_types', g.Invariant('/post_state/effects/*', 'every observed count is an integer'), 'post-state effects', EF03_observed_types),
        g.Guard('EF04_observed_nonnegative', g.Invariant('/post_state/effects/*', 'every integer observed count is not negative'), 'post-state effects', EF04_observed_nonnegative),
        g.Guard('EF05_expected_types', g.Invariant('/semantic_adapter/effects/*', 'every adapter count is an integer'), 'post-state effects', EF05_expected_types),
        g.Guard('EF06_expected_nonnegative', g.Invariant('/semantic_adapter/effects/*', 'every integer adapter count is not negative'), 'post-state effects', EF06_expected_nonnegative),
        g.Guard('EF07_effects_equal', g.Invariant('/post_state/effects', 'well-typed observed effects equal the adapter effects'), 'post-state effects', EF07_effects_equal),
    ])

    def check(value):
        table.require('EF01_effects_object', value, context)
        table.require('EF02_effects_keys', value, context)
        table.require('EF03_observed_types', value, context)
        table.require('EF04_observed_nonnegative', value, context)
        table.require('EF05_expected_types', value, context)
        table.require('EF06_expected_nonnegative', value, context)
        table.require('EF07_effects_equal', value, context)
        return True
    return g.Case(table, check, context)
