"""DCH guard table og_receipt: CH2 original: first-AppendReceipt and original full-value commitment copies (SP-286/CV-339).

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('number_refusals', 'commitment', 'expected_commitment', 'receipt_equal')


def OG08_receipt_numbers(value, context):
    return 'original_refused' if value['number_refusals'] != [] else None


def OG09_original_commitment(value, context):
    return 'original_refused' if value['commitment'] != value['expected_commitment'] else None


def OG10_receipt_identity(value, context):
    return 'original_refused' if value['receipt_equal'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('OG08_receipt_numbers', g.Invariant('/original/receipt', 'all receipt Storage integers use storage_uint64'), 'original_refused', OG08_receipt_numbers),
        g.Guard('OG09_original_commitment', g.Invariant('/original/commitment/sha256', 'equals shared full_value_commitment of the independently held original'), 'original_refused', OG09_original_commitment),
        g.Guard('OG10_receipt_identity', g.Invariant('/original/first_receipt', 'the result receipt equals the separately held first receipt'), 'original_refused', OG10_receipt_identity),
    ])

    def check(value):
        table.require('OG08_receipt_numbers', value, context)
        table.require('OG09_original_commitment', value, context)
        table.require('OG10_receipt_identity', value, context)
        return True
    return g.Case(table, check, context)
