import pm_guard_isolation as g

FIELDS = ('capture_created', 'transition_session_id', 'payload_session_id', 'family', 'existing_grant', 'payload_grant_ref', 'recipient_scope', 'payload_scope', 'after_grants', 'wanted_grants')


def TB21_no_capture(value, context):
    return 'transition_refused' if value['capture_created'] else None


def TB22_session(value, context):
    return 'transition_refused' if value['transition_session_id'] != value['payload_session_id'] else None


def TB23_existing_grant(value, context):
    return 'transition_refused' if value['family'] == 'browser.context_shared' and value['existing_grant'] is not None and value['existing_grant'] != value['payload_grant_ref'] else None


def TB24_recipient_scope(value, context):
    return 'transition_refused' if value['family'] == 'browser.context_shared' and value['recipient_scope'] != value['payload_scope'] else None


def TB25_after_grants(value, context):
    return 'transition_refused' if value['after_grants'] != value['wanted_grants'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TB21_no_capture', g.Invariant('/capture_created', 'sharing creates no page capture'), 'transition_refused', TB21_no_capture),
        g.Guard('TB22_session', g.Invariant('/transition_session_id', 'the transition BrowserSession is the payload session'), 'transition_refused', TB22_session),
        g.Guard('TB23_existing_grant', g.Invariant('/existing_grant', 'a recipient already shared keeps its own grant ref'), 'transition_refused', TB23_existing_grant),
        g.Guard('TB24_recipient_scope', g.Invariant('/recipient_scope', 'the recipient scope is the payload scope'), 'transition_refused', TB24_recipient_scope),
        g.Guard('TB25_after_grants', g.Invariant('/after_grants', 'the grants after are exactly the decided result'), 'transition_refused', TB25_after_grants),
    ])

    def check(value):
        table.require('TB21_no_capture', value, context)
        table.require('TB22_session', value, context)
        table.require('TB23_existing_grant', value, context)
        table.require('TB24_recipient_scope', value, context)
        table.require('TB25_after_grants', value, context)
        return True
    return g.Case(table, check, context)
