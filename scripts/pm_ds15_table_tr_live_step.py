import pm_guard_isolation as g

FIELDS = ('session_state', 'step_revision', 'previous_revision')


def TLU01_running(value, context):
    return 'transition_refused' if value['session_state'] != 'running' else None


def TLU02_revision(value, context):
    return 'transition_refused' if not value['step_revision'] > value['previous_revision'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TLU01_running', g.Invariant('/session_state', 'the session is running'), 'transition_refused', TLU01_running),
        g.Guard('TLU02_revision', g.Invariant('/step_revision', 'the step revision is above the previous revision'), 'transition_refused', TLU02_revision),
    ])

    def check(value):
        table.require('TLU01_running', value, context)
        table.require('TLU02_revision', value, context)
        return True
    return g.Case(table, check, context)
