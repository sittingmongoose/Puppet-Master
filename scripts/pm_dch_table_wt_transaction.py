"""DCH guard table wt_transaction: worktree: original transaction observations under the exact family owner.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('operation_identity', 'operation_order')


def WT11_operation_identity(value, context):
    return 'worktree_refused' if value['operation_identity'] is not True else None


def WT12_operation_order(value, context):
    return 'worktree_refused' if value['operation_order'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WT11_operation_identity', g.Invariant('/original/operation', 'operation family and frozen operation id match the original intent'), 'worktree_refused', WT11_operation_identity),
        g.Guard('WT12_operation_order', g.Invariant('/original/operation/actions', 'observed actions preserve the exact owner ordering and no replayed effect'), 'worktree_refused', WT12_operation_order),
    ])

    def check(value):
        table.require('WT11_operation_identity', value, context)
        table.require('WT12_operation_order', value, context)
        return True
    return g.Case(table, check, context)
