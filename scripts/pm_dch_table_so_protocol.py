"""DCH guard table so_protocol: ACD-627 original Stop source: actual active reply, frozen targets and grace, delivery and queue hold.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('reply_active', 'intent_turn', 'reply_turn', 'intent_targets', 'reply_targets', 'grace_ms', 'grace_starts', 'delivered_leases', 'frozen_leases', 'queue_held')


def SO01_active_reply(value, context):
    return 'stop_request_refused' if value['reply_active'] is not True else None


def SO02_active_turn(value, context):
    return 'stop_request_refused' if value['intent_turn'] != value['reply_turn'] else None


def SO03_target_snapshot(value, context):
    return 'stop_request_refused' if value['intent_targets'] != value['reply_targets'] else None


def SO04_grace_deadline(value, context):
    return 'stop_request_refused' if value['grace_ms'] != 3000 else None


def SO05_single_grace(value, context):
    return 'stop_request_refused' if value['grace_starts'] != 1 else None


def SO06_delivery_leases(value, context):
    return 'stop_request_refused' if value['delivered_leases'] != value['frozen_leases'] else None


def SO07_queue_held(value, context):
    return 'stop_request_refused' if value['queue_held'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SO01_active_reply', g.Invariant('/original/reply/active', 'the selector resolved the actual active reply'), 'stop_request_refused', SO01_active_reply),
        g.Guard('SO02_active_turn', g.Invariant('/original/intent/assistant_turn_id', 'equals the actual active assistant turn'), 'stop_request_refused', SO02_active_turn),
        g.Guard('SO03_target_snapshot', g.Invariant('/original/intent/target_work', 'equals that reply exact model/tool/subagent work and leases'), 'stop_request_refused', SO03_target_snapshot),
        g.Guard('SO04_grace_deadline', g.Invariant('/original/pending/deadline_ms', 'the frozen deadline is the original start plus cancel_grace_ms 3000'), 'stop_request_refused', SO04_grace_deadline),
        g.Guard('SO05_single_grace', g.Invariant('/original/pending/grace_starts', 'retries and restart never start a new grace period'), 'stop_request_refused', SO05_single_grace),
        g.Guard('SO06_delivery_leases', g.Invariant('/original/delivery/leases', 'cancellation is delivered to exactly the frozen leases'), 'stop_request_refused', SO06_delivery_leases),
        g.Guard('SO07_queue_held', g.Invariant('/original/pending/queue_held', 'composer Stop holds this reply queue'), 'stop_request_refused', SO07_queue_held),
    ])

    def check(value):
        table.require('SO01_active_reply', value, context)
        table.require('SO02_active_turn', value, context)
        table.require('SO03_target_snapshot', value, context)
        table.require('SO04_grace_deadline', value, context)
        table.require('SO05_single_grace', value, context)
        table.require('SO06_delivery_leases', value, context)
        table.require('SO07_queue_held', value, context)
        return True
    return g.Case(table, check, context)
