"""DS15 guard table bs_digests: Browser source CV-366 semantic hashes, recomputed.

Method B guard rows (scripts/pm_guard_isolation.py) for the DS15 checkers. Each predicate reads one
observation the checker derives from the complete boundary input (recomputed hashes and identities,
canonical-byte sizes, resolved records, presence, typed copies). Predicates never recompute, repair or
call helpers. The checkers refuse only through these rows, in this order
(pm-ds15-event-contracts.py:refusal), and check that every factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-ds15-table-generate.py; edit the row spec there.
"""
import pm_guard_isolation as g

FIELDS = ('accepted_source_sha256', 'record_hash', 'source_sha256', 'unsigned_hash', 'original_input_semantic_sha256', 'input_hash', 'original_output_semantic_sha256', 'output_hash')


def BS03_accepted_source_hash(value, context):
    return 'browser_source_hash' if value['accepted_source_sha256'] != value['record_hash'] else None


def BS04_source_hash(value, context):
    return 'browser_source_hash' if value['source_sha256'] != value['unsigned_hash'] else None


def BS05_input_hash(value, context):
    return 'browser_source_hash' if value['original_input_semantic_sha256'] != value['input_hash'] else None


def BS06_output_hash(value, context):
    return 'browser_source_hash' if value['original_output_semantic_sha256'] != value['output_hash'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('BS03_accepted_source_hash', g.Invariant('/accepted_source_sha256', 'equals the recomputed hash of the resolved record'), 'browser_source_hash', BS03_accepted_source_hash),
        g.Guard('BS04_source_hash', g.Invariant('/source_sha256', 'equals the recomputed hash of the unsigned source'), 'browser_source_hash', BS04_source_hash),
        g.Guard('BS05_input_hash', g.Invariant('/original_input_semantic_sha256', 'equals the recomputed hash of original_input'), 'browser_source_hash', BS05_input_hash),
        g.Guard('BS06_output_hash', g.Invariant('/original_output_semantic_sha256', 'equals the recomputed hash of original_output'), 'browser_source_hash', BS06_output_hash),
    ])

    def check(value):
        table.require('BS03_accepted_source_hash', value, context)
        table.require('BS04_source_hash', value, context)
        table.require('BS05_input_hash', value, context)
        table.require('BS06_output_hash', value, context)
        return True
    return g.Case(table, check, context)
