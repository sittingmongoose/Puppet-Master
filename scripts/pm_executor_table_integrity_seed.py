"""DX guard table integrity_seed: Fixture integrity: a negative is its named valid seed plus its declared defect.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('kind', 'rebuilt', 'specimen')


def IF03_capture_seed(value, context):
    return 'coherent negative seed' if value['kind'] == 'capture' and value['rebuilt'] != value['specimen'] else None


def IF04_disclosure_seed(value, context):
    return 'coherent disclosure seed' if value['kind'] == 'disclosure' and value['rebuilt'] != value['specimen'] else None


def IC08_shape_seed(value, context):
    return 'coherent shape seed' if value['kind'] == 'shape' and value['rebuilt'] != value['specimen'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IF03_capture_seed', g.Invariant('/cases/*/seed_changes', 'seed plus defect changes encodes to the negative'), 'coherent negative seed', IF03_capture_seed),
        g.Guard('IF04_disclosure_seed', g.Invariant('/history_cases/*/seed_disclosure', 'seed disclosure plus defect changes encodes to the disclosure'), 'coherent disclosure seed', IF04_disclosure_seed),
        g.Guard('IC08_shape_seed', g.Invariant('/cases/*/seed', 'shape seed plus defect changes encodes to the case'), 'coherent shape seed', IC08_shape_seed),
    ])

    def check(value):
        table.require('IF03_capture_seed', value, context)
        table.require('IF04_disclosure_seed', value, context)
        table.require('IC08_shape_seed', value, context)
        return True
    return g.Case(table, check, context)
