"""DC guard table envelope_datetime: CV-1101 (sweep part 2B): EventRecord timestamps through the shared date_time predicate, one profile per field.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('occurred_at_valid', 'observed_at_valid', 'persisted_at_valid')


def EV15_occurred_at_format(value, context):
    return 'event_record_schema' if value['occurred_at_valid'] is not True else None


def EV16_observed_at_format(value, context):
    return 'event_record_schema' if value['observed_at_valid'] is not True else None


def EV17_persisted_at_format(value, context):
    return 'event_record_schema' if value['persisted_at_valid'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('EV15_occurred_at_format', g.Invariant('/occurred_at_utc', 'passes the shared date_time predicate, EVENT_RECORD profile (CV-317/CV-1101)'), 'event_record_schema', EV15_occurred_at_format),
        g.Guard('EV16_observed_at_format', g.Invariant('/observed_at_utc', 'passes the shared date_time predicate, STORAGE_UTC_Z profile (CV-253)'), 'event_record_schema', EV16_observed_at_format),
        g.Guard('EV17_persisted_at_format', g.Invariant('/persisted_at_utc', 'passes the shared date_time predicate, STORAGE_UTC_Z profile (CV-253)'), 'event_record_schema', EV17_persisted_at_format),
    ])

    def check(value):
        table.require('EV15_occurred_at_format', value, context)
        table.require('EV16_observed_at_format', value, context)
        table.require('EV17_persisted_at_format', value, context)
        return True
    return g.Case(table, check, context)
