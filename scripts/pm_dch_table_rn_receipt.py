"""DCH guard table rn_receipt: record_number_rule: exactly one sealed write receipt selects the retained original's recipe.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('store_in_custody', 'receipt_count')


def RN07_receipt_present(value, context):
    return 'original_unavailable' if value['store_in_custody'] is True and value['receipt_count'] == 0 else None


def RN08_receipt_unique(value, context):
    return 'recipe_unsupported' if value['store_in_custody'] is True and value['receipt_count'] != 0 and value['receipt_count'] != 1 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RN07_receipt_present', g.Invariant('/provenance/source_value_sha256', 'the sealed catalogue holds a write receipt for this exact original (Store and source commitment)'), 'original_unavailable', RN07_receipt_present),
        g.Guard('RN08_receipt_unique', g.Invariant('/provenance/source_value_sha256', 'the sealed catalogue holds exactly one write receipt for this exact original'), 'recipe_unsupported', RN08_receipt_unique),
    ])

    def check(value):
        table.require('RN07_receipt_present', value, context)
        table.require('RN08_receipt_unique', value, context)
        return True
    return g.Case(table, check, context)
