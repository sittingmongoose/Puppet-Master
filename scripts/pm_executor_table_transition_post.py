"""DX guard table transition_post: Transition: successor, post-state, CAS revision and sequence.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('after', 'rule_after', 'post_state', 'post_revision_canonical', 'next_revision_canonical', 'post_sequence_canonical', 'payload_sequence_canonical')


def TX05_successor(value, context):
    return 'illegal successor' if value['after'] != value['rule_after'] else None


def TX06_post_state(value, context):
    return 'post-state' if value['post_state'] != value['after'] else None


def TX07_post_cas(value, context):
    return 'post-state CAS' if value['post_revision_canonical'] != value['next_revision_canonical'] else None


def TX08_post_sequence(value, context):
    return 'post-state sequence' if value['post_sequence_canonical'] != value['payload_sequence_canonical'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TX05_successor', g.Invariant('/transition/after', 'equals the matching rule successor'), 'illegal successor', TX05_successor),
        g.Guard('TX06_post_state', g.Invariant('/post_state/state', 'equals the successor'), 'post-state', TX06_post_state),
        g.Guard('TX07_post_cas', g.Invariant('/post_state/revision', 'equals the transition revision plus one'), 'post-state CAS', TX07_post_cas),
        g.Guard('TX08_post_sequence', g.Invariant('/post_state/event_sequence', 'equals the payload event_sequence'), 'post-state sequence', TX08_post_sequence),
    ])

    def check(value):
        table.require('TX05_successor', value, context)
        table.require('TX06_post_state', value, context)
        table.require('TX07_post_cas', value, context)
        table.require('TX08_post_sequence', value, context)
        return True
    return g.Case(table, check, context)
