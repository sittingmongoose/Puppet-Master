import pm_guard_isolation as g

FIELDS = ('thread_durable_before', 'role', 'creates_thread', 'lineage_owner')


def TM05_draft_user(value, context):
    return 'thread_refused' if value['thread_durable_before'] is False and value['role'] != 'user' else None


def TM06_first_creates(value, context):
    return 'thread_refused' if value['thread_durable_before'] is False and value['role'] == 'user' and value['creates_thread'] is not True else None


def TM07_no_recreate(value, context):
    return 'thread_refused' if value['thread_durable_before'] is True and value['creates_thread'] is not False else None


def TM08_lineage_owner(value, context):
    return 'thread_refused' if value['lineage_owner'] != 'transcript' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TM05_draft_user', g.Invariant('/operation/outcome/message/role', 'without a durable thread only a user message commits'), 'thread_refused', TM05_draft_user),
        g.Guard('TM06_first_creates', g.Invariant('/operation/outcome/creates_thread', 'the first user-message commit creates the durable thread'), 'thread_refused', TM06_first_creates),
        g.Guard('TM07_no_recreate', g.Invariant('/operation/outcome/creates_thread', 'a message in a durable thread creates no thread'), 'thread_refused', TM07_no_recreate),
        g.Guard('TM08_lineage_owner', g.Invariant('/operation/outcome/lineage_owner', 'edit/supersession lineage stays under the transcript owner'), 'thread_refused', TM08_lineage_owner),
    ])

    def check(value):
        table.require('TM05_draft_user', value, context)
        table.require('TM06_first_creates', value, context)
        table.require('TM07_no_recreate', value, context)
        table.require('TM08_lineage_owner', value, context)
        return True
    return g.Case(table, check, context)
