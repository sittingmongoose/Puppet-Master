"""DC guard table int_ledger_row_b: Ledger row: retention, aliases, source refs, case ids and admission.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('retention_policy_id', 'aliases', 'ledger_source_ref_present', 'unknown_case_ids', 'admission_status', 'authority_contract_ref')


def IL17_retention_policy(value, context):
    return 'retention_policy_ref' if value['retention_policy_id'] != 'RP-CHAT-THREAD-LIFETIME' else None


def IL18_no_alias(value, context):
    return 'no_alias' if value['aliases'] != [] else None


def IL19_source_ref(value, context):
    return 'row_source_ref_to_ledger' if value['ledger_source_ref_present'] is not True else None


def IL20_case_ids(value, context):
    return 'validation_case_ids_unknown' if value['unknown_case_ids'] != [] else None


def IL21_authority_ref(value, context):
    return 'admitted_without_authority_ref' if value['admission_status'] == 'admitted_static_contract' and not value['authority_contract_ref'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IL17_retention_policy', g.Invariant('/rows/<i>/registry_row/retention_policy_ref/policy_id', 'is RP-CHAT-THREAD-LIFETIME'), 'retention_policy_ref', IL17_retention_policy),
        g.Guard('IL18_no_alias', g.Invariant('/rows/<i>/registry_row/legacy/aliases', 'is empty'), 'no_alias', IL18_no_alias),
        g.Guard('IL19_source_ref', g.Invariant('/rows/<i>/registry_row/source_refs', 'cites the ledger row'), 'row_source_ref_to_ledger', IL19_source_ref),
        g.Guard('IL20_case_ids', g.Invariant('/rows/<i>/validation_case_ids', 'are fixture case or oracle ids'), 'validation_case_ids_unknown', IL20_case_ids),
        g.Guard('IL21_authority_ref', g.Invariant('/rows/<i>/authority_contract_ref', 'an admitted row has an authority contract ref'), 'admitted_without_authority_ref', IL21_authority_ref),
    ])

    def check(value):
        table.require('IL17_retention_policy', value, context)
        table.require('IL18_no_alias', value, context)
        table.require('IL19_source_ref', value, context)
        table.require('IL20_case_ids', value, context)
        table.require('IL21_authority_ref', value, context)
        return True
    return g.Case(table, check, context)
