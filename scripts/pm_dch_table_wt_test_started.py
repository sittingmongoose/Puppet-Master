"""DCH guard table wt_test_started: ACD-624 original pre-merge test launch source.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('lock', 'operation', 'target', 'payload_target', 'strategy', 'payload_strategy', 'guard_mismatches', 'safe_point_present', 'rebase_conflict')


def WS01_lock(value, context):
    return 'worktree_refused' if value['lock'] != value['operation'] else None


def WS02_target(value, context):
    return 'worktree_refused' if value['target'] != value['payload_target'] else None


def WS03_strategy(value, context):
    return 'worktree_refused' if value['strategy'] != value['payload_strategy'] else None


def WS04_guards(value, context):
    return 'worktree_refused' if value['guard_mismatches'] != [] else None


def WS05_snapshot(value, context):
    return 'worktree_refused' if value['safe_point_present'] is not True else None


def WS06_rebase_conflict(value, context):
    return 'worktree_refused' if value['rebase_conflict'] is not False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WS01_lock', g.Invariant('/operation/outcome/lock_owner', 'the original operation holds the merge lock'), 'worktree_refused', WS01_lock),
        g.Guard('WS02_target', g.Invariant('/operation/outcome/target', 'equals the original test target'), 'worktree_refused', WS02_target),
        g.Guard('WS03_strategy', g.Invariant('/operation/outcome/strategy', 'equals the original strategy'), 'worktree_refused', WS03_strategy),
        g.Guard('WS04_guards', g.Invariant('/operation/outcome/guards', 'dirty/conflict/active-run/detached-HEAD guards were rechecked and clear'), 'worktree_refused', WS04_guards),
        g.Guard('WS05_snapshot', g.Invariant('/operation/outcome/safe_point_ref', 'a safe-point worktree snapshot exists before mutation-capable tests'), 'worktree_refused', WS05_snapshot),
        g.Guard('WS06_rebase_conflict', g.Invariant('/operation/outcome/rebase_conflict', 'tests do not start after an earlier rebase conflict'), 'worktree_refused', WS06_rebase_conflict),
    ])

    def check(value):
        table.require('WS01_lock', value, context)
        table.require('WS02_target', value, context)
        table.require('WS03_strategy', value, context)
        table.require('WS04_guards', value, context)
        table.require('WS05_snapshot', value, context)
        table.require('WS06_rebase_conflict', value, context)
        return True
    return g.Case(table, check, context)
