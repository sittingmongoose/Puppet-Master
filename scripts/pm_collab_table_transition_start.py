"""DC guard table transition_start: started or start_commit: no run yet and the expected revision is current.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('run_exists', 'start_previous_revision', 'start_latest_revision')


def TR08_already_started(value, context):
    return 'conflict:already_started' if value['run_exists'] is True else None


def TR09_start_commit_revision(value, context):
    return 'conflict:stale_definition_revision' if value['start_previous_revision'] != value['start_latest_revision'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR08_already_started', g.Invariant('/collaboration_run_id', 'has no started run'), 'conflict:already_started', TR08_already_started),
        g.Guard('TR09_start_commit_revision', g.Invariant('/previous_definition_revision', 'start_commit: equals the latest revision'), 'conflict:stale_definition_revision', TR09_start_commit_revision),
    ])

    def check(value):
        table.require('TR08_already_started', value, context)
        table.require('TR09_start_commit_revision', value, context)
        return True
    return g.Case(table, check, context)
