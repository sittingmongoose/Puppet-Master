"""DC guard table source_digests: Source custody: semantic and record digests and the record reference.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('semantic_sha256', 'expected_semantic_sha256', 'owner_record_sha256', 'actual_record_sha256', 'context_record_sha256', 'owner_record_ref', 'expected_record_ref', 'context_record_ref')


def SF08_semantic_digest(value, context):
    return 'source_digest' if value['semantic_sha256'] != value['expected_semantic_sha256'] else None


def SF09_record_digest(value, context):
    return 'source_record_digest' if value['owner_record_sha256'] != value['actual_record_sha256'] else None


def SF10_context_record_digest(value, context):
    return 'source_record_digest' if value['context_record_sha256'] != value['actual_record_sha256'] else None


def SF11_record_ref(value, context):
    return 'source_record_ref' if value['owner_record_ref'] != value['expected_record_ref'] else None


def SF12_context_record_ref(value, context):
    return 'source_record_ref' if value['owner_record_ref'] != value['context_record_ref'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SF08_semantic_digest', g.Invariant('/semantic_sha256', 'equals the producer digest of the body'), 'source_digest', SF08_semantic_digest),
        g.Guard('SF09_record_digest', g.Invariant('/owner_record_sha256', 'equals the canonical digest of owner_record'), 'source_record_digest', SF09_record_digest),
        g.Guard('SF10_context_record_digest', g.Invariant('/<context>/owner_record_sha256', 'equals the canonical digest of owner_record'), 'source_record_digest', SF10_context_record_digest),
        g.Guard('SF11_record_ref', g.Invariant('/owner_record_ref', 'equals the family record reference of the body'), 'source_record_ref', SF11_record_ref),
        g.Guard('SF12_context_record_ref', g.Invariant('/<context>/owner_record_ref', 'equals the source owner_record_ref'), 'source_record_ref', SF12_context_record_ref),
    ])

    def check(value):
        table.require('SF08_semantic_digest', value, context)
        table.require('SF09_record_digest', value, context)
        table.require('SF10_context_record_digest', value, context)
        table.require('SF11_record_ref', value, context)
        table.require('SF12_context_record_ref', value, context)
        return True
    return g.Case(table, check, context)
