"""DG6A guard table history_checkpoint: Retained read: checkpoint publication and original checkpoint (collect-all by guard).

Method B guard rows (scripts/pm_guard_isolation.py) for the DG6A checkers. Each predicate reads one
observation the checker derives from the complete boundary input (recomputed digests and identities,
canonical-byte sizes, typed joins, presence). Predicates never recompute, repair or call helpers.
The checkers refuse only through these rows, in this order (scripts/pm_dg6a_tables.py).
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-dg6a-table-generate.py; edit the row spec there.
"""
import pm_guard_isolation as g

FIELDS = ('checkpoint_current', 'checkpoint_valid', 'publication_exact', 'event_current')


def HG01_checkpoint_publication(value, context):
    return 'checkpoint_publication' if value['checkpoint_current'] is not True else None


def HG02_checkpoint_checker(value, context):
    return 'checkpoint_original' if value['checkpoint_valid'] is not True else None


def HG03_checkpoint_publication_exact(value, context):
    return 'checkpoint_original' if value['checkpoint_valid'] is True and value['publication_exact'] is not True else None


def HG04_event_publication(value, context):
    return 'event_publication' if value['event_current'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('HG01_checkpoint_publication', g.Invariant('/checkpoint_current', 'the checkpoint state is current'), 'checkpoint_publication', HG01_checkpoint_publication),
        g.Guard('HG02_checkpoint_checker', g.Invariant('/checkpoint_valid', 'the checkpoint passes its family checkpoint checker against the original'), 'checkpoint_original', HG02_checkpoint_checker),
        g.Guard('HG03_checkpoint_publication_exact', g.Invariant('/publication_exact', 'its publication fields exactly equal the independent original checkpoint'), 'checkpoint_original', HG03_checkpoint_publication_exact),
        g.Guard('HG04_event_publication', g.Invariant('/event_current', 'the event state is current'), 'event_publication', HG04_event_publication),
    ])

    def check(value):
        table.require('HG01_checkpoint_publication', value, context)
        table.require('HG02_checkpoint_checker', value, context)
        table.require('HG03_checkpoint_publication_exact', value, context)
        table.require('HG04_event_publication', value, context)
        return True
    return g.Case(table, check, context)
