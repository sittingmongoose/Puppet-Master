def assert_schema_closure():
    """Every $ref in every lane resource resolves, including branches no fixture visits (check 9),
    and the logical_event / publication definitions keep the structure the rows decompose."""
    count = 0
    for schema in [ENVELOPE, RECEIPTS] + list(SCHEMAS.values()):
        Draft202012Validator.check_schema(schema)
        resolver = REGISTRY.resolver(base_uri=schema['$id'])

        def walk(node):
            nonlocal count
            if isinstance(node, dict):
                if '$ref' in node:
                    try:
                        resolver.lookup(node['$ref'])
                    except Unresolvable as error:
                        raise AssertionError(('unresolved schema reference', schema['$id'], node['$ref'])) from error
                    count += 1
                for child in node.values():
                    walk(child)
            elif isinstance(node, list):
                for child in node:
                    walk(child)
        walk(schema)
    for f in FAMILIES:
        logical = SCHEMAS[f]['$defs']['logical_event']['allOf']
        assert logical[0] == {'$ref': ENVELOPE['$id']}, f
        assert set(logical[1]['properties']) == {'event_type', 'payload_schema_id', 'payload'}, f
        assert logical[1]['properties']['payload'] == {'$ref': '#/$defs/payload'}, f
        pub = PUB_DEF[f]
        assert tuple(pub['required']) == JOURNAL_SCALARS + ('prepared_event', 'first_append_receipt', 'full_value_commitment'), f
        assert pub['additionalProperties'] is False and set(pub['properties']) == set(pub['required']), f
    return count


def _formats(node, base, path=(), seen=None):
    """(path, format) of every formatted string reachable from a definition (item 12 inventory).
    References resolve through the closed registry, relative ones against their own document."""
    out = []
    seen = set() if seen is None else seen
    if isinstance(node, dict):
        if 'format' in node:
            out.append((path, node['format']))
        if '$ref' in node:
            resolved = REGISTRY.resolver(base_uri=base).lookup(node['$ref'])
            target_base = node['$ref'].split('#')[0] or base
            key = (path, target_base, node['$ref'])
            if key not in seen:
                seen.add(key)
                out += _formats(resolved.contents, target_base, path, seen)
        for k, v in node.items():
            if k == 'properties':
                for name, sub in v.items():
                    out += _formats(sub, base, path + (name,), seen)
            elif k in ('allOf', 'anyOf', 'oneOf'):
                for sub in v:
                    out += _formats(sub, base, path, seen)
            elif k in ('if', 'then', 'else', 'items', 'not', 'additionalProperties') and isinstance(v, dict):
                out += _formats(v, base, path, seen)
    return out


