def retention_facts(f, registry):
    group = FAMILY_ROWS[f]['group']
    policy = GROUP_POLICY[group]
    row = next((r for r in registry['families'] if r.get('family_id') == FAMILY_ROWS[f]['storage_family_id']), None)
    objects = [p for p in registry['retention_policies'] if p.get('policy_id') == policy]
    obj = objects[0] if len(objects) == 1 else None
    if policy in APPROVED_POLICY:
        terms = obj is not None and exact(obj, APPROVED_POLICY[policy])
    elif policy == 'RP-GOAL-THREAD-LIFETIME':
        terms = obj is not None and obj.get('retain_indefinitely') is True and obj.get('max_cardinality') is None
    else:
        terms = obj is not None and obj.get('retain_indefinitely') is True and obj.get('ttl_seconds') is None
    return dict(row_present=row is not None, policy_ref=row is None or row.get('retention_policy_ref') == policy,
                policy_object=len(objects) == 1, policy_terms=obj is None or terms,
                canonical_class=row is None or (row.get('recovery_disposition', {}).get('authority_class') == 'canonical_non_rebuildable'
                                                and row['recovery_disposition'].get('backup_required') is True),
                decision_named=row is None or f'Card 1 {group}' in str(row.get('retention_compaction')))


def retention_cell(f, registry):
    first = refusal('rt', retention_facts(f, registry))
    return 'bound' if first is None else ('refused', first)
