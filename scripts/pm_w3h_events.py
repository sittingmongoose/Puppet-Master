def H(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def _subject_item(p, facts):
    after = facts.get('after', {})
    return after.get(p['todo_id']) if p['todo_id'] in after else facts.get('before', {}).get(p['todo_id'])


def _members(facts):
    return {k: v for k, v in facts['after'].items() if v.get('member', True)}


def _cycle_free(graph):
    state = {}

    def visit(node):
        if state.get(node) == 1:
            return False
        if state.get(node) == 2:
            return True
        state[node] = 1
        for dep in graph[node]['depends_on']:
            # A self edge is TD10's defect, never a cycle here (one invariant per row).
            if dep != node and dep in graph and not visit(dep):
                return False
        state[node] = 2
        return True
    return all(visit(n) for n in graph)


