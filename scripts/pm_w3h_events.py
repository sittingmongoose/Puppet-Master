def binding_of(w):
    ev = logical_of(w)
    commit = w['publication'].get('full_value_commitment')
    return OriginalBinding(w['storage']['storage_instance_id'], ev['scope_kind'], w['source']['server_id'], ev['project_id'],
                           ev['event_type'], ev['event_id'], ev['idempotency_key'], w['publication']['owner_operation_id'],
                           commit['sha256'] if type(commit) is dict else 'prepared')


def seal_write_receipt(w):
    """Writer side only: Storage seals the receipt of the original it writes, with the writer's own recipe."""
    b = binding_of(w)
    w['storage'].setdefault('sealed', []).append(dict(locator=w['storage']['journal_key'], binding=dict(b.__dict__),
                                                      recipe=dict(RECIPES[(w['family'], w['scope'])].__dict__)))
    return w


def sealed_at(w):
    return [r for r in w['storage'].get('sealed', []) if type(r) is dict and r.get('locator') == w['storage']['journal_key']]


class W3HOriginalOwner:
    """Answers only from the one sealed receipt of the exact original locator; never a default."""

    def __init__(self, w):
        self._w = w

    def authenticated_original(self, original_ref):
        receipts = [r for r in self._w['storage'].get('sealed', []) if r.get('locator') == original_ref]
        if len(receipts) != 1:
            raise Refusal('original_unavailable' if not receipts else 'recipe_ambiguous')
        r = receipts[0]
        ev = logical_of(self._w)
        return OriginalCustody(OriginalBinding(**r['binding']), RecipeTuple(**r['recipe']),
                               storage_value_bytes(ev, profile=EVENT_VALUE),
                               storage_value_bytes(self._w['source']['result'], profile=EVENT_VALUE),
                               storage_value_bytes(self._w['publication']['first_append_receipt'], profile=EVENT_VALUE))


def _frozen(f, scope):
    def verify(custody):
        return custody.recipe == RECIPES[(f, scope)]
    return FrozenRecipe(verify)


def retained_facts(w, read):
    f = w['family']
    receipts = sealed_at(w)
    r = receipts[0] if len(receipts) == 1 else None
    known = r is not None and _ok(lambda: RecipeTuple(**r['recipe']) in RECIPES.values())
    ev = _ok(lambda: logical_of(w) is not None) and logical_of(w)
    bound = r is not None and type(ev) is dict and _ok(lambda: OriginalBinding(**r['binding']) == binding_of(w))
    tuple_ok = known and type(ev) is dict and _ok(lambda: RecipeTuple(**r['recipe']) == RECIPES.get((f, ev['scope_kind'])))
    verified = verify_publication(w, 'frozen') is None
    token, live = read['token'], read['live']
    covered = token['covered']
    return dict(receipt_present=len(receipts) >= 1, receipt_unique=len(receipts) <= 1,
                receipt_binding=r is None or bound, recipe_known=r is None or not bound or known,
                recipe_edition=r is None or not bound or not known or tuple_ok,
                original_verified=r is None or not bound or not tuple_ok or verified,
                reader_enabled=read['reader_enabled'] is True, read_permission=read['read_permission'] is True,
                not_deleted=read['deleted'] is False, read_only=exact(read['requested_effects'], 0),
                token_instance=token['storage_instance_id'] == w['storage']['storage_instance_id'],
                token_frontier=exact(token['frontier'], live['frontier']), token_snapshot=token['snapshot_id'] == live['snapshot_id'],
                coverage=all(covered[i][1] + 1 == covered[i + 1][0] for i in range(len(covered) - 1)) and covered[0][0] == 0
                and covered[-1][1] >= live['frontier'],
                selection=token['partition'] == w['publication']['scope_partition'] and token['event_type'] == f)


def default_read(w):
    return dict(reader_enabled=True, read_permission=True, deleted=False, requested_effects=0,
                token=dict(storage_instance_id=w['storage']['storage_instance_id'], frontier=41, snapshot_id='snap-tx-1',
                           covered=[[0, 20], [21, 41]], partition=w['publication']['scope_partition'], event_type=w['family']),
                live=dict(frontier=41, snapshot_id='snap-tx-1'))


def retained_read(w, read):
    """('available', event) or ('unavailable'|'unsupported', refusal). Never creates a receipt or alters bytes."""
    facts = retained_facts(w, read)
    first = refusal('rr', facts)
    if first is None:
        first = refusal('rd', facts)
    if first is not None:
        return ('unsupported' if first[2] in ('recipe_unsupported', 'recipe_ambiguous') else 'unavailable', first)
    dispatcher = RetainedDispatcher(W3HOriginalOwner(w), {RECIPES[(w['family'], w['scope'])]: _frozen(w['family'], w['scope'])})
    custody = dispatcher.resolve(w['storage']['journal_key'], binding_of(w), disclose=lambda b: True)
    assert custody.binding == binding_of(w)
    return ('available', logical_of(w))


# --- compound ToDo cohorts -----------------------------------------------------------------------------------
def derive_todo_facts(before, after):
    """The exact ToDo facts an owner mutation produced, from actual before/after item graphs."""
    out = set()
    for k, v in after.items():
        b = before.get(k)
        if b is None:
            out.add(('todo.created', k))
            continue
        if b.get('member', True) and not v.get('member', True):
            out.add(('todo.removed_from_current_list', k))
        if v['depends_on'] != b['depends_on']:
            out.add(('todo.dependency_changed', k))
        if v['display_order'] != b['display_order']:
            out.add(('todo.reordered', k))
        if v['status'] != b['status']:
            out.add(('todo.status_changed', k))
        if v.get('title_ref') != b.get('title_ref'):
            out.add(('todo.updated', k))
        if v.get('binding') != b.get('binding'):
            out.add(('todo.work_bound', k))
    return sorted(out)


def compound(cw):
    members = cw['members']
    ids = [logical_of(m)['event_id'] for m in members]
    derived = derive_todo_facts(cw['before'], cw['after'])
    facts = dict(members_derived=sorted((m['family'], m['source']['result']['todo_id']) for m in members) == derived,
                 members_admitted=all(cw['admitted'].get(f) is True for f, _ in derived),
                 members_atomic=len({cw['txn'].get(i) for i in ids}) == 1 and None not in {cw['txn'].get(i) for i in ids},
                 group_complete=sorted(cw['group']['members']) == sorted(ids),
                 group_receipts=not cw['ack_claims_complete'] or all(type(cw['group']['receipts'].get(i)) is dict for i in ids),
                 members_verified=all(verify_publication(m, 'current') is None for m in members))
    first = refusal('cp', facts)
    return 'published' if first is None else ('refused', first)


