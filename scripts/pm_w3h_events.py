    admission = dict(family_admitted=True, edition_admitted=True, writer_enabled=True, permission_current=True,
                     stop_clear=True, dedupe_available=True)
    return dict(family=f, scope=scope, variant=variant, admission=admission, source=source, storage=storage,
                publication=publication)


