def retry(w, incoming):
    """Exact retry: ('return_original_without_effect', receipt) or ('refused', code). No new effect either way."""
    f = w['family']
    original = logical_of(w)
    shaped = _ok(lambda: _incoming_ok(f, incoming))
    nums = shaped and _ok(lambda: _payload_numbers(f, incoming['payload']) and (
        incoming['producer_sequence_id'] is None or current_integer(incoming['producer_sequence_id'], minimum=0) is not None))
    pub = w['publication']
    present = shaped and type(original) is dict and pub.get('physical_key') == w['storage']['journal_key'] and _ok(lambda: (
        partition_of(incoming['scope_kind'], incoming['project_id']), incoming['event_type'], incoming['idempotency_key'])
        == (partition_of(original['scope_kind'], original['project_id']), original['event_type'], original['idempotency_key']))
    verified = not present or verify_publication(w, 'frozen') is None
    policy = incoming.get('replay_policy') if type(incoming) is dict else None
    facts = dict(
        incoming_policy=_ok(lambda: current_append_policy(policy) is not None) or policy != 'projector_replay_only',
        dedupe_available=w['admission']['dedupe_available'] is True,
        incoming_shape=shaped, incoming_numbers=not shaped or nums, original_present=not nums or present,
        original_verified=not present or verified,
        semantic_equal=not (present and verified and nums) or _ok(
            lambda: producer_semantic_digest(incoming) == producer_semantic_digest(original)))
    first = refusal('ry', facts)
    if first is not None:
        return ('refused', first)
    return ('return_original_without_effect', copy.deepcopy(pub['first_append_receipt']))


def _state(value):
    return 'absent' if value is None else value.get('state') if type(value) is dict else 'invalid'


def cleanup_facts(f, request):
    policy = GROUP_POLICY[FAMILY_ROWS[f]['group']]
    trigger = {'RP-AUTHORITY-INDEFINITE': 'owning_data_deleted', 'RP-CHAT-THREAD-LIFETIME': 'thread_deleted_purge_due',
               'RP-GOAL-THREAD-LIFETIME': 'goal_thread_deleted'}[policy]
    r = request
    return dict(policy_bound=r['policy_ref'] == policy, policy_eligible=r['trigger'] == trigger,
                settled_only=r['original_state'] == 'settled', pending_released=r['pending_result'] is False,
                append_resolved=r['append_unresolved'] is False, ack_resolved=r['ack_unresolved'] is False,
                receipt_kept=r['deletes_receipt'] is False, recovery_anchor=r['recovery_anchor'] is False,
                live_reference=r['live_reference'] is False, hold_clear=r['hold'] is False,
                backup_settled=r['backup_settled'] is True, not_index=r['as_index'] is False)


def cleanup(f, request):
    first = refusal('cl', cleanup_facts(f, request))
    return 'removed' if first is None else ('refused', first)


def transition(t):
    """One journal write: t = {world (custody for the proposed value), prior, expected, proposed, cleanup}."""
    w, prior, proposed = t['world'], t['prior'], t['proposed']
    edge = (_state(prior), _state(proposed))
    same = exact(prior, proposed)
    both = type(prior) is dict and type(proposed) is dict
    if proposed is not None:
        pw = dict(w, publication=proposed)
        mode = 'current' if edge in (('absent', 'prepared'), ('prepared', 'appended')) else 'frozen'
        verified = verify_publication(pw, mode) is None
    else:
        verified = True
    facts = dict(cas_expected=exact(t['expected'], prior),
                 edge_legal=same or edge in LEGAL_EDGES or edge == ('absent', 'absent'),
                 frozen_event=not both or exact(proposed.get('prepared_event'), prior.get('prepared_event')),
                 frozen_copies=not both or all(exact(proposed.get(k), prior.get(k)) for k in COPIED),
                 proposed_verified=same or verified,
                 cleanup_authorized=edge != ('settled', 'absent') or (type(t.get('cleanup')) is dict and cleanup(w['family'], t['cleanup']) == 'removed'))
    first = refusal('tr', facts)
    if first is not None:
        return ('refused', first)
    return ('read_only_resolution' if same else 'written', copy.deepcopy(proposed))


