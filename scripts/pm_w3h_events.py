def _materialize(w):
    """(logical_event, notes) after the ev rows' facts; logical is None unless the route resolved."""
    pub = w['publication']
    pe = pub.get('prepared_event') if type(pub) is dict else None
    if type(pe) is not dict:
        return None
    if type(pe.get('payload')) is dict and pe.get('payload_ref') is None:
        return copy.deepcopy(pe)
    ref = pe.get('payload_ref')
    if pe.get('payload') is None and type(ref) is dict:
        pack = w['storage']['packs'].get(ref.get('blake3_id'))
        body = decode_storage_value(pack['bytes'], profile=EVENT_VALUE)
        logical = copy.deepcopy(pe)
        logical['payload'] = body
        logical['payload_ref'] = ref['ref']
        return logical
    return None


def _payload_numbers(f, payload):
    for name, minimum, maximum, nullable in INT_SLOTS[f]:
        value = payload.get(name)
        if value is None and nullable:
            continue
        if number(value) and type(value) is not bool and _ok(lambda: admits(_slot_validator(f, name), value)):
            current_integer(value, minimum=minimum, maximum=maximum)
    return True


