import pm_guard_isolation as g
FIELDS = ('has_golden', 'observed', 'golden')


def IF05_numeric_golden(value, context):
    return 'numeric golden bytes/hash' if value['has_golden'] is True and value['observed'] != value['golden'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('IF05_numeric_golden', g.Invariant('/numeric_cases/*/expected_value', 'equals the recomputed result'), 'numeric golden bytes/hash', IF05_numeric_golden),
    ])

    def check(value):
        table.require('IF05_numeric_golden', value, context)
        return True
    return g.Case(table, check, context)
