"""DX guard table retry_after_http_date: EP-032 rate_limited, current edition: a non-decimal Retry-After is an RFC 9110 HTTP-date naming a real UTC second.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('form', 'shared_refusal')


def RG01_http_date_grammar(value, context):
    return 'Retry-After HTTP-date' if value['form'] is None else None


def RG02_http_date_calendar(value, context):
    return 'Retry-After HTTP-date' if value['form'] is not None and value['shared_refusal'] is not None else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RG01_http_date_grammar', g.Invariant('/retry_after_header', 'the whole header is one HTTP-date form (IMF-fixdate, rfc850-date or asctime-date)'), 'Retry-After HTTP-date', RG01_http_date_grammar),
        g.Guard('RG02_http_date_calendar', g.Invariant('/retry_after_header', 'the HTTP-date names a real date and time (shared date_time)'), 'Retry-After HTTP-date', RG02_http_date_calendar),
    ])

    def check(value):
        table.require('RG01_http_date_grammar', value, context)
        table.require('RG02_http_date_calendar', value, context)
        return True
    return g.Case(table, check, context)
