"""DT guard table tool_request: tool_request_join: tool requests carry the exact tool_use_id; node requests omit it.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('request_kind', 'payload_tool_use_id', 'before_tool_use_id', 'payload_has_tool_use_id')


def TJ1_tool_use_present(value, context):
    return 'transition_refused' if value['request_kind'] == 'tool' and value['payload_tool_use_id'] is None else None


def TJ2_tool_use_copy(value, context):
    return 'transition_refused' if value['request_kind'] == 'tool' and value['payload_tool_use_id'] is not None and value['payload_tool_use_id'] != value['before_tool_use_id'] else None


def TJ3_node_omits_tool(value, context):
    return 'transition_refused' if value['request_kind'] != 'tool' and value['payload_has_tool_use_id'] is True else None


def TJ4_node_before_tool(value, context):
    return 'transition_refused' if value['request_kind'] != 'tool' and value['before_tool_use_id'] is not None else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TJ1_tool_use_present', g.Invariant('/payload/tool_use_id', 'a tool request payload carries a non-null tool_use_id'), 'transition_refused', TJ1_tool_use_present),
        g.Guard('TJ2_tool_use_copy', g.Invariant('/payload/tool_use_id', 'a tool request payload tool_use_id equals the blocked request'), 'transition_refused', TJ2_tool_use_copy),
        g.Guard('TJ3_node_omits_tool', g.Invariant('/payload/tool_use_id', 'a node request payload omits tool_use_id'), 'transition_refused', TJ3_node_omits_tool),
        g.Guard('TJ4_node_before_tool', g.Invariant('/before/tool_use_id', 'a node request has a null blocked tool_use_id'), 'transition_refused', TJ4_node_before_tool),
    ])

    def check(value):
        table.require('TJ1_tool_use_present', value, context)
        table.require('TJ2_tool_use_copy', value, context)
        table.require('TJ3_node_omits_tool', value, context)
        table.require('TJ4_node_before_tool', value, context)
        return True
    return g.Case(table, check, context)
