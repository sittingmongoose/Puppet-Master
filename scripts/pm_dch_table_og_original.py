"""DCH guard table og_original: CH2 original: independently committed intent, result, EventRecord and first receipt.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('original_store', 'store', 'record_equal', 'intent_mismatches', 'result_equal', 'receipt_event', 'original_event', 'receipt_sequence', 'original_sequence')


def OG02_original_store(value, context):
    return 'original_refused' if value['original_store'] != value['store'] else None


def OG03_original_event(value, context):
    return 'original_refused' if value['record_equal'] is not True else None


def OG04_intent_copies(value, context):
    return 'original_refused' if value['intent_mismatches'] != [] else None


def OG05_result_copies(value, context):
    return 'original_refused' if value['result_equal'] is not True else None


def OG06_receipt_event(value, context):
    return 'original_refused' if value['receipt_event'] != value['original_event'] else None


def OG07_receipt_sequence(value, context):
    return 'original_refused' if value['receipt_sequence'] != value['original_sequence'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('OG02_original_store', g.Invariant('/original/storage_instance_id', 'equals the actual reading Store'), 'original_refused', OG02_original_store),
        g.Guard('OG03_original_event', g.Invariant('/original/record', 'the candidate equals the committed original EventRecord'), 'original_refused', OG03_original_event),
        g.Guard('OG04_intent_copies', g.Invariant('/original/intent', 'every independently frozen accepted input equals the canonical result input'), 'original_refused', OG04_intent_copies),
        g.Guard('OG05_result_copies', g.Invariant('/original/result', 'the resolved body equals the independently committed original result'), 'original_refused', OG05_result_copies),
        g.Guard('OG06_receipt_event', g.Invariant('/original/receipt/event_id', 'equals the committed original event identity'), 'original_refused', OG06_receipt_event),
        g.Guard('OG07_receipt_sequence', g.Invariant('/original/receipt/sequence_id', 'equals the original Storage-assigned sequence'), 'original_refused', OG07_receipt_sequence),
    ])

    def check(value):
        table.require('OG02_original_store', value, context)
        table.require('OG03_original_event', value, context)
        table.require('OG04_intent_copies', value, context)
        table.require('OG05_result_copies', value, context)
        table.require('OG06_receipt_event', value, context)
        table.require('OG07_receipt_sequence', value, context)
        return True
    return g.Case(table, check, context)
