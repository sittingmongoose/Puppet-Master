import pm_guard_isolation as g
FIELDS = ('project', 'payload_project', 'storage', 'original_storage')


def HD04_project(value, context):
    return 'history Project' if value['project'] != value['payload_project'] else None


def HD05_storage(value, context):
    return 'history Storage root' if value['storage'] != value['original_storage'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('HD04_project', g.Invariant('/disclosure/project_id', 'equals the payload Project'), 'history Project', HD04_project),
        g.Guard('HD05_storage', g.Invariant('/disclosure/storage_instance_id', 'equals the original Storage root'), 'history Storage root', HD05_storage),
    ])

    def check(value):
        table.require('HD04_project', value, context)
        table.require('HD05_storage', value, context)
        return True
    return g.Case(table, check, context)
