import pm_guard_isolation as g
FIELDS = ('restore_required', 'safe_point_present', 'anchor_present')


def NB02_restore_safe_point(value, context):
    return 'restore anchor' if value['restore_required'] is True and value['safe_point_present'] is not True else None


def NB03_restore_anchor(value, context):
    return 'restore anchor' if value['restore_required'] is True and value['safe_point_present'] is True and value['anchor_present'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('NB02_restore_safe_point', g.Invariant('/payload/safe_point_id', 'is present when a safe-point restore is required'), 'restore anchor', NB02_restore_safe_point),
        g.Guard('NB03_restore_anchor', g.Invariant('/payload/anchor_ref', 'is present when a safe-point restore is required'), 'restore anchor', NB03_restore_anchor),
    ])

    def check(value):
        table.require('NB02_restore_safe_point', value, context)
        table.require('NB03_restore_anchor', value, context)
        return True
    return g.Case(table, check, context)
