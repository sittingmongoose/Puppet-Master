"""DX guard table shape_scheduler: Shape oracle scheduler.pass: unique candidates, partition, capacity, order and score joins.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('ready_unique', 'partition_unique', 'ready_ids', 'partition_ids', 'selected_count', 'available_slots', 'selected_ids', 'ordered_ids')


def SY01_unique_ready(value, context):
    return 'duplicate node' if value['ready_unique'] is not True else None


def SY02_unique_partition(value, context):
    return 'duplicate node' if value['partition_unique'] is not True else None


def SY03_partition(value, context):
    return 'capacity/partition' if value['ready_unique'] is True and value['partition_unique'] is True and value['ready_ids'] != value['partition_ids'] else None


def SY04_capacity(value, context):
    return 'capacity/partition' if value['selected_count'] > value['available_slots'] else None


def SY05_order(value, context):
    return 'selection order' if value['selected_ids'] != value['ordered_ids'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SY01_unique_ready', g.Invariant('/payload/ready_nodes', 'ready ids are unique'), 'duplicate node', SY01_unique_ready),
        g.Guard('SY02_unique_partition', g.Invariant('/payload/selected_nodes', 'selected and non-selected ids are unique together'), 'duplicate node', SY02_unique_partition),
        g.Guard('SY03_partition', g.Invariant('/payload/selected_nodes', 'selected plus non-selected equals the ready set'), 'capacity/partition', SY03_partition),
        g.Guard('SY04_capacity', g.Invariant('/payload/available_slots', 'selects at most available_slots'), 'capacity/partition', SY04_capacity),
        g.Guard('SY05_order', g.Invariant('/payload/selected_nodes', 'are the first ready nodes in score order'), 'selection order', SY05_order),
    ])

    def check(value):
        table.require('SY01_unique_ready', value, context)
        table.require('SY02_unique_partition', value, context)
        table.require('SY03_partition', value, context)
        table.require('SY04_capacity', value, context)
        table.require('SY05_order', value, context)
        return True
    return g.Case(table, check, context)
