"""DF guard table graph_method: Source graph: method binding.

Method B guard rows for the DF FileSafe checkers. Each predicate reads one
observation record that the lane checker derives from the complete boundary
input (recomputed digests, decoded values, resolved routes, presence);
predicates never recompute, repair or call helpers. The checkers refuse only
through these rows (pm_filesafe_tables.refusals), in this order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-filesafe-table-generate.py; do not edit by hand.
"""
import pm_guard_isolation as g

FIELDS = ('interface_id', 'expected_interface', 'component', 'producer', 'adoption')


def GR07_interface(value, context):
    return 'method_binding' if value['interface_id'] != value['expected_interface'] else None


def GR08_component(value, context):
    return 'method_binding' if value['component'] != value['producer'] else None


def GR09_adoption(value, context):
    return 'native_adoption_overclaim' if value['adoption'] != 'specified_unimplemented' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('GR07_interface', g.Invariant('/methods/interface_id', 'equals the scope-specific original-source interface'), 'method_binding', GR07_interface),
        g.Guard('GR08_component', g.Invariant('/methods/component', 'equals the graph producer'), 'method_binding', GR08_component),
        g.Guard('GR09_adoption', g.Invariant('/methods/adoption_disposition', 'is specified_unimplemented'), 'native_adoption_overclaim', GR09_adoption),
    ])

    def check(value):
        table.require('GR07_interface', value, context)
        table.require('GR08_component', value, context)
        table.require('GR09_adoption', value, context)
        return True
    return g.Case(table, check, context)
