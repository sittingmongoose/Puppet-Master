"""DCH guard table rt_identity: retry_outcome: idempotency lifetime and global event id integrity.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('original_lifetime', 'retry_lifetime', 'original_event_id', 'retry_event_id')


def RT10_reused_event_id(value, context):
    return 'conflict' if value['original_lifetime'] != value['retry_lifetime'] and value['original_event_id'] == value['retry_event_id'] else None


def RT11_event_id(value, context):
    return 'conflict' if value['original_lifetime'] == value['retry_lifetime'] and value['original_event_id'] != value['retry_event_id'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RT10_reused_event_id', g.Invariant('/retry/event_id', 'an event id is never reused for another idempotency lifetime'), 'conflict', RT10_reused_event_id),
        g.Guard('RT11_event_id', g.Invariant('/retry/event_id', 'a retry in the same lifetime carries the original event id'), 'conflict', RT11_event_id),
    ])

    def check(value):
        table.require('RT10_reused_event_id', value, context)
        table.require('RT11_event_id', value, context)
        return True
    return g.Case(table, check, context)
