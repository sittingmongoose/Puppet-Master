import pm_guard_isolation as g
FIELDS = ('used_type', 'count_type', 'used', 'count_before')


def RT04_used_type(value, context):
    return 'original per-error retry counter' if value['used_type'] != 'int' else None


def RT05_count_type(value, context):
    return 'original per-error retry counter' if value['count_type'] != 'int' else None


def RT06_used_nonnegative(value, context):
    return 'original per-error retry counter' if value['used_type'] == 'int' and value['used'] < 0 else None


def RT07_used_join(value, context):
    return 'original per-error retry counter' if value['used_type'] == 'int' and value['count_type'] == 'int' and value['used'] != value['count_before'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RT04_used_type', g.Invariant('/records/retry/body/used', 'is an integer'), 'original per-error retry counter', RT04_used_type),
        g.Guard('RT05_count_type', g.Invariant('/records/failure/body/retry_count_before', 'is an integer'), 'original per-error retry counter', RT05_count_type),
        g.Guard('RT06_used_nonnegative', g.Invariant('/records/retry/body/used', 'an integer counter is not negative'), 'original per-error retry counter', RT06_used_nonnegative),
        g.Guard('RT07_used_join', g.Invariant('/records/retry/body/used', 'equals the failure retry_count_before'), 'original per-error retry counter', RT07_used_join),
    ])

    def check(value):
        table.require('RT04_used_type', value, context)
        table.require('RT05_count_type', value, context)
        table.require('RT06_used_nonnegative', value, context)
        table.require('RT07_used_join', value, context)
        return True
    return g.Case(table, check, context)
