"""DCH guard table wt_pr_created: ACD-620 original auto-push and actual Create PR API outcome.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('push', 'api_status', 'url', 'payload_url', 'number', 'payload_number')


def WP01_push(value, context):
    return 'worktree_refused' if value['push'] != 'succeeded' else None


def WP02_api(value, context):
    return 'worktree_refused' if value['api_status'] != 'created' else None


def WP03_url(value, context):
    return 'worktree_refused' if value['url'] != value['payload_url'] else None


def WP04_number(value, context):
    return 'worktree_refused' if value['number'] != value['payload_number'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WP01_push', g.Invariant('/operation/outcome/push', 'auto-push succeeded'), 'worktree_refused', WP01_push),
        g.Guard('WP02_api', g.Invariant('/operation/outcome/api/status', 'the API returned the actual created PR'), 'worktree_refused', WP02_api),
        g.Guard('WP03_url', g.Invariant('/operation/outcome/api/pr_url', 'equals the original API URL'), 'worktree_refused', WP03_url),
        g.Guard('WP04_number', g.Invariant('/operation/outcome/api/pr_number', 'equals the original API PR number'), 'worktree_refused', WP04_number),
    ])

    def check(value):
        table.require('WP01_push', value, context)
        table.require('WP02_api', value, context)
        table.require('WP03_url', value, context)
        table.require('WP04_number', value, context)
        return True
    return g.Case(table, check, context)
