"""DX guard table trace_new: Trace model: a new identity needs an open writer and an append.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('writer_open', 'op')


def TA03_writer_open(value, context):
    return 'writer_withdrawn' if value['writer_open'] is not True else None


def TA04_replay_original(value, context):
    return 'missing_original' if value['writer_open'] is True and value['op'] == 'replay' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TA03_writer_open', g.Invariant('/writer', 'is open'), 'writer_withdrawn', TA03_writer_open),
        g.Guard('TA04_replay_original', g.Invariant('/op', 'a replay has an original'), 'missing_original', TA04_replay_original),
    ])

    def check(value):
        table.require('TA03_writer_open', value, context)
        table.require('TA04_replay_original', value, context)
        return True
    return g.Case(table, check, context)
