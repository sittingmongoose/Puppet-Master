"""DF guard table app_operation_coverage: Application original: every changed path has an operation.

Method B guard rows for the DF FileSafe checkers. Each predicate reads one
observation record that the lane checker derives from the complete boundary
input (recomputed digests, decoded values, resolved routes, presence);
predicates never recompute, repair or call helpers. The checkers refuse only
through these rows (pm_filesafe_tables.refusals), in this order.
FIELDS names every observation the rows read; the checker passes no other.
Generated by scripts/pm-filesafe-table-generate.py; do not edit by hand.
"""
import pm_guard_isolation as g

FIELDS = ('changed_paths', 'operation_paths')


def OC01_coverage(value, context):
    return 'application_operation_coverage' if len([path for path in value['changed_paths'] if path not in value['operation_paths']]) != 0 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('OC01_coverage', g.Invariant('/restore_transaction/operations', 'every path whose pre-restore and target entries differ has an operation'), 'application_operation_coverage', OC01_coverage),
    ])

    def check(value):
        table.require('OC01_coverage', value, context)
        return True
    return g.Case(table, check, context)
