"""DFM guard table trace_reader: Reader and event revisions and reader authority (validate_case).

Method B guard rows for scripts/pm-filemanager-event-contracts.py, generated by
scripts/pm-filemanager-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(recomputed keys, identities and digests, exact types, resolved rows); a
predicate never recomputes, repairs or calls helpers. The checker refuses
only through these rows, in this order (table_refusals in the checker).
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('reader_revision_ok', 'event_revision_ok', 'reader_true')


def TR01_reader_revision(value, context):
    return 'unsupported revision' if value['reader_revision_ok'] is not True else None


def TR02_event_revision(value, context):
    return 'unsupported revision' if value['event_revision_ok'] is not True else None


def TR03_reader_enabled(value, context):
    return 'reader withdrawn' if value['reader_true'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR01_reader_revision', g.Invariant('/reader_revision', 'is 1.0.0'), 'unsupported revision', TR01_reader_revision),
        g.Guard('TR02_event_revision', g.Invariant('/event_revision', 'is 1.0.0'), 'unsupported revision', TR02_event_revision),
        g.Guard('TR03_reader_enabled', g.Invariant('/reader_enabled', 'is exactly true'), 'reader withdrawn', TR03_reader_enabled),
    ])

    def check(value):
        table.require('TR01_reader_revision', value, context)
        table.require('TR02_event_revision', value, context)
        table.require('TR03_reader_enabled', value, context)
        return True
    return g.Case(table, check, context)
