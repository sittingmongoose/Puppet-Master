"""DT guard table cp_schema: checkpoint_result: prior and proposed checkpoint schemas, rebuild flag type.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('previous_present', 'previous_errors', 'governed_type', 'proposed_errors')


def CP01_previous_schema(value, context):
    return 'schema_refused' if value['previous_present'] is True and value['previous_errors'] != 0 else None


def CP02_rebuild_type(value, context):
    return 'unavailable' if value['governed_type'] != 'bool' else None


def CP03_proposed_schema(value, context):
    return 'schema_refused' if value['proposed_errors'] != 0 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP01_previous_schema', g.Invariant('/previous', 'a prior checkpoint satisfies the checkpoint schema'), 'schema_refused', CP01_previous_schema),
        g.Guard('CP02_rebuild_type', g.Invariant('/context/governed_rebuild', 'is exactly a bool'), 'unavailable', CP02_rebuild_type),
        g.Guard('CP03_proposed_schema', g.Invariant('/proposed', 'the proposed checkpoint satisfies the checkpoint schema'), 'schema_refused', CP03_proposed_schema),
    ])

    def check(value):
        table.require('CP01_previous_schema', value, context)
        table.require('CP02_rebuild_type', value, context)
        table.require('CP03_proposed_schema', value, context)
        return True
    return g.Case(table, check, context)
