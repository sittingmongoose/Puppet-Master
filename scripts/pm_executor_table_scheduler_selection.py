"""DX guard table scheduler_selection: scheduler.pass: source selection, unique candidates, partition and capacity.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('source_selected_canonical', 'payload_selected_canonical', 'ready_unique', 'partition_unique', 'ready_ids', 'partition_ids', 'selected_count', 'fill_count')


def SH01_source_selection(value, context):
    return 'scheduler source selection' if value['source_selected_canonical'] != value['payload_selected_canonical'] else None


def SH02_unique_ready(value, context):
    return 'duplicate candidate' if value['ready_unique'] is not True else None


def SH03_unique_partition(value, context):
    return 'duplicate candidate' if value['partition_unique'] is not True else None


def SH04_partition(value, context):
    return 'candidate partition' if value['ready_unique'] is True and value['partition_unique'] is True and value['ready_ids'] != value['partition_ids'] else None


def SH05_capacity(value, context):
    return 'fill available capacity' if value['selected_count'] != value['fill_count'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SH01_source_selection', g.Invariant('/records/scheduler/body/selected_nodes', 'equals the payload selection by canonical bytes'), 'scheduler source selection', SH01_source_selection),
        g.Guard('SH02_unique_ready', g.Invariant('/payload/ready_nodes', 'ready node ids are unique'), 'duplicate candidate', SH02_unique_ready),
        g.Guard('SH03_unique_partition', g.Invariant('/payload/selected_nodes', 'selected and non-selected ids are unique together'), 'duplicate candidate', SH03_unique_partition),
        g.Guard('SH04_partition', g.Invariant('/payload/selected_nodes', 'selected plus non-selected equals the ready set'), 'candidate partition', SH04_partition),
        g.Guard('SH05_capacity', g.Invariant('/payload/available_slots', 'fills min(ready, available_slots)'), 'fill available capacity', SH05_capacity),
    ])

    def check(value):
        table.require('SH01_source_selection', value, context)
        table.require('SH02_unique_ready', value, context)
        table.require('SH03_unique_partition', value, context)
        table.require('SH04_partition', value, context)
        table.require('SH05_capacity', value, context)
        return True
    return g.Case(table, check, context)
