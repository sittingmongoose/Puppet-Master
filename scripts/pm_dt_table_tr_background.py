def RB2_copies(value, context):
    return 'transition_refused' if value['copy_mismatches'] != [] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RB1_committed', g.Invariant('/before/queue_state', 'is committed'), 'transition_refused', RB1_committed),
        g.Guard('RB2_copies', g.Invariant('/payload', 'enqueue, queue record, scope, Host and root refs equal the durable intent'), 'transition_refused', RB2_copies),
    ])

    def check(value):
        table.require('RB1_committed', value, context)
        table.require('RB2_copies', value, context)
        return True
    return g.Case(table, check, context)
