"""DCH guard table tj_passed: test_joins: a passed terminal is an exact zero exit.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('kind', 'exit_code_refusal', 'exit_code')


def TJ06_passed_exit_kind(value, context):
    return 'test_join_refused' if value['kind'] != 'exit' else None


def TJ07_passed_exit_type(value, context):
    return 'test_join_refused' if value['kind'] == 'exit' and value['exit_code_refusal'] is not None else None


def TJ08_passed_exit_zero(value, context):
    return 'test_join_refused' if value['kind'] == 'exit' and value['exit_code_refusal'] is None and value['exit_code'] != 0 else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TJ06_passed_exit_kind', g.Invariant('/source/outcome/kind', 'a passed test outcome is an exit'), 'test_join_refused', TJ06_passed_exit_kind),
        g.Guard('TJ07_passed_exit_type', g.Invariant('/source/outcome/exit_code', 'a passed exit code is a CV-1100 current integer'), 'test_join_refused', TJ07_passed_exit_type),
        g.Guard('TJ08_passed_exit_zero', g.Invariant('/source/outcome/exit_code', 'a passed exit code is zero'), 'test_join_refused', TJ08_passed_exit_zero),
    ])

    def check(value):
        table.require('TJ06_passed_exit_kind', value, context)
        table.require('TJ07_passed_exit_type', value, context)
        table.require('TJ08_passed_exit_zero', value, context)
        return True
    return g.Case(table, check, context)
