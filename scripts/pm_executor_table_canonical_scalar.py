"""DX guard table canonical_scalar: Canonical scalars: JSON integer domain and, under the current recipe, exact binary64 integers.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('scalar_type', 'current_recipe', 'binary64_exact')


def CS01_scalar_domain(value, context):
    return 'canonical integer value domain' if value['scalar_type'] not in ('NoneType', 'str', 'bool', 'int') else None


def CS02_exact_binary64(value, context):
    return 'canonical exact binary64 integer' if value['scalar_type'] == 'int' and value['current_recipe'] is True and value['binary64_exact'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CS01_scalar_domain', g.Invariant('/**', 'every scalar is null, string, boolean or integer'), 'canonical integer value domain', CS01_scalar_domain),
        g.Guard('CS02_exact_binary64', g.Invariant('/**', 'under the current recipe an integer is an exact finite binary64 integer'), 'canonical exact binary64 integer', CS02_exact_binary64),
    ])

    def check(value):
        table.require('CS01_scalar_domain', value, context)
        table.require('CS02_exact_binary64', value, context)
        return True
    return g.Case(table, check, context)
