import pm_guard_isolation as g

FIELDS = ('route', 'payload_ref_verified', 'resolved_digest', 'captured_payload_digest', 'event_payload_digest')


def SV20_ref_verified(value, context):
    return 'payload_unavailable' if value['route'] == 'ref' and value['payload_ref_verified'] is not True else None


def SV21_ref_body(value, context):
    return 'payload_unavailable' if value['route'] == 'ref' and value['resolved_digest'] != value['captured_payload_digest'] else None


def SV22_inline_body(value, context):
    return 'join_refused' if value['route'] == 'inline' and value['event_payload_digest'] != value['captured_payload_digest'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SV20_ref_verified', g.Invariant('/payload_ref_verified', 'a referenced body is verified exactly True'), 'payload_unavailable', SV20_ref_verified),
        g.Guard('SV21_ref_body', g.Invariant('/resolved_payload', 'the resolved body equals the captured payload bytes'), 'payload_unavailable', SV21_ref_body),
        g.Guard('SV22_inline_body', g.Invariant('/event/payload', 'the inline body equals the captured payload bytes'), 'join_refused', SV22_inline_body),
    ])

    def check(value):
        table.require('SV20_ref_verified', value, context)
        table.require('SV21_ref_body', value, context)
        table.require('SV22_inline_body', value, context)
        return True
    return g.Case(table, check, context)
