"""DC guard table transition_finding_added: finding_added: targets, reviewers and unique finding.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('target_hashes', 'run_target_hashes', 'originating_reviewer_ids', 'roster', 'finding_known')


def TR55_targets(value, context):
    return 'conflict:target_hash_mismatch' if value['target_hashes'] != value['run_target_hashes'] else None


def TR56_reviewers(value, context):
    return 'conflict:slot_not_in_roster' if set(value['originating_reviewer_ids']) - set(value['roster']) else None


def TR57_finding_new(value, context):
    return 'conflict:finding_already_added' if value['finding_known'] is True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TR55_targets', g.Invariant('/target_hashes', 'equal the run target hashes'), 'conflict:target_hash_mismatch', TR55_targets),
        g.Guard('TR56_reviewers', g.Invariant('/originating_reviewer_ids', 'every reviewer is in the roster'), 'conflict:slot_not_in_roster', TR56_reviewers),
        g.Guard('TR57_finding_new', g.Invariant('/finding_id', 'is not already added'), 'conflict:finding_already_added', TR57_finding_new),
    ])

    def check(value):
        table.require('TR55_targets', value, context)
        table.require('TR56_reviewers', value, context)
        table.require('TR57_finding_new', value, context)
        return True
    return g.Case(table, check, context)
