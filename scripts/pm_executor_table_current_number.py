"""DX guard table current_number: CV-1100 current JSON number admission of a raw spelling (shared loads_current_json).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('parse_refusal',)


def CN01_integer_token(value, context):
    return 'integer_token' if value['parse_refusal'] == 'integer_token' else None


def CN02_json_syntax(value, context):
    return 'json_syntax' if value['parse_refusal'] == 'json_syntax' else None


def CN03_json_other(value, context):
    return 'current_json' if value['parse_refusal'] not in (None, 'integer_token', 'json_syntax') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CN01_integer_token', g.Invariant('/spelling', 'an integer token is 0 or -?[1-9][0-9]* (no -0)'), 'integer_token', CN01_integer_token),
        g.Guard('CN02_json_syntax', g.Invariant('/spelling', 'is JSON (no leading zeros)'), 'json_syntax', CN02_json_syntax),
        g.Guard('CN03_json_other', g.Invariant('/spelling', 'has no other current JSON refusal (non-finite constants, duplicate keys, Unicode)'), 'current_json', CN03_json_other),
    ])

    def check(value):
        table.require('CN01_integer_token', value, context)
        table.require('CN02_json_syntax', value, context)
        table.require('CN03_json_other', value, context)
        return True
    return g.Case(table, check, context)
