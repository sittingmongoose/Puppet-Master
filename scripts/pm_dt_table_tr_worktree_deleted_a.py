"""DT guard table tr_worktree_deleted_a: transition worktree.deleted: state and grace period.

Method B guard rows for scripts/pm-dt-event-contracts.py, generated by
scripts/pm-dt-table-generate.py (edit the row spec there, then regenerate).
Each predicate reads one observation record that the lane checker derives from
the complete boundary input (canonical bytes, digests, recomputed identities,
type names, presence); predicates never recompute, repair or call helpers. The
checker refuses only through these rows, in this order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('before_state', 'outcome_state', 'elapsed_unsigned', 'grace_unsigned', 'elapsed', 'grace')


def WD1_cleanup_eligible(value, context):
    return 'transition_refused' if value['before_state'] != 'cleanup_eligible' else None


def WD2_deleted(value, context):
    return 'transition_refused' if value['outcome_state'] != 'deleted' else None


def WD3_elapsed_unsigned(value, context):
    return 'transition_refused' if value['elapsed_unsigned'] is False else None


def WD4_grace_unsigned(value, context):
    return 'transition_refused' if value['grace_unsigned'] is False else None


def WD5_grace_elapsed(value, context):
    return 'transition_refused' if value['elapsed_unsigned'] is True and value['grace_unsigned'] is True and value['elapsed'] < value['grace'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WD1_cleanup_eligible', g.Invariant('/before/allocation_state', 'is cleanup_eligible'), 'transition_refused', WD1_cleanup_eligible),
        g.Guard('WD2_deleted', g.Invariant('/owner_result/allocation_state', 'is deleted'), 'transition_refused', WD2_deleted),
        g.Guard('WD3_elapsed_unsigned', g.Invariant('/before/elapsed_grace_ms', 'is an exact integer in 0..2^64-1 (shared current_integer)'), 'transition_refused', WD3_elapsed_unsigned),
        g.Guard('WD4_grace_unsigned', g.Invariant('/payload/grace_period_ms', 'is an exact integer in 0..2^64-1 (shared current_integer)'), 'transition_refused', WD4_grace_unsigned),
        g.Guard('WD5_grace_elapsed', g.Invariant('/before/elapsed_grace_ms', 'is at least the grace period'), 'transition_refused', WD5_grace_elapsed),
    ])

    def check(value):
        table.require('WD1_cleanup_eligible', value, context)
        table.require('WD2_deleted', value, context)
        table.require('WD3_elapsed_unsigned', value, context)
        table.require('WD4_grace_unsigned', value, context)
        table.require('WD5_grace_elapsed', value, context)
        return True
    return g.Case(table, check, context)
