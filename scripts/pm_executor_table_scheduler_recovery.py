"""DX guard table scheduler_recovery: scheduler.pass: recovery and watchdog wake reasons.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('recovered', 'wake_reason', 'all_watchdog')


def WK09_recovery_wake(value, context):
    return 'first recovery wake' if value['recovered'] is True and value['wake_reason'] != 'startup_recovered' else None


def WK10_watchdog(value, context):
    return 'watchdog pending event' if value['wake_reason'] == 'watchdog_recheck' and value['all_watchdog'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WK09_recovery_wake', g.Invariant('/payload/wake_reason', 'is startup_recovered after recovery'), 'first recovery wake', WK09_recovery_wake),
        g.Guard('WK10_watchdog', g.Invariant('/records/scheduler/body/wakes/*/reason', 'a watchdog recheck has only watchdog wakes'), 'watchdog pending event', WK10_watchdog),
    ])

    def check(value):
        table.require('WK09_recovery_wake', value, context)
        table.require('WK10_watchdog', value, context)
        return True
    return g.Case(table, check, context)
