"""DCH guard table wt_unbound: ACD-626 explicit cleanup or verified missing-path origin.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('origin', 'expected_origin', 'reason', 'path_exists')


def WU01_origin(value, context):
    return 'worktree_refused' if value['origin'] != value['expected_origin'] else None


def WU02_missing_path(value, context):
    return 'worktree_refused' if value['reason'] == 'path_missing' and value['path_exists'] is not False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WU01_origin', g.Invariant('/operation/outcome/origin', 'unbind follows explicit cleanup or original path revalidation'), 'worktree_refused', WU01_origin),
        g.Guard('WU02_missing_path', g.Invariant('/operation/outcome/path_exists', 'path_missing is supported by the original actual path observation'), 'worktree_refused', WU02_missing_path),
    ])

    def check(value):
        table.require('WU01_origin', value, context)
        table.require('WU02_missing_path', value, context)
        return True
    return g.Case(table, check, context)
