"""DCH guard table cp_dataset: checkpoint_joins: index dataset names and the index row checkpoint reference.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('token_dataset', 'expected_dataset', 'node_dataset', 'source_dataset', 'index_ref', 'expected_ref')


def CP18_token_dataset(value, context):
    return 'checkpoint_refused' if value['token_dataset'] != value['expected_dataset'] else None


def CP19_node_dataset(value, context):
    return 'checkpoint_refused' if value['node_dataset'] != value['expected_dataset'] else None


def CP20_source_dataset(value, context):
    return 'checkpoint_refused' if value['source_dataset'] != value['expected_dataset'] else None


def CP21_index_ref(value, context):
    return 'checkpoint_refused' if value['index_ref'] != value['expected_ref'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP18_token_dataset', g.Invariant('/value/source_token/index_dataset_name', 'is event_record_index.v2@<generation>'), 'checkpoint_refused', CP18_token_dataset),
        g.Guard('CP19_node_dataset', g.Invariant('/source/checkpoint/generations/<g>/index_dataset_name', 'is event_record_index.v2@<generation>'), 'checkpoint_refused', CP19_node_dataset),
        g.Guard('CP20_source_dataset', g.Invariant('/source/dataset_name', 'is event_record_index.v2@<generation>'), 'checkpoint_refused', CP20_source_dataset),
        g.Guard('CP21_index_ref', g.Invariant('/source/index_row/checkpoint_ref', 'equals the generic key plus the generation pointer'), 'checkpoint_refused', CP21_index_ref),
    ])

    def check(value):
        table.require('CP18_token_dataset', value, context)
        table.require('CP19_node_dataset', value, context)
        table.require('CP20_source_dataset', value, context)
        table.require('CP21_index_ref', value, context)
        return True
    return g.Case(table, check, context)
