import pm_guard_isolation as g

FIELDS = ('session_exact', 'host_exact', 'revision_exact', 'window_exact')


def HR1_session(value, context):
    return 'original host snapshot mismatch' if value['session_exact'] is not True else None


def HR2_host(value, context):
    return 'original host snapshot mismatch' if value['session_exact'] is True and value['host_exact'] is not True else None


def HR3_revision(value, context):
    return 'original host snapshot mismatch' if value['session_exact'] is True and value['host_exact'] is True and value['revision_exact'] is not True else None


def HR4_window(value, context):
    return 'original window mismatch' if value['window_exact'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('HR1_session', g.Invariant('/session_exact', 'prior_host_snapshot.app_session_id equals payload app_session_id'), 'original host snapshot mismatch', HR1_session),
        g.Guard('HR2_host', g.Invariant('/host_exact', 'prior_host_snapshot.host equals the payload source host'), 'original host snapshot mismatch', HR2_host),
        g.Guard('HR3_revision', g.Invariant('/revision_exact', 'prior_host_snapshot.host_revision equals the payload prior host revision'), 'original host snapshot mismatch', HR3_revision),
        g.Guard('HR4_window', g.Invariant('/window_exact', 'prior_host_snapshot.window_id is the payload window_id for a detached window, else null'), 'original window mismatch', HR4_window),
    ])

    def check(value):
        table.require('HR1_session', value, context)
        table.require('HR2_host', value, context)
        table.require('HR3_revision', value, context)
        table.require('HR4_window', value, context)
        return True
    return g.Case(table, check, context)
