"""DCH guard table wt_original: worktree: independently committed original intent, outcome and first receipt.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('original_store', 'store', 'record_equal', 'intent_mismatches', 'result_equal', 'receipt_event', 'original_event', 'receipt_sequence', 'original_sequence')


def WT02_original_store(value, context):
    return 'worktree_refused' if value['original_store'] != value['store'] else None


def WT03_original_event(value, context):
    return 'worktree_refused' if value['record_equal'] is not True else None


def WT04_intent_copies(value, context):
    return 'worktree_refused' if value['intent_mismatches'] != [] else None


def WT05_result_copies(value, context):
    return 'worktree_refused' if value['result_equal'] is not True else None


def WT06_receipt_event(value, context):
    return 'worktree_refused' if value['receipt_event'] != value['original_event'] else None


def WT07_receipt_sequence(value, context):
    return 'worktree_refused' if value['receipt_sequence'] != value['original_sequence'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WT02_original_store', g.Invariant('/original/storage_instance_id', 'equals the actual reading Store'), 'worktree_refused', WT02_original_store),
        g.Guard('WT03_original_event', g.Invariant('/original/record', 'the candidate equals the committed original EventRecord'), 'worktree_refused', WT03_original_event),
        g.Guard('WT04_intent_copies', g.Invariant('/original/intent', 'every independently frozen input equals the canonical result input'), 'worktree_refused', WT04_intent_copies),
        g.Guard('WT05_result_copies', g.Invariant('/original/result', 'the resolved body equals the independently committed original result'), 'worktree_refused', WT05_result_copies),
        g.Guard('WT06_receipt_event', g.Invariant('/original/receipt/event_id', 'equals the committed original event identity'), 'worktree_refused', WT06_receipt_event),
        g.Guard('WT07_receipt_sequence', g.Invariant('/original/receipt/sequence_id', 'equals the original Storage-assigned sequence'), 'worktree_refused', WT07_receipt_sequence),
    ])

    def check(value):
        table.require('WT02_original_store', value, context)
        table.require('WT03_original_event', value, context)
        table.require('WT04_intent_copies', value, context)
        table.require('WT05_result_copies', value, context)
        table.require('WT06_receipt_event', value, context)
        table.require('WT07_receipt_sequence', value, context)
        return True
    return g.Case(table, check, context)
