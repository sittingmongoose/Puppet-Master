"""DCH guard table cp_node: checkpoint_joins: current generation node and index sequence type.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('node_present', 'index_sequence_type', 'event_sequence_type')


def CP02_generation_node(value, context):
    return 'checkpoint_refused' if value['node_present'] is not True else None


def CP03_sequence_type(value, context):
    return 'checkpoint_refused' if value['index_sequence_type'] != value['event_sequence_type'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('CP02_generation_node', g.Invariant('/source/checkpoint/generations', 'names the token generation'), 'checkpoint_refused', CP02_generation_node),
        g.Guard('CP03_sequence_type', g.Invariant('/source/index_row/sequence_id', 'has exactly the retained event sequence type'), 'checkpoint_refused', CP03_sequence_type),
    ])

    def check(value):
        table.require('CP02_generation_node', value, context)
        table.require('CP03_sequence_type', value, context)
        return True
    return g.Case(table, check, context)
