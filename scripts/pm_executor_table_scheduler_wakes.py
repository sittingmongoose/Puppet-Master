"""DX guard table scheduler_wakes: scheduler.pass: primary, coalesced and recovery wakes.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('wake_count', 'wake_reason', 'primary_reason', 'coalesced', 'later_reasons', 'wake_refs', 'later_ids', 'recovered_type')


def WK04_wake_present(value, context):
    return 'primary wake' if value['wake_count'] < 1 else None


def WK05_primary_wake(value, context):
    return 'primary wake' if value['wake_count'] >= 1 and value['wake_reason'] != value['primary_reason'] else None


def WK06_coalesced(value, context):
    return 'coalesced wakes' if value['coalesced'] != value['later_reasons'] else None


def WK07_wake_refs(value, context):
    return 'wake event joins' if value['wake_refs'] != value['later_ids'] else None


def WK08_recovered_type(value, context):
    return 'scheduler recovered boolean' if value['recovered_type'] != 'bool' else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('WK04_wake_present', g.Invariant('/records/scheduler/body/wakes', 'has at least one wake'), 'primary wake', WK04_wake_present),
        g.Guard('WK05_primary_wake', g.Invariant('/payload/wake_reason', 'equals the earliest wake reason'), 'primary wake', WK05_primary_wake),
        g.Guard('WK06_coalesced', g.Invariant('/payload/coalesced_wake_reasons', 'equals the later wake reasons in order'), 'coalesced wakes', WK06_coalesced),
        g.Guard('WK07_wake_refs', g.Invariant('/payload/wake_event_refs', 'equals the later wake event ids in order'), 'wake event joins', WK07_wake_refs),
        g.Guard('WK08_recovered_type', g.Invariant('/records/scheduler/body/recovered', 'is a boolean'), 'scheduler recovered boolean', WK08_recovered_type),
    ])

    def check(value):
        table.require('WK04_wake_present', value, context)
        table.require('WK05_primary_wake', value, context)
        table.require('WK06_coalesced', value, context)
        table.require('WK07_wake_refs', value, context)
        table.require('WK08_recovered_type', value, context)
        return True
    return g.Case(table, check, context)
