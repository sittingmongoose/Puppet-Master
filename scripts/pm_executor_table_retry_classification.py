"""DX guard table retry_classification: EP-032: no blind retry of a non-retryable class.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('class_type', 'failure_class')


def RC01_class_type(value, context):
    return 'no blind retry' if value['class_type'] != 'str' else None


def RC02_retryable(value, context):
    return 'no blind retry' if value['class_type'] == 'str' and value['failure_class'] in ('graph_integrity', 'verification_failed', 'reviewer_findings', 'quota_exceeded') else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RC01_class_type', g.Invariant('/failure_class', 'is a string'), 'no blind retry', RC01_class_type),
        g.Guard('RC02_retryable', g.Invariant('/failure_class', 'is not graph_integrity, verification_failed, reviewer_findings or quota_exceeded'), 'no blind retry', RC02_retryable),
    ])

    def check(value):
        table.require('RC01_class_type', value, context)
        table.require('RC02_retryable', value, context)
        return True
    return g.Case(table, check, context)
