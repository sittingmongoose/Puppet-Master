"""DC guard table source_review: Source custody: Review targets, reviewers and counts.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('body_review_targets', 'context_review_targets', 'reviewer_ids_is_list', 'vote_targets', 'context_reviewer_ids', 'vote_reviewers', 'counted_vote_count', 'distinct_reviewer_count', 'vote_count', 'distinct_reviewer_count_for_votes', 'dissent_count', 'record_dissent_count')


def SF52_review_targets(value, context):
    return 'source_review_targets' if value['body_review_targets'] != value['context_review_targets'] else None


def SF53_reviewer_control(value, context):
    return 'source_review_targets' if value['reviewer_ids_is_list'] is False else None


def SF54_vote_targets(value, context):
    return 'source_review_targets' if value['vote_targets'] != [] and set(value['vote_targets']) - set(value['body_review_targets']) else None


def SF55_vote_reviewers(value, context):
    return 'source_review_targets' if value['context_reviewer_ids'] is not None and set(value['vote_reviewers']) - set(value['context_reviewer_ids']) else None


def SF56_counted_votes(value, context):
    return 'source_review_counts' if value['counted_vote_count'] != value['distinct_reviewer_count'] else None


def SF57_votes_unique(value, context):
    return 'source_review_counts' if value['vote_count'] != value['distinct_reviewer_count_for_votes'] else None


def SF58_dissent(value, context):
    return 'source_review_counts' if value['dissent_count'] != value['record_dissent_count'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('SF52_review_targets', g.Invariant('/semantic_body/target_hashes', 'equals the captured Review targets'), 'source_review_targets', SF52_review_targets),
        g.Guard('SF53_reviewer_control', g.Invariant('/<context>/reviewer_ids', 'is a list of distinct strings'), 'source_review_targets', SF53_reviewer_control),
        g.Guard('SF54_vote_targets', g.Invariant('/owner_record/reviewer_votes/target_hash', 'every vote target is a body target'), 'source_review_targets', SF54_vote_targets),
        g.Guard('SF55_vote_reviewers', g.Invariant('/owner_record/reviewer_votes/reviewer_id', 'every vote reviewer is a captured reviewer'), 'source_review_targets', SF55_vote_reviewers),
        g.Guard('SF56_counted_votes', g.Invariant('/semantic_body/counted_vote_count', 'dispositioned: equals the distinct reviewers'), 'source_review_counts', SF56_counted_votes),
        g.Guard('SF57_votes_unique', g.Invariant('/owner_record/reviewer_votes', 'dispositioned: one vote per reviewer'), 'source_review_counts', SF57_votes_unique),
        g.Guard('SF58_dissent', g.Invariant('/semantic_body/dissent_count', 'dispositioned: equals the record dissent count'), 'source_review_counts', SF58_dissent),
    ])

    def check(value):
        table.require('SF52_review_targets', value, context)
        table.require('SF53_reviewer_control', value, context)
        table.require('SF54_vote_targets', value, context)
        table.require('SF55_vote_reviewers', value, context)
        table.require('SF56_counted_votes', value, context)
        table.require('SF57_votes_unique', value, context)
        table.require('SF58_dissent', value, context)
        return True
    return g.Case(table, check, context)
