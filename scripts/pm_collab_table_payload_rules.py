"""DC guard table payload_rules: CV-460 payload layers 2-6: epoch, timestamp, identity recipe and family arithmetic.

Method B guard rows for scripts/pm_collaboration_events.py, generated by
scripts/pm-collab-table-generate.py. Each predicate reads one observation
record that the lane checker derives from the complete boundary input
(canonical digests, recomputed identities, resolved routes); predicates never
recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_collaboration_events.py:table_refusals), and asserts
that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('epoch_type', 'epoch_negative', 'family_timestamp_valid', 'idempotency_key', 'expected_idempotency_key', 'previous_definition_revision', 'expected_previous_definition_revision', 'reviewer_sum', 'requested_reviewer_count')


def PR01_epoch_integer(value, context):
    return 'epoch_type' if value['epoch_type'] != 'int' else None


def PR02_epoch_nonnegative(value, context):
    return 'epoch_type' if value['epoch_negative'] is True else None


def PR03_family_timestamp(value, context):
    return 'valid_utc_datetime' if value['family_timestamp_valid'] is not True else None


def PR04_idempotency_recipe(value, context):
    return 'identity_recipe' if value['idempotency_key'] != value['expected_idempotency_key'] else None


def PR05_revision_rule(value, context):
    return 'revision_rule' if value['previous_definition_revision'] != value['expected_previous_definition_revision'] else None


def PR06_review_counts(value, context):
    return 'review_counts' if value['reviewer_sum'] != value['requested_reviewer_count'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('PR01_epoch_integer', g.Invariant('/recovery_epoch', 'is an exact int'), 'epoch_type', PR01_epoch_integer),
        g.Guard('PR02_epoch_nonnegative', g.Invariant('/recovery_epoch', 'an int epoch is not negative'), 'epoch_type', PR02_epoch_nonnegative),
        g.Guard('PR03_family_timestamp', g.Invariant('/<family timestamp>', 'is a UTC timestamp ending in Z'), 'valid_utc_datetime', PR03_family_timestamp),
        g.Guard('PR04_idempotency_recipe', g.Invariant('/idempotency_key', 'equals the SP-460/CV-366 recipe for the payload and epoch'), 'identity_recipe', PR04_idempotency_recipe),
        g.Guard('PR05_revision_rule', g.Invariant('/previous_definition_revision', 'configuration_changed: equals definition_revision - 1'), 'revision_rule', PR05_revision_rule),
        g.Guard('PR06_review_counts', g.Invariant('/requested_reviewer_count', 'artifact_finalized: completed + failed equals requested'), 'review_counts', PR06_review_counts),
    ])

    def check(value):
        table.require('PR01_epoch_integer', value, context)
        table.require('PR02_epoch_nonnegative', value, context)
        table.require('PR03_family_timestamp', value, context)
        table.require('PR04_idempotency_recipe', value, context)
        table.require('PR05_revision_rule', value, context)
        table.require('PR06_review_counts', value, context)
        return True
    return g.Case(table, check, context)
