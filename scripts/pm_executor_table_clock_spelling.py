"""DX guard table clock_spelling: Owner clocks: whole-string RFC3339 spelling and the UTC route (instant).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('spelling_valid', 'utc_required', 'utc_spelling', 'parses')


def TS01_spelling(value, context):
    return 'whole-string source timestamp' if value['spelling_valid'] is not True else None


def TS02_utc_route(value, context):
    return 'whole-string source timestamp' if value['spelling_valid'] is True and value['utc_required'] is True and value['utc_spelling'] is not True else None


def TS03_parses(value, context):
    return 'whole-string source timestamp' if value['spelling_valid'] is True and (value['utc_required'] is not True or value['utc_spelling'] is True) and value['parses'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TS01_spelling', g.Invariant('/**/*_utc', 'the whole string is a date-time with a calendar-valid date where the recipe requires it'), 'whole-string source timestamp', TS01_spelling),
        g.Guard('TS02_utc_route', g.Invariant('/**/*_utc', 'a UTC clock ends in uppercase Z under the current recipe'), 'whole-string source timestamp', TS02_utc_route),
        g.Guard('TS03_parses', g.Invariant('/**/*_utc', 'a valid spelling parses to an instant'), 'whole-string source timestamp', TS03_parses),
    ])

    def check(value):
        table.require('TS01_spelling', value, context)
        table.require('TS02_utc_route', value, context)
        table.require('TS03_parses', value, context)
        return True
    return g.Case(table, check, context)
