"""DX guard table clock_spelling: Owner clocks, frozen v0 edition: the v0 spelling and its original clock parse (v0_instant; SP-500..515).

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('spelling_valid', 'parses')


def TS01_spelling(value, context):
    return 'whole-string source timestamp' if value['spelling_valid'] is not True else None


def TS03_parses(value, context):
    return 'whole-string source timestamp' if value['spelling_valid'] is True and value['parses'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('TS01_spelling', g.Invariant('/**/*_utc', 'the whole string matches the frozen v0 date-time spelling'), 'whole-string source timestamp', TS01_spelling),
        g.Guard('TS03_parses', g.Invariant('/**/*_utc', 'a valid v0 spelling parses to an instant'), 'whole-string source timestamp', TS03_parses),
    ])

    def check(value):
        table.require('TS01_spelling', value, context)
        table.require('TS03_parses', value, context)
        return True
    return g.Case(table, check, context)
