"""DX guard table retry_identity: Retry: classification, error identity and attempt joins.

Method B guard rows for the DX checkers, generated by
scripts/pm-executor-table-generate.py. Each predicate reads one observation
record that the checker derives from the complete boundary input (recomputed
digests and identities, canonical bytes, resolved routes, presence); predicates
never recompute, repair or call helpers. The checker refuses only through these
rows, in this order (pm_executor_event_semantics.py:refuse), and the full
semantic CLI asserts that the factory requires its rows in table order.
FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g
FIELDS = ('retry_class', 'payload_class', 'failure_class', 'retry_error', 'failure_error', 'failure_attempt', 'attempt_record', 'retry_scheduled', 'prior_attempt')


def RT01_retry_class(value, context):
    return 'retry classification' if value['retry_class'] != value['payload_class'] else None


def RT02_failure_class(value, context):
    return 'retry classification' if value['payload_class'] != value['failure_class'] else None


def RT03_error_identity(value, context):
    return 'per-error counter identity' if value['retry_error'] != value['failure_error'] else None


def RT08_failed_attempt(value, context):
    return 'original failed attempt' if value['failure_attempt'] != value['attempt_record'] else None


def RT09_prior_attempt(value, context):
    return 'classified prior attempt' if value['retry_scheduled'] is True and value['prior_attempt'] != value['failure_attempt'] else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RT01_retry_class', g.Invariant('/records/retry/body/failure_class', 'equals the payload class'), 'retry classification', RT01_retry_class),
        g.Guard('RT02_failure_class', g.Invariant('/records/failure/body/failure_class', 'equals the payload class'), 'retry classification', RT02_failure_class),
        g.Guard('RT03_error_identity', g.Invariant('/records/retry/body/error_id', 'equals the failure error id'), 'per-error counter identity', RT03_error_identity),
        g.Guard('RT08_failed_attempt', g.Invariant('/records/failure/body/attempt_id', 'equals the failed attempt record'), 'original failed attempt', RT08_failed_attempt),
        g.Guard('RT09_prior_attempt', g.Invariant('/records/retry/body/prior_attempt_id', 'run.node_retry_scheduled: equals the failed attempt'), 'classified prior attempt', RT09_prior_attempt),
    ])

    def check(value):
        table.require('RT01_retry_class', value, context)
        table.require('RT02_failure_class', value, context)
        table.require('RT03_error_identity', value, context)
        table.require('RT08_failed_attempt', value, context)
        table.require('RT09_prior_attempt', value, context)
        return True
    return g.Case(table, check, context)
