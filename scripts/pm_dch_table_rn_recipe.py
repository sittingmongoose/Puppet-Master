"""DCH guard table rn_recipe: record_number_rule: retained-original recipe selection from independent write receipts.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('provenance_type', 'store_type', 'digest_type', 'claim_present', 'claim', 'receipt_recipe', 'store_descriptor_valid', 'store_in_custody', 'receipt_count', 'recipe_installed')


def RN01_provenance_object(value, context):
    return 'recipe_refused' if value['provenance_type'] != 'dict' else None


def RN02_store_type(value, context):
    return 'recipe_refused' if value['provenance_type'] == 'dict' and value['store_type'] != 'str' else None


def RN03_digest_type(value, context):
    return 'recipe_refused' if value['provenance_type'] == 'dict' and value['digest_type'] != 'str' else None


def RN04_recipe_claim(value, context):
    return 'recipe_refused' if value['store_type'] == 'str' and value['digest_type'] == 'str' and value['claim_present'] is True and value['claim'] != value['receipt_recipe'] else None


def RN05_custody_store(value, context):
    return 'original_unavailable' if value['store_descriptor_valid'] is True and value['store_in_custody'] is not True else None


def RN06_recipe_installed(value, context):
    return 'recipe_unsupported' if value['store_in_custody'] is True and value['receipt_count'] == 1 and value['recipe_installed'] is not True else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RN01_provenance_object', g.Invariant('/provenance', 'a supplied provenance is exactly a JSON object'), 'recipe_refused', RN01_provenance_object),
        g.Guard('RN02_store_type', g.Invariant('/provenance/storage_instance_id', 'the provenance Store is exactly a string'), 'recipe_refused', RN02_store_type),
        g.Guard('RN03_digest_type', g.Invariant('/provenance/source_value_sha256', 'the provenance source digest is exactly a string'), 'recipe_refused', RN03_digest_type),
        g.Guard('RN04_recipe_claim', g.Invariant('/provenance/recipe_id', 'a claimed recipe equals the receipt-selected recipe; it never selects one'), 'recipe_refused', RN04_recipe_claim),
        g.Guard('RN05_custody_store', g.Invariant('/provenance/storage_instance_id', 'a retained original belongs to a Store whose write custody the sealed receipt catalogue holds'), 'original_unavailable', RN05_custody_store),
        g.Guard('RN06_recipe_installed', g.Invariant('/provenance/source_value_sha256', 'the receipt-selected recipe and its pinned resources have an installed frozen verifier'), 'recipe_unsupported', RN06_recipe_installed),
    ])

    def check(value):
        table.require('RN01_provenance_object', value, context)
        table.require('RN02_store_type', value, context)
        table.require('RN03_digest_type', value, context)
        table.require('RN04_recipe_claim', value, context)
        table.require('RN05_custody_store', value, context)
        table.require('RN06_recipe_installed', value, context)
        return True
    return g.Case(table, check, context)
