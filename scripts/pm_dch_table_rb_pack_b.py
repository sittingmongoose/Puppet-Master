"""DCH guard table rb_pack_b: resolve_body: pack thread copy, custody flags and deletion.

Method B guard rows for scripts/pm_dch_events.py and scripts/pm_dch_stop.py,
generated by scripts/pm-dch-table-generate.py (edit the row spec there, then
regenerate). Each predicate reads one observation record that the lane checker
derives from the complete boundary input (canonical bytes, digests, recomputed
identities, type names, presence, mismatch lists); predicates never recompute,
repair or call helpers. The checker refuses only through these rows, in this
order. FIELDS names every observation the rows read; the checker passes no other.
"""
import pm_guard_isolation as g

FIELDS = ('pack_thread_id', 'body_thread_id', 'authorized', 'hold_access_allowed', 'bytes_durable', 'index_durable', 'readback_verified', 'deleted')


def RB12_thread_copy(value, context):
    return 'body_unavailable' if value['pack_thread_id'] != value['body_thread_id'] else None


def RB13_authorized(value, context):
    return 'body_unavailable' if value['authorized'] is not True else None


def RB14_hold_access(value, context):
    return 'body_unavailable' if value['hold_access_allowed'] is not True else None


def RB15_bytes_durable(value, context):
    return 'body_unavailable' if value['bytes_durable'] is not True else None


def RB16_index_durable(value, context):
    return 'body_unavailable' if value['index_durable'] is not True else None


def RB17_readback_verified(value, context):
    return 'body_unavailable' if value['readback_verified'] is not True else None


def RB18_not_deleted(value, context):
    return 'body_unavailable' if value['deleted'] is not False else None


def case(value):
    context = None
    table = g.GuardTable([
        g.Guard('RB12_thread_copy', g.Invariant('/source/thread_id', 'equals the pack body thread_id'), 'body_unavailable', RB12_thread_copy),
        g.Guard('RB13_authorized', g.Invariant('/source/authorized', 'is exactly true'), 'body_unavailable', RB13_authorized),
        g.Guard('RB14_hold_access', g.Invariant('/source/hold_access_allowed', 'is exactly true'), 'body_unavailable', RB14_hold_access),
        g.Guard('RB15_bytes_durable', g.Invariant('/source/bytes_durable', 'is exactly true'), 'body_unavailable', RB15_bytes_durable),
        g.Guard('RB16_index_durable', g.Invariant('/source/index_durable', 'is exactly true'), 'body_unavailable', RB16_index_durable),
        g.Guard('RB17_readback_verified', g.Invariant('/source/readback_verified', 'is exactly true'), 'body_unavailable', RB17_readback_verified),
        g.Guard('RB18_not_deleted', g.Invariant('/source/deleted', 'is exactly false'), 'body_unavailable', RB18_not_deleted),
    ])

    def check(value):
        table.require('RB12_thread_copy', value, context)
        table.require('RB13_authorized', value, context)
        table.require('RB14_hold_access', value, context)
        table.require('RB15_bytes_durable', value, context)
        table.require('RB16_index_durable', value, context)
        table.require('RB17_readback_verified', value, context)
        table.require('RB18_not_deleted', value, context)
        return True
    return g.Case(table, check, context)
